"""Крок 24б: `колір_річ` бази (`git show <ревізія>`) проти дерева на каталозі — буре сім'ї тону ДО (коробка
`БУРЕ_СІМ_Ї`) → ПІСЛЯ (`колір_тон.сім_я_кольору` — brown) з переходами за сім'єю модуля; сім'я й нейтраль речі
(`сім_я_меж`, `нейтраль_меж`, `роди_нейтралі_меж`) на всіх речах з кольором (вимір і вікно слова); пари
`та_сама_сім_я` серед бурих ДО ∪ ПІСЛЯ (поза ними злиття бурих не діє); вікна лексикону попарно й проти виміру;
`сім_ї_тонів` на 20 000 випадкових наборах із 2–6 речей. Запуск із кореня (розпакований `джерела/каталог_повний.xml`):
python3 -W ignore аудит/перевірка/річ_колір_межі_крок24б/до_після.py <ревізія> > …/до_після.txt"""
import collections, importlib.util, itertools, random, subprocess, sys, tempfile
sys.path.insert(0, "джерела")
import колір_річ as П, колір_тон as Т, фід_каталог as ФК, verify as V  # noqa: E402
from колір_простір_перетворення import lch, hex_з_lab  # noqa: E402
т = subprocess.run(["git", "show", f"{sys.argv[1]}:джерела/колір_річ.py"], check=True, capture_output=True).stdout
ф = tempfile.NamedTemporaryFile(suffix=".py", delete=False); ф.write(т); ф.close()
сп = importlib.util.spec_from_file_location("кр_база", ф.name); Д = importlib.util.module_from_spec(сп); сп.loader.exec_module(Д)
кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
речі = [р for р in кат if П.межі_кольору(р) is not None]
виміри = [р for р in речі if П.не_вимір(р) is None]
print(f"речей з кольором: {len(речі)}; з виміром: {len(виміри)}; вікном слова: {len(речі) - len(виміри)}")

# 1. Буре точки виміру
пер, пр, бурі = collections.Counter(), collections.defaultdict(list), [set(), set()]
for і, р in enumerate(виміри):
    lab = [float(x) for x in П.точка_кольору(р)]
    L, C, h = lch(lab)
    б = (Д.буре_сім_я(L, C, h), П.буре_сім_я(L, C, h))
    for к in (0, 1):
        if б[к]:
            бурі[к].add(і)
    if б[0] != б[1]:
        в = Т.сім_ї_кольору(lab)
        к = ("буре → " if б[0] else "не буре → ") + (Т.сім_я_кольору(lab)[0] if б[0] else "brown") + \
            (" (значні: " + "+".join(x for x, _ in в) + ")" if len(в) > 1 else "")
        пер[к] += 1
        if len(пр[к]) < 4:
            пр[к].append(f"{р.get('id')} {hex_з_lab(lab)} L{L:.0f} C{C:.0f} h{h:.0f} «{(р.get('колір_назва') or '').strip().lower()}»")
print(f"\n1. буре (точка виміру): {len(бурі[0])} → {len(бурі[1])}; змінилось {sum(пер.values())}")
for к, n in пер.most_common():
    print(f"  {к}: {n} — {'; '.join(пр[к])}")

# 2. Сім'я й нейтраль речі — ті самі функції бази й дерева
for ім in ("сім_я_меж", "нейтраль_меж", "роди_нейтралі_меж", "рід_нейтралі"):
    різні = [р.get("id") for р in речі if getattr(Д, ім)(р) != getattr(П, ім)(р)]
    print(f"\n2. {ім}: змінилось {len(різні)} з {len(речі)}" + (f" — {різні[:5]}" if різні else ""))

# 3. Пари `та_сама_сім_я` серед бурих (ДО ∪ ПІСЛЯ)
об = sorted(бурі[0] | бурі[1]); пп = collections.Counter(); пп_пр = collections.defaultdict(list); всього = 0
for а, б in itertools.combinations(об, 2):
    всього += 1
    в = (Д.та_сама_сім_я(виміри[а], виміри[б]), П.та_сама_сім_я(виміри[а], виміри[б]))
    if в[0] != в[1]:
        пп[в] += 1
        if len(пп_пр[в]) < 3:
            пп_пр[в].append(" + ".join(f"{hex_з_lab([float(x) for x in П.точка_кольору(виміри[і])])} «{(виміри[і].get('колір_назва') or '').strip().lower()}»" for і in (а, б)))
print(f"\n3. та_сама_сім_я, пари серед бурих ДО ∪ ПІСЛЯ ({len(об)} речей, {всього} пар): змінилось {sum(пп.values())}")
for в, n in пп.most_common():
    print(f"  {в[0]} → {в[1]}: {n} — {'; '.join(пп_пр[в])}")

# 4. Вікна лексикону: попарно й проти 500 випадкових вимірів
rnd = random.Random(24)
вікна = [dict(колір_назва=с, колір_не_вимір=dict(свідок="слово крамниці", слово=с, вікно=в)) for с, в in V.ЛЕКСИКОН.items()]
вибірка = rnd.sample(виміри, 500)
пари = list(itertools.combinations(вікна, 2)) + [(в, м) for в in вікна for м in вибірка]
різні = sum(Д.та_сама_сім_я(а, б) != П.та_сама_сім_я(а, б) for а, б in пари)
print(f"\n4. та_сама_сім_я з вікнами слова ({len(вікна)} вікон, {len(пари)} пар): змінилось {різні}")

# 5. `сім_ї_тонів` на випадкових наборах
змін, пр5 = 0, []
for _ in range(20000):
    н = rnd.sample(речі, rnd.randint(2, 6))
    д, п = Д.сім_ї_тонів(н), П.сім_ї_тонів(н)
    if д != п:
        змін += 1
        if len(пр5) < 3:
            пр5.append(f"{[р.get('id') for р in н]}: {д} → {п}")
print(f"\n5. сім_ї_тонів на 20 000 наборах із 2–6 речей: змінилось {змін}")
for x in пр5:
    print("  " + x)
