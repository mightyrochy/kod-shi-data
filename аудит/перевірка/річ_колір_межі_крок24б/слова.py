"""Крок 24б: переходи буре ДО (коробка `БУРЕ_СІМ_Ї` бази c2107769, тут формулою) → ПІСЛЯ (`колір_річ.буре_сім_я`
дерева) за групою слова крамниці, нейтраль K-COL-06 і C* 15. Запуск із кореня:
python3 -W ignore аудит/перевірка/річ_колір_межі_крок24б/слова.py > …/слова.txt"""
import collections, sys, re
sys.path.insert(0, "джерела")
import колір_річ as П, колір_тон as Т, фід_каталог as ФК
from колір_простір_перетворення import lch
from реєстр_правил import C as РС
кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
гр = [("червоне", r"бордо|бургунд|вишн|черв|марсал|винн|малин|рубін"), ("чорне", r"чорн|графіт"), ("беж/кемел", r"беж|кемел|карамел|айвор|пудр|какао|мокко|молоч|крем|вершк|пісоч"),
      ("коричневе", r"корич|шокол|каштан|кава|теракот|рудий|мідн"), ("олива/хакі", r"олив|хакі|зелен|болот"), ("жовте", r"жовт|гірчи|лимон|золот")]
лік = collections.Counter()
for р in кат:
    if П.межі_кольору(р) is None or П.не_вимір(р) is not None: continue
    lab = tuple(float(x) for x in П.точка_кольору(р)); L, Cc, h = lch(lab)
    до = (L < 30 and Cc < 25 and П._на_дузі_пів(h, max(L - 3, 18), 95)) or (L < 68 and Cc <= 45 and П._на_дузі_пів(h, max(L - 3, 45), 95))
    після = П.буре_сім_я(L, Cc, h)
    if до == після: continue
    сл = (р.get("колір_назва") or "").lower()
    г = next((н for н, рх in гр if re.search(рх, сл)), "інше")
    лік[("→буре" if після else "буре→", г, "нейтраль" if П.нейтраль(lab) else "колір", "C≥15" if Cc >= 15 else "C<15")] += 1
for к, n in sorted(лік.items(), key=lambda x: -x[1]): print(к, n)
