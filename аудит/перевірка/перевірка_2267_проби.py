# -*- coding: utf-8 -*-
"""Проби перевірки #2267 (храповик кореня): власні 10 випадків мірила наряду + обходи. Не стенд виконавця.

Кожен випадок — тимчасовий git-репозиторій (база → голова) і справжній `храповик_кореня.py` окремим процесом.
ЗАПУСК: python3 аудит/перевірка/перевірка_2267_проби.py <шлях храповик_кореня.py голови #2267>
Рядок «OK» — результат, як у таблиці наряду / як мусить бути; «РОЗБІЖНІСТЬ» — обхід чи вада.
"""
import os
import subprocess
import sys
import tempfile

РАТ = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else 'джерела/прилади/храповик_кореня.py'


def гіт(д, *а):
    return subprocess.run(['git', '-C', д, '-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', *а],
                          capture_output=True, text=True, check=True).stdout.strip()


def писати(д, файли):
    for шлях, вміст in файли.items():
        ф = os.path.join(д, шлях)
        if вміст is None:
            os.remove(ф)
            continue
        os.makedirs(os.path.dirname(ф), exist_ok=True)
        open(ф, 'w', encoding='utf-8').write(вміст)


def випадок(назва, база, голова, чекали, храповик=None):
    with tempfile.TemporaryDirectory() as т:
        р = os.path.join(т, 'р')
        os.makedirs(р)
        гіт(р, 'init', '-q', '-b', 'main')
        писати(р, база)
        гіт(р, 'add', '-A')
        гіт(р, 'commit', '-qm', 'б')
        б = гіт(р, 'rev-parse', 'HEAD')
        писати(р, голова)
        гіт(р, 'add', '-A')
        гіт(р, 'commit', '-qm', 'г')
        с = os.path.join(т, 'с.md')
        п = subprocess.run([sys.executable, храповик or РАТ, '--репо', р, '--база', б], capture_output=True, text=True,
                           env=dict(os.environ, GITHUB_STEP_SUMMARY=с))
        є = 'ЧЕРВОНИЙ' if п.returncode == 1 else ('зелений' if п.returncode == 0 else f'код {п.returncode}')
        print(('OK ' if є == чекали else 'РОЗБІЖНІСТЬ ') + f'[{назва}] чекали {чекали}, є {є}')
        for р_ in п.stdout.splitlines():
            if р_.startswith('- '):
                print('      ', р_)


Паспорт = lambda п='джерела/прилади/л.py', е='': f'# К\n\nприлад: {п}\n{е}'
Д = 'джерела/дані.txt'
П = 'джерела/прилади/л.py'
Х = 'джерела/прилади/спільне.py'
прилад = lambda: ("import sys\nprint('шум')\nprint('місць:', sum(1 for l in open('джерела/дані.txt', encoding='utf-8')"
                  " if 'X' in l))\n")
дані = lambda н, т='': ''.join('X\n' for _ in range(н)) + 'ok\n' + т
Б = lambda н=5: {'аудит/корені/Кр.md': Паспорт(), П: прилад(), Д: дані(н)}


def мірило():
    print('--- 10 випадків мірила наряду (власні дані)')
    випадок('1 5→7', Б(), {Д: дані(7)}, 'ЧЕРВОНИЙ')
    випадок('2 5→5', Б(), {Д: дані(5, 'ще\n')}, 'зелений')
    випадок('3 5→3', Б(), {Д: дані(3)}, 'зелений')
    випадок('4 прилад+джерела', Б(), {П: прилад() + '#\n', Д: дані(4)}, 'ЧЕРВОНИЙ')
    випадок('5 лише прилад', Б(), {П: прилад() + '#\n'}, 'зелений')
    б6 = Б()
    б6['аудит/корені/Кр.md'] = Паспорт(е='база: аудит/дані.lst\n')
    б6['аудит/дані.lst'] = 'a\n'
    випадок('6 база+показ', б6, {'аудит/дані.lst': 'a\nb\n', 'показ/к.js': '1\n'}, 'ЧЕРВОНИЙ')
    випадок('7а без «місць:»', Б(), {П: "print('N 5')\n"}, 'ЧЕРВОНИЙ')
    випадок('7б код 3', Б(), {П: прилад() + 'sys.exit(3)\n'}, 'ЧЕРВОНИЙ')
    випадок('8 без «прилад:»', {'аудит/корені/Кр.md': '# К\n\nнема\n', Д: дані(5)}, {Д: дані(9)}, 'зелений')
    б9 = {'аудит/корені/А.md': Паспорт(), 'аудит/корені/Б.md': Паспорт('джерела/прилади/м.py'), П: прилад(),
          'джерела/прилади/м.py': прилад().replace('дані.txt', 'б.txt'), Д: дані(2), 'джерела/б.txt': дані(4)}
    випадок('9 два корені', б9, {'джерела/б.txt': дані(6)}, 'ЧЕРВОНИЙ')
    випадок('10 нема аудит/корені/', {Д: дані(5)}, {Д: дані(9)}, 'зелений')


def обходи():
    print('--- обходи: чекали — ЧЕРВОНИЙ (ріст чи зняття приладу мусить не проходити)')
    приладХ = "import sys,os\nsys.path.insert(0,os.path.dirname(__file__))\nimport спільне\nprint('місць:', спільне.лічи(open('джерела/дані.txt',encoding='utf-8').read()))\n"
    хелпер = lambda п='X': f"def лічи(т):\n    return sum(1 for l in т.splitlines() if '{п}' in l)\n"
    Бх = {'аудит/корені/Кр.md': Паспорт(), П: приладХ, Х: хелпер(), Д: дані(5)}
    випадок('11311 helper ослаблено + 5 нових місць', Бх, {Х: хелпер('Y'), Д: дані(10)}, 'ЧЕРВОНИЙ')
    випадок('рядок «прилад:» знято з паспорта + ріст 5→9', Б(), {'аудит/корені/Кр.md': '# К\n\nнема\n', Д: дані(9)},
            'ЧЕРВОНИЙ')
    випадок('паспорт видалено + ріст 5→9', Б(), {'аудит/корені/Кр.md': None, Д: дані(9)}, 'ЧЕРВОНИЙ')
    суворий = ("import sys\nс = '--строго' in sys.argv\nL = open('джерела/дані.txt', encoding='utf-8').read().splitlines()\n"
               "print('місць:', sum(1 for l in L if l == 'X' or (с and l == 'Y')))\n")
    випадок('аргумент «--строго» знято з паспорта + 3 нові Y',
            {'аудит/корені/Кр.md': Паспорт(П + ' --строго'), П: суворий, Д: 'X\nX\nY\nY\nY\n'},
            {'аудит/корені/Кр.md': Паспорт(), Д: 'X\nX\nY\nY\nY\nY\nY\nY\n'}, 'ЧЕРВОНИЙ')
    # 11312: храповик з допуском +10 % над базою; стенд виконавця його не відрізняє від справжнього.
    з = open(РАТ, encoding='utf-8').read()
    слабкий = з.replace('elif на_голові > на_базі:', 'elif на_голові > на_базі + на_базі // 10:')
    if слабкий == з:
        print('НЕ ВИМІРЯНО: рядок порівняння в коді храповика змінився')
        return
    with tempfile.TemporaryDirectory() as т:
        ф = os.path.join(т, 'храповик_кореня.py')
        open(ф, 'w', encoding='utf-8').write(слабкий)
        стенд = os.path.join(os.path.dirname(РАТ), 'стенд_храповика_кореня.py')
        if os.path.isfile(стенд):
            print('стенд виконавця на ослабленому храповику:',
                  subprocess.run([sys.executable, стенд, '--храповик', ф], capture_output=True, text=True).stdout.splitlines()[-1])
        випадок('11312 храповик з допуском +10 %: ріст 100→109', {'аудит/корені/Кр.md': Паспорт(), П: прилад(), Д: дані(100)},
                {Д: дані(109)}, 'ЧЕРВОНИЙ', храповик=ф)


мірило()
обходи()
