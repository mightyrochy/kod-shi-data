"""Звіряє породжені межі з прямим читанням усіх областей джерела.

Власна перевірка виконавця, не незалежне приймання сімей. Запуск із кореня:
python аудит/перевірка/річ_колір_межі_поверхні.py
"""
import collections
import csv
import importlib.util
import itertools
import json
import math
from pathlib import Path
import unittest


КОРІНЬ = Path(__file__).resolve().parents[2]
ШЛЯХ = КОРІНЬ / "джерела/лабораторія/колір_сім_ї_межі.py"
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("поверхні", ШЛЯХ)
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МОДУЛЬ)


def середина(низ, верх):
    """Бере внутрішню точку також для необмеженого інтервалу джерела."""
    return (низ + верх) / 2 if math.isfinite(верх) else низ + 1


class ПеревіркаПоверхонь(unittest.TestCase):
    """Звіряє покриття меж без використання сітки генератора як еталона."""

    @classmethod
    def setUpClass(клас):
        """Читає джерело без читача генератора й готує прямий пошук за областями."""
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        _, клас.власники = МОДУЛЬ.прочитати_сім_ї(МОДУЛЬ.ТАБЛИЦЯ.read_text(encoding="utf-8"))
        рядки = МОДУЛЬ.КЛІТИНКИ.read_text(encoding="utf-8").splitlines()
        клас.клітинки = [
            (int(рядок["Number"]),
             tuple((float(рядок[вісь + "min"]), float(рядок[вісь + "max"])) for вісь in "HVC"))
            for рядок in csv.DictReader(
                (рядок for рядок in рядки if рядок and not рядок.startswith("#")), delimiter="\t")]
        клас.осі = [sorted({край for _, межі in клас.клітинки for край in межі[вісь]})
                    for вісь in range(3)]
        клас.аркуші = collections.defaultdict(list)
        for номер, межі in клас.клітинки:
            клас.аркуші[межі[0]].append((номер, межі))

    def прямий_пошук(self, точка):
        """Шукає родину у вихідних клітинках, зокрема на останньому аркуші циклу."""
        H, V, C = точка
        if not 0 < V < 10 or C < 0:
            return None
        знайдені = []
        for (низ, верх), клітинки in self.аркуші.items():
            if низ < H < верх:
                знайдені = [self.власники[номер] for номер, межі in клітинки
                            if межі[1][0] < V < межі[1][1] and межі[2][0] < C < межі[2][1]]
                break
        self.assertEqual(len(знайдені), 1, точка)
        return знайдені[0]

    def test_усі_межі_джерела(self):
        """Перевіряє всі площини й кожну ділянку повного спільного розбиття."""
        групи = collections.defaultdict(list)
        for грань in self.вихід["межі"]:
            self.assertNotEqual(*грань["сім_ї"])
            self.assertTrue(any(грань["сім_ї"]))
            інтервали = [[math.inf if край == "+inf" else край for край in межі]
                         for межі in грань["інтервали"]]
            групи[грань["вісь"], грань["координата"]].append((грань["сім_ї"], інтервали))
        перевірено = 0
        використано = set()
        for вісь, координати in enumerate(self.осі):
            інші = [номер for номер in range(3) if номер != вісь]
            діапазони = [list(zip(self.осі[номер], self.осі[номер][1:])) for номер in інші]
            for індекс, координата in enumerate(координати):
                if вісь == 0 and індекс == len(координати) - 1:
                    continue  # H=101 — той самий стик, що H=1.
                if not math.isfinite(координата):
                    continue  # Нескінченність не є площиною.
                for ділянка in itertools.product(*діапазони):
                    точка = [None] * 3
                    for номер, межі in zip(інші, ділянка):
                        точка[номер] = середина(*межі)
                    боки = []
                    for зсув in (-1, 0):
                        край = індекс + зсув
                        if вісь == 0:
                            край %= len(координати) - 1
                        if 0 <= край < len(координати) - 1:
                            точка[вісь] = середина(координати[край], координати[край + 1])
                            боки.append(self.прямий_пошук(точка))
                        else:
                            боки.append(None)
                    очікується = [боки] if боки[0] != боки[1] else []
                    знайдено = []
                    for номер, (сім_ї, межі) in enumerate(групи["HVC"[вісь], координата]):
                        if all(низ < точка[інша] < верх for інша, (низ, верх) in zip(інші, межі)):
                            знайдено.append(сім_ї)
                            використано.add((вісь, координата, номер))
                    self.assertEqual(знайдено, очікується, (вісь, координата, ділянка))
                    перевірено += 1
        self.assertEqual(len(використано), len(self.вихід["межі"]))
        print(f"Ділянок площин звірено з джерелом: {перевірено}; "
              f"граней охоплено: {len(використано)}; розбіжностей: 0")

    def test_артефакт_відтворюється(self):
        """Перевіряє походження та повний детермінований вихід методу."""
        self.assertEqual(self.вихід, МОДУЛЬ.породити())
        self.assertEqual((len(self.вихід["сім_ї"]), self.вихід["блоків"], self.вихід["клітинок"]),
                         (12, 267, 932))

    def test_приклад_рожеве_червоне(self):
        """Зберігає залежність сім'ї від хроми за фіксованих тону й світлоти."""
        self.assertEqual([self.прямий_пошук((2, 6, C)) for C in (4, 6, 10, 16)],
                         ["red", "pink", "pink", "red"])

    def test_внутрішні_стики_й_нескінченність(self):
        """Не залишає фальшиву межу між клітинками однієї сім'ї та стелю C."""
        клітинки = [(1, ((1, 51), (0, 10), (0, math.inf))),
                     (2, ((51, 101), (0, 10), (0, math.inf)))]
        осі, сітка = МОДУЛЬ.розбити_простір(клітинки, {1: "red", 2: "red"})
        межі = МОДУЛЬ.побудувати_межі(осі, сітка)
        self.assertEqual(len(межі), 3)  # Лише V=0, V=10 і C=0.
        self.assertFalse(any(грань["вісь"] == "H" for грань in межі))
        self.assertTrue(any(math.inf in інтервал for грань in межі for інтервал in грань["інтервали"]))

    def test_циклічний_стик(self):
        """Орієнтує обидва стики двох різних сімей без дубля H=101."""
        клітинки = [(1, ((1, 51), (0, 10), (0, math.inf))),
                     (2, ((51, 101), (0, 10), (0, math.inf)))]
        осі, сітка = МОДУЛЬ.розбити_простір(клітинки, {1: "red", 2: "green"})
        межі = [грань for грань in МОДУЛЬ.побудувати_межі(осі, сітка) if грань["вісь"] == "H"]
        self.assertEqual([(грань["координата"], грань["сім_ї"]) for грань in межі],
                         [(1, ["green", "red"]), (51, ["red", "green"])])

    def test_увігнуті_області(self):
        """Не заповнює відсутню частину L-подібної поверхні при об'єднанні."""
        ділянки = {(0, 0), (1, 0), (0, 1)}
        прямокутники = list(МОДУЛЬ.об_єднати_прямокутники(ділянки))
        відновлено = [пара for ((низ, верх), (ліво, право)) in прямокутники
                      for пара in itertools.product(range(низ, верх), range(ліво, право))]
        self.assertEqual(set(відновлено), ділянки)
        self.assertEqual(len(відновлено), len(ділянки))

    def test_неповне_й_перекрите_джерело(self):
        """Відмовляє і при прогалині всередині повної області, і при перекритті."""
        початок = (1, ((1, 51), (0, 10), (0, math.inf)))
        кінець = (2, ((61, 101), (0, 10), (0, math.inf)))
        with self.assertRaisesRegex(ValueError, "Прогалина"):
            МОДУЛЬ.розбити_простір([початок, кінець], {1: "red", 2: "green"})
        кінець = (2, ((41, 101), (0, 10), (0, math.inf)))
        with self.assertRaisesRegex(ValueError, "Перекриття"):
            МОДУЛЬ.розбити_простір([початок, кінець], {1: "red", 2: "green"})

    def test_неузгоджена_таблиця(self):
        """Не дозволяє тихо пропустити блок або призначити його двом сім'ям."""
        with self.assertRaisesRegex(ValueError, "Повтор номера"):
            МОДУЛЬ.прочитати_сім_ї("| `red` | червона | 1–2 |\n| `pink` | рожева | 2 |")
        with self.assertRaisesRegex(ValueError, "не збігаються"):
            МОДУЛЬ.розбити_простір(self.клітинки, {1: "red"})


if __name__ == "__main__":
    unittest.main()
