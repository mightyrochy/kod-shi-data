"""Порівнює прилад бази й голови на формах З1–З3 та на всьому дереві без зміни продукту."""
import os
from pathlib import Path
import subprocess
import tempfile
import types
import sys

КОРІНЬ = Path(__file__).resolve().parents[2]
ПРИЛАД = 'джерела/прилади/корінь_річ_колір_межі.py'
БАЗА = '1c24f5ab02861314deb0e1088e26ec7fe5e3e60c'


def завантажити(старий=False):
    """Завантажує прилад із зафіксованого main або поточного дерева."""
    модуль = types.ModuleType('прилад')
    модуль.__file__ = str(КОРІНЬ / ПРИЛАД)
    код = subprocess.check_output(['git', 'show', f'{БАЗА}:{ПРИЛАД}'], cwd=КОРІНЬ).decode('utf-8') if старий \
        else (КОРІНЬ / ПРИЛАД).read_text(encoding='utf-8')
    exec(compile(код, модуль.__file__, 'exec'), модуль.__dict__)
    return модуль


def зібрати(м, дерево):
    """Збирає місця обома шляхами без друку кожного рядка."""
    збір = м.Збір()
    імена, тепло = м.імена_визначень(дерево), м.тепла_кутом(дерево)
    for шлях, файл, вид in м.файли(дерево):
        if вид == 'py':
            м.обхід_python(шлях, файл, збір, імена, тепло)
        else:
            м.обхід_js(шлях, файл, збір)
    return збір.м


def підсумок(місця):
    """Повертає кількість місць і числа за чотирма пунктами класу."""
    return [len(місця)] + [sum(п in з['пункти'] for з in місця.values()) for п in (1, 2, 3, 4)]


def головна():
    """Друкує ДО→ПІСЛЯ, перевіряє позитивні й негативні приклади та повторюваність."""
    до, після = завантажити(True), завантажити()
    приклади = {
        'З1-підтон': ('py', '''def підтон_риси(a, b, h):
    """Словесний підтон риси з Lab."""
    return ("рожевий/холодний" if h < 35 else
            "жовтий/теплий" if h < 70 else "нейтральний")
''', {1, 2}),
        'З1-передавання': ('py', '''def оцінити(дані, width):
    точка = дані["hue"]
    інша = точка
    return інша < 70
''', {1, 2}),
        'З1-LCh': ('py', '''def оцінити(дані):
    x, y, z = to_lch(дані)
    return z < 70
''', {1, 2}),
        'З2-межі': ('py', 'МЕЖІ: dict = {"hue": (20, 60)}\n', {1}),
        'З2-вікна': ('py', '''ВІКНА: dict[str, tuple] = {
    "red": (20, 70, 10, 80, 0, 40),
    "green": (20, 70, 10, 80, 100, 160),
    "blue": (20, 70, 10, 80, 220, 280),
}
''', {4}),
        'З3-LCh': ('js', '''function convert(L, C, h) {
    const angle = h * Math.PI / 180;
    const a = C * Math.cos(angle);
    const b = Math.sin(angle) * C;
    return [L, a, b];
}
''', {1}),
        'З3-RGB': ('js', '''function family(r, g, b) {
    return r > g && r > b ? 'red' : 'other';
}
''', {2}),
        'З3-RGB-масив': ('js', '''function classify(rgb) {
    return rgb[0] > rgb[1] ? 'red' : 'other';
}
''', {2}),
        'не-колір': ('py', '''def площа(width, h):
    return h < 70
''', set()),
        'не-таблиця': ('py', 'РОЗМІРИ: dict = {"width": (20, 60)}\n', set()),
        'не-сектор-зображення': ('py', '''def обробити(w, h):
    """Працює з Lab кольором зображення."""
    return min(w, h) // 40
''', set()),
        'не-JS': ('js', '''// r > g; C * Math.cos(angle); C * Math.sin(angle)
const text = "r > b";
function rotate(x) { return Math.cos(x); }
''', set()),
    }
    with tempfile.TemporaryDirectory(prefix='межі-', dir=os.environ['TEMP']) as тека:
        for назва, (вид, код, очікувані) in приклади.items():
            шлях = Path(тека) / f'нейтральний.{вид}'
            шлях.write_text(код, encoding='utf-8')
            числа = []
            for м in (до, після):
                збір = м.Збір()
                if вид == 'py':
                    м.обхід_python(шлях, str(шлях), збір, set(), set())
                else:
                    м.обхід_js(шлях, str(шлях), збір)
                числа.append(підсумок(збір.м))
            отримані = {п for п in (1, 2, 3, 4) if числа[1][п]}
            assert отримані == очікувані, (назва, отримані, очікувані)
            print(f'{назва}: {числа[0]} → {числа[1]}')
    if '--лише-проби' in sys.argv:
        return
    а, б = зібрати(до, КОРІНЬ), зібрати(після, КОРІНЬ)
    assert б == зібрати(після, КОРІНЬ), 'Число чи склад не відтворюється'
    print(f'Повне дерево [місць, п1, п2, п3, п4]: {підсумок(а)} → {підсумок(б)}; повтор тотожний')
    for знак, ключі in (('+', б.keys() - а.keys()), ('−', а.keys() - б.keys())):
        for файл, рядок in sorted(ключі):
            текст = (КОРІНЬ / файл).read_text(encoding='utf-8').splitlines()[рядок - 1].strip()
            print(f'{знак} {файл}:{рядок}: {текст[:180]}')


def вибірка():
    """Друкує відтворювану вибірку місць і коротких файлів без місць для читання людиною."""
    м = завантажити()
    місця = зібрати(м, КОРІНЬ)
    print(f'Повне дерево [місць, п1, п2, п3, п4]: {підсумок(місця)}')
    ключі = sorted(місця)
    print('20 місць:')
    for i in range(20):
        файл, рядок = ключі[i * (len(ключі) - 1) // 19]
        текст = (КОРІНЬ / файл).read_text(encoding='utf-8').splitlines()[рядок - 1]
        print(f'{файл}:{рядок} · {місця[файл, рядок]["пункти"]} · {текст.strip()}')
    з_місцями = {ф for ф, _ in місця}
    без = []
    for шлях, файл, _ in м.файли(КОРІНЬ):
        текст = Path(шлях).read_text(encoding='utf-8')
        if файл not in з_місцями and 15 <= len(текст.splitlines()) <= 300:
            без.append((файл, текст))
    без.sort(key=lambda пара: (len(пара[1].splitlines()), пара[0]))
    assert len(без) >= 20, 'Потрібно двадцять різних файлів'
    print('20 файлів без місць (повний текст для огляду):')
    for i in range(20):
        файл, текст = без[i]
        print(f'ФАЙЛ {файл}\n{текст}')


if __name__ == '__main__':
    вибірка() if '--вибірка' in sys.argv else головна()
