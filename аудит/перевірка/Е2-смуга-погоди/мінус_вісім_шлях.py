import os, sys, json, glob
ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ТУТ, "..", "..", ".."))
ЗАПИС = glob.glob(os.path.join(ТУТ, "..", "..", "проби", "нічні", "20261107", "ж7_мінус_вісім_пішки", "VIDPOVIDI",
                               "seed3_01_*.txt"))[0]
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела")); os.chdir(os.path.join(КОРІНЬ, "джерела"))
import мовний_шар as м
СЛОВА = "мінус вісім, до офісу пішки"
СИРА = open(ЗАПИС, encoding="utf8").read().split("── ВІДПОВІДЬ")[1].split("──\n", 1)[1]


def хід(відповідь):
    р = м.прийняти_розмову(відповідь)
    return м.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=[СЛОВА], частини=р["частини"], не_взято=р.get("не_взято"))


for назва, відп in (("запис", СИРА), ("контрфакт: смуга з quote", СИРА.replace(
        '"weather_band": "frost"', '"weather_band": {"quote": "мінус вісім", "value": "frost"}'))):
    в = хід(відп)
    print("%s · паспорт смуга_погоди=%s · recorded=%s" % (назва, в["паспорт"].get("смуга_погоди"),
                                                         json.dumps(в["записано"], ensure_ascii=False)))
    print("   вигадки смуги: %s" % [x for x in в["вигадки"] if "weather_band" in x])
    print("   текст ходу: %r · знято: %s" % (в["текст"], [(x.get("чому"), x.get("числа")) for x in в["відкинуто"]]))
    for т in ("Так, до офісу пішки, на роботу, а надворі мороз.", "Так, до офісу пішки, на роботу."):
        т2, відк = м.суд_репліки(т, {"recorded": в["записано"]})
        print("   репліка %r → %s" % (т, "показано" if т2 else "знято: %s" % [(x.get("чому"), x.get("слова"))
                                                                         for x in відк]))
