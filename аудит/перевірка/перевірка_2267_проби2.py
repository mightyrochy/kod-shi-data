РАТ = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else 'джерела/прилади/храповик_кореня.py'


def гіт(д, *а):
    return subprocess.run(['git', '-C', д, '-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', *а],
                          capture_output=True, text=True, check=True).stdout.strip()


def писати(д, файли):
    for шлях, вміст in файли.items():
        ф = os.path.join(д, шлях)
        if вміст is None:
            os.remove(ф)
            continue
        os.makedirs(os.path.dirname(ф), exist_ok=True)
        open(ф, 'w', encoding='utf-8').write(вміст)


def випадок(назва, база, голова, чекали):
    with tempfile.TemporaryDirectory() as т:
        р = os.path.join(т, 'р')
        os.makedirs(р)
        гіт(р, 'init', '-q', '-b', 'main')
        писати(р, база)
        гіт(р, 'add', '-A')
        гіт(р, 'commit', '-qm', 'б')
        б = гіт(р, 'rev-parse', 'HEAD')
        писати(р, голова)
        гіт(р, 'add', '-A')
        гіт(р, 'commit', '-qm', 'г')
        п = subprocess.run([sys.executable, РАТ, '--репо', р, '--база', б], capture_output=True, text=True,
                           env=dict(os.environ, GITHUB_STEP_SUMMARY=os.path.join(т, 'с.md')))
        є = 'ЧЕРВОНИЙ' if п.returncode == 1 else ('зелений' if п.returncode == 0 else f'код {п.returncode}')
        print(('OK ' if є == чекали else 'РОЗБІЖНІСТЬ ') + f'[{назва}] чекали {чекали}, є {є}')


