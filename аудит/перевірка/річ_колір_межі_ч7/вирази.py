"""Ч7: старий вираз кожного місця проти його заміни з `колір_тон` / `колір_простір_перетворення` — поштучно.

Запуск з `джерела/`: python3 ../аудит/перевірка/річ_колір_межі_ч7/вирази.py
Вхід: 10⁶ випадкових кутів і дуг (кінці — в [0, 360), як їх дають `межі_кольору`, `запис_кольору` і `дуга_кола`;
на каталозі поза [0, 360) — 0 з 19 086 дуг) плюс край: цілі й півградуси, −ε, 360 − ulp, точка (x, x).
Друкує для кожної пари кількість розбіжностей і найбільшу різницю.
"""
import math, os, random, sys
sys.path.insert(0, os.getcwd())
import колір_тон as КТ
from колір_простір_перетворення import lab_з_lch

г = random.Random(11)
N = 1_000_000
кути = [г.uniform(0.0, 360.0) for _ in range(N)]
кути += [k / 2.0 for k in range(720)] + [0.0, 359.99999999999994, 180.0, 1e-300]
дуги = [(г.uniform(0.0, 360.0), г.uniform(0.0, 360.0)) for _ in range(N)]
дуги += [(a / 2.0, b / 2.0) for a in range(0, 720, 7) for b in range(0, 720, 5)]
дуги += [(x, x) for x in (0.0, 10.0, 359.5)] + [(359.99999999999994, 0.0), (0.0, 359.99999999999994)]
сирі = [г.uniform(-720.0, 720.0) for _ in range(N)] + [-1e-15, -1e-300, -360.0, 720.0, -0.0]


def звірити(назва, пари):
    n = розб = 0; макс = 0.0
    for старе, нове in пари:
        n += 1
        if старе != нове:
            розб += 1
            if isinstance(старе, float):
                макс = max(макс, abs(старе - нове))
    print("%-58s %9d  розбіжних %d%s" % (назва, n, розб, ("  найбільша %.3g" % макс) if розб else ""))
    return розб


def ш_старе(д):
    return (д[1] - д[0]) % 360.0


def сер_brief(д):   # brief._дуга_середина на main
    a, b = float(д[0]) % 360, float(д[1]) % 360
    if b < a:
        b += 360.0
    return ((a + b) / 2.0) % 360.0


def сер_ширина(д):   # coordination._хрома_ok_межі і measure_person_axis.центр_вікна на main
    return (д[0] + ((д[1] - д[0]) % 360.0) / 2.0) % 360.0


def тони_старі(д):   # колір_річ.тони_дуги на main (без кінців інших дуг)
    ш = (д[1] - д[0]) % 360.0
    return [(д[0] + min(k, ш)) % 360.0 for k in range(int(ш) + 2)]


print("`% 360` → нормувати: різниться лише там, де x % 360 == 360.0 (x — від'ємне −ε)")
звірити("x % 360 ↔ нормувати(x), сирі кути", ((x % 360.0, КТ.нормувати(x)) for x in сирі))
print("   де саме:", [x for x in сирі if x % 360.0 != КТ.нормувати(x)])
звірити("(д1 − д0) % 360 ↔ ширина_дуги(д)", ((ш_старе(д), КТ.ширина_дуги(д)) for д in дуги))
звірити("(к − к0) % 360 ↔ зсув_за_ходом(к0, к)", (((b - a) % 360.0, КТ.зсув_за_ходом(a, b)) for a, b in дуги))
звірити("coordination/measure: середина ↔ середина_дуги", ((сер_ширина(д), КТ.середина_дуги(д)) for д in дуги))
р = звірити("brief._дуга_середина ↔ середина_дуги", ((сер_brief(д), КТ.середина_дуги(д)) for д in дуги))
звірити("колір_річ.тони_дуги ↔ тони_дуги + точка_дуги(·, 1)",
        ((тони_старі(д), КТ.тони_дуги(д) + [КТ.точка_дуги(д, 1.0)]) for д in дуги[:200000] + дуги[N:]))
звірити("coordination: min(|Δ|, 360 − |Δ|) ↔ відстань_тонів",
        ((min(abs(a - b), 360 - abs(a - b)), КТ.відстань_тонів(a, b)) for a, b in дуги))
звірити("колір_річ._сектори: ш > 360 − 30 ↔ ш + 30 > 360",
        ((ш_старе(д) > 330.0, КТ.ширина_дуги(д) + 30.0 > 360.0) for д in дуги))
звірити("cos/sin кута тону ↔ lab_з_lch",
        (((50.0, c * math.cos(math.radians(h)), c * math.sin(math.radians(h))), lab_з_lch(50.0, c, h))
         for c, h in zip((г.uniform(0, 130) for _ in кути), кути)))
звірити("measure._lab ↔ lab_з_lch",
        (((50.0, c * math.cos(math.radians(h)), c * math.sin(math.radians(h))), lab_з_lch(50.0, c, h))
         for c, h in ((г.uniform(0, 130), x) for x in кути[:200000])))
print("повне коло (0, 360) — поза доменом (кінці дуг вікон і схем — у [0, 360)): старі середини",
      сер_brief((0.0, 360.0)), сер_ширина((0.0, 360.0)), "↔ середина_дуги", КТ.середина_дуги((0.0, 360.0)))

# brief: розбіжність середини — у кількох останніх бітах; чи доходить вона до зразка слота (`колір_слота` → hex)?
import types
