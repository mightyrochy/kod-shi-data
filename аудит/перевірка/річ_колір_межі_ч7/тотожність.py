def канон(v):
    """Канонічний `repr`: множини — відсортовані, словники — за ключем, числа — точні."""
    if isinstance(v, dict):
        return "{" + ",".join("%s:%s" % (канон(k), канон(v[k])) for k in sorted(v, key=repr)) + "}"
    if isinstance(v, (set, frozenset)):
        return "set[" + ",".join(sorted(канон(x) for x in v)) + "]"
    if isinstance(v, (list, tuple)):
        return ("[%s]" if isinstance(v, list) else "(%s)") % ",".join(канон(x) for x in v)
    return repr(v)


def sha(рядок):
    return hashlib.sha256(рядок.encode("utf-8")).hexdigest()


