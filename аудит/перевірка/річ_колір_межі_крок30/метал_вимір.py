"""Крок 30 (14355) — знімок металу прикрас на каталозі: для кожного запису ювелірного слота (`palettes.слот_металу`)
код матеріалу (`метал`), вхід A14 (`частка_металу`, тон кадру), колір поза металом (`колір_вставки`), спір складу з
кольором (`метал_спір`), `palettes.метал_меж`, `колір_металу`, `колір_невідомий`, `несе_колір`, `нейтраль_невідома`;
рядки металу пулу `рядки_у_фід` на 300 людях (сід 26, як крок 29). Однаковий для всіх дерев (публічні імена).
Запуск із кореня дерева (розпакований `джерела/каталог_повний.xml`): python3 -W ignore <шлях> > знімок.json"""
import json, random, sys, time
sys.path.insert(0, "джерела")
import palettes as П, фід_каталог as ФК, colorspace as cs  # noqa: E402
т0 = time.time()
кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
записи = {}
for і, р in enumerate(кат):
    if not П.слот_металу(р.get("слот"), р.get("тип")):
        continue
    вст = р.get("колір_вставки")
    з = dict(слот=р.get("слот"), тип=р.get("тип"), метал=р.get("метал"), колір=str(р.get("колір_назва") or ""),
             частка=р.get("частка_металу"), тон_кадру=р.get("частка_металу_тон_кадру"),
             вставки=None if вст is None else len(вст), хром_вставка=bool(П.хроматична_вставка(р)),
             спір=bool(р.get("метал_спір")), меж=(П.метал_меж(р, р.get("слот"), р.get("тип")) if hasattr(П, "метал_меж") else None),
             тон_речі=(П.метал_речі(р) if not hasattr(П, "метал_меж") else None),
             колір_металу=bool(П.колір_металу(р)), невідомий=bool(П.колір_невідомий(р)), несе=П.несе_колір(р),
             нейтраль_невідома=bool(П.нейтраль_невідома(р)))
    записи[f"{і}:{р.get('id')}"] = з
rnd = random.Random(26)
шк = ["#f3d9c6", "#e8c1a0", "#d9a77f", "#c08a63", "#9a6646", "#6e4630", "#f1d3c2", "#e2b597", "#b9805b", "#5a3825"]
вол = ["#2a1f1a", "#4b3428", "#6d4c35", "#a07850", "#d2b48c", "#e6cf9a", "#8a3b1f", "#b5562b", "#9a9a9a", "#0f0f10"]
очі = ["#4a2f1f", "#6b4a2b", "#7fa6c8", "#3d6e9e", "#5f8a5a", "#7b8b6a", "#8a9aa8", "#2e2a28", "#6a7f9a", "#9b8a5a"]
палітри = []
for _ in range(300):
    F = cs.features(cs.hx(rnd.choice(шк)), cs.hx(rnd.choice(вол)), cs.hx(rnd.choice(очі)))
    пал = П.палітра_практична(F)
    палітри.append(dict(метал=пал.get("метал")))
json.dump(dict(записів=len(кат), записи=записи, палітри=палітри, секунд=round(time.time() - т0)),
          sys.stdout, ensure_ascii=False)
