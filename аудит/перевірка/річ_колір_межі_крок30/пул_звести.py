"""Зведення знімка пулу прикрас (`пул_металу.py`): на прогін — рядки металу на слот, речі за роллю рядка й кодом металу,
і перші п'ять кандидатів кожного ювелірного слота за тоном коду матеріалу (тепле → золото, холодне → срібло, без коду —
«нема»). Запуск: python3 пул_звести.py знімок.json [знімок.json …]"""
import json, sys, collections as C
ТЕПЛІ = {"золото", "бронза", "латунь", "мідь"}
ХОЛОДНІ = {"срібло", "біле_золото", "платина", "сталь"}
тон = lambda м: "золото" if м in ТЕПЛІ else "срібло" if м in ХОЛОДНІ else "міст" if м else "нема"
for ф in sys.argv[1:]:
    d = json.load(open(ф, encoding="utf-8")); print("==", ф)
    for к, в in d.items():
        к2 = в["композитор"]
        рядки = C.Counter(р for x in к2.values() for р in x["рядки"])
        роль = C.Counter(str(р["роль"]).split(":")[0] for x in к2.values() for р in x["речі"])
        мет = C.Counter(тон(р["метал"]) for x in к2.values() for р in x["речі"])
        вх_мет = sum(1 for x in к2.values() for р in x["речі"] if str(р["роль"]).startswith("метал_палітри"))
        топ5 = C.Counter(тон(р["метал"]) for x in к2.values() for р in x["речі"][:5])
        print(f" {к}: пул {в['пул']}; рядків металу {sum(рядки.values())}; речей {sum(роль.values())}; "
              f"за роллю {dict(роль)}; за тоном коду {dict(мет)}; увійшли рядком металу {вх_мет}; "
              f"перші 5 на слот ({len(к2)} слотів) {dict(топ5)}")
