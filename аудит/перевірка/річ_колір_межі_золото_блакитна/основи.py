"""Основи з сім'єю «нейтраль», чий колір нейтраллю не є (15941). Нейтраль — одне визначення, `колір_річ.нейтраль`
(сім'ї `колір_тон`). Для кожної жінки записів нічного прогону (`повтор.json` усіх сцен теки, без повторів жінки)
збирає справжній пакет палітри (`міст_основи.пакет` тим шляхом, що й `вибір_палітри.перелік`) і лічить по всіх
клітинках ґратки в рядах «нейтралі», «кольори», «інші»: сім'я «нейтраль» при `колір_річ.нейтраль(hex)` = None
(«нейтраль, а колір») і навпаки. Для сцени `ж3_театр_блакитні_нейтралі` — ще основи, що йдуть стилістці дротом
(`вибір_палітри.перелік` → `_основа_дротом`, `family` = neutral). Працює й на дереві до правки.
Запуск із кореня дерева: python3 -W ignore <шлях>/основи.py <тека прогону>"""
import glob, json, os, sys
sys.path.insert(0, os.path.abspath("джерела"))
os.chdir("джерела")
import вибір_палітри as ВП, colorspace as cs, колір_річ as КР  # noqa: E402
тека = os.path.abspath(os.path.join("..", sys.argv[1])) if not os.path.isabs(sys.argv[1]) else sys.argv[1]
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
вх0.pop("каталог", None)


def вхід(ж, сцена=None):
    в = dict(вх0, шкіра=ж["skin"][0], волосся=ж["hair"], очі=ж["eyes"])
    if сцена:
        в.update(сценарій={"нагода": "театр", "пора": "вечір"}, випадок="сьогодні театр, вечірня вистава")
    return в


def нейтраль(hx):
    return КР.нейтраль(cs.hx(hx)) is not None


жінки = {}
for п in sorted(glob.glob(os.path.join(тека, "*", "повтор.json"))):
    ж = json.load(open(п, encoding="utf-8")).get("жінка")
    if ж:
        жінки.setdefault(json.dumps([ж["skin"], ж["hair"], ж["eyes"]], sort_keys=True), (os.path.basename(os.path.dirname(п)), ж))
разом = dict(клітинок=0, нейтраль_а_колір=0, колір_а_нейтраль=0)
for _, (сц, ж) in sorted(жінки.items(), key=lambda x: x[1][0]):
    d, _її = ВП._її(вхід(ж))
    F, T, зріст, kw = ВП._МВ.збірка(d, лише_палітра=True)
    п = ВП._МО.пакет(F, T, зріст, kw, ВП._МВ.якір(d), d.get("намір") or ВП.ТИПОВИЙ_НАМІР, ВП._МВ.самозвіт(d),
                     d.get("вибір_кольору"), d.get("драп"), явні=ВП._П.ПОЗА_ЩОДЕННИМ)
    ок = п.get("основи_кольорів") or {}
    ряд = [о for к in ("нейтралі", "кольори", "інші") for о in (ок.get(к) or [])]
    нк = [о for о in ряд if о.get("сім_я") == "нейтраль" and not нейтраль(о["hex"])]
    кн = [о for о in ряд if о.get("сім_я") != "нейтраль" and нейтраль(о["hex"])]
    разом["клітинок"] += len(ряд); разом["нейтраль_а_колір"] += len(нк); разом["колір_а_нейтраль"] += len(кн)
    print("%-32s клітинок %3d · нейтраль, а колір %2d · колір, а нейтраль %d%s" % (
        сц, len(ряд), len(нк), len(кн),
        (" · напр. " + ", ".join("%s C*=%.1f" % (о["hex"], cs.lch(cs.hx(о["hex"]))[1]) for о in нк[:3])) if нк else ""))
print("УСІ ЖІНКИ (%d): клітинок %d · нейтраль, а колір %d · колір, а нейтраль %d" % (
    len(жінки), разом["клітинок"], разом["нейтраль_а_колір"], разом["колір_а_нейтраль"]))
ж3 = json.load(open(os.path.join(тека, "ж3_театр_блакитні_нейтралі", "повтор.json"), encoding="utf-8"))["жінка"]
п = ВП.перелік(вхід(ж3, сцена=True))
осн = п.get("основи") or []
дріт = [(о, ВП._основа_дротом(о)) for о in осн]
нк = [(о, д) for о, д in дріт if д["family"] == "neutral" and not нейтраль(о["hex"])]
print("СЦЕНА ж3_театр_блакитні_нейтралі: основ дротом %d · family neutral %d · з них колір (не нейтраль) %d%s" % (
    len(осн), sum(д["family"] == "neutral" for _, д in дріт), len(нк),
    (": " + ", ".join("%s %s C*=%.1f" % (д["id"], о["hex"], cs.lch(cs.hx(о["hex"]))[1]) for о, д in нк)) if нк else ""))
for о, д in дріт:
    if о["hex"].lower() in ("#ccd8eb",):
        print("  #ccd8eb:", д["id"], д["colour"], "family", д["family"])
