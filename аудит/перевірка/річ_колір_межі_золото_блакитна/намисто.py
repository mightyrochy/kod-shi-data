"""15940 — золоте намисто в пулі руки 1 сцени `ж1_213_золоте_намисто` (нічний Е1 16.11). Записана відповідь моделі
розмови (обмін `00001.json`) читається тим самим шаром, що наживо (`мовний_шар.прийняти_вхід("scenario")` →
`паспорт_з_шару`), паспорт іде в `запити` на `стенд_вх.json` (жінка ж1, `каталог_повний.xml`). Друкує поле прикрас
паспорта, рядки «не взято» шару й порядок пулу кожного ювелірного слота: id, код металу, колір крамниці; позиція
першої речі з кодом «золото» в слоті «намисто» і в пулі пакета моделі (типи `necklace`). Другий прогін — та сама сцена
без її слова про прикраси (поле знято з відповіді): порядок мусить бути той самий, що доти. Однаковий для всіх дерев.
Запуск із кореня дерева: python3 -W ignore <шлях> <тека сцени> > вивід.txt"""
import json, os, sys, tempfile
ТЕКА = os.path.abspath(sys.argv[1])
_д = os.path.abspath("джерела"); sys.path.insert(0, _д); os.chdir(_д)
import bridge as B, feed as Ф, мовний_шар as М  # noqa: E402
import композитор_збирання as КЗ, композитор_слоти as КС  # noqa: E402
_ЗЛОВ, _орк = {}, КС.кандидати_на_слот
def _обгортка(речі, вікна, слот, *а, **к):
    в = _орк(речі, вікна, слот, *а, **к)
    if слот in ("намисто", "кольє", "прикраси", "сережки", "браслет", "каблучка", "брошка"):
        _ЗЛОВ[слот] = [(r.get("id"), r.get("метал"), r.get("колір")) for r in в[0]]
    return в
КЗ._кандидати_на_слот = _обгортка
об = json.load(open(os.path.join(ТЕКА, "VIDPOVIDI", "обмін", "00001.json"), encoding="utf-8"))
т = json.loads(об["відповідь"]["body"])["content"][0]["text"]
оновлення = json.loads(т[т.index("{"):т.rindex("}") + 1])["update"]
слова = json.load(open(os.path.join(ТЕКА, "повтор.json"), encoding="utf-8"))["змінні"]["CHAT_TEXT"]
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
вх0["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх0["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_15940.json")
if not os.path.exists(вх0["кеш_кольорів"]): json.dump({}, open(вх0["кеш_кольорів"], "w"))
for назва, онов in (("сцена", оновлення),
                    ("без слова про прикраси", dict(оновлення, wants=[{к: x for к, x in р.items() if к != "jewelry"}
                                                                      for р in оновлення.get("wants") or []]))):
    р = М.прийняти_вхід("scenario", json.dumps(онов, ensure_ascii=False))
    п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=[слова], не_взято=р.get("не_взято"),
                         не_записано_ходу=р.get("не_записано"))["паспорт"]
    print("==", назва, "· прикраси паспорта:", п.get("прикраси"), "· перенесено:", р.get("перенесено"),
          "· не взято:", [x.split(" · model_said")[0] for x in р.get("не_взято") or []])
    _ЗЛОВ.clear()
    з = json.loads(B.виклик("запити", json.dumps(dict(вх0, паспорт=п, пакети=1), ensure_ascii=False)))
    for слот, речі in sorted(_ЗЛОВ.items()):
        перше = next((і + 1 for і, (_, м, _к) in enumerate(речі) if м == "золото"), None)
        print(" слот %s: речей %d · перше золото %s · перші 5: %s" % (слот, len(речі), перше,
              "; ".join("%s %s/%s" % x for x in речі[:5])))
    рука = json.loads(з["B"])
    кол = рука["pool"]["cols"]
    нам = [dict(zip(кол, р)) for р in рука["pool"]["rows"] if dict(zip(кол, р)).get("type") == "necklace"]
    перше = lambda к: next((і + 1 for і, р in enumerate(нам) if р.get("color") == к), None)
    print(" пул руки 1 (B), намиста %d: перше golden %s, перше silvery %s · кольори перших 10: %s" % (
          len(нам), перше("golden"), перше("silvery"), ", ".join(str(р.get("color")) for р in нам[:10])))
