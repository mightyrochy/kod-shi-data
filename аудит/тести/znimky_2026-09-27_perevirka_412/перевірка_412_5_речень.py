"""Перевірка #412: 5 НОВИХ речень (яких нема в пробах PR), перевірка вручну сесією-перевірником.
Про помітність, стриманість, комфорт, «щоб мама схвалила», «хочу виглядати вищою».
Ті самі функції шляху, що в проби/шлях_шар_суть.py, але вручну звірено ОЧИМА (не лише лічба слів):
суть бажання, не лише слова, має дійти до рядка випадку (руки 1, 3-4)."""
import sys, os, re, json
sys.path.insert(0, os.getcwd())
import мовний_шар as МШ, пакет_моделі as ПМ, дріт_моделі as Д, міст_вхід as МВ

Т = lambda т: {"free_text": т, "lang": "uk"}

РЕЧЕННЯ = [
 # 1. Помітність
 ("іду на день народження подруги, хочу бути найпомітнішою в кімнаті",
  dict(event=Т("день народження подруги"), occasion="celebration", goal="express",
       quotes=dict(occasion="день народження", goal="хочу бути найпомітнішою в кімнаті"))),
 # 2. Стриманість
 ("робоча нарада з новими клієнтами, хочу лишитись непомітною, не привертати уваги",
  dict(event=Т("робоча нарада з новими клієнтами"), occasion="work", goal="conceal",
       quotes=dict(occasion="робоча нарада", goal="хочу лишитись непомітною, не привертати уваги"))),
 # 3. Комфорт (довгий переліт)
 ("летимо в відпустку, дев'ять годин у літаку, хочу щоб нічого не тиснуло і не муляло",
  dict(event=Т("летимо в відпустку"), occasion="travel", intent="comfort_first",
       quotes=dict(occasion="летимо в відпустку", intent="хочу щоб нічого не тиснуло і не муляло"),
       rest=Т("дев'ять годин у літаку"))),
 # 4. «щоб мама схвалила»
 ("іду знайомитись з його батьками на обід, хочу щоб мама схвалила",
  dict(event=Т("знайомитись з його батьками на обід"), intent="context_optimal",
       quotes=dict(intent="хочу щоб мама схвалила"))),
 # 5. «хочу виглядати вищою»
 ("на випускний вечір, я невисока, хочу виглядати вищою",
  dict(event=Т("випускний вечір"), occasion="celebration", wants=[dict(feature="heels", quote="хочу виглядати вищою")],
       quotes=dict(occasion="випускний вечір"), rest=Т("я невисока"))),
]

слова_ = lambda т: set(re.findall(r"[а-яіїєґʼ']{4,}", т.lower().replace("’", "'")))

print("=" * 78)
for слова, в in РЕЧЕННЯ:
    п = МШ.паспорт_з_шару(в, {}, None, None, слова_ходу=слова)["паспорт"]
    d = МВ._застосувати_паспорт({"паспорт": п, "сценарій": {}})
    рука1_dict = Д.випадок(ПМ.випадок_для_пакета(п, d["випадок"], d["сценарій"], d["вимоги"]))
    рука1 = json.dumps(рука1_dict, ensure_ascii=False)
    їх, а, б = слова_(слова), слова_(рука1), слова_(d["випадок"] + " " + d["вимоги"])
    print("«%s»" % слова)
    print("  рядок випадку (руки 3-4, ремонт, вибір, опис):\n    %s" % d["випадок"])
    print("  вимоги: %s" % d["вимоги"])
    print("  рука 1 case (goal/intent quotes): goal_quote=%r intent_quote=%r"
          % (рука1_dict.get("goal_quote"), рука1_dict.get("intent_quote")))
    print("  слів дійшло рука1: %d/%d (не дійшло: %s)" % (len(їх & а), len(їх), ", ".join(sorted(їх - а)) or "—"))
    print("  слів дійшло руки3-4: %d/%d (не дійшло: %s)" % (len(їх & б), len(їх), ", ".join(sorted(їх - б)) or "—"))
    print("-" * 78)
