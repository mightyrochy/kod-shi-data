def головна():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--оновити', action='store_true', help='записати відтворені звіт і додаток')
    args = cli.parse_args()
    сирі = дошка()
    рядки = читати_csv('рядки.csv')
    кроки = читати_csv('кроки.csv')
    перевірити(рядки, сирі)
    групи = defaultdict(list)
    for р in рядки:
        групи[р['група']].append(р)
    перевірити_кроки(кроки, групи)
    вивід = {
        'ЗВІТ.md': звіт(рядки, кроки, групи, сирі),
        'ДОДАТОК.md': додаток(рядки, сирі),
    }
    assert len(вивід['ЗВІТ.md'].splitlines()) <= 200, 'Звіт перевищує 200 рядків'
    for назва, зміст in вивід.items():
        файл = ТЕКА / назва
        if args.оновити:
            файл.write_text(зміст, encoding='utf-8')
        else:
            assert файл.read_text(encoding='utf-8') == зміст, f'{назва} відрізняється від лічби'
    print(f'Звірено {len(рядки)} рядків, {len(групи)} груп і {sum(bool(к["PR"]) for к in кроки)} злиттів за паспортами.')
    print('Звіт і дослівна вибірка з 30 рядків відтворюються.')


if __name__ == '__main__':
    головна()
