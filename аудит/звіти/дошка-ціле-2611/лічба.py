def поля(рядок):
    return dict(
        (ключ.strip(), значення.strip())
        for блок in re.findall(r'<!-- дошка:\s*(.*?)\s*-->', рядок)
        for пара in блок.split(';') if '=' in пара
        for ключ, значення in [пара.split('=', 1)]
    )


def перевірити(рядки, джерело):
    номери = [int(р['номер']) for р in рядки]
    assert len(номери) == len(set(номери)), 'У CSV є повторені номери'
    assert set(номери) <= джерело.keys(), 'У CSV є номери поза знімком'
    явні = {}
    for номер, (_, р) in джерело.items():
        клітинки = re.split(r'(?<!\\)\|', р)
        стан = клітинки[4].replace('*', '').strip().upper()
        запис = поля(р)
        if not стан.startswith('ЗАКРИТО') and запис.get('рід') in РОДИ:
            явні[номер] = запис
    assert {int(р['номер']) for р in рядки if р['формат'] == 'явний'} == явні.keys(), 'Покриття явних родів неповне'
    for р in рядки:
        номер = int(р['номер'])
        assert р['рід'] in РОДИ and р['група'] in ПОКРИТТЯ and р['речення'].endswith('.'), номер
        assert р['корінь із поля'] == поля(джерело[номер][1]).get('корінь', ''), номер
        date.fromisoformat(р['дата'])
        if номер in явні:
            assert (р['рід'], р['дата']) == (явні[номер]['рід'], явні[номер]['дата']), номер


def таблиця(заголовки, рядки):
    def клітина(x):
        return str(x).replace('|', r'\|').replace('\n', ' ')
    return ['| ' + ' | '.join(map(клітина, рядок)) + ' |'
            for рядок in (заголовки, ('---',) * len(заголовки), *рядки)]


def тиждень(день):
    k = (date.fromisoformat(день) - ВІД).days
    return 'раніше' if k < 0 else (ВІД + timedelta(days=k - k % 7)).strftime('%d.%m')


def відлік(крок, групи):
    if not крок['дата UTC']:
        return '', '', '', '', ''
    день = date.fromisoformat(крок['дата UTC'][:10])
    дати = [date.fromisoformat(р['дата']) for назва in крок['групи'].split(' / ') for р in групи[назва]]
    return (
        sum(ВІД <= д < день for д in дати),
        дати.count(день),
        sum(max(ВІД, день + timedelta(days=1)) <= д <= ДО for д in дати),
        sum(день - timedelta(days=7) <= д < день for д in дати),
        sum(день < д <= день + timedelta(days=7) for д in дати),
    )


def перевірити_кроки(кроки, групи):
    поля_лічби = ('від 26.10 до', 'у день', 'після до 26.11', '7 днів до', '7 днів після')
    історія = {
        sha: (час, назва)
        for рядок in git('log', '--first-parent', '--format=%H%x09%cI%x09%s', ЗНІМОК).splitlines()
        for sha, час, назва in [рядок.split('\t', 2)]
    }
    бачені = set()
    for крок in кроки:
        ключ = крок['паспорт'], крок['PR']
        assert ключ not in бачені, ключ
        бачені.add(ключ)
        if крок['PR']:
            час, назва = історія[крок['SHA']]
            час_utc = datetime.fromisoformat(час).astimezone(tz=timezone.utc).isoformat(timespec='seconds')
            assert (час_utc, назва) == (крок['дата UTC'], крок['назва злиття']), ключ
        assert tuple(крок[п] for п in поля_лічби) == tuple(map(str, відлік(крок, групи))), ключ


def розділ_злиттів(кроки):
    паспорти = defaultdict(list)
    for к in кроки:
        паспорти[к['паспорт']].append(к)
    внесено = []
    for паспорт, кк in sorted(паспорти.items()):
        справжні = [к for к in кк if к['PR']]
        if справжні:
            дати = f"{справжні[0]['дата UTC'][:10]} … {справжні[-1]['дата UTC'][:10]}"
            внесено.append((паспорт, len(справжні), дати, кк[0]['групи']))
        else:
            внесено.append((паспорт, 0, '—', кк[0]['групи']))
    return внесено


