"""Міряє мірки у всьому каталозі й відтворює вибірку. Модель і мережа не потрібні."""
import gzip
import importlib.util
import json
import random
import sys
from collections import Counter
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
from фід_мірки import довжина_крамниці, мірки_крамниці
from ядро import записи_речей, знання, річ

спец = importlib.util.spec_from_file_location("посадка", ТЕКА.parent / "посадка-вимір/вимір.py")
посадка = importlib.util.module_from_spec(спец)
спец.loader.exec_module(посадка)


def перевірити():
    """Зіставляє старий вимір і нові поля `Річ` за всіма ідентифікаторами сирого каталогу."""
    старі = {ід: в for ід, _, в in посадка.каталог()}
    сирі = {}
    with gzip.open(КОРІНЬ / "каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8") as потік:
        next(потік)
        for рядок in потік:
            дані = json.loads(рядок)
            пар = {к.lower().strip(): в for к, в, *_ in дані["параметри"]}
            офер = dict(назва=дані["назва"], опис=пар.get("опис") or дані.get("опис"), параметри=пар)
            сирі[дані["ід"]] = офер
    assert сирі.keys() == старі.keys()
    факти, відкинуто = {}, []
    вихід = {}
    лічба = Counter()
    for ід, було in старі.items():
        слот = було.get("слот", (None,))[0]
        офер = сирі[ід]
        пар = офер["параметри"]
        заміри = мірки_крамниці(офер, слот)
        факти[ід] = заміри
        новий, = записи_речей.вкласти([dict(id=ід, слот=слот, мірки_крамниці=заміри)], {})
        запис = річ.читати(новий)
        суд = знання.старий_запис(запис)
        дані = {к: в for к, в in було.items() if к not in (
            "довжина_см", "мірка_краю", "посадка_пояса", "каблук", "таблиця_мірок", "точка_довжини")}
        if isinstance(дані.get("край", (None,))[0], (int, float)):
            дані.pop("край")
        if "довжина_виробу" in заміри:
            факт = запис.поля["довжина_виробу"]
            assert факт.джерело == "крамниця" and факт.значення["unit"] == "cm"
            дані["довжина_см"] = (факт.значення["value"], факт.джерело)
            лічба["довжина зі старих 4334" if "довжина_см" in було else "довжина поза старим читачем"] += 1
        elif "довжина_см" in було:
            відкинуто.append((ід, "довжина", довжина_крамниці(офер, слот)[1]))
        if "довжина_виробу_см" in суд:
            вимір = tuple(суд[к] for к in ("довжина_виробу_см", "довжина_виробу_точка", "довжина_виробу_розкид_см"))
            дані["мірка_краю"] = (вимір, "крамниця")
            дані["край"] = (вимір[0], "крамниця")
        if "таблиця_мірок" in заміри:
            таблиця = запис.поля["мірки_крамниці"].значення["таблиця_мірок"]
            assert таблиця["source"] == "крамниця"
            дані["таблиця_мірок"] = (таблиця, "крамниця")
        elif пар.get("таблиця_мірок"):
            відкинуто.append((ід, "таблиця", "немає клітини з явною одиницею і прив’язкою до розміру"))
        if "посадка" in суд:
            дані["посадка_пояса"] = (суд["посадка"], "крамниця")
        if "каблук_см" in суд:
            дані["каблук"] = (суд["каблук_см"], "крамниця")
        вихід[ід] = дані
    застосовність = {ід: {в.get("слот", (None,))[0], в.get("тип", (None,))[0]} for ід, в in старі.items()}
    правила = {стан: посадка.покриття(набір, застосовність)["щонайменше_один_свідок_кожної_ролі"]
               for стан, набір in (("до", старі), ("після", вихід))}
    return сирі, факти, відкинуто, лічба, правила


def main():
    сирі, факти, відкинуто, лічба, правила = перевірити()
    print(json.dumps(dict(
        каталог=len(сирі), факти=Counter(поле for в in факти.values() for поле in в),
        довжини=лічба, відкинуто=Counter(f"{поле}: {причина}" for _, поле, причина in відкинуто),
        правила=правила), ensure_ascii=False, indent=2))
    if len(sys.argv) > 1:
        тека = Path(sys.argv[1])
        тека.mkdir(parents=True, exist_ok=True)
        with (тека / "відкинуто.tsv").open("w", encoding="utf-8") as файл:
            файл.write("ід\tполе\tпричина\n")
            for рядок in відкинуто:
                файл.write("\t".join(рядок) + "\n")
        генератор = random.Random(4941)
        бачено = set()
        with (тека / "вибірка.jsonl").open("w", encoding="utf-8") as файл:
            for поле in ("довжина_виробу", "таблиця_мірок"):
                для_вибірки = (ід for ід, в in факти.items() if поле in в and ід not in бачено)
                іди = генератор.sample(sorted(для_вибірки), 20)
                бачено.update(іди)
                for ід in іди:
                    офер = сирі[ід]
                    ряд = dict(ід=ід, поле=поле, факт=факти[ід][поле], назва=офер["назва"])
                    if поле == "довжина_виробу":
                        ряд["параметри"] = {к: в for к, в in офер["параметри"].items() if "довжин" in к}
                        ряд["опис"] = офер["опис"]
                    else:
                        ряд["текст_таблиці"] = офер["параметри"]["таблиця_мірок"]
                    файл.write(json.dumps(ряд, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
