"""Рекомендовані основи на записаному профілі стенда з відповідями драпування другого проходу власника 28.11.

Запуск із кореня репозиторію: python3 -I аудит/звіти/барви-вимір-2811/вимір_відповіді.py
Друкує по гамі: рекомендовані кольорові (назва, L*, C*), нейтралі, скільки «не радимо», осі людини й значення осі
контрасту в усіх основ. Без моделі.
"""
import json
import os
import sys

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
os.chdir(os.path.join(КОРІНЬ, "джерела"))
sys.path.insert(0, ".")
import bridge  # noqa: E402

ДРАП = {"білий": "вершковий", "метал": "золото", "нейтралі": "теплі", "барви": "приглушені"}
профіль = json.load(open("стенд_вх.json", encoding="utf-8"))
for гама in ("приглушені", "середні", "насичені"):
    вх = dict(профіль, самозвіт=dict(ДРАП), драп_сирий=ДРАП, вибір_кольору={"насиченість": гама})
    п = json.loads(bridge.виклик("палітри", json.dumps(вх, ensure_ascii=False)))
    о = п["основи"]
    рек = [x for x in о["рекомендовані"] if x["ключ"].endswith(гама)]
    інші = [x for x in о["інші"] if x["ключ"].endswith(гама)]
    print(гама)
    print("  кольорові:", [(x.get("відтінок") or x["назва"], x["осі"]["L"], x["осі"]["Cstar"])
                           for x in рек if not x["нейтраль"]])
    print("  нейтралі:", [(x.get("відтінок") or x["назва"], x["hex"]) for x in рек if x["нейтраль"]])
    print("  не радимо:", len(інші), "| осі людини:", п.get("осі_коди"),
          "| вісь контрасту в усіх основ:", sorted({x["осі"]["K"] for x in рек + інші}))
