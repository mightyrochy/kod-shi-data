"""Вимір 28.11: що показують плитки схем для кожної рекомендованої основи записаного профілю `джерела/стенд_вх.json`.

Запуск з кореня репозиторію: `python3 аудит/звіти/барви-вимір-2811/вимір.py > аудит/звіти/барви-вимір-2811/вивід.txt`.
Лише читає: викликає `bridge.виклик("палітри", …)` — те саме, що екран палітри; моделі не треба.
"""
import json
import math
import os
import sys
from collections import defaultdict
from itertools import combinations

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "джерела"))
sys.path.insert(0, ".")
import bridge  # noqa: E402
import colorspace as cs  # noqa: E402
from bases import ПІДЛОГА_РЕКОМЕНДАЦІЇ  # noqa: E402

ПОРІГ_ЗБІГУ = 2.5


def виклик(ім, вх):
    return json.loads(bridge.виклик(ім, json.dumps(вх, ensure_ascii=False)))


def lab(hx):
    return cs.to_lab(tuple(int(hx.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4)))


def тон(hx):
    L, a, b = lab(hx)
    return round(math.degrees(math.atan2(b, a)) % 360), round(math.hypot(a, b)), round(L)


with open("стенд_вх.json", encoding="utf-8") as ф:
    профіль = json.load(ф)
п0 = виклик("палітри", профіль)
осн = п0["основи"]
унікальні = list({о["hex"]: о for о in осн["рекомендовані"]}.values())
нейтр = [о for о in унікальні if о.get("нейтраль")]
кольор = [о for о in унікальні if not о.get("нейтраль")]
print(f"рекомендованих рядків {len(осн['рекомендовані'])}, різних кольорів {len(унікальні)}: "
      f"нейтралей {len(нейтр)}, кольорових {len(кольор)}; «інші» {len(осн['інші'])}")
print("бали рекомендованих:", sorted({о.get("бал") for о in осн["рекомендовані"]}))
print(f"без обраної основи: плиток зі зразками {п0['схем_показано']} із {len(п0['гілки'])}")

всі, нейтральні_плитки, близькі = {}, [], []
for о in унікальні:
    вибір = dict(база=о["ключ"], база_hex=о["hex"], база_назва=о.get("відтінок"),
                 база_тип="нейтраль" if о.get("нейтраль") else "колір")
    п = виклик("палітри", dict(профіль, вибір_кольору=вибір))
    h, C, L = тон(о["hex"])
    print(f"\n{о.get('відтінок')} {о['hex']} · тон {h}° · C {C} · L {L} · нейтраль={bool(о.get('нейтраль'))}: "
          f"плиток зі зразками {п['схем_показано']} із {len(п['гілки'])}")
    if о.get("нейтраль"):
        нейтральні_плитки.append(п["схем_показано"])
    for г in п["гілки"]:
        print("   ", г["схема"], г["зразки"], "· бракує тону" if г["бракує_тону_для_зразків"] else "")
        if not о.get("нейтраль"):
            всі[(о.get("відтінок"), г["схема"])] = г["зразки"]
            if г["схема"] == "тональна" and len(г["зразки"]) > 1:
                d = min(cs.de00(lab(о["hex"]), lab(з)) for з in г["зразки"] if з != о["hex"])
                if d < 5:
                    близькі.append((о.get("відтінок"), round(d, 1)))

print("\n== ПІДСУМОК ==")
print(f"нейтральні основи: кількість плиток зі зразками = {нейтральні_плитки}")
над_підлогою = {о["сім_я"] for о in осн["рекомендовані"] + осн["інші"]
                if not о["нейтраль"] and о["бал"] >= ПІДЛОГА_РЕКОМЕНДАЦІЇ}
print(f"сімей тону на підлозі рекомендації або вище: {len(над_підлогою)}")
сім_ї = defaultdict(list)
for о in кольор:
    сім_ї[round(тон(о["hex"])[0] / 15) * 15 % 360].append(о.get("відтінок"))
print(f"кольорових рекомендованих {len(кольор)}; груп тону (крок 15°): {len(сім_ї)} — "
      + "; ".join(f"{k}°: {len(v)}" for k, v in sorted(сім_ї.items())))
for сх in ("нейтрали+акцент", "тональна", "аналогова", "приглушена_комплементарна", "тріада"):
    хвости = [(назва, [lab(x) for x in з[1:]]) for (назва, с), з in всі.items()
              if с == сх and len(з) > 1]
    збіги = {назва: {назва} for назва, _ in хвости}
    for (а, х), (б, у) in combinations(хвости, 2):
        if len(х) == len(у) and all(cs.de00(к, л) < ПОРІГ_ЗБІГУ for к, л in zip(х, у)):
            збіги[а].add(б)
            збіги[б].add(а)
    найбільша = max(збіги.values(), key=len, default=set())
    print(f"{сх}: найбільша група збігів (ΔE00 < {ПОРІГ_ЗБІГУ}) — "
          f"{len(найбільша)} з {len(хвости)} основ {sorted(найбільша) if len(найбільша) > 1 else ''}")
print("тональна, де партнер майже той самий колір, що основа (ΔE00 < 5):", близькі)
