#!/usr/bin/env python3
"""Лічить усі числа ЗВІТУ з CSV поруч (їх будує зібрати.py). Запуск з кореня репозиторію:
python3 -I аудит/звіти/перевірки-користь-2611/порахувати.py  → друкує й пише числа.txt та додаток.md.
Нічого не читає, крім CSV цього каталогу."""
import csv, os, random, re, collections as C

ТУТ = os.path.dirname(os.path.abspath(__file__))
SEED = 26112026
ВИХІД = []


def читай(н):
    return list(csv.DictReader(open(os.path.join(ТУТ, н), encoding='utf-8')))


def п(*a):
    s = ' '.join(str(x) for x in a)
    ВИХІД.append(s)
    print(s)


def відс(a, b):
    return f'{100 * a / b:.0f}%' if b else '—'


pr = {int(r['PR']): r for r in читай('pr.csv')}
вер = читай('вердикти.csv')
for r in вер:
    r['pr'] = int(r['PR'])
заув = читай('зауваження.csv')
крізь = читай('пройшло_крізь.csv')
дошка = {int(r['id']): r for r in читай('дошка_рядки.csv')}
сесії = читай('сесії_дошки.csv')
витрати = читай('витрати_перевірок.csv')
cx_з = читай('codex_зауваження.csv')
cx_п = читай('codex_підсумки.csv')
злиті = {n for n, r in pr.items() if r['злито'] == 'так'}

п('## 1. Обсяг: PR вікна 12.11 00:00 – 26.11 00:00 UTC (злито або закрито)')
п('усього PR', len(pr), '· злито', len(злиті), '· закрито без злиття', len(pr) - len(злиті))
for к in ('документ', 'прилад', 'продукт'):
    п(f'  клас {к}: злито', sum(1 for n in злиті if pr[n]['клас'] == к), '· закрито без злиття',
      sum(1 for n, r in pr.items() if r['клас'] == к and n not in злиті))

# покриття: хто мав вердикт Claude/agy/Codex (звіт чи автозвіт, не коміт-злиття) / будь-який вердикт / Codex-підсумок
вер_pr = C.defaultdict(list)
for r in вер:
    вер_pr[r['pr']].append(r)
ознака_вердикту = {n for n, rs in вер_pr.items() if any(x['вердикт'] in ('ПЕРЕВІРЕНО', 'ДОРОБИТИ', 'КОЛО', 'ЗАБЛОКОВАНО') for x in rs)}
з_файлу = set()
for r in сесії:
    з_файлу.update(int(x) for x in r['PR_з_шапки_і_рядків'].split() if x)
cx_pr = {int(r['PR']) for r in cx_п}
cx_знахідки_pr = {int(r['PR']) for r in cx_п if r['є_знахідки'] == 'true'}
cx_нерозв_pr = {int(r['PR']) for r in cx_п if r['нерозв_знахідки'] == 'true'}
п('')
п('## 2. Покриття перевіркою (злиті PR вікна)')
для = {}
for к in ('документ', 'прилад', 'продукт'):
    ц = {n for n in злиті if pr[n]['клас'] == к}
    для[к] = ц
    п(f'  {к}: {len(ц)} злито; з вердиктом перевірки {len(ц & ознака_вердикту)} ({відс(len(ц & ознака_вердикту), len(ц))});'
      f' з вердиктом лише в темі коміту злиття {len({n for n in ц if n in вер_pr} - ознака_вердикту)};'
      f' зі згадкою в файлі дошки сесії перевірки {len(ц & з_файлу)}; з рецензією Codex (підсумок) {len(ц & cx_pr)};'
      f' без жодного сліду перевірки чи рецензії {len(ц - ознака_вердикту - з_файлу - cx_pr - set(вер_pr))}')
усі = set(злиті)
п(f'  разом злито: з вердиктом {len(усі & ознака_вердикту)}; без вердикту {len(усі - ознака_вердикту)}')
п('  PR з вердиктом, злитих у вікні, але чий вердикт датовано до 12.11 — у таблиці їх нема: усі вердикти з датою вікна')
п('  PR (будь-який стан) з вердиктами в таблиці:', len(ознака_вердикту), '· із них поза вікном', len([n for n in ознака_вердикту if n not in pr]))
п('  PR вікна, у яких Codex-рецензія лишила знахідку:', len(cx_знахідки_pr & set(pr)), '· лишилась нерозв’язаною на останньому підсумку:', len(cx_нерозв_pr & set(pr)))
п('  PR вікна, на які Codex поставив підсумок:', len(cx_pr & set(pr)))

п('')
п('## 3. Вердикти (таблиця вердикти.csv)')
п('рядків усього', len(вер), '· за джерелом', dict(C.Counter(r['джерело'] for r in вер)))
осн = [r for r in вер if r['джерело'] != 'коміт-злиття' and r['вердикт'] in ('ПЕРЕВІРЕНО', 'ДОРОБИТИ', 'КОЛО', 'ЗАБЛОКОВАНО')]
п('вердиктів із явним словом у звіті/автозвіті/згадці:', len(осн))
таб = C.Counter((r['рушій'], r['вердикт']) for r in вер)
for рушій in ('Claude', 'Codex', 'agy (Gemini)', 'не названо'):
    п(f'  {рушій}:', {в: таб[(рушій, в)] for в in ('ПЕРЕВІРЕНО', 'ДОРОБИТИ', 'КОЛО', 'ЗАБЛОКОВАНО', 'БЕЗ_МІТКИ') if таб[(рушій, в)]})
п('  моделі:', dict(C.Counter(r['модель'] for r in вер if r['джерело'] != 'коміт-злиття')))
п('  за ризиком (явні вердикти):')
for р in ('Р0', 'Р1', 'Р2', 'Р3', ''):
    rs = [r for r in осн if r['ризик'] == р]
    if rs:
        п(f'    {р or "не названо"}: {len(rs)} · ПЕРЕВІРЕНО {sum(1 for r in rs if r["вердикт"]=="ПЕРЕВІРЕНО")} · ДОРОБИТИ/КОЛО {sum(1 for r in rs if r["вердикт"] in ("ДОРОБИТИ","КОЛО"))}')
перші = [r for r in осн if r['коло'] == '1']
наступні = [r for r in осн if r['коло'] != '1']
п(f'  перші вердикти по PR: {len(перші)} · з них ДОРОБИТИ/КОЛО {sum(1 for r in перші if r["вердикт"] in ("ДОРОБИТИ","КОЛО"))}'
  f' ({відс(sum(1 for r in перші if r["вердикт"] in ("ДОРОБИТИ","КОЛО")), len(перші))})')
п(f'  повторні вердикти: {len(наступні)} · ПЕРЕВІРЕНО {sum(1 for r in наступні if r["вердикт"]=="ПЕРЕВІРЕНО")} · ДОРОБИТИ/КОЛО {sum(1 for r in наступні if r["вердикт"] in ("ДОРОБИТИ","КОЛО"))}')
первинні_до = {r['pr'] for r in перші if r['вердикт'] in ('ДОРОБИТИ', 'КОЛО')}
з_потім = {r['pr'] for r in наступні if r['вердикт'] == 'ПЕРЕВІРЕНО'} | {r['pr'] for r in вер if r['джерело'] == 'коміт-злиття' and r['вердикт'] == 'ПЕРЕВІРЕНО'}
п(f'  PR, чий перший вердикт ДОРОБИТИ/КОЛО: {len(первинні_до)}; з них злито у вікні {len(первинні_до & злиті)};'
  f' з наступним ПЕРЕВІРЕНО {len(первинні_до & з_потім)}; закрито без злиття {len([n for n in первинні_до if n in pr and n not in злиті])}')
п('  КОЛО (друга доробка) всього:', sum(1 for r in вер if r['вердикт'] == 'КОЛО'))

без_в = sorted(n for n in з_файлу if n not in вер_pr)
п(f'  PR зі згадкою в файлах дошки сесій перевірки ({len(з_файлу)}), для яких у таблиці нема вердикту: {len(без_в)}')
п('')
п('## 4. Зауваження (таблиця зауваження.csv)')
ок = C.Counter(r['джерело'] for r in заув)
п('усього', len(заув), dict(ок))
п('  рядків дошки «виявлено: перевірка», дата 12–25.11:',
  sum(1 for r in дошка.values() if r['виявлено'] == 'перевірка' and '2026-11-12' <= r['дата'] <= '2026-11-25'),
  '· з них збігаються з блокуючими вердиктів:', sum(1 for n, r in дошка.items() if r['виявлено'] == 'перевірка' and '2026-11-12' <= r['дата'] <= '2026-11-25' and any(z['джерело'] == 'вердикт-блокуюче' and z['рядок_дошки'] == str(n) for z in заув)),
  '· блокуючі вердиктів з рядком дошки (будь-яка дата):', sum(1 for r in заув if r['джерело'] == 'вердикт-блокуюче' and r['рядок_дошки']),
  '· ручні (без рядка дошки):', sum(1 for r in заув if r['джерело'] == 'вердикт-блокуюче' and not r['рядок_дошки']))
нд = [r for r in заув if r['джерело'] != 'codex-рецензія']
п('  без Codex-рецензій (вердикт-блокуюче + дошка-перевірка):', len(нд), '· за класом', dict(sorted(C.Counter(r['клас'] for r in нд).items())))
п('  Codex-рецензії (інлайн):', ок['codex-рецензія'], '· за класом шляху', dict(C.Counter(r['клас'] for r in заув if r['джерело'] == 'codex-рецензія')),
  '· вага', dict(C.Counter(r['вага'] for r in cx_з)))
п('  за механізмом/джерелом×класом:')
for дж in ('вердикт-блокуюче', 'дошка-перевірка'):
    п('   ', дж, dict(sorted(C.Counter(r['клас'] for r in заув if r['джерело'] == дж).items())))
п('  блокуючі вердиктів за ризиком:', dict(C.Counter((r['ризик'] or '?') for r in заув if r['джерело'] == 'вердикт-блокуюче')))
п('  блокуючі (а)/(б) за ризиком:', dict(C.Counter((r['ризик'] or '?') for r in заув if r['джерело'] == 'вердикт-блокуюче' and r['клас'] in ('а', 'б'))))
п('  блокуючі вердиктів за рушієм:', dict(C.Counter((r['рушій'] or '?') for r in заув if r['джерело'] == 'вердикт-блокуюче')))
п('  рядки дошки перевірки за рушієм — не лічу: рядок дошки не зберігає, яка модель його дала (див. «Не виміряно»)')

п('')
п('## 5. Доля вад (а) екран жінки і (б) хибна відповідь продукту')
for дж in ('вердикт-блокуюче', 'дошка-перевірка'):
    for кл in ('а', 'б'):
        п(f'  {дж} · {кл}:', dict(C.Counter(r['доля'] for r in заув if r['джерело'] == дж and r['клас'] == кл)))
аб = [r for r in заув if r['джерело'] != 'codex-рецензія' and r['клас'] in ('а', 'б')]
п('  (а)+(б) разом без Codex:', len(аб), dict(C.Counter(r['доля'] for r in аб)))
ст = lambda r: дошка[int(r['рядок_дошки'])]['статус'] if r['рядок_дошки'] else 'нема рядка'
п('  (а)+(б) за статусом рядка дошки на дату виміру:', dict(C.Counter(ст(r) for r in аб)))
п('  (а)+(б) блокуючі вердиктів: виправлено до злиття', sum(1 for r in аб if r['джерело'] == 'вердикт-блокуюче' and r['доля'] == 'виправлено до злиття'),
  '· злито без доробки', sum(1 for r in аб if r['джерело'] == 'вердикт-блокуюче' and r['доля'] == 'злито без доробки'))
п('  із них виправлено до злиття за рушієм:', dict(C.Counter(r['рушій'] for r in аб if r['джерело'] == 'вердикт-блокуюче' and r['доля'] == 'виправлено до злиття')))
зв = [r for r in аб if r['джерело'] == 'дошка-перевірка' and r['доля'] == 'злито з вадою']
пор = C.Counter()
for r in зв:
    д, м = дошка[int(r['рядок_дошки'])]['дата'], pr[int(r['PR'])]['злито_utc'][:10]
    пор['рядок датовано до дня злиття' if д < м else ('у день злиття' if д == м else 'після дня злиття')] += 1
п('  дошка-перевірка (а)/(б) «злито з вадою»: дата рядка щодо дня злиття PR:', dict(пор))
п('  Codex інлайн на продуктовому коді (клас «аб» не розділено):', sum(1 for r in заув if r['джерело'] == 'codex-рецензія' and r['клас'] == 'аб'))

п('')
п('## 6. Що пройшло крізь перевірку (виявлено живий/тестувальниця/власник, внесено #PR із вердиктом ПЕРЕВІРЕНО)')
крізь_pr = {int(r['PR']) for r in крізь}
жв = [r for r in дошка.values() if r['виявлено'] in ('живий', 'тестувальниця', 'власник') and '2026-11-12' <= r['дата'] <= '2026-11-25']
п('  рядків дошки живий/тестувальниця/власник за 12–25.11:', len(жв), dict(C.Counter(r['виявлено'] for r in жв)))
з_пр = [r for r in жв if re.search(r'#\d{4}', r['внесено'])]
п('  із них з «внесено: #PR»:', len(з_пр), '· «внесено: давнє»:', sum(1 for r in жв if r['внесено'].strip().startswith('давнє')))
п('  із #PR, що має вердикт ПЕРЕВІРЕНО у таблиці (джойн):', len(крізь), '· різних PR', len({r['PR'] for r in крізь}))
п('  за класом:', dict(C.Counter(r['клас'] for r in крізь)), '· за хто виявив:', dict(C.Counter(r['виявлено'] for r in крізь)))
п('  за джерелом вердикту:', dict(C.Counter(r['джерело_вердикту'] for r in крізь)), '· за рушієм:', dict(C.Counter(r['рушій_вердикту'] for r in крізь)))
п('  у них PR злито:', sum(1 for r in крізь if r['PR_злито'] == 'так'), '· рядок досі ВІДКРИТО:', sum(1 for r in крізь if r['статус'] == 'ВІДКРИТО'))
п('  PR із ПЕРЕВІРЕНО в таблиці, злитих у вікні:', len({r['pr'] for r in вер if r['вердикт'] == 'ПЕРЕВІРЕНО' and r['pr'] in злиті}))
стан = C.Counter()
for r in з_пр:
    k = [int(x) for x in re.findall(r'#(\d{4})', r['внесено'])]
    k = [x for x in k if x in вер_pr or x in pr]
    if not k:
        стан['PR поза вікном і без вердикту'] += 1
        continue
    x = next((y for y in k if y in крізь_pr), k[0])
    if x in крізь_pr:
        стан['PR має ПЕРЕВІРЕНО'] += 1
    elif x in вер_pr:
        стан['PR має лише ДОРОБИТИ/КОЛО/інше'] += 1
    elif x in pr:
        стан['PR у вікні без вердикту перевірки'] += 1
п('  рядки з «внесено: #PR» за станом PR (перший PR з тексту):', dict(стан))
п('  а (екран жінки) серед пройшло крізь, ризик перевірки:', dict(C.Counter(r['ризик'] or '?' for r in крізь if r['клас'] == 'а')))

п('')
п('## 7. Ціна перевірок')
сума = lambda rs: sum(float(r['cost_usd_у_вікні']) for r in rs)
пер = [r for r in витрати if r['що'] == 'перевірка PR']
ін = [r for r in витрати if r['що'] != 'перевірка PR']
п(f'  сесій перевірки Claude (вікно): {len(пер)} · вартість {сума(пер):.2f} USD · за моделлю {dict(C.Counter(r["модель"] for r in пер))}')
п(f'  виключено «оцінка прогону/звіту»: {len(ін)} сесій, {сума(ін):.2f} USD (це перевірка прогону, не PR)')
п('  вартість за таблицею:', {t: round(сума([r for r in пер if r['таблиця'] == t]), 2) for t in sorted({r['таблиця'] for r in пер})})
клод_в = [r for r in вер if r['рушій'] == 'Claude' and r['джерело'] in ('звіт', 'згадка') and r['вердикт'] != 'БЕЗ_МІТКИ']
п(f'  вердиктів Claude (звіти/згадки з явним словом): {len(клод_в)} → {сума(пер) / max(len(клод_в),1):.2f} USD на вердикт (знаменник занижений: вердикти з теми коміту й БЕЗ_МІТКИ не лічено)')
зуп = [r for r in аб if r['джерело'] == 'вердикт-блокуюче' and r['доля'] == 'виправлено до злиття']
п(f'  зупинених до злиття вад (а)/(б): {len(зуп)} (усі рушії) → {сума(пер) / max(len(зуп),1):.2f} USD на ваду, якщо віднести всю вартість Claude на них (верхня оцінка ціни)')
зуп_cl = [r for r in зуп if r['рушій'] == 'Claude']
п(f'  з них за Claude: {len(зуп_cl)} → {сума(пер) / max(len(зуп_cl),1):.2f} USD на ваду')
всі_аб_cl = [r for r in аб if r['джерело'] == 'вердикт-блокуюче' and r['рушій'] == 'Claude']
п(f'  вад (а)/(б) у блокуючих вердиктів Claude (зупинено або злито): {len(всі_аб_cl)}')
п(f'  Codex: підсумків-рецензій на PR вікна {len(cx_pr & set(pr))}; інлайн-коментарів {len(cx_з)}; автозвітів-вердиктів у таблиці {sum(1 for r in вер if r["рушій"]=="Codex")}; токени/вартість — не виміряно')
п(f'  agy (Gemini): вердиктів {sum(1 for r in вер if r["рушій"].startswith("agy"))}; токени/вартість — не виміряно')

# --- додаток: 20 випадкових зауважень
ключі = sorted(range(len(заув)), key=lambda i: (заув[i]['джерело'], заув[i]['ключ']))
rnd = random.Random(SEED)
вибір = sorted(rnd.sample(ключі, 20), key=lambda i: (заув[i]['джерело'], заув[i]['ключ']))
cx_за_id = {r['id']: r for r in cx_з}
рядки = ['# Додаток: 20 випадкових зауважень дослівно', '',
         f'Вибір: `random.Random({SEED}).sample` з усіх {len(заув)} рядків `зауваження.csv`, відсортованих за (джерело, ключ). '
         'Текст — як у таблиці (дошка: перша клітинка рядка; Codex: коментар без розмітки; довше 600 знаків скорочено «…»).', '']
for н, i in enumerate(вибір, 1):
    r = заув[i]
    pr_н = r['PR']
    посил = f'https://github.com/mightyrochy/kod-shi-data/pull/{pr_н}' if pr_н else '—'
    if r['джерело'] == 'codex-рецензія':
        посил += f'#discussion_r{r["ключ"]}'
    текст = r['текст'] if len(r['текст']) < 600 else r['текст'][:600] + '…'
    рядки.append(f'{н}. **{r["джерело"]} · клас {r["клас"]}** ({r["спосіб_класу"]}) · PR {pr_н or "не визначено"} · {посил}')
    рядки.append(f'   рядок дошки: {r["рядок_дошки"] or "—"}; блокуюче: {r["блокуюче"]}; доля: {r["доля"]}; ризик: {r["ризик"] or "—"}; рушій: {r["рушій"] or "—"}')
