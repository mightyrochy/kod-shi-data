"""Зіставити ваги й доставку знахідок у штатному вердикті на фіксованому каталозі."""
import argparse
from collections import Counter, defaultdict
import gzip
import json
from itertools import zip_longest
from pathlib import Path
import sys
from unittest.mock import patch


КОРІНЬ = Path(__file__).resolve().parents[3]


def представники(речі, ключ, вимір):
    """Перший за ід виміряний представник кожної групи, у спільному порядку."""
    групи = {ключ(річ): річ for річ in reversed(речі) if вимір(річ) is not None}
    return [групи[к] for к in sorted(групи, key=str)]


def взуття(каталог):
    """Входи K-SHO-04 з повного каталогу за вибіркою #3911."""
    import аксесуари_взуття as суд

    пари = [р for р in каталог if р.get("слот") == "взуття"]
    низи = [р for р in каталог if р.get("слот") in ("низ", "сукня", "комплект")]
    реп_н = представники(низи, lambda р: (суд.гола_нога([р]), round(суд.L(р)[0] / 20)), суд.L)
    реп_п = представники([р for р in пари if р.get("виріз_стопи")],
                          lambda р: (р["виріз_стопи"], round(суд.L(р)[0] / 20)), суд.L)
    колготи = [dict(р, слот="колготи", id="колг-" + str(р["id"]), den=40) for р in реп_н[::3]]
    особи = (None, dict(L_шкіри=45.0), dict(L_шкіри=75.8))
    for пара in пари:
        for речі in [[пара, низ] for низ in реп_н] + [[пара]]:
            for і, особа in enumerate(особи):
                yield f"взуття:{і}", речі, суд.лінія_ноги(речі, особа=особа)
            for колгота in колготи:
                склад = речі + [колгота]
                yield "взуття:колготи", склад, суд.лінія_ноги(склад, особа=особи[-1])
    for низ in низи:
        for пара in реп_п:
            речі = [пара, низ]
            yield "взуття:низ", речі, суд.лінія_ноги(речі, особа=особи[-1])


def огляд(каталог):
    """Кожна річ у відповідному слоті фіксованого образу на повному суді."""
    import аксесуари_ціна as ціна
    import colorspace
    import суд_огляд as суд
    import trace

    вхід = json.loads((КОРІНЬ / "джерела" / "стенд_вх.json").read_text())
    профіль = colorspace.features(*(colorspace.hx(hex) for hex in
                                     (вхід["шкіра"], вхід["волосся"][0], вхід["очі"])))
    основа = {слот: next(р for р in каталог if р.get("слот") == слот and р.get("lab"))
              for слот in ("верх", "низ", "взуття")}
    for річ in каталог:
        слот = річ.get("слот")
        заміщені = {"верх", "низ"} if слот in ("сукня", "комплект") else {слот}
        речі = [річ] + [р for с, р in основа.items() if с not in заміщені]
        trace.ЗАПИСИ.clear()
        емісії = []
        обмежити = суд.обмежити_вагу

        def записати(знахідки):
            """Записати знахідки стану безпосередньо перед фільтром огляду."""
            готові = обмежити(знахідки)
            емісії.extend(dict(з) for з in готові)
            return готові

        with patch.object(суд, "обмежити_вагу", записати):
            суд.review(профіль, речі, вхід["сценарій"], source="protocolized")
        yield "огляд", речі, емісії
        ранг = ціна.ЦІНА_РАНГ_ПОРІГ
        for значення in (ранг, ранг + 0.00001, ранг + 0.026, 0.9, 1.0):
            yield f"ціна:{значення}", [річ], ціна.цінність_речей([dict(річ, ціна_ранг=значення)])


def знімок(параметри):
    """Рядок на кожну емісію з ефективною вагою та фактом доставки моделі."""
    sys.path.insert(0, str(параметри.джерела.resolve()))
    from реєстр_сила import обмежити_вагу
    from вердикт_моделі import знахідки_вердикту
    import trace

    with gzip.open(параметри.каталог, "rt", encoding="utf-8") as файл:
        каталог = sorted(json.load(файл), key=lambda р: str(р["id"]))
    набори = (взуття, огляд) if параметри.набір == "усі" else (globals()[параметри.набір],)
    with gzip.open(параметри.вихід, "wt", encoding="utf-8") as файл:
        файл.write(json.dumps({"каталог": len(каталог)}) + "\n")
        for набір in набори:
            for сцена, речі, знахідки in набір(каталог):
                іди = [р["id"] for р in речі]
                записи = []
                for з in знахідки:
                    if not з.get("правило"):
                        continue
                    готова = обмежити_вагу([dict(з)])[0]
                    рядки, вето = знахідки_вердикту([з], "о1")
                    записи.append([з["правило"], з.get("сила"), з.get("сила_нп"), готова.get("сила_нп"),
                                   bool(готова.get("під_підлогою")), bool(рядки) or bool(вето)])
                файл.write(json.dumps([сцена, іди, записи], ensure_ascii=False) + "\n")
                trace.ЗАПИСИ.clear()


def підрахувати(сцена, іди, записи_до, записи_після, підсумок, приклади):
    """Зіставити знахідки одного незмінного входу по правилах."""
    до, після = defaultdict(Counter), defaultdict(Counter)
    for коли, записи, групи in (("до", записи_до, до), ("після", записи_після, після)):
        for правило, сила, сира, ефективна, підлога, доставлено in записи:
            групи[правило][сила, сира, ефективна, підлога, доставлено] += 1
            ліч = підсумок[правило]
            ліч[коли] += 1
            if not доставлено:
                ліч[f"{коли} · не доставлено"] += 1
                ліч[f"{коли} · не доставлено: {сила}; вага={ефективна}; під підлогою={підлога}"] += 1
    for правило in до.keys() | після.keys():
        ліч = підсумок[правило]
        старі, нові = до[правило], після[правило]
        старі_решта, нові_решта = старі - нові, нові - старі
        ліч["до · незбіглих"] += старі_решта.total()
        ліч["після · незбіглих"] += нові_решта.total()
        if len(старі_решта) == len(нові_решта) == 1 and старі_решта.total() == нові_решта.total():
            старий, новий = next(iter(старі_решта)), next(iter(нові_решта))
            if старий[2] != новий[2]:
                ліч[f"вага {старий[2]} → {новий[2]}"] += старі_решта.total()
            if not старий[-1] and новий[-1] and правило not in приклади:
                приклади[правило] = dict(сцена=сцена, іди=іди, до=старий, після=новий)
        elif старі_решта or нові_решта:
            ліч["сцен з неоднозначним зіставленням емісій"] += 1


def архів_взуття(шлях):
    """Прочитати пари з 8 486 відсівами K-SHO-04 у вимірі #3911."""
    if шлях is None:
        return Counter()
    with gzip.open(шлях, "rt", encoding="utf-8") as файл:
        return Counter(з[0] for з in json.load(файл) if з[2] == "K-SHO-04" and з[8])


def зіставити(параметри):
    """Порахувати зміни ваги й доставки на тих самих записаних входах."""
    підсумок = defaultdict(Counter)
    приклади = {}
    архів = архів_взуття(параметри.архів_взуття)
    з_архіву = {"до": Counter(), "після": Counter()}
    with (gzip.open(параметри.до, "rt", encoding="utf-8") as файл_до,
          gzip.open(параметри.після, "rt", encoding="utf-8") as файл_після):
        каталог_до, каталог_після = json.loads(next(файл_до)), json.loads(next(файл_після))
        if каталог_до != каталог_після:
            raise SystemExit(f"Різні каталоги: {каталог_до}, {каталог_після}")
        for до, після in zip_longest(файл_до, файл_після):
            if до is None or після is None:
                raise SystemExit("Кількість сцен до й після різна")
            зліва, справа = json.loads(до), json.loads(після)
            if зліва[:2] != справа[:2]:
                raise SystemExit(f"Різні входи: {зліва[:2]}, {справа[:2]}")
            сцена, іди, записи_до = зліва
            підрахувати(сцена, іди, записи_до, справа[2], підсумок, приклади)
            if архів and сцена.startswith("взуття:"):
                тип = сцена.split(":", 1)[1]
                ключ = "+".join(іди) + (f"@о{тип}" if тип.isdigit() else "")
                for коли, записи in (("до", записи_до), ("після", справа[2])):
                    if ключ in архів:
                        з_архіву[коли][ключ] += sum(з[0] == "K-SHO-04" and з[-1] for з in записи)
    звіт = dict(каталог=каталог_до["каталог"], правила=підсумок, приклади=приклади)
    if архів:
        звіт["архів K-SHO-04"] = dict(входів=архів.total(),
                                     доставлено_до=(з_архіву["до"] & архів).total(),
                                     доставлено_після=(з_архіву["після"] & архів).total())
    print(json.dumps(звіт, indent=2, ensure_ascii=False, sort_keys=True))


def main():
    """Записати одну ревізію або зіставити два записи."""
    cli = argparse.ArgumentParser(description=__doc__)
    команди = cli.add_subparsers(required=True)
    запис = команди.add_parser("знімок")
    запис.add_argument("каталог", type=Path, help="gzip JSON зі штатного feed.прогін")
    запис.add_argument("вихід", type=Path)
    запис.add_argument("--джерела", type=Path, default=КОРІНЬ / "джерела")
    запис.add_argument("--набір", choices=("усі", "взуття", "огляд"), default="усі")
    запис.set_defaults(дія=знімок)
    порівняння = команди.add_parser("зіставити")
    порівняння.add_argument("до", type=Path)
    порівняння.add_argument("після", type=Path)
    порівняння.add_argument("--архів-взуття", dest="архів_взуття", type=Path)
    порівняння.set_defaults(дія=зіставити)
    параметри = cli.parse_args()
    параметри.дія(параметри)


if __name__ == "__main__":
    main()
