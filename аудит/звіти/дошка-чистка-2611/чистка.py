#!/usr/bin/env python3
"""Переносить рядки з дошки вибраного коміту main і відтворює звіт."""
import argparse
from collections import Counter, defaultdict
from pathlib import Path, PurePosixPath
import re
import shlex
import subprocess
import sys

РЕПОЗИТОРІЙ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(РЕПОЗИТОРІЙ / 'джерела/прилади'))
from дошка_поля import БЛОК, ПРОДУКТ, РЯДОК, межі_стану, метадані, ранг_рядка, шляхи_дошки
from згорнути_дошку import ШАПКА_ЗАКРИТИХ, ШАПКА_ТАБЛИЦІ

ДОШКА = 'аудит/БЕКЛОГ.md'
РОДИ_ЗАСТАРІЛИХ = ('мірило', 'вимір', 'процес', 'рішення')
ЗВОРОТНІ_ЛАПКИ = re.compile(r'`([^`]+)`')
ПОЗИЦІЯ = re.compile(r'(?::\d+(?:[-:]\d+)?|#[^#]*)$')
ЛІТЕРАЛЬНИЙ_ШЛЯХ = re.compile(r'[\w.\-/]+')
КОМАНДА = re.compile(r'(?:python(?:3(?:\.\d+)?)?|node|bash|pwsh|cat|rg|git)\s')
СУФІКС = re.compile(r'\.[a-zA-Z][a-zA-Z0-9]{0,7}$')
БЕЗ_ПОЛІВ = 'без блоку полів'


def git(*аргументи):
    """Читає байти з Git у цьому репозиторії."""
    return subprocess.check_output(['git', *аргументи], cwd=РЕПОЗИТОРІЙ)


def дерево(основа):
    """Індексує файли, назви й теки з дерева коміту, незалежно від checkout."""
    файли = {шлях for шлях in git('ls-tree', '-r', '--name-only', '-z', основа).decode().split('\0') if шлях}
    скорочені, теки, кореневі, суфікси = set(), set(), set(), set()
    for файл in файли:
        шлях = PurePosixPath(файл)
        кореневі.add(шлях.parts[0])
        теки.update(str(тека) for тека in шлях.parents)
        скорочені.update('/'.join(шлях.parts[і:]) for і in range(1, len(шлях.parts)))
        if СУФІКС.fullmatch(шлях.suffix):
            суфікси.add(шлях.suffix.lower())
    return файли, скорочені, теки, кореневі, суфікси


def посилання(рядок):
    """Виділяє цитати та буквальні аргументи поширених команд, записаних у лапках."""
    for текст in ЗВОРОТНІ_ЛАПКИ.findall(рядок):
        текст = текст.strip()
        if КОМАНДА.match(текст):
            try:
                yield from shlex.split(текст)[1:]
            except ValueError:
                continue
        else:
            yield текст


def названі_файли(рядок, індекс):
    """Знаходить буквальні посилання на наявні чи відсутні файли у зворотних лапках."""
    файли, скорочені, теки, кореневі, суфікси = індекс
    знайдено = {}
    for шлях in посилання(рядок):
        явно_від_кореня = шлях.startswith(('./', '/'))
        if шлях.endswith('/') or шлях.startswith('//'):
            continue
        шлях = ПОЗИЦІЯ.sub('', шлях.removeprefix('./').removeprefix('/'))
        верх = шлях.split('/', 1)[0]
        if шлях in файли or (not явно_від_кореня and верх not in кореневі and шлях in скорочені):
            знайдено[шлях] = True
        elif (шлях not in теки and ЛІТЕРАЛЬНИЙ_ШЛЯХ.fullmatch(шлях) and
              '..' not in PurePosixPath(шлях).parts and PurePosixPath(шлях).suffix.lower() in суфікси):
            знайдено[шлях] = False
    return знайдено


def категорії(рядок):
    """Повертає рід, місяць появи й корінь з полів поза статусом."""
    від, до = межі_стану(рядок) or (0, 0)
    зовні = рядок[:від] + рядок[до:]
    поля = метадані(зовні)
    рід = поля.get('рід', 'без роду' if БЛОК.search(рядок) else БЕЗ_ПОЛІВ)
    місяць = поля['дата'][:7] if 'дата' in поля else 'без дати'
    return рід, місяць, поля.get('корінь', 'без поля')


def розподілити(до, індекс):
    """Ділить вихідні байти між дошкою й архівами та готує переліки для звіту."""
    активні, закриті, застарілі = [], {}, {}
    причини, без_файлу, відсутні_у_продукті = {}, defaultdict(list), {}
    залишок = [Counter(), Counter(), Counter()]
    очікувані = {}
    for байти in до.splitlines(keepends=True):
        рядок = байти.decode()
        м = РЯДОК.match(рядок)
        if not м:
            активні.append(байти)
            continue
        номер = int(м[1])
        if номер in очікувані:
            raise ValueError(f'номер {номер} повторено у вихідній дошці')
        очікувані[номер] = байти
        стан = ранг_рядка(рядок)
        if стан == 3:
            закриті[номер] = байти
            continue
        рід, місяць, корінь = категорії(рядок)
        файли = названі_файли(рядок, індекс)
        нема = sorted(файл for файл, знайдено in файли.items() if not знайдено)
        if стан == 1 and (рід in РОДИ_ЗАСТАРІЛИХ or рід == БЕЗ_ПОЛІВ) and файли and not any(файли.values()):
            застарілі[номер] = байти
            причини[номер] = нема
            continue
        if not файли:
            без_файлу[рід, місяць].append(номер)
        if рід in ПРОДУКТ and нема:
            відсутні_у_продукті[номер] = нема
        активні.append(байти)
        for лічба, категорія in zip(залишок, (рід, місяць, корінь)):
            лічба[категорія] += 1
    return перевірити(очікувані, активні, закриті, застарілі), причини, без_файлу, відсутні_у_продукті, залишок


def перевірити(очікувані, активні, закриті, застарілі):
    """Звіряє рівність за номером і байтами та відсутність закритих у робочій дошці."""
    після = {}
    for рядок in активні:
        текст = рядок.decode()
        м = РЯДОК.match(текст)
        if м:
            if ранг_рядка(текст) == 3:
                raise ValueError(f'рядок {м[1]}: закритий рядок у робочій дошці')
            після[int(м[1])] = рядок
    усі = після | закриті | застарілі
    if усі != очікувані or len(усі) != len(після) + len(закриті) + len(застарілі):
        raise ValueError('номери або байти рядків після перенесення не збігаються з вихідною дошкою')
    return після, закриті, застарілі, b''.join(активні)


def файли_переліку(файли):
    """Форматує список названих файлів для Markdown."""
    return ', '.join(f'`{файл}`' for файл in файли)


def список_номерів(номери):
    """Друкує відсортовані номери з розривом довгих списків."""
    номери = sorted(номери)
    return '\n'.join(', '.join(map(str, номери[і:і + 30])) for і in range(0, len(номери), 30)) or '—'


def таблиця(назва, лічба):
    """Друкує таблицю категорій залишку."""
    return '\n'.join([f'| {назва} | Рядків |', '|---|---:|',
                      *(f'| {ключ} | {число} |' for ключ, число in sorted(лічба.items()))])


def звіт(основа, до, обсяг, дані, без_файлу, відсутні_у_продукті, залишок):
    """Створює звіт з обсягом, розподілом і переліками номерів."""
    активні, закриті, застарілі, _ = дані
    загалом = len(активні) + len(закриті) + len(застарілі)
    робоча, архів_закрито, архів_застаріле = обсяг
    лічба_без_файлу = sum(map(len, без_файлу.values()))
    текст = [
        '# Дошка-чистка-архів', '', f'Вхідне дерево `main` — `{основа}`.', '',
        '| Файл | Номери ДО → ПІСЛЯ | Фізичні рядки ДО → ПІСЛЯ | Байти ДО → ПІСЛЯ |',
        '|---|---:|---:|---:|',
        f'| Робоча дошка | {загалом} → {len(активні)} | {len(до.splitlines())} → {len(робоча.splitlines())} | {len(до)} → {len(робоча)} |',
        f'| Архів закритих | 0 → {len(закриті)} | 0 → {len(архів_закрито.splitlines())} | 0 → {len(архів_закрито)} |',
        f'| Архів застарілих | 0 → {len(застарілі)} | 0 → {len(архів_застаріле.splitlines())} | 0 → {len(архів_застаріле)} |',
        '', f'Побайтово звірено всі {загалом} пронумерованих рядків. Номерів у двох місцях і закритих у робочій дошці — 0.',
        '', '## Що лишилося', '',
    ]
    for назва, лічба in zip(('Рід', 'Місяць появи', 'Корінь (значення поля)'), залишок):
        текст.extend([таблиця(назва, лічба), ''])
    текст.extend([
        f'## Перенесено як закрите ({len(закриті)})', '', список_номерів(закриті), '',
        f'## Перенесено як застаріле ({len(застарілі)})', '', список_номерів(застарілі), '',
        'Причина для кожного номера є в [архіві застарілих](../../дошка_архів/застаріле.md#причини-перенесення).', '',
        f'## Лишилося без названого файлу ({лічба_без_файлу})', '',
    ])
    for (рід, місяць), номери in sorted(без_файлу.items()):
        текст.extend([f'### {рід} · {місяць} ({len(номери)})', '', список_номерів(номери), ''])
    текст.extend([
        f'## Для менеджера: названого файлу нема у рядках продукту ({len(відсутні_у_продукті)})', '',
        'Ці рядки лишилися в робочій дошці.', '',
        *(f'- **{номер}.** {файли_переліку(файли)}' for номер, файли in sorted(відсутні_у_продукті.items())),
        '', '## Відтворення', '',
        '```sh', f'python3 аудит/звіти/дошка-чистка-2611/чистка.py --основа {основа}', '```', '',
        '`--лише-перевірити` звіряє ці чотири файли з результатом повторного обчислення без запису.',
        'Файли звіряються за деревом коміту. Для повторного запису використовуйте окрему робочу копію.',
        'Повні шляхи звіряються від кореня. Імена без повного шляху звіряються за кінцевими компонентами,',
        'якщо перша компонента не є кореневою текою. Суфікс `:рядок` або `#якір` відкидається.',
        'Для відсутніх файлів беруться буквальні шляхи з розширенням, яке є у дереві.',
        'У цитованих командах розпізнаються файлові аргументи. Теки й шаблони пропускаються.',
        'Рід, місяць появи й корінь взято тільки з полів дошки.',
        '',
    ])
    return '\n'.join(текст)


def головна():
    """Звіряє вихідний коміт і записує перевірені архіви та звіт."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--основа', required=True, help='коміт main до перенесення')
    парсер.add_argument('--лише-перевірити', action='store_true', help='звірити результат без запису')
    аргументи = парсер.parse_args()
    основа = git('rev-parse', '--verify', '--end-of-options', f'{аргументи.основа}^{{commit}}').decode().strip()
    шляхи = шляхи_дошки(РЕПОЗИТОРІЙ / ДОШКА)
    індекс = дерево(основа)
    if any(шлях.relative_to(РЕПОЗИТОРІЙ).as_posix() in індекс[0] for шлях in шляхи[1:]):
        парсер.error('в основі вже є архів дошки. Виберіть коміт main до перенесення.')
    до = git('show', f'{основа}:{ДОШКА}')
    дані, причини, без_файлу, відсутні_у_продукті, залишок = розподілити(до, індекс)
    _, закриті, застарілі, робоча = дані
    шапка = '# Застарілі рядки дошки\n\n' + ШАПКА_ТАБЛИЦІ
    примітки = '\n## Причини перенесення\n\n' + ''.join(
        f'- **{номер}.** названих файлів нема: {файли_переліку(файли)}\n' for номер, файли in sorted(причини.items()))
    архів_закрито = ШАПКА_ЗАКРИТИХ.encode() + b''.join(закриті.values())
    архів_застаріле = шапка.encode() + b''.join(застарілі.values()) + примітки.encode()
    обсяг = робоча, архів_закрито, архів_застаріле
    шлях_звіту = Path(__file__).with_name('ЗВІТ.md')
    вміст_звіту = звіт(основа, до, обсяг, дані, без_файлу, відсутні_у_продукті, залишок).encode()
    результат = dict(zip((*шляхи, шлях_звіту), (*обсяг, вміст_звіту)))
    if аргументи.лише_перевірити:
        for шлях, вміст in результат.items():
            if not шлях.is_file() or шлях.read_bytes() != вміст:
                парсер.exit(1, f'Вміст {шлях.relative_to(РЕПОЗИТОРІЙ)} відрізняється від очікуваного.\n')
        print(f'Збіглися всі {len(результат)} файли, номери й байти рядків.')
    else:
        for шлях, вміст in результат.items():
            шлях.parent.mkdir(parents=True, exist_ok=True)
            шлях.write_bytes(вміст)



if __name__ == '__main__':
    головна()
