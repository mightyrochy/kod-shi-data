def розібрати_json(текст):
    текст = текст.strip()
    if текст.startswith("```") and текст.endswith("```"):
        текст = текст.split("\n", 1)[1][:-3].strip()
    return json.loads(текст) if текст.startswith("{") else {}


def номер(рядок):
    збіг = НОМЕР.fullmatch(рядок.strip()) if isinstance(рядок, str) else None
    return f"#{збіг[1]}·{збіг[2]}" if збіг else None


def траси():
    ключі = defaultdict(list)
    for шлях in git("ls-tree", "-r", "--name-only", "-z", BASE, ПОВТОР).decode().split("\0"):
        if not шлях.endswith("/вимір_меж.jsonl.gz"):
            continue
        сцена = Path(шлях).parent.name
        for р in рядки(шлях):
            м = json.loads(р["рядок"])
            if not м.get("рядки") or "43400" not in м["межі"]:
                continue
            відбитки = defaultdict(set)
            for к, іди in м["рядки"].items():
                відбитки[відбиток(json.loads(к))].update(іди)
            ключі[сцена, str(р["прохід"])].append((відбитки, set(м["межі"]["43400"]["ід"]), м["сід"]))
    return ключі


def звірені_траси():
    кандидати = траси()
    зведено = {}
    for р in рядки(f"{ПОВТОР}/журнал_моста.jsonl.gz"):
        if р.get("запис") is None or "запит" not in р:
            continue
        сцена, прохід, індекс = р["сит"], р["прохід"], р["запис"]
        ключі = {відбиток(x) for x in записи_таблиці(json.loads(р["запит"]))}
        for відбитки, зріз, сід in кандидати[сцена, прохід]:
            збіг = len(set().union(*(відбитки.get(k, ()) for k in ключі)) & зріз) / len(зріз)
            if збіг >= 0.9 and збіг > зведено.get((сцена, прохід, індекс), (0, None, None))[0]:
                зведено[сцена, прохід, індекс] = збіг, відбитки, сід
    return зведено


def кращі_відповідності(рядки_пулу, відбитки):
    """Підтвердити коди крамниць за однозначними рядками цього самого історичного запиту."""
    видимі = {n: відбитки.get(відбиток(r), set()) for r in рядки_пулу if (n := номер(r.get("n")))}
    голоси = defaultdict(Counter)
    for n, іди in видимі.items():
        крамниці = {крамниця(i) for i in іди}
        if len(крамниці) == 1:
            голоси[n.split("·")[1]].update(крамниці)
    впізнано = {код: next(iter(c)) for код, c in голоси.items() if len(c) == 1 and c.total() >= 2}
    повторні = Counter(впізнано.values())
    for n, іди in видимі.items():
        магазин = впізнано.get(n.split("·")[1], "")
        if магазин and повторні[магазин] == 1:
            видимі[n] = {i for i in іди if крамниця(i) == магазин}
    return видимі


def властивості(іди, картки):
    дані = [картки[i] for i in іди if i in картки]
    ціни = [r["ціна"] for r in дані if r["ціна"] is not None]
    return {
        "речей": len(іди),
        "у_повному_фіді": len(дані),
        "з_фото": sum(bool(r["фото"]) for r in дані),
        "медіана_фото": statistics.median(r["фото"] for r in дані) if дані else None,
        "з_описом": sum(bool(r["довжина_опису"]) for r in дані),
        "медіана_довжини_опису": statistics.median(r["довжина_опису"] for r in дані) if дані else None,
        "з_ціною": len(ціни),
        "медіана_ціни": statistics.median(ціни) if ціни else None,
    }


def вибір_стилістки(картки, вихід):
    зведено = звірені_траси()
    групи = defaultdict(Counter)
    появи, вибори = Counter(), Counter()
    непевні_переможці = set()
    лічба = Counter()
    запити = [("ситуація", "прохід", "рядок_джерела", "запис_моста", "рядків_пулу", "взятих_номерів",
               "взято_поза_пулом", "збіг_траси", "сід_траси", "зіставлено_крамниць",
               "зіставлено_речей", "виборів_з_ід")]
    джерела = git("ls-tree", "-r", "--name-only", "-z", BASE, МІСТ).decode().split("\0")
    for шлях in sorted(s for s in джерела if s.endswith("/обміни.jsonl")):
        сцена = Path(шлях).parent.name
        лічба["сцен"] += 1
        черга = Counter()
        for лінія, обмін in enumerate(рядки(шлях), 1):
            if not обмін.get("відповідь"):
                continue
            прохід = str(обмін["прохід"])
            індекс = черга[прохід]
            черга[прохід] += 1
            if обмін.get("статус") != 200:
                continue
            тіло = json.loads(обмін["запит"])
            try:
                пакет = розібрати_json(текст_запиту(тіло))
            except (ValueError, IndexError):
                continue
            if not (isinstance(пакет.get("pool"), dict) and "rows" in пакет["pool"]):
                continue
            лічба["запитів_з_пулом"] += 1
            blocks = json.loads(обмін["відповідь"]).get("content", [])
            try:
                відповідь = розібрати_json("".join(б["text"] for б in blocks if б.get("type") == "text"))
            except (ValueError, IndexError):
                continue
            if not isinstance(відповідь.get("outfits"), list):
                continue
            rs = записи_таблиці(пакет)
            if not rs:
                continue
            лічба["запитів_з_образами"] += 1
            лічба["запитів_з_фото"] += any(б.get("type") == "image" for m in тіло["messages"]
                                           for б in m["content"] if isinstance(m["content"], list))
            взято = {n for o in відповідь["outfits"] for x in o.get("items", []) if (n := номер(x))}
            лічба["нерозібраних_посилань"] += sum(номер(x) is None for o in відповідь["outfits"] for x in o.get("items", []))
            номери = {номер(r.get("n")) for r in rs}
            assert len(номери - {None}) == sum(bool(номер(r.get("n"))) for r in rs)
            поза = len(взято - номери)
            лічба["посилань_поза_пулом"] += поза
            збіг, відбитки, сід = зведено.get((сцена, прохід, індекс), (None, {}, None))
            лічба["запитів_зі_слідом"] += збіг is not None
            відповідності = кращі_відповідності(rs, відбитки)
            крамниць, ідзі, виборів = 0, 0, 0
            ід_запиту = {}
            for i, r in enumerate(rs):
                n = номер(r.get("n"))
                обрано = n in взято
                дециль = 1 + i * 10 // len(rs)
                групи["позиція", дециль]["показано"] += 1
                групи["позиція", дециль]["взято"] += обрано
                можливі = відповідності.get(n, set())
                магазини = {крамниця(ід) for ід in можливі}
                if len(магазини) == 1:
                    групи["крамниця", next(iter(магазини))]["показано"] += 1
                    групи["крамниця", next(iter(магазини))]["взято"] += обрано
                    крамниць += 1
                if len(можливі) == 1:
                    ід = next(iter(можливі))
                    ід_запиту[ід] = обрано or ід_запиту.get(ід, False)
                    ідзі += 1
                    виборів += обрано
                elif обрано:
                    непевні_переможці.update(можливі)
            появи.update(ід_запиту.keys())
            вибори.update(i for i, обрано in ід_запиту.items() if обрано)
            лічба["показів_у_зіставлених_запитах"] += len(rs) if збіг is not None else 0
            лічба["виборів_у_зіставлених_запитах"] += len(взято & номери) if збіг is not None else 0
            лічба["зіставлено_показів_до_ід"] += ідзі
            лічба["зіставлено_виборів_до_ід"] += виборів
            запити.append((сцена, прохід, лінія, індекс, len(rs), len(взято & номери), поза,
                           round(збіг, 6) if збіг is not None else "", сід, крамниць, ідзі, виборів))
    сумарно = Counter()
    for (вісь, _), ч in групи.items():
        if вісь == "позиція":
            сумарно.update(ч)
    крамниці_відомі = sum((ч for (вісь, _), ч in групи.items() if вісь == "крамниця"), Counter())
    групи["крамниця", "невідома"] = сумарно - крамниці_відомі
    for к in ("показано", "взято"):
        лічба[f"загалом_{к}"] = сумарно[к]
        лічба[f"крамниця_відома_{к}"] = крамниці_відомі[к]

    регулярні = {i for i, n in появи.items() if n >= ЧАСТО}
    взяті = {i for i in регулярні if вибори[i]}
    жодного = регулярні - взяті - непевні_переможці
    таблиця(вихід / "вибір-запити.csv", запити)
    таблиця(вихід / "вибір-групи.csv", [
        ("групування", "група", "показано", "взято", "частка"),
        *((вісь, к, ч["показано"], ч["взято"], round(ч["взято"] / ч["показано"], 8))
          for (вісь, к), ч in sorted(групи.items()) if ч["показано"]),
    ])
    таблиця(вихід / "вибір-речі.csv", [
        ("ід", "крамниця", "однозначно_показано", "однозначно_взято", "можливий_неоднозначний_вибір",
         "у_повному_фіді", "фото", "довжина_опису", "ціна"),
        *((i, крамниця(i), n, вибори[i], i in непевні_переможці, i in картки,
           *(картки.get(i, {}).get(k) for k in ("фото", "довжина_опису", "ціна")))
          for i, n in sorted(появи.items())),
    ])
    return {
        "лічба": dict(лічба),
        "децилі": {str(n): групи["позиція", n] for n in range(1, 11)},
        "від_скількох_появ_часто": ЧАСТО,
        "речей_часто": len(регулярні),
        "можливий_неоднозначний_вибір_серед_частих": len(регулярні & непевні_переможці - взяті),
        "часті_взято": властивості(взяті, картки),
        "часті_жодного_разу": властивості(жодного, картки),
    }


