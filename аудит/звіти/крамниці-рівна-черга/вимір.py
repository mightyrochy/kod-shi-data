def вхід(каталог, фільтри, смуга):
    from композитор_слоти import пізні_слота
    from пакет_моделі import рядки_кандидатів
    import семплер

    підготовлено = {}
    for слот, фільтр in фільтри.items():
        ранг = пізні_слота(слот, ошатність=смуга)
        групи = {}
        for річ in sorted(каталог, key=lambda r: r["id"]):
            if річ.get("слот") == слот and фільтр(річ):
                групи.setdefault(річ.get("group_id") or річ["id"], річ)
        # Одна річ із групи варіантів, як у доборі композитора, зі сталим представником.
