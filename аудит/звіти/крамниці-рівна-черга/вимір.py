def повний_фід():
    картки = {}
    with gzip.GzipFile(fileobj=BytesIO(файл("каталог_повний.xml.gz"))) as потік:
        for _, o in XML.iterparse(потік, events=("end",)):
            if o.tag != "offer":
                continue
            магазин = o.findtext("param[@name='магазин']")
            ід = o.attrib["id"]
            опис = " ".join(" ".join(x.itertext()) for x in o.findall("description"))
            опис = " ".join(re.sub(r"<[^>]+>", " ", опис).split())
            ціна = o.findtext("price")
            картки[f"{ід}@{магазин}"] = {
                "крамниця": магазин,
                "фото": len({x.text for x in o.findall("picture") if x.text}),
                "довжина_опису": len(опис),
                "ціна": float(ціна) if ціна else None,
            }
            o.clear()
    return картки


