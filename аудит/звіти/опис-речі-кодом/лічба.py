def прочитати_tsv(шлях):
    with open(шлях, encoding="utf-8") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def свотчі(набір):
    """{номер: [hex, …]} — підібрані власником середини, інакше визнаний ним свотч коду (ПІСЛЯ, тоді ДО)."""
    ключ = json.loads((ОГЛЯД / f"ключ_{набір}.json").read_text(encoding="utf-8"))["речі"]
    результат = {}
    for р in прочитати_tsv(ОГЛЯД / f"лічба_{набір}_власник.tsv"):
        н = int(р["номер"])
        if н > 40:
            continue
        перший = р["середина_1_hex_OKLab"].split(" | ")[0]
        другий = р["середина_2_hex_OKLab"].split(" | ")[0]
        if not перший:
            for стан in ("ПІСЛЯ", "ДО"):
                if р[f"{стан}_більшість"] == "п":
                    перший = ключ[str(н)][стан]["hex"]
                    break
        if перший:
            результат[н] = [перший] + ([другий] if другий else [])
    return результат


@lru_cache(maxsize=None)
def lab_манселла(H, V, C):
    H = 5.0 if H is None else H
    H = H + 100 if H < 1 else H
    C = max(float(C), 1e-6)
    V = min(float(V), 9.99)
    V_пряме = max(V, 1.0)
    while True:
        try:
            lab, _ = ПРЯМЕ(H, V_пряме, C)
            break
        except Exception:
            if C <= 1e-6:
                raise
            C = max(1e-6, C - 0.25)
    lab = tuple(map(float, lab))
    if V < 1:
        Y = float(colour.notation.munsell.luminance_ASTMD1535(V)) / 100
        L = 116 * Y ** (1 / 3) - 16 if Y > 216 / 24389 else 24389 / 27 * Y
        lab = (L, lab[1], lab[2])
    return lab


def манселл_свотча(hex_):
    try:
        return блоки.свотч_у_munsell(hex_)
    except ValueError:
        lab = простір.hx(hex_)
        if lch(lab)[1] > 0.5:
            raise
        xyz = простір.to_xyz(lab)
        V = float(colour.notation.munsell.munsell_value_ASTMD1535(min(float(xyz[1]) * 100, 100.0)))
        return (30.0, min(V, 10.0), 0.0)


def de2000(a, b):
    return float(colour.delta_E(a, b, method="CIE 2000"))


def ознаки(lab):
    L, C, _ = lch(lab)
    т = КТ.тепло_кольору(lab)
    return {
        "родини": frozenset(к for к, _ in КТ.сім_ї_кольору(lab)),
        "підтон": "не визначено" if т is None else "тепле" if т > 0 else "холодне" if т < 0 else "межа",
        "L": L,
        "хрома": "тон не визначений" if C <= JND else "гучний" if C >= ГУЧНИЙ_C else "тихий",
    }


