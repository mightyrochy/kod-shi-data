def відхилення(пари_):
    """Скільки бракує клітинці сітки, щоб містити свотч, по кожній осі: [(вісь, C клітинки, нестача)]."""
    рядки = []
    for _, _, _, (H, V, C), _, _, к in пари_:
        if к is None or к["різні"]:
            continue
        д = З.ділянка(к, НУЛЬ)
        if к["V"] is not None:
            рядки.append(("V", 0.0, max(д["V"][0] - V, V - д["V"][1], 0.0)))
        if к["C"] is not None:
            сер = (к["C"][0] + к["C"][1]) / 2
            рядки.append(("C", сер, max(д["C"][0] - C, C - д["C"][1], 0.0)))
            if д["H"] is not None and C > 0.5:
                від, до = д["H"]
                нестача = 0.0 if (H - від) % 100 <= (до - від) % 100 else min((від - H) % 100, (H - до) % 100)
                рядки.append(("H", сер, нестача))
    return рядки


def калібрувати(пари_, покриття):
    """Найвужчий допуск кожної осі, що покриває задану частку свотчів калібрування."""
    в = відхилення(пари_)
    по = lambda вісь: [(c, н) for о, c, н in в if о == вісь]
    квантиль = lambda xs: sorted(xs)[min(len(xs) - 1, math.ceil(покриття * len(xs)) - 1)]
    д = dict(НУЛЬ)
    д["V"] = round(квантиль([н for _, н in по("V")]), 2)
    найкраще = None
    for a in [x / 4 for x in range(0, 17)]:
        for b in [x / 20 for x in range(0, 11)]:
            xs = по("C")
            if sum(н <= a + b * c + 1e-9 for c, н in xs) >= покриття * len(xs):
                ціна = statistics.mean(a + b * c for c, _ in xs)
                if найкраще is None or ціна < найкраще[0]:
                    найкраще = (ціна, a, b)
    д["C_a"], д["C_b"] = найкраще[1], найкраще[2]
    найкраще = None
    for h0 in [x / 2 for x in range(0, 31)]:
        for h1 in [x / 2 for x in range(0, 41)]:
            xs = по("H")
            if sum(н <= h0 + h1 / max(c, 1.0) + 1e-9 for c, н in xs) >= покриття * len(xs):
                ціна = statistics.mean(h0 + h1 / max(c, 1.0) for c, _ in xs)
                if найкраще is None or ціна < найкраще[0]:
                    найкраще = (ціна, h0, h1)
    д["H_0"], д["H_1"] = найкраще[1], найкраще[2]
    return д


# ─── ознаки ділянки ───
def точки_ділянки(д, кроків=4):
    V = [min(max(д["V"][0] + (д["V"][1] - д["V"][0]) * i / (кроків - 1), 0.6), 9.9) for i in range(кроків)]
    C = [д["C"][0] + (д["C"][1] - д["C"][0]) * i / (кроків - 1) for i in range(кроків)]
    if д["H"] is None:
        H = [float(x) for x in range(5, 101, 10)]
    else:
        дуга = (д["H"][1] - д["H"][0]) % 100
        H = [(д["H"][0] + дуга * i / (кроків - 1) - 1e-9) % 100 + 1e-9 for i in range(кроків)]
    return [lab_манселла(round(h, 3), round(v, 3), round(c, 3)) for h in H for v in V for c in C]


def порівняти_ознаки(свотч_lab, точки):
    """Для кожної ознаки: «певно» — та сама в усіх точках ділянки; «можливо» — хоч в одній; «хибно»."""
    с = ознаки(свотч_lab)
    о = [ознаки(т) for т in точки]
    збіги = {
        "родина": [bool(с["родини"] & x["родини"]) for x in о],
        "підтон": [с["підтон"] == x["підтон"] for x in о],
        "світлота": [abs(с["L"] - x["L"]) < КРОК_L for x in о],
        "хрома": [с["хрома"] == x["хрома"] for x in о],
    }
    return {к: "певно" if all(v) else "можливо" if any(v) else "хибно" for к, v in збіги.items()}


def лічба_кольору(набір, прогін, допуск):
    рядки = []
    for номер, поз, h, (H, V, C), lab, рядок, к in пари(набір, прогін):
        р = dict(набір=набір, номер=номер, позиція=поз, свотч=h, свотч_HVC=f"{H:.1f} {V:.2f} {C:.2f}", колір=рядок or "")
        if к is None:
            рядки.append(р | dict(у_ділянці="нема запису"))
            continue
        д = З.ділянка(к, допуск)
        т = точка(к)
        р["у_клітинці"] = "так" if З.у_ділянці(З.ділянка(к, НУЛЬ), H, V, C) else "ні"
        р["у_ділянці"] = "так" if З.у_ділянці(д, H, V, C) else "ні"
        р["ширина_H"] = 100.0 if д["H"] is None else round((д["H"][1] - д["H"][0]) % 100, 2)
        р["ширина_V"] = round(д["V"][1] - д["V"][0], 2)
        р["ширина_C"] = round(д["C"][1] - д["C"][0], 2)
        if т is not None:
            р["ΔE2000_середини"] = round(de2000(т, lab), 2)
            for ознака, v in порівняти_ознаки(lab, [т]).items():
                р[f"середина_{ознака}"] = "так" if v == "певно" else "ні"
        for ознака, v in порівняти_ознаки(lab, точки_ділянки(д)).items():
            р[f"ділянка_{ознака}"] = v
        рядки.append(р)
    return рядки


def звести(рядки):
    n = len(рядки)
    є = [р for р in рядки if "ширина_V" in р]
    т = [р for р in є if "ΔE2000_середини" in р]
    лік = lambda поле, зн, з=None: sum(р.get(поле) == зн for р in (рядки if з is None else з))
    return {
        "свотчів": n,
        "у_клітинці_без_допуску": лік("у_клітинці", "так"),
        "у_ділянці": лік("у_ділянці", "так"),
        "ширина_медіана": {о: statistics.median(р[f"ширина_{о}"] for р in є) for о in "HVC"},
        "ΔE2000_середини_медіана": round(statistics.median(р["ΔE2000_середини"] for р in т), 2),
        "середина": {о: лік(f"середина_{о}", "так") for о in ("родина", "підтон", "світлота", "хрома")},
        "середина_з": len(т),
        "ділянка": {о: {v: лік(f"ділянка_{о}", v) for v in ("певно", "можливо", "хибно")}
                    for о in ("родина", "підтон", "світлота", "хрома")},
    }


