def без_частки(колір):
    return колір.rsplit(" ", 1)[0] if колір.endswith("%") else колір


def пам_ять(прогін):
    """{слова кольору: {фішка: скільки разів}} — як один прогін переклав ті самі слова в різних речах."""
    п = {}
    for річ in прогін.values():
        for колір, слова in річ["слова"]:
            п.setdefault(слова, {}).setdefault(без_частки(колір), 0)
            п[слова][без_частки(колір)] += 1
    return п


def з_пам_яттю(річ, пам):
    """Запис, у якому фішку кожного кольору взято з пам'яті за його словами (перша записана фішка слів)."""
    за_кольором = {к: пам[с] for к, с in річ["слова"] if с in пам}
    зам = lambda к: (за_кольором[к] + к[len(без_частки(к)):]) if к in за_кольором else к
    новий = []
    for ч in річ["запис"]:
        ч = dict(ч)
        if "кольори" in ч:
            ч["кольори"] = [зам(к) for к in ч["кольори"]]
        if "візерунок" in ч:
            ч["візерунок"] = [{**ш, **({"кольори": [зам(к) for к in ш["кольори"]]} if "кольори" in ш else {})}
                              for ш in ч["візерунок"]]
        новий.append(ч)
    return З.перевірити(новий)


def у_допуску(а, б, допуск):
    """Чи кожен колір запису б лежить серединою фішки в ділянці відповідного кольору запису а (ті самі поля решти)."""
    ка, кб = З.кольори_запису(а), З.кольори_запису(б)
    if len(ка) != len(кб):
        return False
    for x, y in zip(ка, кб):
        рx, рy = З.розібрати_колір(x), З.розібрати_колір(y)
        if рx["різні"] or рy["різні"]:
            if рx["різні"] != рy["різні"]:
                return False
            continue
        H, V, C = З.середина(рy)
        д = З.ділянка(рx, допуск)
        if V is not None and not (д["V"][0] <= V <= д["V"][1]):
            return False
        if C is not None and not (д["C"][0] <= C <= д["C"][1]):
            return False
        if H is not None and д["H"] is not None and (C or 0) > 0.5 and \
                (H - д["H"][0]) % 100 > (д["H"][1] - д["H"][0]) % 100:
            return False
    return True


