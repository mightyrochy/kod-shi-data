def прочитати_прогін(тека, n):
    шлях = тека / f"переклад_{n}.json"
    if not шлях.exists():
        return None
    сирі = json.loads(шлях.read_text(encoding="utf-8"))
    результат = {}
    for ключ, річ in сирі.items():
        try:
            канон, хиба = З.перевірити(річ["запис"]), ""
        except (З.Хиба, KeyError, TypeError, ValueError) as х:
            канон, хиба = None, str(х)
        результат[ключ] = dict(запис=канон, хиба=хиба, не_лягло=(річ.get("не_лягло") or "").strip(),
                               слова=[(к, " ".join(с.lower().split())) for к, с in річ.get("слова") or []])
    return результат


def кольори_основи(запис):
    """Кольори першої частини — тло й мотиви — за часткою (без частки — у порядку запису)."""
    основа = запис[0]
    усі = list(основа["кольори"]) + [к for шар in основа.get("візерунок", []) for к in шар.get("кольори", [])]
    розібрані = [З.розібрати_колір(к) for к in усі]
    порядок = sorted(range(len(усі)), key=lambda i: (-(розібрані[i]["частка"] or 100), i))
    return [(усі[i], розібрані[i]) for i in порядок]


def точка(к):
    """Lab середини клітинки або None, коли слова не кажуть хоч однієї осі."""
    H, V, C = З.середина(к)
    if V is None or C is None or (H is None and к["H"] != "N"):
        return None
    return lab_манселла(H, V, C)


def призначити(labs_свотчів, кольори):
    """Індекс кольору запису для кожного свотча: один свотч — основний колір; два — найменша сума ΔE2000."""
    if len(labs_свотчів) == 1 or len(кольори) == 1:
        return [0] * len(labs_свотчів)
    точки = [точка(к) for _, к in кольори]
    вартість = lambda i, с: 50.0 if точки[i] is None else de2000(точки[i], с)
    return list(min(itertools.permutations(range(len(кольори)), len(labs_свотчів)),
                    key=lambda п: sum(вартість(i, с) for i, с in zip(п, labs_свотчів))))


def пари(набір, прогін):
    """[(номер, позиція, hex, HVC свотча, Lab свотча, рядок кольору, розібраний колір)] для набору."""
    результат = []
    for номер, hexи in sorted(свотчі(набір).items()):
        річ = прогін.get(f"{набір}/{номер}")
        if not річ or not річ["запис"]:
            результат += [(номер, п + 1, h, манселл_свотча(h), простір.hx(h), None, None) for п, h in enumerate(hexи)]
            continue
        кольори = кольори_основи(річ["запис"])
        labs = [простір.hx(h) for h in hexи]
        for п, (h, i) in enumerate(zip(hexи, призначити(labs, кольори))):
            результат.append((номер, п + 1, h, манселл_свотча(h), labs[п], *кольори[i]))
    return результат


