def перелік(вісь):
    if isinstance(вісь, dict):
        return "; ".join(f"`{к}` — {о}" for к, о in вісь.items())
    return ", ".join(f"`{з}`" for з in вісь)


def головне():
    В, П, Ч = ОСІ["візерунок"], ОСІ["поверхня"], ОСІ["частина"]
    візерунок = [f"- `мотив`: {перелік(В['мотив'])}.",
                 "- `вид` (уточнення мотиву, необов'язкове): " +
                 "; ".join(f"{м} — {перелік(в)}" for м, в in В["вид"].items()) + "."]
    візерунок += [f"- `{вісь}`: {перелік(В[вісь])}." for вісь in В if вісь not in ("мотив", "вид")]
    візерунок.append("- `кольори` — кольори мотиву.")
    поверхня = [f"- `{вісь}`: {перелік(П[вісь])}." for вісь in П]
    поверхня.append(f"- `де` для деталі: {перелік(Ч['де']['деталь'])}; для предмета: {перелік(Ч['де']['предмет'])}.")
    (ТЕКА / "запит_перекладу.md").write_text(
        ПРАВИЛА.format(візерунок="\n".join(візерунок), поверхня="\n".join(поверхня)), encoding="utf-8")
    рядки = []
    with open(КОРІНЬ / "аудит/проби/річ_колір_огляд_людьми/назви.tsv", encoding="utf-8") as ф:
        for р in csv.DictReader(ф, delimiter="\t"):
            рядки.append((f"{р['набір']}/{р['номер']}", р["назва"]))
    for набір, файл in (("важкі", "описи_важких.tsv"), ("важкі2", "описи_важких_2.tsv")):
        if (ТЕКА / файл).exists():
            with open(ТЕКА / файл, encoding="utf-8") as ф:
                for р in csv.DictReader(ф, delimiter="\t"):
                    рядки.append((f"{набір}/{р['номер']}", р["опис"]))
    with open(ТЕКА / "описи.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.writer(ф, delimiter="\t", lineterminator="\n")
        п.writerow(["ключ", "опис"])
        п.writerows(рядки)
    print(len(рядки), "описів;", len((ТЕКА / "запит_перекладу.md").read_text(encoding="utf-8")), "знаків запиту")


if __name__ == "__main__":
    головне()
