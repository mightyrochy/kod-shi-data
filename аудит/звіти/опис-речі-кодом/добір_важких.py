"""Добір найважчих для запису речей каталогу: по одній на вид складності, першими — ті, що несуть кілька видів.

Вид — те, чого чинний перелік продукту `verify.КЛАСИ_МОТИВУ` не має або має лише як «принт», і те, що око бачить
поза кольором і принтом (наряд, «Що є і де ламається»), плюс знайдене в каталозі цією сесією. Слова тут — лише
сито добору кандидатів для проби; у продукті код слів не читає (п.12).

Добір детермінований: вид має бути в назві крамниці (опис крамниць повен слів про інші речі), у виді перемагає
річ із найбільшим числом видів у назві, далі — за sha1 ід; виду нема в жодній назві — те саме за описом.
Річ береться, коли маніфест кадрів знає щонайменше два її кадри зі статусом 200 і шириною ≥ 600.

    python аудит/звіти/опис-речі-кодом/добір_важких.py   → важкі_речі.tsv
"""
import csv
import gzip
import hashlib
import json
import re
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]

ВИДИ = [
    ("напис", r"напис|слоган|літер|lettering"),
    ("логотип", r"логотип|лого\b|монограм"),
    ("орнамент", r"орнамент|етно|вишиванк"),
    ("ромб", r"ромб|аргайл"),
    ("ялинка-лапка", r"ялинк|гусяч|лапк|пепіта"),
    ("твід-букле", r"твід|букле"),
    ("паєтки", r"паєтк|пайєтк"),
    ("люрекс-метал", r"люрекс|металік|металев(ий|им) блиск|ламе\b|фольг"),
    ("меланж", r"меланж"),
    ("малюнок", r"малюнк|малюнок|зображенн"),
    ("жакард", r"жакард"),
    ("листя", r"лист(я|ям|ков)|тропік|тропіч|пальм"),
    ("градієнт", r"градієнт|омбре|деграде"),
    ("тай-дай", r"тай[- ]?дай|tie[- ]?dye|батик"),
    ("прозоре", r"прозор|органз|шифон|сітк(а|и|ою|у)\b"),
    ("шкіра", r"екошкір|еко-шкір|шкірян|лакован"),
    ("деним", r"джинс|денім|деним|варен|потертост"),
    ("хутро", r"хутр|екохутр|тедді"),
    ("мереживо", r"мережив|гіпюр|кружев"),
    ("вишивка", r"вишивк|вишит|аплікац"),
    ("кольороблок", r"кольороблок|колор-?блок|color ?block|двоколірн|контрастн(і|ими) вставк"),
    ("печворк", r"печворк|клапт"),
    ("анімалістичний", r"леопард|зебр|зміїн|пітон|тигров|анімаліст"),
    ("пейслі", r"пейслі|огірк|турецьк(ий|им) огір"),
    ("камуфляж", r"камуфляж|мілітарі принт"),
    ("абстракція", r"абстрак|мармур|розвод|акварел"),
    ("плісе", r"плісе|плісир|гофр"),
    ("оксамит", r"оксамит|велюр|вельвет"),
    ("стьобане", r"стьоб|стеган"),
    ("в'язка-коси", r"\bкос(и|ами)\b|ажурн|араны|аранськ"),
    ("оздоба", r"бахром|пір'я|страз|намистин|перлин|люверс|заклеп"),
    ("клітинка-складна", r"тартан|шотландк|віші|принц уельськ|глен"),
    ("горох", r"горох|горошок"),
    ("смужка-складна", r"різнокольоров(а|у|ій) смуж|багатоколірн|смуж.{0,40}різн(ої|ою) ширин"),
    ("блиск", r"атлас|сатин|шовк|блиск|глянц|перламутр"),
    ("геометрія", r"геометр|зигзаг|шеврон"),
]
ВИДИ = [(назва, re.compile(зразок)) for назва, зразок in ВИДИ]


def головне():
    маніфест = json.load(gzip.open(КОРІНЬ / "каталог_маніфест_кадрів.json.gz", "rt", encoding="utf-8"))["кадри"]
    кандидати = {назва: [] for назва, _ in ВИДИ}
    лічба = {назва: 0 for назва, _ in ВИДИ}
    усіх = 0
    with gzip.open(КОРІНЬ / "каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8") as ф:
        for рядок in ф:
            р = json.loads(рядок)
            if "ід" not in р:
                continue
            усіх += 1
            текст = ((р.get("назва") or "") + " " + (р.get("опис") or "")).lower()
            мої = [назва for назва, зразок in ВИДИ if зразок.search(текст)]
            for назва in мої:
                лічба[назва] += 1
            if not мої or not р["ід"].startswith("ж-"):
                continue
            кадри = [к for к in р.get("кадри", []) if маніфест.get(к, [0])[0] == 200 and маніфест[к][2] >= 600]
            if len(кадри) < 2:
                continue
            у_назві = [назва for назва, зразок in ВИДИ if зразок.search((р.get("назва") or "").lower())]
            for назва in мої:
                кандидати[назва].append((назва not in у_назві, -len(у_назві), hashlib.sha1(р["ід"].encode()).hexdigest(), р["ід"], мої,
                                         р.get("назва") or "", р.get("адреса") or "", кадри[:4]))
    взято, рядки = set(), []
    for назва, _ in ВИДИ:
        for _, _, _, ід, мої, назва_речі, адреса, кадри in sorted(кандидати[назва]):
            if ід not in взято:
                взято.add(ід)
                рядки.append([len(рядки) + 1, ід, назва, " ".join(мої), лічба[назва], назва_речі, адреса,
                              " ".join(кадри)])
                break
    with open(ТЕКА / "важкі_речі.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.writer(ф, delimiter="\t", lineterminator="\n")
        п.writerow(["номер", "ід", "вид_добору", "види_в_тексті", "речей_каталогу_з_видом", "назва_крамниці",
                    "адреса", "кадри"])
        п.writerows(рядки)
    print(f"записів {усіх}; дібрано {len(рядки)}")
    for назва, _ in ВИДИ:
        print(f"{назва}\t{лічба[назва]}")


if __name__ == "__main__":
    головне()
