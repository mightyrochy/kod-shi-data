"""Запис «річ кодом» (проба): розбір, перевірка, канонічний вигляд, ділянка кольору.

Будова (повний опис — `ЗВІТ.md`, «Будова запису»; значення осей — `осі.json`, єдине джерело й для запиту
перекладачеві, і для перевірки):

    Запис   = [Частина, …]                      перша — основа речі
    Частина = {що?, де?, частка?, кольори, візерунок?, матеріал?, блиск?, прозорість?, рельєф?, ворс?, нитка?,
               обробка?, оздоба?}
    Шар     = {мотив, вид?, масштаб?, розміщення?, напрям?, порядок?, край?, лінія?, техніка?, кольори?}
    Колір   = "ТОН СВІТЛОТА/ХРОМА ЧАСТКА%" — клітинка сітки Манселла; «?» — слова осі не кажуть; «a..b» — проміжок;
              «N 9.5» — без тону; «різні» — кілька різних тонів, яких слова не називають.

Поля нема — «не сказано». Запис нічого не знає про допуск слів: ділянку кольору, з якою рахують читачі, дає
`ділянка()` — клітинка, розширена допуском `ДОПУСК` (один на весь каталог, відкалібрований `лічба.py` на свотчах
власника; зміна допуску не потребує переопису жодної речі).
"""
import json
import re
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
ОСІ = json.loads((ТЕКА / "осі.json").read_text(encoding="utf-8"))
СЕКТОРИ = ("R", "YR", "Y", "GY", "G", "BG", "B", "PB", "P", "RP")
КРОКИ_ТОНУ = (2.5, 5.0, 7.5, 10.0)
ХРОМИ = (1, 2, 3, 4, 6, 8, 10, 12, 14, 16)
ПОЛЯ_ЧАСТИНИ = ("що", "де", "частка", "кольори", "візерунок", "матеріал", "блиск", "прозорість", "рельєф", "ворс",
                "нитка", "обробка", "оздоба")
ПОЛЯ_ШАРУ = ("мотив", "вид", "масштаб", "розміщення", "напрям", "порядок", "край", "лінія", "техніка", "кольори")
СПИСКОВІ = ("рельєф", "обробка", "оздоба")
# Допуск слів понад клітинку сітки: (V, C = a + b·C, H = h0 + h1 / max(C, 1)); калібрування — `лічба.py`, sproba1.
ДОПУСК = json.loads((ТЕКА / "допуск.json").read_text(encoding="utf-8")) if (ТЕКА / "допуск.json").exists() else \
    {"V": 0.0, "C_a": 0.0, "C_b": 0.0, "H_0": 0.0, "H_1": 0.0}


class Хиба(ValueError):
    pass


def значення(вісь):
    return list(вісь) if isinstance(вісь, (dict, list)) else вісь


# ─── колір ───
def _тон(s):
    if s == "N":
        return "N"
    м = re.fullmatch(r"(\d+(?:\.\d+)?)(RP|YR|GY|BG|PB|R|Y|G|B|P)", s)
    if not м or float(м[1]) not in КРОКИ_ТОНУ:
        raise Хиба(f"тон поза сіткою: {s}")
    H = 10 * СЕКТОРИ.index(м[2]) + float(м[1])
    return H if H <= 100 else H - 100


def _вісь(s, розбір):
    """«a», «a..b» чи «?» → (низ, верх) у значеннях сітки або None."""
    if s == "?":
        return None
    кінці = s.split("..")
    if len(кінці) > 2:
        raise Хиба(f"проміжок: {s}")
    return розбір(кінці[0]), розбір(кінці[-1])


def _світлота(s):
    x = float(s)
    if not (0.5 <= x <= 9.5 and (2 * x).is_integer()):
        raise Хиба(f"світлота поза сіткою: {s}")
    return x


def _хрома(s):
    x = float(s)
    if x not in ХРОМИ:
        raise Хиба(f"хрома поза сіткою: {s}")
    return x


def розібрати_колір(рядок):
    """Рядок кольору → {H, V, C: (низ, верх) | None — «не сказано»; ахроматичний: H «N»; частка: int | None}."""
    слова = рядок.split()
    частка = None
    if слова and слова[-1].endswith("%"):
        частка = int(слова.pop()[:-1])
        if not (0 < частка <= 100 and частка % 5 == 0):
            raise Хиба(f"частка: {рядок}")
    if слова == ["різні"]:
        return dict(різні=True, H=None, V=None, C=None, частка=частка)
    if len(слова) != 2:
        raise Хиба(f"колір: {рядок}")
    тон, решта = слова
    if тон == "N":
        if "/" in решта:
            raise Хиба(f"N без хроми: {рядок}")
        return dict(різні=False, H="N", V=_вісь(решта, _світлота), C=(0.0, 0.0), частка=частка)
    if "/" not in решта:
        raise Хиба(f"нема хроми: {рядок}")
    v, c = решта.split("/")
    H = _вісь(тон, _тон)
    if H and "N" in H:
        raise Хиба(f"N у проміжку тону: {рядок}")
    return dict(різні=False, H=H, V=_вісь(v, _світлота), C=_вісь(c, _хрома), частка=частка)


def ділянка(колір, допуск=None):
    """Ділянка Манселла, з якою рахують читачі: H — дуга (від, до) кроків ASTM за годинниковою чи None (усе коло),
    V і C — (низ, верх). Клітинка сітки (пів кроку в кожен бік) плюс допуск слів."""
    д = ДОПУСК if допуск is None else допуск
    к = розібрати_колір(колір) if isinstance(колір, str) else колір
    V = (0.0, 10.0) if к["V"] is None else (max(0.0, к["V"][0] - 0.25 - д["V"]), min(10.0, к["V"][1] + 0.25 + д["V"]))
    if к["H"] == "N":
        return dict(H=None, V=V, C=(0.0, 0.5 + д["C_a"]))
    if к["C"] is None:
        C, середина = (0.0, 20.0), 6.0
    else:
        пів = lambda c: 0.5 if c <= 4 else 1.0
        C = (max(0.0, к["C"][0] - пів(к["C"][0]) - д["C_a"] - д["C_b"] * к["C"][0]),
             к["C"][1] + пів(к["C"][1]) + д["C_a"] + д["C_b"] * к["C"][1])
        середина = (к["C"][0] + к["C"][1]) / 2
    if к["H"] is None:
        H = None
    else:
        пів = 1.25 + д["H_0"] + д["H_1"] / max(середина, 1.0)
        дуга = (к["H"][1] - к["H"][0]) % 100 + 2 * пів
        H = None if дуга >= 100 else ((к["H"][0] - пів) % 100, (к["H"][1] + пів) % 100)
    return dict(H=H, V=V, C=C)


def середина(колір):
    """Точка для показу й відстаней: середина клітинки; None для осі, якої слова не кажуть."""
    к = розібрати_колір(колір) if isinstance(колір, str) else колір
    сер = lambda п: None if п is None else (п[0] + п[1]) / 2
    if к["H"] == "N":
        return (None, сер(к["V"]), 0.0)
    H = None if к["H"] is None else (к["H"][0] + ((к["H"][1] - к["H"][0]) % 100) / 2 - 1) % 100 + 1
    return (H, сер(к["V"]), сер(к["C"]))


def у_ділянці(д, H, V, C):
    if not (д["V"][0] <= V <= д["V"][1] and д["C"][0] <= C <= д["C"][1]):
        return False
    return д["H"] is None or C <= 0.5 or (H - д["H"][0]) % 100 <= (д["H"][1] - д["H"][0]) % 100


# ─── перевірка й канонічний вигляд ───
def _одне(назва, значення_, дозволені):
    if значення_ not in дозволені:
        raise Хиба(f"{назва}: «{значення_}» нема серед {', '.join(дозволені)}")


def _кольори(список, де):
    if not isinstance(список, list) or not список:
        raise Хиба(f"{де}: кольори порожні")
    розібрані = [розібрати_колір(к) for к in список]
    return [к for _, _, к in sorted(((-(р["частка"] or 100), i, к) for i, (р, к) in enumerate(zip(розібрані, список))))]


def перевірити(запис):
    """Перевіряє запис проти `осі.json` і повертає канонічний: поля в сталому порядку, кольори за часткою."""
    if not isinstance(запис, list) or not запис:
        raise Хиба("запис — непорожній список частин")
    В, П, Ч = ОСІ["візерунок"], ОСІ["поверхня"], ОСІ["частина"]
    результат = []
    for i, частина in enumerate(запис):
        зайві = set(частина) - set(ПОЛЯ_ЧАСТИНИ)
        if зайві:
            raise Хиба(f"частина {i + 1}: зайві поля {sorted(зайві)}")
        нова = {}
        if "що" in частина:
            _одне("що", частина["що"], [к for к in Ч["що"] if к != "основа"])
            _одне("де", частина.get("де"), Ч["де"][частина["що"]])
        elif "де" in частина:
            raise Хиба(f"частина {i + 1}: «де» без «що»")
        for поле in ПОЛЯ_ЧАСТИНИ:
            if поле not in частина:
                continue
            x = частина[поле]
            if поле in ("що", "де"):
                нова[поле] = x
            elif поле == "частка":
                if not (isinstance(x, int) and 0 < x < 100 and x % 5 == 0):
                    raise Хиба(f"частка частини: {x}")
                нова[поле] = x
            elif поле == "кольори":
                нова[поле] = _кольори(x, f"частина {i + 1}")
            elif поле == "візерунок":
                шари = []
                for шар in x:
                    зайві = set(шар) - set(ПОЛЯ_ШАРУ)
                    if зайві or "мотив" not in шар:
                        raise Хиба(f"шар: зайві поля {sorted(зайві)} або нема мотиву")
                    новий = {}
                    for п in ПОЛЯ_ШАРУ:
                        if п not in шар:
                            continue
                        if п == "кольори":
                            новий[п] = _кольори(шар[п], "шар")
                        elif п == "вид":
                            _одне("вид", шар[п], В["вид"].get(шар["мотив"], []))
                            новий[п] = шар[п]
                        else:
                            _одне(п, шар[п], значення(В[п]))
                            новий[п] = шар[п]
                    шари.append(новий)
                if шари:
                    нова[поле] = шари
            elif поле in СПИСКОВІ:
                if not isinstance(x, list) or not x:
                    raise Хиба(f"{поле}: непорожній список")
                for з in x:
                    _одне(поле, з, значення(П[поле]))
                нова[поле] = sorted(set(x), key=значення(П[поле]).index)
            else:
                _одне(поле, x, значення(П[поле]))
                нова[поле] = x
        if "кольори" not in нова:
            raise Хиба(f"частина {i + 1}: нема кольорів")
        результат.append(нова)
    return результат


def рядком(запис):
    """Канонічний рядок запису — те, що зберігає каталог і чим міряно довжину."""
    return json.dumps(запис, ensure_ascii=False, separators=(",", ":"))


if __name__ == "__main__":
    import sys
    for шлях in sys.argv[1:]:
        дані = json.loads(Path(шлях).read_text(encoding="utf-8"))
        хиб = 0
        for ключ, річ in дані.items():
            try:
                перевірити(річ["запис"])
            except Хиба as х:
                хиб += 1
                print(шлях, ключ, х)
        print(шлях, len(дані), "записів, хибних", хиб)
