"""Що читачі продукту беруть із запису «річ кодом»: вхід кожного рахунку — кодом із запису, без слів.

Доказ пункту «має сенс»: для кожного запису прогону виводить ті входи, які сьогодні читають рахунки продукту
(перелік читачів із файлами й рядками — `читачі_продукту.md`), і лічить, скільки записів дають читачеві певну
відповідь, а скільки — чесне «невідомо». Пороги — з реєстру продукту (`реєстр_правил.C`), визначення сім'ї й
підтону — `колір_тон`; нічого з цього проба не копіює числом.

Колір читається не точкою, а ділянкою (фішка запису плюс допуск слів): рахунок із порогом відповідає «так», коли
вся ділянка по один бік порога, «ні» — коли по другий, інакше «невідомо» — та сама тризначна логіка, якою продукт
уже читає вікна кольору (`колір_річ.py:963–990`).

    python аудит/звіти/опис-речі-кодом/читачі.py в2   → в2/читачі.tsv, в2/читачі_підсумок.json
"""
import csv
import json
import sys
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
sys.path.insert(0, str(ТЕКА))
import лічба as Л  # noqa: E402
import запис as З  # noqa: E402

ГУЧНИЙ_C = Л.ГУЧНИЙ_C                      # «гучна» річ: C* ≥ hi_C
ІНТЕРЕС_C = float(Л.РЕЄСТР["інтерес_c_мін"]) if "інтерес_c_мін" in Л.РЕЄСТР else 18.0
ТЕМНІ_L, СВІТЛІ_L = 45.0, 70.0             # класи слова `колір_річ.КЛАСИ_КОЛЬОРУ`; траур `occasion.py:22`
ТРАУР_C = 18.0
# клас мотиву, який сьогодні знає продукт (`verify.КЛАСИ_МОТИВУ`), — виводиться з осей запису
КЛАС_ПРОДУКТУ = {"смуга": "смужка", "клітинка": "клітинка", "горох": "горох", "квіти": "квітковий",
                 "шкура": "анімалістичний", "геометрія": "геометричний", "абстракція": "абстрактний"}
ФОРМА = {"горох": "крива", "квіти": "крива", "рослини": "крива", "шкура": "крива", "смуга": "кутова",
         "клітинка": "кутова", "геометрія": "кутова", "поля": "кутова"}   # R-PRN-04, `колір_принти.ФОРМА_МОТИВУ`
БЛИСК = {"матова": 0, "ледь": 1, "шовковиста": 2, "глянцева": 3}           # шкала R-TEX-02


def три(значення, поріг, більше=True):
    """Тризначна відповідь рахунку з порогом за проміжком (низ, верх)."""
    низ, верх = значення
    if низ >= поріг:
        return "так" if більше else "ні"
    if верх < поріг:
        return "ні" if більше else "так"
    return "невідомо"


def вхід_кольору(колір):
    """Проміжки L*, C* і множини сімей та підтонів продукту по всій ділянці кольору."""
    к = З.розібрати_колір(колір)
    if к["різні"]:
        return None
    точки = Л.точки_ділянки(З.ділянка(к))
    оз = [Л.ознаки(т) for т in точки]
    C = [Л.lch(т)[1] for т in точки]
    return dict(L=(min(о["L"] for о in оз), max(о["L"] for о in оз)), C=(min(C), max(C)),
                родини=frozenset().union(*(о["родини"] for о in оз)),
                спільні=frozenset.intersection(*(о["родини"] for о in оз)), підтони={о["підтон"] for о in оз})


def текстура(ч):
    """Код шкали фактури продукту (`суд_річ.ТКАНИНА_ФОРМАЛЬНІСТЬ`) з осей поверхні; None — осі не сказано."""
    м, рельєф, блиск = ч.get("матеріал"), ч.get("рельєф", []), ч.get("блиск")
    if м == "шкіра":
        return "patent" if блиск == "глянцева" else "leather"
    if м == "деним":
        return "denim"
    if "вузлики" in рельєф or ч.get("ворс") == "кучерявий":
        return "tweed-boucle"
    if м == "в'язане":
        return "knit-chunky" if ч.get("товщина") == "товста" or "коси" in рельєф else "knit-fine"
    if м == "трикотаж":
        return "knit-fine"
    if блиск == "шовковиста":
        return "satin"
    if блиск == "глянцева":
        return "smooth-shine"
    if блиск in ("матова", "ледь") and (м == "тканина" or "гладка" in рельєф):
        return "smooth-matte"
    return None


def входи(запис):
    основа = запис[0]
    тло = [вхід_кольору(к) for к in основа["кольори"]]
    усі = [вхід_кольору(к) for к in З.кольори_запису([основа])]
    головний = тло[0]
    р = {}
    if головний is None:
        for поле in ("гучна", "інтерес_хромою", "темна", "світла", "траурна", "родина", "підтон"):
            р[поле] = "невідомо"
    else:
        р["гучна"] = три(головний["C"], ГУЧНИЙ_C)
        р["інтерес_хромою"] = три(головний["C"], ІНТЕРЕС_C)
        р["темна"] = три(головний["L"], ТЕМНІ_L, більше=False)
        р["світла"] = три(головний["L"], СВІТЛІ_L)
        темна, тиха = три(головний["L"], ТЕМНІ_L, False), три(головний["C"], ТРАУР_C, False)
        р["траурна"] = "ні" if "ні" in (темна, тиха) else "так" if (темна, тиха) == ("так", "так") else "невідомо"
        р["родина"] = "+".join(sorted(головний["спільні"])) or "невідомо"   # одна сім'я на всю ділянку
        р["можливих_родин"] = len(головний["родини"])
        р["підтон"] = next(iter(головний["підтони"])) if len(головний["підтони"]) == 1 else "невідомо"
        р["L"] = "%.0f–%.0f" % головний["L"]
        р["C"] = "%.0f–%.0f" % головний["C"]
    р["кольорів"] = len(усі)
    р["частки_є"] = "так" if any(З.розібрати_колір(к)["частка"] for к in З.кольори_запису([основа])) else "ні"
    шари = основа.get("візерунок")
    кольорові = [ш for ш in шари or [] if "кольори" in ш or ш.get("техніка") not in ("рельєф", "ажур")]
    р["є_принт"] = "невідомо" if шари is None else "так" if кольорові else "ні"
    if кольорові:
        ш = кольорові[0]
        р["мотив"] = ш["мотив"] + ("/" + ш["вид"] if "вид" in ш else "")
        р["клас_продукту_сьогодні"] = "камуфляж" if ш.get("вид") == "камуфляж" else \
            КЛАС_ПРОДУКТУ.get(ш["мотив"], "принт")
        р["форма_мотиву"] = {"крива": "крива", "пряма": "кутова"}.get(ш.get("лінія")) or ФОРМА.get(ш["мотив"], "невідомо")
        р["масштаб"] = ш.get("масштаб", "невідомо")
        р["розміщення"] = ш.get("розміщення", "невідомо")
        світлоти = [x["L"] for x in усі if x]
        р["контраст_світлоти_в_принті"] = "невідомо" if len(світлоти) < 2 else \
            три((max(a for a, _ in світлоти) - min(b for _, b in світлоти), max(b for _, b in світлоти) -
                 min(a for a, _ in світлоти)), Л.КРОК_L)
    відблиск = основа.get("відблиск")
    р["блиск_0_3"] = 3 if відблиск in ("металевий", "іскристий") else БЛИСК.get(основа.get("блиск"), "невідомо")
    р["метал"] = "так" if відблиск == "металевий" else "ні" if "блиск" in основа or відблиск else "невідомо"
    р["текстура"] = текстура(основа) or "невідомо"
    р["прозорість"] = основа.get("прозорість", "невідомо")
    р["частин"] = len(запис)
    return р


def головне(тека):
    З.ОСІ = json.loads((тека / "осі.json").read_text(encoding="utf-8"))
    З.ДОПУСК = json.loads((тека / "допуск.json").read_text(encoding="utf-8"))
    прогін = Л.прочитати_прогін(тека, 1)
    рядки = [dict(ключ=к) | входи(р["запис"]) for к, р in прогін.items() if р["запис"]]
    поля = ["ключ", "L", "C", "гучна", "інтерес_хромою", "темна", "світла", "траурна", "родина", "можливих_родин", "підтон",
            "кольорів", "частки_є", "є_принт", "мотив", "клас_продукту_сьогодні", "форма_мотиву", "масштаб", "розміщення",
            "контраст_світлоти_в_принті", "блиск_0_3", "метал", "текстура", "прозорість", "частин"]
    with open(тека / "читачі.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, поля, delimiter="\t", lineterminator="\n", restval="")
        п.writeheader()
        п.writerows(рядки)
    підсумок = {"записів": len(рядки)}
    for поле in ("гучна", "інтерес_хромою", "темна", "світла", "траурна", "родина", "підтон", "є_принт", "блиск_0_3",
                 "метал", "текстура", "прозорість"):
        певні = sum(str(р[поле]) != "невідомо" for р in рядки)
        підсумок[поле] = {"певна_відповідь": певні, "невідомо": len(рядки) - певні}
    підсумок["можливих_родин_медіана"] = Л.statistics.median(р["можливих_родин"] for р in рядки if "можливих_родин" in р)
    принти = [р for р in рядки if р["є_принт"] == "так"]
    підсумок["принтів"] = len(принти)
    підсумок["принт_клас_продукту_сьогодні"] = {к: sum(р["клас_продукту_сьогодні"] == к for р in принти)
                                                for к in sorted({р["клас_продукту_сьогодні"] for р in принти})}
    for поле in ("форма_мотиву", "масштаб", "розміщення", "контраст_світлоти_в_принті"):
        підсумок["принт_" + поле] = {"певна_відповідь": sum(р[поле] != "невідомо" for р in принти),
                                     "невідомо": sum(р[поле] == "невідомо" for р in принти)}
    (тека / "читачі_підсумок.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n",
                                               encoding="utf-8")
    print(json.dumps(підсумок, ensure_ascii=False))


if __name__ == "__main__":
    головне(ТЕКА / sys.argv[1])
