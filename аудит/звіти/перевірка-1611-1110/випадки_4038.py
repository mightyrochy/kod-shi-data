"""Власні випадки перевірки #4038 (голова 9cce11cb): колір → найближча клітинка ґратки основ за ΔE2000.
Запуск із кореня дерева голови: python3 -W ignore <шлях>/випадки_4038.py. Кольори задано числами L,C,h (не з ґратки),
очікувана клітинка — за дугами `palettes.СІМ_Ї` і нарядом."""
import sys
sys.path.insert(0, "джерела")
import palettes as П, міст_основи as МО, colorspace as cs, колір_образу as КО
from колір_простір_перетворення import de00
осн, пор = МО.ґратка_основ()
випадки = [("рожева холодна, світла приглушена h342", 86, 10, 342, "д13·холодна·86·приглушені"),
           ("рожева холодна, центр д2 h356", 86, 10, 356, "д2·холодна·86·приглушені"),
           ("рожева холодна L68 середня h342", 68, 26, 342, "д13·холодна·68·середні"),
           ("червона тепла L68 середня h29", 68, 26, 29, "д1·тепла·68·середні"),
           ("фіолетова холодна L50 середня h298", 50, 35, 298, "д11·холодна·50·середні"),
           ("фіолетова тепла L32 середня h315", 32, 54, 315, "д10·тепла·32·середні"),
           ("помаранчева тепла L86 середня h60", 86, 21, 60, "д3·тепла·86·середні"),
           ("нейтраль L50 C3", 50, 3, 60, "н·нейтраль·50·приглушені"),
           ("рожева тепла L86 середня h33", 86, 17, 33, "СВОЯ тепла рожева (наряд)"),
           ("рожева тепла L68 середня h33", 68, 26, 33, "СВОЯ тепла рожева (наряд)")]
for о, L, C, h, оч in випадки:
    hx = П.hex_з_lab(П.lab_з_lch(L, C, h))
    к = min(пор, key=lambda k: de00(cs.hx(hx), cs.hx(осн[k][0])))
    d = de00(cs.hx(hx), cs.hx(осн[к][0]))
    print("%-42s %s → %-26s %s ΔE2000 %.2f | очікував: %-28s | %s" % (
        о, hx, к, осн[к][0], d, оч, "так" if к == оч else "НІ"))
