"""Відбитки пулів, запитів і час підготовки на одному прогрітому каталозі.

Запуск із кореня дерева правки:
    python3 аудит/звіти/ядро-час-збирання/4939/відбитки.py /tmp/каталог.xml 3d423bd8
Каталог — розпакований каталог_повний.xml.gz. Базовий коміт має бути в історії дерева.
"""
from argparse import ArgumentParser
import gzip
from hashlib import sha256
import json
import os
from pathlib import Path
import subprocess
import sys
from time import perf_counter, process_time
from types import ModuleType
from unittest.mock import patch

МОДУЛІ = ("річ", "пул", "запит", "руки", "протокол")
СЦЕНИ = ("с3", "с5", "с8")
КОРІНЬ = Path(__file__).resolve().parents[4]


def відбиток(дані):
    """Міряє точний порядок полів JSON у UTF-8 без службового пробілу."""
    сума = sha256()
    кодувач = json.JSONEncoder(ensure_ascii=False, separators=(",", ":"))
    for частина in кодувач.iterencode(дані):
        сума.update(частина.encode())
    return сума.hexdigest()


def вкласти_модулі(ядро, модулі):
    """Підключає всі частини одного базового або нового ядра."""
    for імʼя, модуль in модулі.items():
        setattr(ядро, імʼя, модуль)
        sys.modules[модуль.__name__] = модуль


def базові_модулі(ядро, коміт):
    """Бере замінені частини з указаного коміту та їхні спільні дані з дерева."""
    модулі = {імʼя: ModuleType(f"ядро.{імʼя}") for імʼя in МОДУЛІ}
    вкласти_модулі(ядро, модулі)
    for імʼя, модуль in модулі.items():
        шлях = f"джерела/ядро/{імʼя}.py"
        сире = subprocess.check_output(["git", "show", f"{коміт}:{шлях}"], cwd=КОРІНЬ)
        модуль.__file__ = str(КОРІНЬ / шлях)
        модуль.__package__ = "ядро"
        exec(compile(сире, f"{коміт}:{шлях}", "exec"), модуль.__dict__)
    return модулі


def вхід_сцени(назва, версія, каталог):
    """Фіксує однакові записані репліки, жіночий профіль, сід і межу запиту."""
    from ядро.тести import ситуації

    профіль = "с5_оксана" if назва == "с5" else "с4_марина"
    шлях = КОРІНЬ / "аудит/проби/н3-стенд/жінки" / (профіль + ".json")
    в = json.loads(шлях.read_text(encoding="utf-8"))
    колір = {к: в[л] for к, л in zip(("шкіра", "волосся", "очі", "кільце"), ("skin", "hair", "eyes", "ring"))}
    мірки = {"зріст": в["мірки"]["зріст"], "обхвати": {к: м for к, м in в["мірки"].items() if к != "зріст"}}
    return {"розмова": f"{назва}-{версія}", "ситуація": ситуації.ситуація(назва).в_json(), "сід": 3,
            "каталог": каталог, "профіль": {"колір": колір, "мірки": мірки},
            "модель": {"межа_повідомлень": 396_000, "мова_картки": "en"}}


def прогнати(назва, версія, модулі, каталог):
    """Міряє приготування й відбиває незмінний дріт початкових запитів."""
    протокол, пул = модулі["протокол"], модулі["пул"]
    записи, зібрати = {}, пул.зібрати

    def стежити(*позиційні, **іменовані):
        """Зберігає кожний варіант пулу для звірки після виміру часу."""
        п = зібрати(*позиційні, **іменовані)
        записи[п.рука, tuple(іменовані.get("зламані", ()))] = п
        return п

    вхід = вхід_сцени(назва, версія, каталог)
    with patch.object(пул, "зібрати", стежити):
        відлік, процес = perf_counter(), process_time()
        в = протокол.почати(вхід, поступово=True) if версія == "після" else протокол.почати(вхід)
        перший, перший_стіна = process_time() - процес, perf_counter() - відлік
        запити = list(в["запити"])
        складання = перший if any(з["вид"] == "складання" for з in запити) else None
        while в.get("ще_руки"):
            в = протокол.наступна_рука(в["сесія"])
            запити.extend(в["запити"])
            if складання is None and any(з["вид"] == "складання" for з in в["запити"]):
                складання = process_time() - процес
        усі, усі_стіна = process_time() - процес, perf_counter() - відлік
    протокол._СЕСІЇ.clear()
    відбитки = {f"пул {рука} {'+'.join(поломки)}": відбиток(п.в_json())
                for (рука, поломки), п in записи.items()}
    for з in sorted(запити, key=lambda з: з["рука"]):
        з.pop("сесія")
        відбитки[f"запит {з['ключ']}"] = відбиток(з)
    print(json.dumps({"сцена": назва, "версія": версія,
                      "процес_с": {"перший_запит": round(перший, 3), "усі_початкові": round(усі, 3),
                                   "перше_складання": round(складання, 3) if складання is not None else None},
                      "стіна_с": [round(перший_стіна, 3), round(усі_стіна, 3)], "ша256": відбитки}, ensure_ascii=False),
          flush=True)
    return відбитки


def головна():
    """Порівнює відбитки трьох сцен на базі й голові."""
    опис = ArgumentParser(description=__doc__)
    опис.add_argument("каталог", type=Path)
    опис.add_argument("база", nargs="?")
    опис.add_argument("--перший-запит", action="store_true", help="Шість повторів старту з готовими записами JSONL.gz")
    пар = опис.parse_args()
    каталог_шлях = пар.каталог.resolve()
    джерела = КОРІНЬ / "джерела"
    os.chdir(джерела)
    sys.path.insert(0, str(джерела))
    import ядро
    from ядро import протокол

    if пар.перший_запит:
        with gzip.open(каталог_шлях, "rt", encoding="utf-8") as файл:
            каталог = [json.loads(рядок) for рядок in файл if рядок.strip()]
        print(json.dumps({"записів_каталогу": len(каталог)}, ensure_ascii=False), flush=True)
        for назва in СЦЕНИ:
            for повтор in (1, 2):
                вхід = вхід_сцени(назва, повтор, каталог)
                відлік, процес = perf_counter(), process_time()
                в = протокол.почати(вхід, поступово=True)
                перший = {"сцена": назва, "прохід": повтор, "процес_с": round(process_time() - процес, 3),
                          "стіна_с": round(perf_counter() - відлік, 3)}
                з, = в["запити"]
                print(json.dumps(dict(перший, вид=з["вид"], рука=з["рука"]), ensure_ascii=False), flush=True)
                протокол._СЕСІЇ.clear()
        return 0
    if not пар.база:
        опис.error("для порівняння потрібен коміт бази")

    після = {імʼя: sys.modules[f"ядро.{імʼя}"] for імʼя in МОДУЛІ}
    до = базові_модулі(ядро, пар.база)
    каталог = протокол._каталог({"каталог": str(каталог_шлях)})
    print(json.dumps({"записів_каталогу": len(каталог)}, ensure_ascii=False), flush=True)
    збігаються = True
    for назва in СЦЕНИ:
        вкласти_модулі(ядро, після)
        нове = прогнати(назва, "після", після, каталог)
        вкласти_модулі(ядро, до)
        давнє = прогнати(назва, "до", до, каталог)
        різниця = [к for к in sorted(нове.keys() | давнє.keys()) if нове.get(к) != давнє.get(к)]
        print(json.dumps({"сцена": назва, "відрізняються": різниця}, ensure_ascii=False), flush=True)
        збігаються &= not різниця
    return 0 if збігаються else 1


if __name__ == "__main__":
    raise SystemExit(головна())
