#!/bin/bash
# Пункт 3 наряду: стендова збірка (`варіант.md`), сцени с3, с5, с8 по одному проходу на кожен варіант, послідовно.
# $1 — тека прогонів; решта — «<варіант>:<сцена>:<межа>» (межа — симв. UTF-16 запиту, `&межа=` у посиланні). Змінні — латиницею.
P=$1; shift; T=$(dirname "$0")
for a in "$@"; do
  IFS=: read -r v s m <<< "$a"
  STOR=/tmp/n4/stor_вар MEZHA=$m bash <(sed 's#рв6_н3_час.js#рв6_н3_час_вар.js#' $T/сцена.sh) $P/${v}_$s $s
done
