# Зводить дані/*.json (вихід `розбір.py`) у таблиці для звіту: секунди до карток за критичним шляхом, виклики по проходах,
# час виклику від токенів (МНК), пункт 3 (варіанти). Запуск: python3 таблиці.py > таблиці.md   (з теки звіту)
import json, glob, os, collections, statistics, sys

тека = os.path.dirname(os.path.abspath(__file__))
файли = sorted(glob.glob(f'{тека}/дані/с?_?.json'))
вар = sorted(glob.glob(f'{тека}/дані/варіанти/*.json'))


def коротко(в):
    return (в.replace('код після «клік» до «складання руки»', 'код ядра до першого виклику (пул, запити)')
              .replace('поза викликами й кодом (показ, черга, очікування сторінки)', 'поза викликами й кодом (показ, черга)'))


def категорія(в, джерело):
    if джерело == 'код':
        return 'код (Pyodide)' if 'клік» до' in в else 'код (Pyodide) між викликами'
    return в


вихід = []
п = вихід.append
п('## 1. Секунди до карток, критичний шлях (с)\n')
назви = collections.OrderedDict()
дані = {}
for ф in файли:
    д = json.load(open(ф))
    ім = os.path.basename(ф)[:-5]
    ряд = collections.Counter()
    for к in д['критичний_шлях']:
        ряд[('код: до першого виклику' if 'до «складання руки»' in к['вид'] and к['джерело'] == 'код'
             else 'код між викликами' if к['джерело'] == 'код'
             else 'поза викликами' if к['джерело'] == 'поза'
             else к['вид'])] += к['с']
    дані[ім] = (д, ряд)
    for к in ряд:
        назви.setdefault(к, 0)
порядок = ['код: до першого виклику', 'складання руки', 'ремонт', 'вибір образу', 'пояснення образу (з фото)', 'пояснення образу (без фото)',
           'переклад', 'код між викликами', 'поза викликами']
решта = [н for н in назви if н not in порядок]
cols = ['с3_1', 'с3_2', 'с5_1', 'с5_2', 'с8_1', 'с8_2']
п('| частина | ' + ' | '.join(cols) + ' |')
п('|---|' + '---|' * len(cols))
for н in порядок + решта:
    п(f'| {н} | ' + ' | '.join(f'{дані[c][1].get(н, 0):.1f}' if c in дані else '—' for c in cols) + ' |')
п('| **до карток (із годинника сторінки)** | ' + ' | '.join(f"**{дані[c][0]['до_карток_с']}**" if c in дані else '—' for c in cols) + ' |')
п('')
п('Критичний шлях: у кожен момент від кліку до карток береться діяльність, що кінчається найпізніше (виклик моделі або крок Python '
  'довший за 20 мс). Паралельні виклики одного кроку (дві руки складання, чотири переклади) лічаться раз — тим, що скінчився останнім.\n')

п('## 2. Виклики моделі від кліку до карток\n')
for c in cols:
    if c not in дані:
        continue
    д = дані[c][0]
    п(f'### {c} (до карток {д["до_карток_с"]} с)\n')
    п('| # | вид | почався, с | скінчився, с | тривав, с | токенів входу | з них з кешу | токенів виходу (думка) | паралельно з # |')
    п('|---|---|---|---|---|---|---|---|---|')
    for i, в in enumerate(д['виклики']):
        п(f"| {i} | {в['вид']} | {в['поч']} | {в['кін']} | {в['с']} | {в['вхід_ток']} | {в['кеш_читання']} | {в['вихід_ток']} ({в['думка_ток']}) | {', '.join(map(str, в['паралельно_з'])) or '—'} |")
    п('')

# МНК: час виклику ~ a + b·вихід + c·вхід (виклики з входом > 9 тис.; без відмінності видів)
п('## 3. Від чого залежить тривалість виклику (МНК по всіх проходах)\n')
точки = []
for c in cols:
    if c in дані:
        for в in дані[c][0]['виклики']:
            if в['вхід_ток'] > 9000 and в['вид'] in ('складання руки', 'ремонт', 'вибір образу', 'пояснення образу (з фото)'):
                точки.append((в['с'], в['вихід_ток'], в['вхід_ток'] / 1000, в['вид'], в['кеш_читання']))
try:
    import numpy as np
    A = np.array([[1, о, в] for _, о, в, _, _ in точки]); y = np.array([т for т, *_ in точки])
    k, *_ = np.linalg.lstsq(A, y, rcond=None)
    pred = A @ k
    r2 = 1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum()
    п(f'{len(точки)} викликів (вхід > 9 тис. токенів, види: складання, ремонт, вибір, пояснення з фото): '
      f'с = {k[0]:.1f} + {k[1]*1000:.1f}·(тис. токенів виходу) + {k[2]:.3f}·(тис. токенів входу); R² = {r2:.2f}. '
      f'Тобто тисяча токенів виходу коштує {k[1]*1000:.1f} с, тисяча токенів входу — {k[2]:.2f} с (гіпотеза: коефіцієнт входу — '
      'з розкиду; виклики входу різного розміру в цій вибірці — 20–180 тис.).\n')
except Exception as е:
    п(f'МНК не пораховано: {е}\n')

# зведення виходу складання
п('## 4. Склад запиту складання (шість проходів, дві руки в кожному)\n')
сум = collections.Counter(); усього = 0; пул = 0; чч = collections.Counter(); ряд = 0; н = 0
for c in cols:
    if c in дані:
        for s in дані[c][0]['склад_запиту_складання']:
            усього += s['симв']; пул += s['пул_симв']; ряд += s['кандидатів']; н += 1
            for к, в in s['колонки_симв'].items(): сум[к] += в
            for к, в in s['частини_симв'].items(): чч[к] += в
п(f'Запитів складання: {н}; у середньому {усього/н:,.0f} симв., кандидатів {ряд/н:.0f}, пул {100*пул/усього:.1f} % запиту.\n'.replace(',', ' '))
п('| частина запиту | симв. у середньому | частка запиту |')
п('|---|---|---|')
п(f'| пул (кандидати) | {пул/н:,.0f} | {100*пул/усього:.1f} % |'.replace(',', ' '))
for к, в in чч.most_common():
    п(f'| {к} | {в/н:,.0f} | {100*в/усього:.1f} % |'.replace(',', ' '))
п('')
п('| колонка кандидата | частка пулу |')
п('|---|---|')
for к, в in сум.most_common():
    п(f'| {к} | {100*в/пул:.1f} % |')
п('')

if вар:
    п('## 5. Пункт 3: варіанти стенда\n')
    п('| варіант | сцена | до карток, с | код до першого виклику, с | складання, с | кандидатів у запиті | токенів входу складання | образів із судом | знахідок суду на образ |')
    п('|---|---|---|---|---|---|---|---|---|')
    for ф in вар:
        д = json.load(open(ф)); ім = os.path.basename(ф)[:-5]
        ряд = collections.Counter()
        for к in д['критичний_шлях']:
            ряд['код' if 'до «складання руки»' in к['вид'] and к['джерело'] == 'код' else к['вид']] += к['с']
        скл = д['склад_запиту_складання']
        п(f"| {ім.split('_')[0]} | {ім.split('_')[1]} | {д['до_карток_с']} | {ряд.get('код', 0):.1f} | {ряд.get('складання руки', 0):.1f} | "
          f"{'/'.join(str(s['кандидатів']) for s in скл)} | {'/'.join(str(s['вхід_ток']) for s in скл)} | {д.get('суд', {}).get('образів', '—')} | {д.get('суд', {}).get('знахідок_на_образ', '—')} |")
    п('')
print('\n'.join(вихід))
