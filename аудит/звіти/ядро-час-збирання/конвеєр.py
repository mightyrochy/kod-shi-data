# Гіпотеза-розрахунок для пункту 4: якби запит руки 1 пішов, щойно рука 1 збудована (а рука 2 будувалась під час відповіді моделі),
# скільки секунд знялось би з критичного шляху. Тривалості Python руки 1/2 — з `порядок_рук.py` (CPython: 29,4 і 36,8 с із 66,6 с),
# перенесені на Pyodide за часткою; тривалості складання рук — з обмінів проходу (відповідь у `виклики_моста.jsonl` за ключем р1/р2).
import json, sys, glob, os
дані = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'дані')
ч1, ч2 = 29.4 / 66.6, 36.8 / 66.6
print('| прохід | код до першого виклику, с | складання руки 1, с | складання руки 2, с | зараз: код + max | конвеєр: max(код1 + с1, код + с2) | знялось, с |')
print('|---|---|---|---|---|---|---|')
for т in sorted(glob.glob('/tmp/n4/р/с?_?')):
    ім = os.path.basename(т)
    д = json.load(open(f'{дані}/{ім}.json'))
    код = next((k['с'] for k in д['критичний_шлях'] if 'до «складання руки»' in k['вид'] and k['джерело'] == 'код'), None)
    відп = {}
    for р in open(f'{т}/виклики_моста.jsonl', encoding='utf8'):
        в = json.loads(р); вх = json.loads(в['вхід'])
        if в['ім'] == 'ядро' and вх.get('дія') == 'відповідь' and 'складання-рука' in str(вх.get('ключ')):
            відп[вх['ключ'][:2]] = (вх.get('відповідь') or {}).get('текст')
    час = {}
    for р in open(f'{т}/обміни.jsonl', encoding='utf8'):
        o = json.loads(р)
        if 'с' in o and o.get('відповідь') in відп.values():
            ключ = next(к for к, v in відп.items() if v == o['відповідь']); час[ключ] = o['с']
    if код is None or len(час) < 2:
        print(f'| {ім} | {код} | {час} | | | | |'); continue
    зараз = код + max(час.values())
    конв = max(код * ч1 + час['р1'], код + час['р2'])
    print(f"| {ім} | {код:.0f} | {час['р1']:.0f} | {час['р2']:.0f} | {зараз:.0f} | {конв:.0f} | {зараз-конв:.0f} |")
