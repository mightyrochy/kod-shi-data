def базовий_запит(база):
    """Завантажує побудову запиту з коміту ДО."""
    код = subprocess.check_output(["git", "show", f"{база}:джерела/ядро/запит.py"], cwd=КОРІНЬ)
    модуль = ModuleType("ядро.запит_база")
    модуль.__file__ = запит.__file__
    модуль.__package__ = "ядро"
    exec(compile(код, модуль.__file__, "exec"), модуль.__dict__)
    return модуль.запит


def вхід(сцена):
    """Бере Ситуацію першої збірки й кольори профілю з тих самих записів Н6."""
    тека, жінка = СЦЕНИ[сцена]
    архів = ЗАПИСИ / тека / "ядро/1" / сцена / "руки.jsonl"
    with архів.open(encoding="utf-8") as файл:
        знімок = next(запис for запис in map(json.loads, файл) if запис["картки"])
    в = json.loads((КОРІНЬ / f"аудит/проби/жінки/ж{жінка}.json").read_text(encoding="utf-8"))
    мірки = в.get("мірки", {"зріст": 168, "груди": 88, "талія": 71, "стегна": 95, "плечі": 39})
    профіль = {
        "колір": {"шкіра": в["skin"], "волосся": в["hair"], "очі": в["eyes"], "кільце": в["ring"]},
        "мірки": {"зріст": мірки["зріст"], "обхвати": {к: м for к, м in мірки.items() if к != "зріст"}},
    }
    картка = next(к["речі"] for к in знімок["картки"] if к["рука"] == 1)
    return ситуація.з_json(знімок["ситуація"]), профіль, картка


def стадії(сцена, каталог, до):
    """Лічить каталог, жорсткі межі, палітру, обидва зрізи і записану картку."""
    день, профіль, картка = вхід(сцена)
    профільний_вхід = {"профіль": профіль}
    риси, палітра = знання.портрет_і_палітра(профільний_вхід, день, із_записами=True)
    день = ситуація.з_профілем(день, палітра, риси, знання.хто_обрав_палітру(профільний_вхід))
    профіль = знання.профіль_суду(профіль)
    кандидати = пул.зібрати(день, 1, 3, каталог, профіль=профіль)
    жорстко_відкинуто = {р["ід"] for р in кандидати.відкинуто if р["межа"] != "палітра_або_доза"}
    всі = {р["id"]: (р["слот"], р["магазин"]) for р in каталог}
    придатні = [в for ід, в in всі.items() if ід not in жорстко_відкинуто]
    відібрані = [всі[р["ід"]] for р in кандидати.речі]
    рядки = []
    for будувати in (до, запит.запит):
        з = будувати("складання", кандидати, день, профіль, модель=МЕЖІ)
        рядки.append([всі[кандидати.записи[н].ід] for н in з.номери])
    обрана = [(р["слот"], р["крамниця"]) for р in картка]
    return (всі.values(), придатні, відібрані, *рядки,
            *(р[:50] for р in рядки), *(р[:100] for р in рядки), обрана)


def таблиця(каталог, до, вихід):
    """Пише всі крамниці за слотами і разом, з окремим знаменником кожної стадії."""
    каталог = записи_речей.вкласти(каталог)
    писач = csv.writer(вихід, delimiter="\t", lineterminator="\n")
    писач.writerow(("сцена", "слот", "крамниця", "стадія", "речі", "усі", "частка %"))
    for сцена in СЦЕНИ:
        for етап, групи in zip(ЕТАПИ, стадії(сцена, каталог, до)):
            групи = list(групи)
            для_зрізу = Counter((слот, крамниця) for слот, крамниця in групи)
            для_зрізу.update(("усі", крамниця) for _, крамниця in групи)
            підсумки = Counter(слот for слот, _ in групи)
            підсумки["усі"] = len(групи)
            for (слот, крамниця), n in sorted(для_зрізу.items()):
                усі = підсумки[слот]
                писач.writerow((сцена, слот, крамниця, етап, n, усі, f"{100 * n / усі:.3f}"))


def main():
    """Відтворює вимір на чистому повному каталозі й пише TSV."""
    розбір = argparse.ArgumentParser(description=__doc__)
    розбір.add_argument("--каталог", help="шлях до підготовленого чистого XML")
    розбір.add_argument("--база", default=БАЗА, help="коміт ДО, має бути у локальному git")
    аргументи = розбір.parse_args()
    шлях = аргументи.каталог or каталог_на_диску("каталог_повний.xml")
    каталог = база_прогону(шлях, ліміт_фото=0, кеш=str(КОРІНЬ / "стенд_кеш_кольорів.json"))["каталог"]
    таблиця(каталог, базовий_запит(аргументи.база), sys.stdout)


if __name__ == "__main__":
    main()
