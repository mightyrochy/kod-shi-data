def помилка(в):
    """Зберігає тест, первісний виняток і рядок, де затребувано ім'я."""
    кадри = traceback.extract_tb(в.__traceback__)
    код = [к for к in кадри if "/джерела/" in к.filename]
    if not код and isinstance(в, ImportError):
        код = [к for к in кадри if к.filename == __file__]
    місце = код[-1] if код else кадри[-1]
    return {"помилка": type(в).__name__, "імʼя": getattr(в, "name", None),
            "текст": str(в).splitlines()[0][:450],
            "місце": f"{місце.filename.rsplit('/джерела/', 1)[-1]}:{місце.lineno}",
            "вираз": місце.line}


def пітон(тека, назва):
    os.chdir(тека)
    sys.path.insert(0, str(тека))
    try:
        with open(os.devnull, "w") as тихо:
            from contextlib import redirect_stdout
            with redirect_stdout(тихо):
                вихід = БАТАРЕЯ[назва]()
        return {"вихід": вихід}
    except Exception as в:
        return помилка(в)


def завдання_пітон(тека, назва):
    # Кожна функція має свій процес і чистий кеш імпортів, зокрема після зламаного імпорту.
    читати, писати = os.pipe()
    pid = os.fork()
    if pid == 0:
        os.close(читати)
        with os.fdopen(писати, "w", encoding="utf-8") as ф:
            json.dump(пітон(тека, назва), ф, ensure_ascii=False)
        os._exit(0)
    os.close(писати)
    with os.fdopen(читати, encoding="utf-8") as ф:
        вивід = ф.read()
    _, статус = os.waitpid(pid, 0)
    if статус or not вивід:
        raise RuntimeError(f"Дочірня проба {назва} завершилася статусом {статус}")
    return json.loads(вивід)


def копія(тека):
    """Усі зміни виміру живуть у тимчасовій копії, включно з розпакованим каталогом."""
    дж = Path(тека) / "джерела"
    shutil.copytree(ДЖЕРЕЛА, дж, ignore=shutil.ignore_patterns("node_modules", "__pycache__"))
    фікстура = Path(тека) / ЗАПИС_С5
    фікстура.parent.mkdir(parents=True)
    shutil.copy2(КОРІНЬ / ЗАПИС_С5, фікстура)
    with gzip.open(дж / (КАТАЛОГ + ".gz"), "rb") as архів:
        xml = XML.parse(архів)
    пропозиції = xml.find(".//offers")
    лишити = set(list(пропозиції)[:8])
    сукні = [р for р in пропозиції if "сукн" in (р.findtext("name") or "").lower()]
    лишити.update(сукні[:16])
