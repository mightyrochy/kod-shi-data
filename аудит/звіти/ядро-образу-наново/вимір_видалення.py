def імпорти_графа(дерево, у_функціях):
    """Усі статичні імпорти, крім гілки CLI. Для ВМ також виключаємо тіла функцій і класів."""
    for вузол in дерево.body:
        if isinstance(вузол, ast.If) and "__name__" in ast.unparse(вузол.test) and "__main__" in ast.unparse(вузол.test):
            continue
        if isinstance(вузол, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and not у_функціях:
            continue
        for н in ast.walk(вузол):
            if isinstance(н, ast.Import):
                yield from (і.name.split(".")[0] + ".py" for і in н.names)
            elif isinstance(н, ast.ImportFrom) and н.level == 0 and н.module:
                yield н.module.split(".")[0] + ".py"


def досяжні(граф, старт):
    стек, взято = [старт], set()
    while стек:
        модуль = стек.pop()
        if модуль not in взято:
            взято.add(модуль)
            стек.extend(граф[модуль] - взято)
    return взято


def міра_графа(дерева):
    верх = {ім: set(імпорти_графа(д, False)) & дерева.keys() for ім, д in дерева.items()}
    усі = {ім: set(імпорти_графа(д, True)) & дерева.keys() for ім, д in дерева.items()}
    мова = "внутрішня_мова.py"
    залежні = {ім for ім in верх if ім != мова and мова in досяжні(верх, ім)}
    невзяті, групи = set(усі), []
    while невзяті:
        ім = min(невзяті)
        група = {інший for інший in досяжні(усі, ім) if ім in досяжні(усі, інший)}
        групи.append(група)
        невзяті -= група
    найбільша = max(групи, key=len, default=set())
    return залежні, найбільша if len(найбільша) > 1 else set()


def переліки(журнал):
    зелений_разом = not журнал["разом_впало"]
    класи = {"зникає": set(), "тримає інша функція": set(), "потрібен ядру": set()}
    for рядок in журнал["вилучення"]:
        if not рядок["продукт"]:
            continue
        ім, впало = рядок["модуль"], рядок["впало"]
        if not впало and (зелений_разом or ім in журнал.get("перевірено_разом", ())):
            класи["зникає"].add(ім)
        elif будь_коли_ядро(впало):
            класи["потрібен ядру"].add(ім)
        elif any(назва.split(".")[0] in ФУНКЦІЇ for назва in впало):
            класи["тримає інша функція"].add(ім)
        elif впало or ім in журнал.get("конфлікт_вилучення", ()):
            класи["потрібен ядру"].add(ім)
    return класи


