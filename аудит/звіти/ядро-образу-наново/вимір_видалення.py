def друк_мірил(журнал):
    джерело = склад_продукту()
    дерева = {ім: ast.parse((ДЖЕРЕЛА / ім).read_text()) for ім in джерело}
    класи = переліки(журнал)
    зникає = класи["зникає"]
    довгі, параметри = {}, {}
    for ім, дерево in дерева.items():
        ф = [н for н in ast.walk(дерево) if isinstance(н, (ast.FunctionDef, ast.AsyncFunctionDef))]
        параметри[ім] = [x for x in ф if sum(a.arg != "self" for a in x.args.posonlyargs + x.args.args + x.args.kwonlyargs
                                             + [i for i in (x.args.vararg, x.args.kwarg) if i]) >= 10]
        довгі[ім] = [x for x in ф if x.end_lineno - x.lineno + 1 >= 300]
    до = міра_графа(дерева)
    після = міра_графа({ім: д for ім, д in дерева.items() if ім not in зникає})

    def міри(файли, граф):
        залежні, коло = граф
        return [sum(len(параметри.get(і, ())) for і in файли), len(залежні & файли),
                len(коло & файли), sum(len(довгі.get(і, ())) for і in файли)]

    def рядків(файли):
        return sum(len((ДЖЕРЕЛА / і).read_text().splitlines()) for і in файли)

    print("Межа чотирьох мірил: маніфест Python (status.МОДУЛІ_ПРОДУКТУ).")
    print("Порядок: параметри 10+, залежні від ВМ, найбільше коло, функції 300+.")
    print("ДО:", міри(джерело, до), "→ ПІСЛЯ:", міри(джерело - зникає, після))
    історичні = історичні_53()
    for ім, файли in класи.items():
        старі = файли & історичні
        print(ім, len(файли), рядків(файли), "із попередніх 53:", len(старі), рядків(старі),
              "мірил ДО:", міри(файли, до), "ПІСЛЯ:", міри(файли, після))
    функції = {}
    for код, назва in ФУНКЦІЇ.items():
        усі = {в["модуль"] for в in журнал["вилучення"] if в["продукт"]
               and any(тест.startswith(код + ".") for тест in в["впало"])}
        своя_категорія = усі & класи["тримає інша функція"]
        старі = своя_категорія & історичні
        функції[назва] = {"в_категорії": len(своя_категорія), "старих": len(старі), "рядків_старих": рядків(старі),
                         "із_ядром": len(усі)}
        print("Функція:", назва, функції[назва])
    частини = {}
    for ім in set().union(*класи.values()) - зникає:
        частини.setdefault(частина(ім), set()).add(ім)
    for назва, файли in sorted(частини.items()):
        print("Частина:", назва, len(файли), рядків(файли), міри(файли, після))
    return {"до": міри(джерело, до), "після": міри(джерело - зникає, після),
            "класи": {к: {"модулі": sorted(ф), "рядки": рядків(ф), "до": міри(ф, до), "після": міри(ф, після)}
                      for к, ф in класи.items()},
            "функції_продукту": функції,
            "частини": {к: {"модулі": sorted(ф), "рядки": рядків(ф), "після": міри(ф, після)}
                        for к, ф in частини.items()},
            "внутрішня_мова": {"до": sorted(до[0]), "після": sorted(після[0])},
            "коло": {"до": sorted(до[1]), "після": sorted(після[1])},
            "функції": {"10+": {ім: [f"{н.name}:{н.lineno}" for н in ф] for ім, ф in параметри.items() if ф},
                        "300+": {ім: [f"{н.name}:{н.lineno}" for н in ф] for ім, ф in довгі.items() if ф}}}


def вибрати_групу(дж, кандидати, контроль, разом):
    """Якщо вилучення разом дало збій, відтворює зелений набір послідовним додаванням."""
    if not разом:
        return кандидати, []
    набір, конфлікт = [], []
    for ім in кандидати:
        проба = набір + [ім]
        пітон = [ф for ф in проба if ф.endswith(".py")]
        js = [ф for ф in проба if ф.startswith("показ/")]
        впало = червоне(без_модулів(дж, пітон, контроль) if пітон else {})
        впало.update(червоне(браузер(дж, [js])[0][1]) if js else {})
        if впало:
            конфлікт.append(ім)
        else:
            набір.append(ім)
    return набір, конфлікт


