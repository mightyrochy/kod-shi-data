# -*- coding: utf-8 -*-
"""Власні випадки перевірки #4035 (нових видів «г» і «г-поле»), яких нема в стенді виконавця.
Запуск: python3 випадки_4035.py <корінь дерева голови> — кожен випадок у своєму тимчасовому дереві `джерела/`.
"""
import sys, tempfile, textwrap
from pathlib import Path

sys.path.insert(0, str(Path(sys.argv[1]) / 'джерела' / 'прилади'))
import корінь_е3_заміна_з_перевіркою as П
import обсяг_приладу as О

СХЕМА = '''
def слово(*з): return з
def обʼєкт(*а, **к): return а
ПІДСТАВИ = ("colour", "kind", "occasion", "day")
ВІДП = обʼєкт({"текст": "", "%s": обʼєкт({"річ": "", "%s": слово(*ПІДСТАВИ)})})
def зробити(**к): return к
зробити(вихід="ВІДП", поля_виходу={"%s.%s": %r})
'''

ВИПАДКИ = [
    # (назва, файл, текст, очікувано лічиться?)
    ('г: стан локальною змінною, потім у dict', 'а.py', '''
        def рішення(заміна):
            стан = "refused"
            return dict(річ=заміна, стан=стан)
        ''', True),
    ('г: «не застосовано» булевим прапорцем', 'а.py', '''
        def рішення(заміна, суд):
            if not суд(заміна):
                return dict(річ=заміна, застосовано=False)
            return dict(річ=заміна, застосовано=True)
        ''', True),
    ('г: «refused» у функції без заміни/swap', 'а.py', '''
        def платіж(сума):
            return dict(стан="refused", сума=сума)
        ''', False),
    ('г: «accepted» у функції заміни', 'а.py', '''
        def рішення(заміна):
            return dict(річ=заміна, стан="accepted")
        ''', False),
    ('г: «kept» ключем state у функції swap_*', 'а.py', '''
        def обрати(swap_answer):
            if not swap_answer.get("to"):
                return {"state": "kept"}
        ''', True),
    ('г JS: подвійні лапки "spares"', 'а.js', '''
        async function рука(в4, зам4){
          if (зам4 && зам4.стан === "spares"){ в4 = await новий(); }
          return в4;
        }
        ''', True),
    ('г JS: стала зліва \'spares\' === зам.стан', 'а.js', '''
        async function рука(в4, зам4){
          if ('spares' === зам4.стан){ в4 = await новий(); }
          return в4;
        }
        ''', True),
    ('г JS: змінна тексту картки з іншим ім\'ям (опис)', 'а.js', '''
        async function рука(опис, зам4){
          if (зам4.стан === 'spares'){ опис = await новий(); }
          return опис;
        }
        ''', True),
    ('г JS: !== spares пише пояснення (не місце)', 'а.js', '''
        async function рука(в4, зам4){
          if (зам4.стан !== 'spares'){ в4 = пояснення(зам4); }
          return в4;
        }
        ''', False),
    ('г-поле: опис називає лише частину значень', 'с.py',
     СХЕМА % ('заміна', 'чому', 'заміна', 'чому', 'one of «colour» or «kind»: why'), True),
    ('г-поле: англійські імена swap.why без значень', 'с.py',
     СХЕМА % ('swap', 'why', 'swap', 'why', 'why the photo warrants it'), True),
    ('г-поле: усі значення в «»', 'с.py',
     СХЕМА % ('заміна', 'чому', 'заміна', 'чому', '«colour», «kind», «occasion» or «day»'), False),
    ('г-поле: перелік у полі не пропозиції (річ.тип)', 'с.py',
     СХЕМА % ('річ_опис', 'чому', 'річ_опис', 'чому', 'free text'), False),
]

добре = 0
for назва, файл, текст, треба in ВИПАДКИ:
    with tempfile.TemporaryDirectory() as т:
        шлях = Path(т) / 'джерела' / файл
        шлях.parent.mkdir(parents=True)
        шлях.write_text(textwrap.dedent(текст).lstrip(), encoding='utf-8')
        О.скинути()
        місця = [к for к in П.сканувати(т)[0] if к.умови in ('г', 'г-поле')]
        є = bool(місця)
        ок = є == треба
        добре += ок
        print(('✔' if ок else '✗'), назва, '— лічиться' if є else '— не лічиться',
              '(треба: %s)' % ('лічиться' if треба else 'не лічиться'),
              '; '.join('%s:%s %s' % (Path(к.файл).name, к.рядок, к.умови) for к in місця))
print('збіг з класом: %d з %d' % (добре, len(ВИПАДКИ)))
