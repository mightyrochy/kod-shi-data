"""Речення пояснень: усі says з text/advice/unknown відповідей ДО і ПІСЛЯ; кандидат у «речення про силует» — за словами
нижче (щедро: зайве оглядач позначить «не про силует»). Пише речення.jsonl (усі) і кандидати.jsonl.
Запуск: python3 речення.py"""
import json, re
П = "/tmp/пс"
СЛОВА = re.compile(r"силует|посад|тал[іi]|стегн|ног[иа]|ніг|довж|пропорц|кр[іо]й|крою|лін[іi]|вертикал|об.?єм|плеч|зріст|зрост|"
                   r"витяг|поділ|кра[йю]|коліна|колін|щиколот|литк|прилега|приталена|приталений|оверсайз|вільн|широк|пряма|прямий|"
                   r"прямі|розмір|сидить|сидітиме|фігур|розклешен|обтяг|завужен|мід[іи]|міні|максі|довгий|довга|коротк|висок|"
                   r"посадк|талію|пояс|заправ|обрис|форм[ау] тіла|корпус|груд|спідниц.*(a|а)-|розширю", re.I)
відп = {}
for л in open(f"{П}/відповіді.jsonl", encoding="utf-8"):
    з = json.loads(л)
    if з.get("статус") == "ok": відп[з["ключ"]] = з
карта = json.load(open(f"{П}/карта_опису.json"))
усі, канд = [], []
for н in sorted(карта):
    for к in ("ДО", "ПІСЛЯ"):
        з = відп.get(f"о{н}:{к}")
        if not з: continue
        т = з["текст"].strip()
        if т.startswith("```"): т = т.strip("`").split("\n", 1)[1]
        try: о = json.loads(т)
        except Exception:
            усі.append({"склад": н, "вид": к, "де": "НЕРОЗБІРНО", "says": т[:300]}); continue
        for де in ("text", "advice", "unknown"):
            for і, р in enumerate(о.get(де) or []):
                if not isinstance(р, dict): continue
                з1 = {"склад": н, "вид": к, "де": де, "і": і, "about": р.get("about"), "says": р.get("says", "")}
                усі.append(з1)
                if СЛОВА.search(з1["says"]): канд.append(з1)
for ім, дані in (("речення.jsonl", усі), ("кандидати.jsonl", канд)):
    with open(f"{П}/{ім}", "w", encoding="utf-8") as ф:
        for з in дані: ф.write(json.dumps(з, ensure_ascii=False) + "\n")
print("речень", len(усі), "кандидатів", len(канд))
