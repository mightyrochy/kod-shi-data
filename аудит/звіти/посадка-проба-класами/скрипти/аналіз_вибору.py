"""Крок 4, підсумок: для кожної сцени — речі всіх 10 образів руки 1 ДО, ДО-повтор і ПІСЛЯ; частка спільних речей
(Жаккар) ДО↔ДО-повтор (шум самої моделі) і ДО↔ПІСЛЯ; чи названо причину силуету в caption/why/day/deliberate
(слова нижче); знахідки судді ядра (не утримані) на образ. Запуск: python3 аналіз_вибору.py → вибір_підсумок.json"""
import json, re, statistics
П = "/tmp/пс"
СИЛ = re.compile(r"силует|тал[іi]|waist|стегн|\bhips?\b|\bніг\b|\bноги\b|\blegs?\b|пропорц|proportion|вертикал|vertical|плеч|shoulder|витяг|elongat|silhouette", re.I)
відп = {}
for л in open(f"{П}/відповіді.jsonl", encoding="utf-8"):
    з = json.loads(л)
    if з["ключ"].startswith("в") and з["статус"] == "ok": відп[з["ключ"]] = з
суд = json.load(open(f"{П}/суд_вибору.json")); карта = json.load(open(f"{П}/карта_вибору.json"))
def розібрати(т):
    т = т.strip()
    if т.startswith("```"): т = т.strip("`").split("\n", 1)[1]
    return json.loads(т[т.index("{"): т.rindex("}") + 1])
def жак(а, б): return round(len(а & б) / len(а | б), 3) if а | б else 1.0
підсумок = {}
for н in sorted(карта):
    о = {}
    for вид in ("ДО", "ДО-повтор", "ПІСЛЯ"):
        з = відп[f"в{н}:{вид}"]; д = розібрати(з["текст"])
        образи = д.get("outfits", [])
        речі = {і for x in образи for і in x.get("items", [])}
        причини = []
        for x in образи:
            слова = " ".join([x.get("caption") or "", x.get("day") or ""] + [в.get("why", "") for в in x.get("deliberate", [])])
            if СИЛ.search(слова): причини.append({"образ": x.get("id"), "слова": слова[:300]})
        вирок = суд.get(f"в{н}:{вид}") or []
        знах = [len(в["знахідки"]) for в in вирок] if isinstance(вирок, list) else []
        о[вид] = {"образів": len(образи), "речі": sorted(речі), "образів_з_причиною_силуету": len(причини), "причини": причини,
                  "знахідок_судді_на_образ": round(statistics.mean(знах), 2) if знах else None,
                  "знахідки_коди": sorted({з["код"] for в in вирок for з in в["знахідки"]}) if isinstance(вирок, list) else [],
                  "токени_вхід": з["вхід_нових"] + з["вхід_кеш_запис"] + з["вхід_кеш_читання"], "токени_вихід": з["вихід"]}
    а, б, в = (set(о[к]["речі"]) for к in ("ДО", "ДО-повтор", "ПІСЛЯ"))
    підсумок[н] = {**карта[н], "жаккар_ДО_повтор": жак(а, б), "жаккар_ДО_ПІСЛЯ": жак(а, в), "жаккар_повтор_ПІСЛЯ": жак(б, в),
                   "лише_в_ПІСЛЯ": len(в - а - б), **{к: о[к] for к in о}}
json.dump(підсумок, open(f"{П}/вибір_підсумок.json", "w"), ensure_ascii=False, indent=1)
for н, x in підсумок.items():
    print(н, x["мета"], "Ж(ДО,повтор)", x["жаккар_ДО_повтор"], "Ж(ДО,ПІСЛЯ)", x["жаккар_ДО_ПІСЛЯ"], "нових", x["лише_в_ПІСЛЯ"],
          "причина силуету", [x[к]["образів_з_причиною_силуету"] for к in ("ДО", "ДО-повтор", "ПІСЛЯ")],
          "суд/образ", [x[к]["знахідок_судді_на_образ"] for к in ("ДО", "ДО-повтор", "ПІСЛЯ")],
          "ток", [(x[к]["токени_вхід"], x[к]["токени_вихід"]) for к in ("ДО", "ПІСЛЯ")])
