"""Крок 4: запит складання руки 1 ядра на кожній з 10 сцен, каталог — пул сцени (`пули.json`: усі речі її складів),
ситуація й профіль — як у поясненні (`ядро_опис.вхід_складу`). Режим «запит»: пише тіло першого запиту складання руки 1 у
`/tmp/пс/вибір_до/<сцена>.json`. Режим «суд»: подає ядру відповідь моделі (ДО чи ПІСЛЯ) на той самий запит і пише вирок
судді по кожному образу.
Запуск: python3 вибір_ядро.py <корінь> запит | суд <відповіді.jsonl>"""
import json, os, sys
sys.argv = [sys.argv[0], sys.argv[1]] + sys.argv[2:]
КОРІНЬ = sys.argv[1]; РЕЖИМ = sys.argv[2]
import importlib.util
сп = importlib.util.spec_from_file_location("я", "/tmp/пс/ядро_опис.py"); я = importlib.util.module_from_spec(сп)
_argv = sys.argv; sys.argv = [_argv[0], КОРІНЬ]; сп.loader.exec_module(я); sys.argv = _argv
from ядро import протокол, пул as _пул
ПУЛ = []
_зібрати = _пул.зібрати
def _лов(*а, **к):
    п = _зібрати(*а, **к)
    if а[1] == 1: ПУЛ.append({н: р.ід for н, р in п.записи.items()})
    return п
_пул.зібрати = _лов
ПУЛИ = json.load(open("/tmp/пс/пули.json")); СКЛАДИ = json.load(open("/tmp/пс/склади.json"))
def вхід_сцени(сцена):
    с = next(x for x in СКЛАДИ if x["тека"] == ПУЛИ[сцена]["тека"])
    вхід, жінка = я.вхід_складу(dict(с, речі=ПУЛИ[сцена]["речі"]))
    return вхід, жінка
def пройти(вхід, відповідь=None):
    в = json.loads(протокол.виклик(json.dumps({"дія": "почати", "вхід": вхід}, ensure_ascii=False)))
    черга = list(в.get("запити", [])); перший = None
    while not в.get("кінець") and черга:
        з = черга.pop(0)
        if з["рука"] == 1 and з["вид"] == "складання" and перший is None:
            перший = з
            if відповідь is None: return перший, None
            відп = {"текст": відповідь}
        elif з["рука"] == 1 and з["вид"] == "вибір":
            return перший, list(я.ВИРОКИ)
        else:
            відп = {"збій": {"вид": "тиша", "секунди": 300}}
        в = json.loads(протокол.виклик(json.dumps({"дія": "відповідь", "сесія": в.get("сесія") or з["сесія"],
                                                     "ключ": з["ключ"], "відповідь": відп}, ensure_ascii=False)))
        черга += в.get("запити", [])
    return перший, list(я.ВИРОКИ)
if РЕЖИМ == "запит":
    os.makedirs("/tmp/пс/вибір_до", exist_ok=True)
    for н, сцена in enumerate(ПУЛИ):
        вхід, жінка = вхід_сцени(сцена)
        ПУЛ.clear()
        з, _ = пройти(вхід)
        json.dump({"сцена": сцена, "жінка": жінка, "профіль_мірки": вхід["профіль"]["мірки"], "запит": з, "ід": ПУЛ[-1]},
                  open(f"/tmp/пс/вибір_до/{н:02d}.json", "w"), ensure_ascii=False)
        print(н, сцена, len(json.loads(з["модель"]["messages"][0]["content"])["pool"]["rows"]) if з else "НЕМА")
if РЕЖИМ == "суд":
    from collections import Counter
    відп = {}
    for л in open(sys.argv[3], encoding="utf-8"):
        з = json.loads(л)
        if з.get("статус") == "ok" and з["ключ"].startswith("в"): відп[з["ключ"]] = з["текст"]
    сцени = list(ПУЛИ); вихід = {}
    for ключ, текст in sorted(відп.items()):
        н, вид = ключ[1:].split(":")
        вхід, _ = вхід_сцени(сцени[int(н)])
        я.ВИРОКИ.clear()
        try:
            _, вироки = пройти(вхід, текст)
        except Exception as e:
            вихід[ключ] = {"збій": f"{type(e).__name__}: {e}"[:300]}; continue
        вихід[ключ] = [{"образ": в.образ if hasattr(в, "образ") else в.в_json()["образ"],
                        "склад": в.в_json()["склад"],
                        "знахідки": [{"код": з["код"], "правило": з["правило"], "адресат": з["адресат"], "вага": з["значення"].get("вага"),
                                      "регістр": з["значення"].get("регістр"), "речі": з["речі"]}
                                     for з in в.в_json()["заяви"] if not з["значення"].get("утримано")]} for в in (вироки or [])]
    json.dump(вихід, open("/tmp/пс/суд_вибору.json", "w"), ensure_ascii=False, indent=1)
    print({к: (len(в) if isinstance(в, list) else в) for к, в in вихід.items()})
