"""Числа (а) і (б) з оцінок наосліп: огляд_<оглядач>.jsonl + наосліп_ключ.jsonl. Речення про силует — те, що оглядач
не позначив «не про силует». (а) склади з ≥1 певним (text/advice) реченням про силует для неї, і з ≥1 таким
правдивим («так»); речення «не знаю» про посадку. (б) частка «так», «майже», «ні» серед речень про силует ДО і ПІСЛЯ.
Розбіжність оглядачів — коли дано два файли. Запуск: python3 підсумок_огляду.py <тека звіту> огляд_claude.jsonl [огляд_інший.jsonl]"""
import json, sys, collections
Т = sys.argv[1]; файли = sys.argv[2:]
ключ = {x["№"]: x for x in map(json.loads, open(f"{Т}/наосліп_ключ.jsonl", encoding="utf-8"))}
табл = {x["№"]: x for x in map(json.loads, open(f"{Т}/наосліп.jsonl", encoding="utf-8"))}
карта = json.load(open(f"{Т}/дані/карта_опису.json"))
огляди = [{x["№"]: x for x in map(json.loads, open(f"{Т}/{ф}", encoding="utf-8"))} for ф in файли]
вих = {}
for ім, о in zip(файли, огляди):
    р = {}
    for вид in ("ДО", "ПІСЛЯ"):
        сил = [н for н, к in ключ.items() if к["вид"] == вид and о[н]["оцінка"] != "не про силует"]
        певні = [н for н in сил if ключ[н]["де"] in ("text", "advice")]
        незнаю = [н for н in сил if ключ[н]["де"] == "unknown"]
        склади = {ключ[н]["склад"] for н in певні}; правдиві = {ключ[н]["склад"] for н in певні if о[н]["оцінка"] == "так"}
        з_метою = {н for н, к in карта.items() if к["мета"]}
        оц = collections.Counter(о[н]["оцінка"] for н in певні)
        р[вид] = {"речень_про_силует": len(сил), "певних": len(певні), "не_знаю_про_посадку": len(незнаю),
                  "складів_з_певним": len(склади), "складів_з_певним_так": len(правдиві),
                  "складів_з_певним_так_з_метою": len(правдиві & з_метою), "складів_з_певним_так_без_мети": len(правдиві - з_метою),
                  "оцінки_певних": dict(оц), "частка_так": round(оц["так"] / len(певні), 3) if певні else None,
                  "оцінки_не_знаю": dict(collections.Counter(о[н]["оцінка"] for н in незнаю)),
                  "ні": [{"№": н, "склад": ключ[н]["склад"], "речення": табл[н]["речення"], "чому": о[н]["чому"]}
                         for н in певні if о[н]["оцінка"] == "ні"]}
    вих[ім] = р
if len(огляди) == 2:
    а, б = огляди; спільні = sorted(set(а) & set(б))
    розб = [н for н in спільні if а[н]["оцінка"] != б[н]["оцінка"]]
    вих["розбіжність"] = {"рядків": len(спільні), "розійшлись": len(розб), "частка": round(len(розб) / len(спільні), 3),
                          "пари": dict(collections.Counter(f'{а[н]["оцінка"]}→{б[н]["оцінка"]}' for н in розб))}
json.dump(вих, open(f"{Т}/огляд_підсумок.json", "w"), ensure_ascii=False, indent=1)
for ім, р in вих.items():
    if ім == "розбіжність": print(ім, р); continue
    for вид, x in р.items(): print(ім, вид, {k: v for k, v in x.items() if k != "ні"}, "ні:", len(x["ні"]))
