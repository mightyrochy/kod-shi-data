"""Запит пояснення руки 1 ядра (`протокол.виклик`, текстова межа картки, мова `uk`) для кожного з 30 складів: каталог —
рядки таблиці каталогу саме речей складу; ситуація — записана (Н6: `руки.jsonl`; Н2: та сама сцена з `ядро/тести/
ситуації.py`); профіль — вхід показу (Н2: `вхід-v1.json`; Н6: файл жінки, без мірок — типові числа стенда 98/92/74/99/168).
Модель-заглушка: складання → усі речі пулу одним образом, ремонт → той самий склад, вибір → o1; руки 2–4 — «тиша».
Запит опису не надсилається: його тіло й фото пишуться у `/tmp/пс/опис_до/<n>.json`.
Запуск: python3 ядро_опис.py <корінь коду> [номер складу]"""
import ast, json, os, pickle, sys
КОРІНЬ = sys.argv[1]; sys.path.insert(0, КОРІНЬ + "/джерела")
from ядро import протокол, руки, суд
ВИРОКИ = []
_судити = суд.судити
def _ловити(*а, **к):
    в = _судити(*а, **к); ВИРОКИ.append(в); return в
суд.судити = _ловити
РЯДКИ = {р["id"]: р for р in pickle.load(open("/tmp/каталог_рядки.pkl", "rb"))}
СКЛАДИ = json.load(open("/tmp/пс/склади.json"))
ДАТА = "2026-11-25"
def v1_н2(сцена):
    в = json.load(open(f"{КОРІНЬ}/аудит/проби/н2-доробка-90ded3b/{сцена}/вхід-v1.json"))["вхід"]
    return ast.literal_eval(в) if isinstance(в, str) else в
ШАБЛОН = v1_н2("с3")
def v1_н6(тека):
    план = json.load(open(f"{КОРІНЬ}/{тека}/план.json"))
    ж = json.load(open(план["вхід"]["ZHINKA"].replace("/home/user/kod-shi-data", КОРІНЬ)))
    м = ж.get("мірки") or {}
    v = json.loads(json.dumps(ШАБЛОН))
    v["колір"].update({"шкіра": ж["skin"], "волосся": ж["hair"], "очі": ж["eyes"], "кільце": ж["ring"]})
    v["мірки"] = {"зріст": м.get("зріст", 168), "обхвати": {"плечі": м.get("плечі", 98), "груди": м.get("груди", 92),
                  "талія": м.get("талія", 74), "стегна": м.get("стегна", 99)}, "аксесуарні": {}}
    v["слова"] = план["слова"]; v["сценарій"] = {}
    return v, план["вхід"]["ZHINKA"].rsplit("/", 1)[-1]
def ситуація_н6(тека):
    с = None
    for л in open(f"{КОРІНЬ}/{тека}/руки.jsonl"):
        о = json.loads(л)
        if о.get("ситуація"): с = о["ситуація"]
    return с
def ситуація_н2(сцена):
    from ядро import ситуація as ч1
    from ядро.тести import ситуації
    с = ситуації.ситуація(сцена)
    return ч1.скласти(1, dict(с.сказала), ДАТА if сцена != "с5" else "2026-08-01").в_json()
def вхід_складу(с):
    т = с["тека"]
    if "н2-доробка" in т:
        сцена = т.rsplit("/", 1)[-1]
        профіль, жінка, сит = v1_н2(сцена), {"с3": "с3_оксана", "с5": "с5_оксана", "с8": "с8_юлія"}[сцена], ситуація_н2(сцена)
        дата = "2026-08-01" if сцена == "с5" else ДАТА
    else:
        (профіль, жінка), сит, дата = v1_н6(т), ситуація_н6(т), ДАТА
    кат = [РЯДКИ[і] for і in с["речі"]]
    return {"розмова": "посадка-" + с["ід"], "сід": 3, "дата": дата, "ситуація": сит, "профіль": профіль,
            "перемикачі": {"вибір": "list", "запис": "повний", "частин": 1}, "каталог": кат,
            "модель": {"вихід": 4000, "мова_картки": "uk"}}, жінка
def прогнати(вхід):
    в = json.loads(протокол.виклик(json.dumps({"дія": "почати", "вхід": вхід}, ensure_ascii=False)))
    черга = list(в.get("запити", [])); опис = None; журнал = []
    while not в.get("кінець") and черга:
        з = черга.pop(0)
        if з["рука"] != 1:
            відп = {"збій": {"вид": "тиша", "секунди": 300}}
        elif з["вид"] in ("складання", "ремонт"):
            тіло = json.loads(з["модель"]["messages"][0]["content"])
            пул = тіло.get("pool") or тіло.get("candidates")
            нн = [р[0] for р in пул["rows"]]
            відп = {"текст": json.dumps({"version": "1", "outfits": [{"id": "o1", "items": нн, "pole": "free"}]})}
            журнал.append((з["вид"], нн))
        elif з["вид"] == "вибір":
            відп = {"текст": json.dumps({"version": "1", "chosen": "o1", "why": "only outfit"})}
        elif з["вид"] == "опис" and опис is None:
            опис = з
            return опис, журнал, в
        else:
            відп = {"збій": {"вид": "тиша", "секунди": 300}}
        в = json.loads(протокол.виклик(json.dumps({"дія": "відповідь", "сесія": в.get("сесія") or з["сесія"],
                                                     "ключ": з["ключ"], "відповідь": відп}, ensure_ascii=False)))
        черга += в.get("запити", [])
    return опис, журнал, в
if __name__ == "__main__":
    os.makedirs("/tmp/пс/опис_до", exist_ok=True)
    які = [int(sys.argv[2])] if len(sys.argv) > 2 else range(len(СКЛАДИ))
    for і in які:
        с = СКЛАДИ[і]
        вхід, жінка = вхід_складу(с)
        ВИРОКИ.clear()
        опис, журнал, кінець = прогнати(вхід)
        if not опис:
            print(і, с["ід"], "НЕМА ОПИСУ", json.dumps(кінець, ensure_ascii=False)[:600]); continue
        тіло = json.loads(опис["модель"]["messages"][0]["content"])
        в_пулі = журнал[0][1] if журнал else []
        json.dump({"склад": с, "жінка": жінка, "профіль_мірки": вхід["профіль"]["мірки"], "запит": опис, "пул": в_пулі,
                   "вирок": ВИРОКИ[-1].в_json() if ВИРОКИ else None},
                  open(f"/tmp/пс/опис_до/{і:02d}.json", "w"), ensure_ascii=False)
        print(і, с["ід"], "речей", len(с["речі"]), "у пулі", len(в_пулі), "фото", len(опис["фото"]), "фактів", len(тіло.get("facts", {})))
