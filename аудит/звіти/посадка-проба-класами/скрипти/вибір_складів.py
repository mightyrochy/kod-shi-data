"""30 складів із записів Н6 і Н2: усі показані картки з реченням «не знаю» про посадку (звіт посадка-вимір, п.3) і
решта — перші різні склади кожної теки за порядком обмінів (складання, ремонт), без повторів набору речей."""
import json
сирі = json.load(open("/tmp/пс/склади_сирі.json")); карта = json.load(open("/tmp/пс/карта.json"))
НЕ_ЗНАЮ = {  # тека (кінець шляху) → обмін, образ показаної картки з реченням «не знаю»
    "н2-доробка-90ded3b/с3": (5, "o4"), "н2-доробка-90ded3b/с5": (4, "o1"), "н2-доробка-90ded3b/с8": (7, "o1"),
    "проба/ядро/1/с3": (3, "o4"), "проба/ядро/1/с11": (3, "o7"), "проба/ядро/1/с14": (3, "o1"),
    "проба/ядро/1/с24": (17, "o1")}
СКІЛЬКИ = {"проба/ядро/1/с25": 2, "с25-обірваний-повтор/ядро/1/с25": 1}
def кінець(т): return "/".join(т.split("/")[-4:]) if "хмара-sonnet" in т else "/".join(т.split("/")[-2:])
import glob
КАРТКИ = {}  # (тека, рука-образ) → іди показаної картки руки 1
for ф in glob.glob("/home/user/kod-shi-data/аудит/звіти/ядро-образу-наново/приймання/хмара-sonnet/*/ядро/1/*/руки.jsonl"):
    for л in open(ф):
        for c in json.loads(л).get("картки") or []:
            if c.get("рука") == 1 and c.get("речі"):
                КАРТКИ.setdefault(ф.rsplit("/", 1)[0].replace("/home/user/kod-shi-data/", ""), []).append(sorted(r["id"] for r in c["речі"]))
for ф in glob.glob("/home/user/kod-shi-data/аудит/проби/н2-доробка-90ded3b/с*/стан.json"):
    for c in json.load(open(ф))["картки"]:
        if c.get("рука") == 1 and c.get("речі"):
            КАРТКИ.setdefault(ф.rsplit("/", 1)[0].replace("/home/user/kod-shi-data/", ""), []).append(sorted(r["id"] for r in c["речі"]))
def іди(с):
    """Неоднозначний номер (кілька рядків каталогу з тими самими ціною, типом, словом кольору й полями) — ід із
    показаної картки руки 1 тієї ж теки, де склад збігся; інакше перший за абеткою (той самий товар, інший варіант)."""
    вар = [карта["|".join([с["тека"], str(с["обмін"]), н])] for н in с["склад"]]
    for картка in КАРТКИ.get(с["тека"], []):
        if all(set(в) & set(картка) for в in вар):
            return [sorted(set(в) & set(картка))[0] for в in вар]
    return [в[0] for в in вар]
вибрані, бачені = [], set()
теки = list(dict.fromkeys(с["тека"] for с in сирі))
for т in теки:
    к = кінець(т).replace("хмара-sonnet/", "").split("/", 0)[0]
    к = "/".join(т.split("/")[-4:]) if "хмара-sonnet" in т else "/".join(т.split("/")[-2:])
    к = к.split("хмара-sonnet/")[-1]
    свої = [с for с in сирі if с["тека"] == т]
    треба = СКІЛЬКИ.get(к, 3)
    взято = []
    нз = НЕ_ЗНАЮ.get(к)
    порядок = sorted(свої, key=lambda с: (0 if нз and (с["обмін"], с["образ"]) == нз else 1, с["обмін"]))
    for с in порядок:
        ії = іди(с)
        if None in ії: continue
        if frozenset(ії) in бачені: continue
        бачені.add(frozenset(ії))
        взято.append({"ід": f"{к}#{с['обмін']}:{с['образ']}", "тека": т, "обмін": с["обмін"], "образ": с["образ"],
                      "вид": с["вид"], "речі": ії, "не_знаю": bool(нз and (с["обмін"], с["образ"]) == нз)})
        if len(взято) == треба: break
    вибрані += взято
print(len(вибрані), sum(в["не_знаю"] for в in вибрані))
for в in вибрані: print(в["ід"], len(в["речі"]), в["не_знаю"])
json.dump(вибрані, open("/tmp/пс/склади.json", "w"), ensure_ascii=False, indent=1)
