def з_тексту(текст):
    текст = текст.strip()
    if текст.startswith("Catalogue photo for item "):
        _, початок, кінець = текст.partition('{"version":')
        текст = початок + кінець
    if текст.startswith("```"):
        текст = текст.split("\n", 1)[-1].lstrip()
    try:
        return json.JSONDecoder().raw_decode(текст)[0]
    except ValueError:
        return {}

