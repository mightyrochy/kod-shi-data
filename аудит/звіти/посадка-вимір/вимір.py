def пояснення_посадки(проходи):
    рахунок = {}
    for прохід, позначки in ПОЯСНЕННЯ.items():
        речення = []
        for картка in проходи[прохід]["картки"]:
            if картка["рука"] in (1, 2):
                речення.extend(re.split(r"(?<=[.!?])\s+|\n+", картка["опис"]))
        for фраза, причина in позначки:
            збіги = [р for р in речення if фраза in р]
            assert len(збіги) == 1, (прохід, фраза, len(збіги))
            рахунок.setdefault(прохід, []).append([збіги[0], причина])
    return рахунок

