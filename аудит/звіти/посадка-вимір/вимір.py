def мітки(модель):
    поля = {"слот": "слот", "тип": "тип", "крій": "крій", "довжина": "довжина_код",
            "тканина": "тканина", "каблук": "каблук_мітка"}
    for запис in рядки(ВИБІРКА / f"{модель}_новий.jsonl"):
        ід = запис["ід"]
        мітка = з_тексту(запис.get("текст") or "")["мітки"]
        дані = {}
        for ключ, поле in поля.items():
            ознака = мітка.get(ключ) or {}
            знач, дж = ознака.get("в"), ознака.get("дж")
            if ключ == "крій" and знач not in КРОЇ:
                continue
            факт(дані, поле, знач, дж)
            if ключ == "довжина" and знач not in НЕВІДОМО:
                слово = переклад_коду("length", знач)
                рівень, _ = атрибути.довжина_речі({"параметри": {"довжина": слово}}, мітка["слот"]["в"]) if слово else (None, None)
                if рівень in РІВЕНЬ_ЗОНА:
                    факт(дані, "край", рівень, дж)
            if ключ == "тканина" and знач not in НЕВІДОМО:
                фактура = переклад_коду("fabric", знач) or знач
                if фактура in ТКАНИНА_ФОРМАЛЬНІСТЬ:
                    факт(дані, "фактура_для_суду", фактура, дж)
            if ключ == "тип" and знач not in НЕВІДОМО:
                тип = переклад_коду("item_type", знач) or знач
                if інтервал_типу(тип)[0] is not None:
                    факт(дані, "тип_для_суду", тип, дж)
        yield ід, дані

def покриття(речі, застосовність):
    поля = defaultdict(Counter)
    лічба_правил = {}
    втрата = defaultdict(Counter)
    for ід, дані in речі.items():
        for поле, (_, дж) in дані.items():
            поля[поле][дж] += 1
    for правило, (_, ролі, _) in ПРАВИЛА.items():
        рахунки = []
        for слоти, входи in ролі:
            є = повні = 0
            for ід, дані in речі.items():
                if not застосовність[ід] & слоти:
                    continue
                є += 1
                бракує = [поле for поле in входи if поле not in дані]
                повні += not бракує
                for поле in бракує:
                    втрата[поле][правило] += 1
            рахунки.append([повні, є])
        лічба_правил[правило] = рахунки
    здатні = [ід for ід, ролі in лічба_правил.items()
              if ПРАВИЛА[ід][0] in ("доказ", "часткова репліка") and ролі
              and all(повні for повні, _ in ролі)]
    return {
        "щонайменше_один_свідок_кожної_ролі": здатні,
        "вхід": {поле: [sum(ліч.values()), ліч] for поле, ліч in sorted(поля.items())},
        "правило_за_ролями_повні_застосовні": лічба_правил,
        "немає_входу": dict(sorted(втрата.items(), key=lambda п: (-len(п[1]), -sum(п[1].values()), п[0]))),
    }

