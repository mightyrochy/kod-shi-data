def умови_прізвиська(к, П, м):
    вид = зн(к, "вид")
    різн = зн(к, "різновид_полотна")
    мат = зн(к, "матеріал")
    засіб = lambda що: є(к, "застібка", що, "засіб")
    def костюм():
        ч = к.get("склад") or []
        if not ч or not any(x.get("вид") in ("жакет", "жилет") for x in ч):
            return False
        р = {x.get("різновид_полотна", різн) for x in ч}
        кл = {str(x.get("колір", к.get("колір"))) for x in ч}
        return None not in р and len(р) == 1 and len(кл) == 1
    return {
        "костюм": lambda: вид == "комплект" and костюм(),
        "джинси": lambda: вид == "штани" and різн == "денім",
        "легінси": lambda: вид == "штани" and зн(к, "прилягання") == "облягає" and зн(к, "полотно") == "трикотаж",
        "лонгслів": lambda: вид == "футболка" and зн(к, "довжина_рукава") in ("зап'ястя", "кисть"),
        "поло": lambda: вид == "футболка" and зн(к, "комір") == "відкладний" and any(
            isinstance(x, dict) and x.get("засіб") == "ґудзики" and x.get("де") == "горловина" for x in к.get("застібка") or []),
        "худі": lambda: вид == "пуловер" and зн(к, "капюшон") in ("є", "знімний"),
        "світшот": lambda: вид == "пуловер" and різн == "футер",
        "водолазка": lambda: вид == "пуловер" and зн(к, "комір") == "гольф",
        "футляр": lambda: вид == "сукня" and зн(к, "силует") in ("прямий", "приталений")
                          and зн(к, "прилягання") in ("облягає", "по_фігурі")
                          and між(П, "тіло", зн(к, "довжина"), "вище_коліна", "нижче_коліна"),
        "тренч": lambda: вид == "пальто" and різн == "плащова" and зн(к, "бортність") == "двобортна"
                         and є(к, "додані_частини", "пасок"),
        "пуховик": lambda: вид in ("куртка", "пальто") and (зн(к, "утеплення") or {}).get("наповнювач") == "пух",
        "шуба": lambda: вид in ("пальто", "куртка") and мат in ("хутро", "штучне_хутро"),
        "дублянка": lambda: вид in ("пальто", "куртка") and мат == "овчина",
        "ботфорти": lambda: вид == "чоботи" and між(П, "тіло", зн(к, "висота_взуття"), "мочка", "вище_коліна"),
        "челсі": lambda: вид == "черевики" and засіб("гумки"),
        "угги": lambda: вид in ("черевики", "чоботи") and мат == "овчина" and зн(к, "форма_каблука") == "немає",
        "ботильйони": lambda: вид == "черевики" and каблук(к, 4) is True,
        "босоніжки": lambda: вид == "сандалі" and каблук(к, 3) is True,
        "човники": lambda: вид == "туфлі" and зн(к, "застібка") == "немає" and каблук(к, 3) is True,
        "палантин": lambda: вид == "шарф" and зн(к, "ширина_шарфа") == "широкий",
        "бейсболка": lambda: вид == "кепка" and зн(к, "структура") == "м'яка",
        "картуз": lambda: вид == "кепка" and зн(к, "структура") == "жорстка",
    }


def прізвисько(пр, П):
    умови = умови_прізвиська(пр["код"], П, пр["місце"])
    for назва in П["поля"]["прізвисько"]["виведено"]:
        if умови[назва]():
            return назва, "умова «%s» збіглась" % назва
    return None, "жодна умова не збіглась — у рядку вид"


