"""Виведені поля коду речі за правилами `проєкт_коду.yaml`, розділ «виведення».

`вивести(пр, П)` → {поле: (значення, слід)}. Значення — код, перелік кодів чи «невідомо»; поля, яке місцю не
стосується, у виході нема. Слід — якими кроками й з яких полів вийшло значення: ним пояснено розбіжності в
`дані/виведення.md`. Код продукту не імпортується: таблиці й джерела порогів — у YAML.
"""

НЕВІДОМО = "невідомо"
ВОВНА = ("вовна", "кашемір", "альпака", "мохер", "ангора")
ТКАНІ = ("тканина", "мереживо", "сітка", "нетканий", "плетіння")


def зн(код, поле):
    """Відоме значення поля; None — нема, «невідомо», «не певний»."""
    в = код.get(поле)
    if в is None or в == НЕВІДОМО or (isinstance(в, dict) and "не_певний" in в):
        return None
    return в


def основа(код):
    """Волокна основи [(волокно, частка чи None)]; одне волокно без частки — 100 %."""
    в = [(x["волокно"], x.get("частка")) for x in код.get("волокно") or [] if isinstance(x, dict)
         and x.get("де", "основа") == "основа" and x.get("волокно") not in (None, НЕВІДОМО)]
    if len(в) == 1 and в[0][1] is None:
        return [(в[0][0], 100)]
    return в


def домінантне(код):
    """Волокно з найбільшою часткою основи; частки невідомі при кількох волокнах — None."""
    в = основа(код)
    if not в or any(ч is None for _, ч in в):
        return None
    return max(в, key=lambda x: x[1])[0]


def частка_вовни(код):
    в = основа(код)
    if not в or any(ч is None for в_, ч in в if в_ in ВОВНА):
        return None
    return sum(ч for в_, ч in в if в_ in ВОВНА)


def в_шкалі(П, шкала, з, від):
    ш = list(П["шкали"][шкала])
    return з in ш and ш.index(з) >= ш.index(від)


def між(П, шкала, з, від, до):
    ш = list(П["шкали"][шкала])
    return з in ш and ш.index(від) <= ш.index(з) <= ш.index(до)


def каблук(код, поріг):
    """True — каблук ≥ поріг; False — нижче; None — невідомо чи інтервал навколо порогу."""
    в = код.get("каблук_см")
    if isinstance(в, (int, float)) and not isinstance(в, bool):
        return в >= поріг
    if isinstance(в, dict) and "не_певний" in в:
        ч = [float(x) for x in str(в["не_певний"]).replace("[", "").replace("]", "").replace("–", ",").split(",")
             if x.strip().replace(".", "").isdigit()]
        if ч and all(x >= поріг for x in ч):
            return True
        if ч and all(x < поріг for x in ч):
            return False
    return None


def є(код, поле, що, ключ="що"):
    """Чи складене поле має частину зі значенням `що` (рядок чи кортеж)."""
    що = (що,) if isinstance(що, str) else що
    return any(isinstance(x, dict) and x.get(ключ) in що for x in код.get(поле) or [])


# ---------------------------------------------------------------- місце
def місце(пр, П):
    вид = зн(пр["код"], "вид")
    if not вид:
        return НЕВІДОМО, "вид невідомо"
    де = [м for м, зн_ in П["поля"]["вид"]["значення_за_місцем"].items() if вид in зн_]
    if len(де) == 1:
        return де[0], "вид %s — у переліку місця %s" % (вид, де[0])
    if "кольє" in де and пр["код"].get("довжина_на_тілі") not in (None, НЕВІДОМО):
        return "кольє", "вид %s — у %s; довжина на тілі відома → кольє" % (вид, " і ".join(де))
    return {"не_певний": де}, "вид %s — у %s, довжина на тілі невідома" % (вид, " і ".join(де))


