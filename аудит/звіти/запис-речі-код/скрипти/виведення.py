def ключ_за_умовою(к, П):
    """Ключі `ключ_за_умовою` (тип_ядра), які можна порахувати з полів."""
    вид, різн = зн(к, "вид"), зн(к, "різновид_полотна")
    if вид == "сукня" and в_шкалі(П, "тіло", зн(к, "довжина"), "середина_литки") and (
            різн in ("сатин", "оксамит") or зн(к, "блиск") == "мерехтливий"
            or any(isinstance(x, dict) and x.get("що") == "паєтки" and x.get("скільки") == "суцільно" for x in к.get("оздоба") or [])):
        return "evening_dress"
    if вид == "комплект" and (зн(к, "полотно") in ("трикотаж", "в'язане")
                              or any(x.get("полотно") in ("трикотаж", "в'язане") for x in к.get("склад") or [])):
        return "casual_suit"
    if вид == "туфлі" and каблук(к, 1.01) is False and зн(к, "товщина_підошви") == "тонка":
        return "ballet_flats"
    if зн(к, "матеріал_підошви") == "джут":
        return "espadrilles"
    if вид == "сумка":
        розм, форма, стр = зн(к, "розмір_сумки"), зн(к, "форма_сумки"), зн(к, "структура")
        ручки = [x.get("вид") for x in к.get("ручки") or [] if isinstance(x, dict)]
        клапан = є(к, "деталі", "клапан")
        if стр in ("напівжорстка", "жорстка") and форма == "півмісяць" and клапан:
            return "saddle_bag"
        if форма == "півмісяць" and стр == "м'яка":
            return "hobo_bag"
        if стр == "жорстка" and форма == "горизонтальна" and розм == "велика":
            return "briefcase"
        if форма in ("циліндр", "мішечок"):
            return "bucket_bag"
        if форма == "горизонтальна" and розм in ("міні", "мала") and "плечова" in ручки:
            return "baguette_bag"
        if розм == "велика" and ручки and set(ручки) <= {"коротка", "плечова"}:
            return "tote"
        if "довга" in ручки and розм in ("міні", "мала", "середня"):
            return "crossbody_bag"
    return None


def умова(к, текст_ознак, П):
    """Ознаки стелі драбини — та сама таблиця, що в YAML; повертає назву ознаки, що збіглась, чи None."""
    вид, різн, пол = зн(к, "вид"), зн(к, "різновид_полотна"), зн(к, "полотно")
    мат, пов, бл = зн(к, "матеріал"), зн(к, "поверхня"), зн(к, "блиск")
    дом = домінантне(к)
    замша = мат == "шкіра" and пов == "ворсова"
    ознаки = {
        "neat": [("кросівки чи кеди", вид in ("кросівки", "кеди")), ("футер чи фліс", різн in ("футер", "фліс")),
                 ("потертий денім", різн == "денім" and пов == "потерта")],
        "smart": [("вид %s" % вид, вид in ("футболка", "кімоно", "мюлі", "шльопанці")),
                  ("матова замша взуття", замша and бл == "матовий" and вид in П["поля"]["вид"]["значення_за_місцем"]["взуття"])],
        "formal": [("в'язаний кардиган", вид == "кардиган" and пол == "в'язане"),
                   ("сандалі на стовпчику", вид == "сандалі" and зн(к, "форма_каблука") == "стовпчик"),
                   ("матова бавовна", дом == "бавовна" and бл == "матовий")],
        "very_smart": [("бавовна", дом == "бавовна"), ("трикотаж чи в'язане", пол in ("трикотаж", "в'язане")),
                       ("замша", замша), ("сандалі", вид == "сандалі"), ("кардиган", вид == "кардиган")],
    }[текст_ознак]
    return next((н for н, так in ознаки if так), None)


def модифікатор(к, ключ_мод, ключ_бази):
    різн, пол = зн(к, "різновид_полотна"), зн(к, "полотно")
    нагода = к.get("нагода_крамниці") or []
    нагода = нагода if isinstance(нагода, list) else [нагода]
    return {
        "джинси": різн == "денім" and ключ_бази != "джинси",
        "трикотаж": пол in ("трикотаж", "в'язане") and ключ_бази in ("сукня_без_уточнення", "спідниця", "штани", "комбінезон",
                                                        "комплект", "блейзер"),
        "сорочка": різн == "сорочкова" and ключ_бази == "сукня_без_уточнення",
        "спортивний": "спорт" in нагода,
        "домашнє": "дім" in нагода,
    }[ключ_мод]


def полярність(к, код_п):
    мат, різн, бл, пов = зн(к, "матеріал"), зн(к, "різновид_полотна"), зн(к, "блиск"), зн(к, "поверхня")
    пол, тов = зн(к, "полотно"), зн(к, "товщина")
    return {
        "leather": мат in ("шкіра", "штучна_шкіра"),
        "satin": різн == "сатин",
        "tweed_boucle": різн in ("твід", "букле"),
        "smooth_shine": бл in ("глянцевий", "дзеркальний") and пов == "гладка",
        "silk_shine": бл == "шовковистий",
        "knit_chunky": пол == "в'язане" and тов == "товста",
        "knit_fine": пол == "в'язане" and тов == "тонка",
        "smooth_matte": бл == "матовий" and пов == "гладка",
    }[код_п]


def щаблі(В, лоу, хай):
    вих = [щ for щ, (л, х) in В["щаблі"].items() if л <= хай and х >= лоу]
    return вих[0] if len(вих) == 1 else "%s–%s" % (вих[0], вих[-1])


def ошатність(пр, П, прізв):
    В = П["виведення"]["ошатність"]
    к = пр["код"]
    слід = []
    умова_т = ключ_за_умовою(к, П)
    ключ = В["ключ_за_умовою"].get(умова_т) if умова_т else None
    if ключ:
        слід.append("тип_ядра %s → %s" % (умова_т, ключ))
    elif прізв and прізв in В["ключ_типу"]:
        ключ = В["ключ_типу"][прізв]
        слід.append("прізвисько %s → %s" % (прізв, ключ))
    elif зн(к, "вид") in В["ключ_типу"]:
        ключ = В["ключ_типу"][зн(к, "вид")]
        слід.append("вид %s → %s" % (зн(к, "вид"), ключ))
    if not ключ:
        return НЕВІДОМО, None, "ключа типу нема (вид %s)" % (зн(к, "вид") or НЕВІДОМО)
    лоу, хай = В["інтервал"][ключ]
    слід[-1] += " %d–%d" % (лоу, хай)
    for м in В["модифікатори"]:
        if модифікатор(к, м["ключ"], ключ):
            мл, мх = В["інтервал"][м["ключ"]]
            нл, нх = max(лоу, мл), min(хай, мх)
            лоу, хай = (нл, нх) if нл <= нх else (мл, мх)
            слід.append("∩ %s %d–%d → %d–%d%s" % (м["ключ"], мл, мх, лоу, хай, "" if нл <= нх else " (порожній — модифікатор)"))
    for п in В["полярності"]:
        if полярність(к, п["код"]):
            лоу, хай = лоу + п["зсув"][0], хай + п["зсув"][1]
            if п["зсув"] != [0, 0]:
                слід.append("полярність %s %+d/%+d → %d–%d" % (п["код"], п["зсув"][0], п["зсув"][1], лоу, хай))
            break
    for с in В["стеля"]:
        н = умова(к, с["щабель"], П)
        if н:
            стеля = В["щаблі"][с["щабель"]][0] - 1
            if хай > стеля:
                хай, лоу = стеля, min(лоу, стеля)
                слід.append("стеля %s вибиває «%s» → %d–%d" % (с["щабель"], н, лоу, хай))
            break
    лоу, хай = max(1, лоу), min(10, хай)
    return щаблі(В, лоу, хай), (лоу, хай), "; ".join(слід)


# ---------------------------------------------------------------- тепло
ПОРЯДОК_ТЕПЛА = ("light", "medium", "warm")


def клас_полотна(к, П, до_товщини=False):
    """Клас полотна після товщини (чи до неї) і слід; None — класу нема."""
    В = П["виведення"]["тепло"]["клас"]
    знайдено = []
    for кл, ознаки in В.items():
        for поле, коди in ознаки.items():
            if поле == "волокно":
                continue
            з = зн(к, {"різновид": "різновид_полотна"}.get(поле, поле))
            if з in коди:
                знайдено.append((кл, "%s %s" % (поле, з)))
    дом, вовна = домінантне(к), частка_вовни(к)
    if вовна is not None and вовна >= 60:
        знайдено.append(("warm", "вовна %d %%" % вовна))
    elif дом and дом not in ВОВНА:
        for кл, ознаки in В.items():
            if дом in ознаки.get("волокно", ()):
                знайдено.append((кл, "волокно %s" % дом))
    elif вовна is not None:
        знайдено.append((None, "вовна %d %% < 60" % вовна))
    if not any(кл for кл, _ in знайдено):
        return None, ", ".join(с for _, с in знайдено) or "ознак класу нема"
    кл = max((кл for кл, _ in знайдено if кл), key=ПОРЯДОК_ТЕПЛА.index)
    слід = ", ".join(с for _, с in знайдено) + " → " + кл
    if до_товщини:
        return кл, слід
    тов = зн(к, "товщина")
    і = ПОРЯДОК_ТЕПЛА.index(кл) + {"тонка": -1, "товста": 1}.get(тов, 0)
    і = min(max(і, 0), 2)
    if ПОРЯДОК_ТЕПЛА[і] != кл:
        слід += "; товщина %s → %s" % (тов, ПОРЯДОК_ТЕПЛА[і])
    return ПОРЯДОК_ТЕПЛА[і], слід


def ступінь_утеплення(к):
    у = к.get("утеплення")
    if isinstance(у, dict) and "не_певний" not in у:
        с = у.get("ступінь")
        return None if с in (None, НЕВІДОМО) else с
    return None


def тепло(пр, П, місця_утеплення):
    к = пр["код"]
    кл, слід = клас_полотна(к, П)
    ст = ступінь_утеплення(к)
    з_утепл = П["виведення"]["тепло"]["утеплення"].get(ст)
    if ст is None and пр["місце"] in місця_утеплення and кл != "warm":
        return НЕВІДОМО, слід + "; утеплення невідоме, клас не warm → невідомо"
    відомі = [x for x in (кл, з_утепл) if x]
    if not відомі:
        return НЕВІДОМО, слід + "; утеплення %s" % (ст or НЕВІДОМО)
    з = max(відомі, key=ПОРЯДОК_ТЕПЛА.index)
    return з, слід + "; утеплення %s → %s" % (ст or НЕВІДОМО, з)


# ---------------------------------------------------------------- погода
def смуги_текстом(В, смуги):
    п = [с for с in В["смуги"] if с in смуги]
    if len(п) == len(В["смуги"]):
        return "усі"
    і = [В["смуги"].index(с) for с in п]
    if і == list(range(і[0], і[-1] + 1)):
        return п[0] if len(п) == 1 else "%s–%s" % (п[0], п[-1])
    return ",".join(п)


def погода(пр, П, тепло_з, прізв):
    В = П["виведення"]["погода"]
    к = пр["код"]
    м = пр["місце"]
    усі = list(В["смуги"])
    ст = ступінь_утеплення(к)
    одяг = П["групи"]["одяг"]
    if зн(к, "вид") in В["шар_види"] or (м == "комплект" and ст in ("тепле", "легке")):
        напов = (к.get("утеплення") or {}).get("наповнювач") if isinstance(к.get("утеплення"), dict) else None
        мат = зн(к, "матеріал")
        if ст == "тепле" and (напов in ("пух", "хутро") or мат in ("хутро", "штучне_хутро", "овчина")):
            см, слід = В["шар"]["тепле_пух_хутро"], "утеплення тепле, %s" % (напов or мат)
        elif ст in ("тепле", "легке"):
            см, слід = В["шар"][ст], "утеплення %s" % ст
        elif тепло_з in ("light", "medium", "warm"):
            см, слід = list(В["шар"][тепло_з]), "тепло %s, утеплення %s" % (тепло_з, ст or НЕВІДОМО)
            if ст is None and усі.index(см[0]) > 0:
                см = [усі[усі.index(см[0]) - 1]] + см
                слід += " → смуга холодніше"
        else:
            return НЕВІДОМО, "тепловий шлях: тепло невідоме"
        вовна = частка_вовни(к)
        if зн(к, "різновид_полотна") == "плащова" and (вовна is None or вовна < 60) and ст in (None, "немає"):
            см = [с for с in см if с not in ("deep_frost", "frost")] or см
            слід += "; тренч-тканина без вовни — без морозних (K-OUT-20)"
        return смуги_текстом(В, см), слід
    if м in одяг:
        кл, слід_к = клас_полотна(к, П, до_товщини=True)
        холодне = ((кл == "warm" and зн(к, "товщина") in ("середня", "товста"))
                   or зн(к, "різновид_полотна") in ("оксамит", "велюр")
                   or (зн(к, "полотно") == "в'язане" and зн(к, "товщина") == "товста"))
        літнє = домінантне(к) == "льон"
        if холодне and not літнє:
            return смуги_текстом(В, В["сезонне"]["холодне"]["смуги"]), "холодне читання тканини (%s)" % слід_к
        if літнє and not холодне:
            return смуги_текстом(В, В["сезонне"]["літнє"]["смуги"]), "літнє читання: льон основою"
        return "усі", "сезонного читання нема (%s)" % слід_к
    if м == "взуття":
        умова_т = ключ_за_умовою(к, П)
        ключ = {"ballet_flats": "балетки", "espadrilles": "еспадрильї"}.get(умова_т) or \
            {"угги": "уггі"}.get(прізв, прізв if прізв in ("човники", "ботфорти", "челсі", "босоніжки") else None) or зн(к, "вид")
        см = [с for с in усі if ключ in В["ноги"].get(с, ())]
        if not см:
            return НЕВІДОМО, "тип %s без рядка в таблиці ніг" % ключ
        слід = "тип %s" % ключ
        if ст == "тепле":
            н = [с for с in см if с in ("deep_frost", "frost", "cold")]
            см = н or ["deep_frost", "frost", "cold"]
            слід += "; утеплення тепле → пальтові смуги%s" % ("" if н else " (зіткнення — бере утеплення)")
        if зн(к, "носок") == "відкритий" or зн(к, "п'ята") in ("відкрита", "ремінець"):
            н = [с for с in см if с in ("mild", "warm", "hot")]
            см = н or ["mild", "warm", "hot"]
            слід += "; відкрите → літні смуги"
        return смуги_текстом(В, см), слід
    if м in ("головний_убір", "шарф"):
        мат, дом = зн(к, "матеріал"), домінантне(к)
        зимовий = (дом in ВОВНА or зн(к, "різновид_полотна") == "фліс"
                   or мат in ("хутро", "штучне_хутро", "овчина"))
        літній = мат == "солома" or дом in ("бавовна", "льон", "шовк")
        if зимовий and not літній:
            return смуги_текстом(В, В["аксесуари"]["зимовий"]["смуги"]), "зимовий матеріал (K-WEA-08)"
        if літній and not зимовий:
            return смуги_текстом(В, В["аксесуари"]["літній"]["смуги"]), "літній матеріал (K-WEA-08)"
        return "усі", "матеріал без сезону чи невідомий"
    return None, ""


# ---------------------------------------------------------------- розтяжність, як носять
def розтяжність(пр, П):
    к = пр["код"]
    пол, мат = зн(к, "полотно"), зн(к, "матеріал")
    ел = [ч for в, ч in основа(к) if в == "еластан"]
    if пол in ("трикотаж", "в'язане"):
        return "тягнеться", "полотно %s" % пол
    if ел and ел[0] is not None and ел[0] >= 2:
        return "тягнеться", "еластан %g %% ≥ 2" % ел[0]
    if мат and мат != "текстиль":
        return "не_тягнеться", "матеріал %s" % мат
    в = основа(к)
    if пол in ТКАНІ and в and all(ч is not None for _, ч in в):
        return "не_тягнеться", "полотно %s, склад відомий, еластану < 2 %%" % пол
    return НЕВІДОМО, "полотно %s, склад %s" % (пол or НЕВІДОМО, "без часток" if в else НЕВІДОМО)


def як_носять(пр, П):
    к = пр["код"]
    вид = зн(к, "вид")
    if вид == "рюкзак":
        return ["на_спині"], "рюкзак"
    if вид == "поясна":
        return ["на_поясі"], "поясна"
    способи = {"коротка": ["у_руці"], "плечова": ["на_плечі"], "довга": ["через_плече"],
               "ланцюжок": ["на_плечі", "через_плече"]}
    вих = ["у_руці"] if вид == "клатч" else []
    for р in к.get("ручки") or []:
        if isinstance(р, dict):
            вих += [с for с in способи.get(р.get("вид"), []) if с not in вих]
    if not вих:
        return НЕВІДОМО, "ручки невідомі"
    return вих, "ручки: " + ", ".join(вих)


# ---------------------------------------------------------------- усе разом
def вивести(пр, П, місця_поля):
    вих = {}
    з, с = місце(пр, П)
    вих["місце"] = (з, с)
    прізв, с = прізвисько(пр, П)
    if прізв:
        вих["прізвисько"] = (прізв, с)
    о, _, с = ошатність(пр, П, прізв)
    вих["ошатність"] = (о, с)
    т = None
    if пр["місце"] in місця_поля("тепло"):
        т, с = тепло(пр, П, місця_поля("утеплення"))
        вих["тепло"] = (т, с)
    if пр["місце"] in місця_поля("погода"):
        вих["погода"] = погода(пр, П, т, прізв)
    if пр["місце"] in місця_поля("розтяжність"):
        вих["розтяжність"] = розтяжність(пр, П)
    if пр["місце"] in місця_поля("як_носять"):
        вих["як_носять"] = як_носять(пр, П)
    return вих
