"""Токени пулу с5 на кандидата за колонками (вибірка 300, мітки Sonnet нового запису) — щоб порівняти стислий рядок
з чинним рядком пулу. Без моделі: ядро складає запит обвʼязкою тестів, токени — `міра_токенів.токенів`, як у `запит.py`.
Запуск з кореня (кілька хвилин): python3 -I аудит/звіти/запис-речі-код/скрипти/колонки_пулу.py > аудит/звіти/запис-речі-код/дані/пул_колонки.txt"""
import json, sys, collections
import os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../.."))
sys.path.insert(0, "аудит/проби/запис-речі-вибірка-300/скрипти"); sys.path.insert(0, "джерела")
import мірило_нового as м
from ядро import протокол
from ядро.тести import обвязка
from міра_токенів import токенів
import запис_речі
рядки = м.каталог()
ід = [в["ід"] for в in json.load(open(м.Д / "вибірка.json", encoding="utf-8")) if в["ід"] in рядки]
ж = м._журнал("sonnet_новий")
кат = []
for і in ід:
    р = dict(рядки[і])
    if і in ж:
        розб = запис_речі.розібрати(ж[і]["текст"])
        р["мітки_речі"] = {"опис": розб["опис"], "мітки": розб["мітки"]}
    кат.append(р)
в = обвязка.почати(протокол, обвязка.вхід_с5(каталог=кат))
запит = next(з for з in в["запити"] if з["вид"] == "складання")
пул = json.loads(запит["модель"]["messages"][0]["content"])["pool"]
к = len(пул["rows"])
усього = токенів(json.dumps(пул["rows"], ensure_ascii=False, separators=(",", ":")))
print("кандидатів", к, "на кандидата", round(усього / к, 1))
for і, кол in enumerate(пул["cols"]):
    т = токенів(json.dumps([р[і] for р in пул["rows"]], ensure_ascii=False, separators=(",", ":")))
    print("%-22s %6.1f" % (кол, т / к), json.dumps(пул["rows"][0][і], ensure_ascii=False)[:60])
