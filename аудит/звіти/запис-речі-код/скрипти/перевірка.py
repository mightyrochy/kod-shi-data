def _без_повторів(завантажувач, вузол, deep=False):
    бачені = set()
    for к, _ in вузол.value:
        ключ = завантажувач.construct_object(к, deep=deep)
        if ключ in бачені:
            raise ValueError("повтор ключа «%s» у рядку %d" % (ключ, к.start_mark.line + 1))
        бачені.add(ключ)
    return завантажувач.construct_mapping(вузол, deep)


_Л.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _без_повторів)


