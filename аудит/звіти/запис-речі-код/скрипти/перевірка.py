def вартість(приклади):
    """Поля на прохід за місцем, вихідні токени й секунди на річ (зі швидкості Sonnet у журналі вибірки 300)."""
    з = [json.loads(л) for л in open(ВИБІРКА / "sonnet_новий.jsonl", encoding="utf-8")]
    з = [x for x in з if x.get("статус") == "ok"]
    вих = [int(x["вихід"]) for x in з]
    сек = [float(x["с"]) for x in з]
    знаків_на_токен = sum(len(x["текст"]) for x in з) / sum(вих)
    опис = []
    for x in з:
        try:
            опис.append(len(json.loads(x["текст"]).get("опис") or "") / знаків_на_токен)
        except ValueError:
            pass
    сх, ск = statistics.mean(вих), statistics.mean(сек)
    б = sum((а - сх) * (с - ск) for а, с in zip(вих, сек)) / sum((а - сх) ** 2 for а in вих)
    а = ск - б * сх
    поля_модель = [п for п, о in ПОЛЯ.items() if о["джерело"] != ["код"]]
    за_місцем = {м: [п for п in поля_модель if м in місця_поля(п)] for м in МІСЦЯ}
    нові = []
    for пр in приклади:
        текст = json.dumps({п: [з, "к" if п in пр.get("крамниця", []) else "ф"] for п, з in пр["код"].items()},
                           ensure_ascii=False, separators=(",", ":"))
        нові.append(len(текст) / знаків_на_токен)
    картки_за_місцем = {}
    for м, пп in за_місцем.items():
        т = []
        for п in пп:
            о = ПОЛЯ[п]
            if п == "вид":
                т += ["%s=%s" % (к, розібрати(в)[1]) for к, в in переліки_вид().get(м, {}).items()]
                continue
            т.append(п + ": " + о["означення"])
            for _, пер in частини(п).items():
                if isinstance(пер, dict):
                    т += ["%s=%s" % (к, розібрати(в)[1]) for к, в in пер.items()]
            if п == "вид":
                т += ["%s=%s" % (к, розібрати(в)[1]) for к, в in переліки_вид().get(м, {}).items()]
        картки_за_місцем[м] = len("\n".join(т)) / знаків_на_токен
    return {"полів_моделі_за_місцем": {м: len(пп) for м, пп in за_місцем.items()},
            "картки_ток_за_місцем": {м: round(т) for м, т in картки_за_місцем.items()},
            "нині_вихід_мед": statistics.median(вих), "нині_с_мед": statistics.median(сек),
            "знаків_на_токен": round(знаків_на_токен, 2), "с_за_токен": round(б, 4), "с_постійні": round(а, 2),
            "новий_код_вихід_мед": round(statistics.median(нові)), "новий_код_вихід_макс": round(max(нові)),
            "нині_опис_вихід_мед": round(statistics.median(опис)),
            "с_код_мед": round(а + б * statistics.median(нові), 1),
            "с_код_і_опис_мед": round(а + б * (statistics.median(нові) + statistics.median(опис)), 1),
            "каталог_речей": РЕЧЕЙ_КАТАЛОГУ,
            "каталог_год_код": round(РЕЧЕЙ_КАТАЛОГУ * (а + б * statistics.median(нові)) / 3600, 1),
            "каталог_год_код_і_опис": round(РЕЧЕЙ_КАТАЛОГУ * (а + б * (statistics.median(нові) + statistics.median(опис))) / 3600, 1),
            "каталог_вихід_млн_ток_код": round(РЕЧЕЙ_КАТАЛОГУ * statistics.median(нові) / 1e6, 1)}


