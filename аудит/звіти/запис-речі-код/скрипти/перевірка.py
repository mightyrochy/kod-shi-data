def таблиця_фактів(шлях):
    рядки = [р for р in open(шлях, encoding="utf-8").read().splitlines() if р.startswith("|")]
    шапка = [к.strip() for к in рядки[0].strip("|").split("|")]
    вихід = {}
    for р in рядки[3:]:
        к = [x.strip() for x in р.strip("|").split("|")]
        вихід[к[0]] = {шапка[і]: (int(к[і]) if к[і].isdigit() else 0) for і in range(1, len(шапка))}
    return вихід


def мірило_а():
    """Пара «вид факту × місце» з часткою ≥ 2 % має поле, що діє для місця, чи причину поза кодом; таблиця — дані/повнота.md."""
    т = таблиця_фактів(Т / "дані/факти_описів.md")
    пер, за_місцем = П["факти"], П.get("факти_місця") or {}
    вади, пар, рядки = [], 0, []
    for вид, частки in т.items():
        if вид not in пер:
            вади.append("вид факту без поля: %s" % вид)
            continue
        for місце, ч in частки.items():
            if ч < 2:
                continue
            пар += 1
            цілі = []
            for ц in (за_місцем.get(вид) or {}).get(місце) or пер[вид]:
                if ц.startswith("поза:"):
                    if ц[5:] not in П["поза_кодом"]:
                        вади.append("%s: «%s» нема в поза_кодом" % (вид, ц))
                    цілі.append(ц.replace("поза:", "поза: ").replace("_", " "))
                elif ц not in ПОЛЯ:
                    вади.append("%s: нема поля %s" % (вид, ц))
                else:
                    мм = місця_поля(ц)
                    if місце in мм or (місце == "прикраси" and мм & set(ГРУПИ["прикраси"])):
                        цілі.append("`%s`" % ц)
            if not цілі:
                вади.append("%s (%s, %d %%): жодне поле не діє для місця" % (вид, місце, ч))
            рядки.append("| %s | %s | %d | %s |" % (вид, місце, ч, ", ".join(цілі) or "**нема**"))
    (Т / "дані/повнота.md").write_text("\n".join(
        ["# Повнота: вид факту описів × місце (частка ≥ 2 %) → поле коду", "",
         "Згенеровано `скрипти/перевірка.py` з `дані/факти_описів.md` і `проєкт_коду.yaml` (`факти`, `факти_місця`).", "",
         "| вид факту | місце | % речей | поле чи причина поза кодом |", "|---|---|---:|---|"] + рядки) + "\n",
        encoding="utf-8")
    return пар, вади


