def назва_значення(поле, частина, з, місце=None):
    if isinstance(з, dict) and "не_певний" in з:
        return " чи ".join(назва_значення(поле, частина, к, місце) for к in з["не_певний"])
    if поле == "вид":
        return розібрати(переліки_вид()[місце][з])[0]
    if isinstance(з, (int, float)):
        return ("%g" % з).replace(".", ",")
    п = частини(поле)[частина]
    if isinstance(з, str) and "–" in з and isinstance(п, dict) and all(к in п for к in з.split("–")):
        return "–".join(розібрати(п[к])[0] for к in з.split("–"))
    if isinstance(п, dict) and з in п:
        return розібрати(п[з])[0]
    return str(з)


def у_рядку(поле, з, місце=None):
    правило = str(ПОЛЯ[поле].get("у_рядку", "ні"))
    if правило.startswith("ні") or з in СТАНИ or з in ("немає", "без", []):
        return False
    if isinstance(з, dict) and list(з.values())[:1] == ["немає"]:
        return False
    м = re.search(r"лише місця ([^—]+)", правило)
    if м and місце not in [x.strip() for x in м.group(1).split(",")] and \
            not (місце in ГРУПИ["прикраси"] and "прикраси" in м.group(1)):
        return False
    if isinstance(з, str):
        try:
            імена = (з, назва_значення(поле, None, з))
        except (KeyError, TypeError):
            імена = (з,)
        м = re.search(r"якщо не ([^,;\s]+)(?: чи ([^,;\s(]+))?", правило)
        if м and (м.group(1) in імена or м.group(2) in імена):
            return False
        м = re.search(r"якщо (?!не |є)([^,;\s]+)(?: чи ([^,;\s—]+))?", правило)
        if м and м.group(1) not in імена and м.group(2) not in імена:
            return False
    return True


def рядок(пр):
    код = dict(пр["код"])
    виведено = пр.get("виведено") or {}
    місце = пр["місце"]
    шматки = []
    for поле in ПОРЯДОК:
        if поле == "вид" and "прізвисько" in виведено:
            continue
        if поле == "полотно" and "різновид_полотна" in код:
            continue
        з = виведено.get(поле, код.get(поле))
        if з is None:
            continue
        if поле == "склад":
            шматки.append(" + ".join(рядок({"код": ч, "місце": ч["місце"]}) for ч in з))
            continue
        if поле not in виведено and not у_рядку(поле, з, місце):
            continue
        if поле == "розтяжність" and з != "тягнеться":
            continue
        ч = частини(поле)
        текст = []
        for в in (з if isinstance(з, list) else [з]):
            if None in ч or (isinstance(в, dict) and "не_певний" in в):
                текст.append(назва_значення(поле, None, в, місце))
            elif isinstance(в, dict):
                if поле == "волокно" and (в.get("де", "основа") != "основа" or текст):
                    continue
                назви = [назва_значення(поле, к, вв) for к, вв in в.items()
                         if к in ЧАСТИНИ_РЯДКА.get(поле, (к,)) and вв not in ЗВИЧНІ.get(поле, ()) and вв not in СТАНИ]
                if назви and " ".join(назви) not in текст:
                    текст.append(" ".join(назви))
        текст = [т for т in текст if т]
        if поле == "довжина_рукава" and з in ("без_рукава", "бретелі"):
            шматки.append(", ".join(текст))
        elif текст:
            шматки.append(ШАБЛОН.get(поле, "{}").format(", ".join(текст)))
    return "; ".join(шматки)


