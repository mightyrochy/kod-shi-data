def значення_ок(поле, частина, з, вади, де):
    п = частини(поле)[частина]
    if isinstance(з, str) and з in СТАНИ:
        return
    if isinstance(з, dict) and "не_певний" in з:
        for к in з["не_певний"]:
            значення_ок(поле, частина, к, вади, де)
        return
    if isinstance(п, tuple):
        if п[0] == "число":
            if not (isinstance(з, (int, float)) or re.fullmatch(r"\d+(\.\d+)?–\d+(\.\d+)?", str(з))):
                вади.append("%s: «%s» не число" % (де, з))
        elif п[0] == "реєстр" and поле == "колір":
            from ядро import відтінки
            if з not in відтінки.КОДИ:
                вади.append("%s: «%s» нема в реєстрі відтінків ядра" % (де, з))
        return
    if isinstance(з, str) and "–" in з and ПОЛЯ[поле].get("шкала") or (частина and "шкала" in (ПОЛЯ[поле].get("склад", {}).get(частина) or {}) and isinstance(з, str) and "–" in з):
        for к in з.split("–"):
            if к not in п:
                вади.append("%s: «%s» поза шкалою" % (де, к))
        return
    if з not in п:
        вади.append("%s: «%s» поза переліком" % (де, з))


def мірило_б(приклади):
    вади = []
    for пр in приклади:
        м = пр["місце"]
        if м not in МІСЦЯ:
            вади.append("%s: місце «%s»" % (пр["ід"], м))
        код = пр["код"]
        if код.get("вид") not in переліки_вид().get(м, {}) and код.get("вид") not in СТАНИ:
            вади.append("%s: вид «%s» не з місця %s" % (пр["ід"], код.get("вид"), м))
        for поле, з in код.items():
            де = "%s.%s" % (пр["ід"], поле)
            if поле == "вид":
                continue
            if поле == "склад":
                for ч in з:
                    вади += мірило_б([{"ід": пр["ід"] + "/" + ч["вид"], "місце": ч["місце"],
                                        "код": {к: в for к, в in ч.items() if к != "місце"}}])
                continue
            if поле not in ПОЛЯ:
                вади.append("%s: поля нема в проєкті" % де)
                continue
            if "код" in ПОЛЯ[поле]["джерело"] and len(ПОЛЯ[поле]["джерело"]) == 1:
                вади.append("%s: виведене поле модель не пише" % де)
            if м not in місця_поля(поле):
                вади.append("%s: поле не діє для місця %s" % (де, м))
            ч = частини(поле)
            значення = з if isinstance(з, list) else [з]
            if ПОЛЯ[поле]["кратність"] == "одне" and isinstance(з, list):
                вади.append("%s: кратність одне, а записано перелік" % де)
            for в in значення:
                if None in ч:
                    значення_ок(поле, None, в, вади, де)
                elif в == "немає" or в in СТАНИ:
                    continue
                elif not isinstance(в, dict):
                    вади.append("%s: складене поле без частин" % де)
                else:
                    for частина, вз in в.items():
                        if частина not in ч:
                            вади.append("%s: частини «%s» нема" % (де, частина))
                        else:
                            значення_ок(поле, частина, вз, вади, де + "." + частина)
        в_частинах = {к for ч in код.get("склад") or [] for к in ч}
        for поле in пр.get("крамниця", []):
            if поле not in код and поле not in в_частинах:
                вади.append("%s: «%s» у крамниця, а не в коді" % (пр["ід"], поле))
        for поле, з in (пр.get("виведено") or {}).items():
            if поле not in ПОЛЯ or str(з).split("–")[0] not in (ПОЛЯ[поле].get("виведено") or {}):
                вади.append("%s: виведено %s=%s поза переліком" % (пр["ід"], поле, з))
    return вади


