def розібрати(рядок):
    """«назва | межа» → (назва, межа); без межі — (назва, "")."""
    назва, _, межа = str(рядок).partition(" | ")
    return назва.strip(), межа.strip()


def перелік(опис):
    """Закритий перелік частини поля: {код: «назва | межа»}, або ('число', одиниці), ('текст',), ('реєстр', що)."""
    if "значення" in опис:
        return опис["значення"]
    if "список" in опис:
        return П["списки"][опис["список"]]
    if "шкала" in опис:
        шк = П["шкали"][опис["шкала"]]
        коди = list(шк)
        if "діапазон" in опис:
            а, б = sorted(коди.index(к) for к in опис["діапазон"])
            коди = коди[а:б + 1]
        вихід = {к: шк[к] for к in коди}
        вихід.update(опис.get("додаткові") or {})
        return вихід
    if "число" in опис:
        return ("число", опис["число"])
    if "текст" in опис:
        return ("текст",)
    if "виведено" in опис:
        return опис["виведено"]
    if "реєстр" in опис:
        return ("реєстр", опис["реєстр"])
    raise ValueError("нема переліку: %s" % опис.get("назва"))


def частини(поле):
    """{частина: перелік} для складеного поля; {None: перелік} для простого."""
    о = ПОЛЯ[поле]
    if поле == "склад":
        return {None: ("частини",)}
    if поле == "вид":
        return {None: {к: в for з in переліки_вид().values() for к, в in з.items()}}
    if "склад" in о:
        return {ч: перелік(д) for ч, д in о["склад"].items()}
    return {None: перелік(о)}


def переліки_вид():
    return ПОЛЯ["вид"]["значення_за_місцем"]


# ---------------------------------------------------------------- (в) межі
def мірило_в():
    вади, лік = [], 0
    усі = [("шкала " + н, ш) for н, ш in П["шкали"].items()] + [("список " + н, с) for н, с in П["списки"].items()]
    for поле, о in ПОЛЯ.items():
        if поле == "вид":
            усі += [("вид/" + м, з) for м, з in переліки_вид().items()]
            continue
        for ч, п in частини(поле).items():
            if isinstance(п, dict) and ("список" not in (о.get("склад", {}).get(ч) or о)) and \
                    ("шкала" not in (о.get("склад", {}).get(ч) or о) or "додаткові" in о):
                усі.append((поле + ("." + ч if ч else ""), п))
    for де, п in усі:
        назви = set()
        for код, р in п.items():
            лік += 1
            назва, межа = розібрати(р)
            if not назва or not межа:
                вади.append("%s.%s: нема %s" % (де, код, "назви" if not назва else "межі"))
            if назва in назви:
                вади.append("%s.%s: назва «%s» повторюється" % (де, код, назва))
            назви.add(назва)
    return лік, вади


