#!/usr/bin/env python3
"""Таблиця наосліп (наряд `Запис-речі-слот-звірка`): 204 речі проходу #4881, де місце в образі із запису (мітка «слот») інше,
ніж у каталозі (колонка «слот» пулу, `аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz`), + 60 випадкових речей, де вони згодні.
Контроль не відрізнити за виглядом рядка: його друге місце — приманка, взята з тих самих пар місць, що й у розбіжностях
(інша сторона пари зі спільним місцем, вагою частоти пари); місця без пари — запасна приманка. Рядки перемішано, хто «місце 1»,
а хто «місце 2» — випадково; ключ (каталог / запис / приманка, розбіжність / контроль) — лише в `наосліп_ключ.jsonl`.
Запуск з кореня: python3 -I <цей файл>"""
import collections, csv, gzip, json, random
З = "аудит/звіти/запис-речі-слот/"
ЗЕРНО = 20261127
записи = json.load(gzip.open("аудит/проби/запис-речі-прохід-сцен/дані/записи_речі.json.gz", "rt", encoding="utf-8"))
каталог_слот = collections.defaultdict(set)
for р in csv.DictReader(gzip.open("аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz", "rt", encoding="utf-8")):
    if р["ід"]: каталог_слот[р["ід"]].add(р["слот"])
assert all(len(каталог_слот[к]) == 1 for к in записи)
базові = {к.split("@")[0] for к in записи}
кат = {}
for л in gzip.open("каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8"):
    р = json.loads(л)
    if р.get("ід") in базові: кат[р["ід"]] = р
розб, згодні = [], []
for к in sorted(записи):
    з = записи[к]["мітки"].get("слот", {}).get("значення"); с = next(iter(каталог_слот[к]))
    if з is None: continue                 # 2 речі без слоту в записі — не розбіжність місця
    (згодні if з == с else розб).append((к, с, з))
assert len(розб) == 204, len(розб)
пари = collections.Counter()
for _, с, з in розб: пари[(с, з)] += 1
сусіди = collections.defaultdict(collections.Counter)
for (с, з), н in пари.items(): сусіди[с][з] += н; сусіди[з][с] += н
ЗАПАСНА = {"взуття": "сумка", "сумка": "пояс", "колготи": "шкарпетки", "шкарпетки": "колготи", "окуляри": "головний_убір",
           "браслет": "каблучка", "брошка": "прикраси", "сережки": "прикраси", "каблучка": "браслет"}
рнд = random.Random(ЗЕРНО)
контроль = sorted(рнд.sample(згодні, 60))
рядки = [("розбіжність", к, с, з) for к, с, з in розб]
for к, с, _ in контроль:
    if сусіди[с]:
        в = sorted(сусіди[с].items()); п = рнд.choices([x for x, _ in в], [н for _, н in в])[0]
    else:
        п = ЗАПАСНА.get(с, "сумка")
    рядки.append(("контроль", к, с, п))
рнд.shuffle(рядки)
таблиця, ключ = [], []
for н, (вид, к, а, б) in enumerate(рядки, 1):
    р = кат[к.split("@")[0]]
    if вид == "розбіжність": місця = [("каталог", а), ("запис", б)]
    else: місця = [("каталог і запис", а), ("приманка", б)]
    рнд.shuffle(місця)
    ряд = f"р{н:03d}"
    таблиця.append({"ряд": ряд, "назва": р["назва"], "кадри": [x for x in р["кадри"] if x.startswith("http")],
                    "місце 1": місця[0][1], "місце 2": місця[1][1]})
    ключ.append({"ряд": ряд, "ід": к, "вид": вид, "місце 1": місця[0][0], "місце 2": місця[1][0],
                 "каталог": а, "запис": б if вид == "розбіжність" else а, **({"приманка": б} if вид == "контроль" else {})})
with open(З + "наосліп.jsonl", "w", encoding="utf-8") as ф:
    for x in таблиця: ф.write(json.dumps(x, ensure_ascii=False) + "\n")
with open(З + "наосліп_ключ.jsonl", "w", encoding="utf-8") as ф:
    for x in ключ: ф.write(json.dumps(x, ensure_ascii=False) + "\n")
print(len(таблиця), "рядків;", sum(x["вид"] == "контроль" for x in ключ), "контроль; без кадрів:", sum(not x["кадри"] for x in таблиця))
print("пари контролю:", collections.Counter((x["каталог"], x["приманка"]) for x in ключ if x["вид"] == "контроль").most_common())
