#!/usr/bin/env python3
"""Зведення огляду наосліп (наряд `Запис-речі-слот-звірка`): таблиця + ключ + огляди оглядачів (`огляд_<хто>.jsonl`) →
`зведення.json` (числа звіту) і `таблиця.md` (кожен ряд із посиланням на кадри й оцінками). Оцінка «місце k» розкривається
ключем у «каталог» / «запис» (розбіжність) чи «згодне» / «приманка» (контроль). Запуск з кореня: python3 -I <цей файл>"""
import collections, glob, json, os
З = "аудит/звіти/запис-речі-слот/"
читати = lambda ф: [json.loads(л) for л in open(ф, encoding="utf-8") if л.strip()]
табл = {р["ряд"]: р for р in читати(З + "наосліп.jsonl")}
ключ = {р["ряд"]: р for р in читати(З + "наосліп_ключ.jsonl")}
огляди = {os.path.basename(ф)[6:-6]: {р["ряд"]: р for р in читати(ф)} for ф in sorted(glob.glob(З + "огляд_*.jsonl"))}
for хто, о in огляди.items(): assert set(о) == set(табл), f"{хто}: не всі ряди"
ДЖ = {"каталог": "каталог", "запис": "запис", "каталог і запис": "згодне", "приманка": "приманка"}
def вердикт(р, к):
    """розбіжність → каталог | запис | обидва | жодне; контроль → правильне | обидва | хибне"""
    о = р["оцінка"]
    if о in ("місце 1", "місце 2"): д = ДЖ[к[о]]
    else: д = о
    if к["вид"] == "контроль": return {"згодне": "правильне", "приманка": "хибне", "жодне": "хибне", "обидва": "обидва"}[д]
    return д
def точніше(р, к):
    return ДЖ[к[р["точніше"]]] if р.get("оцінка") == "обидва" and р.get("точніше") in ("місце 1", "місце 2") else None
В = {хто: {ряд: вердикт(о[ряд], ключ[ряд]) for ряд in табл} for хто, о in огляди.items()}
розб = sorted(р for р in ключ if ключ[р]["вид"] == "розбіжність"); контр = sorted(р for р in ключ if ключ[р]["вид"] == "контроль")
з = {"рядів": len(табл), "розбіжностей": len(розб), "контролю": len(контр), "оглядачі": list(огляди), "розбіжності": {}, "контроль": {},
     "згода_оглядачів": {}, "за_парами": {}, "обидва_точніше": {}}
for хто in огляди:
    з["розбіжності"][хто] = dict(collections.Counter(В[хто][р] for р in розб).most_common())
    з["контроль"][хто] = dict(collections.Counter(В[хто][р] for р in контр).most_common())
    з["обидва_точніше"][хто] = dict(collections.Counter(str(точніше(огляди[хто][р], ключ[р])) for р in розб if В[хто][р] == "обидва").most_common())
хто_ = list(огляди)
if len(хто_) == 2:
    а, б = хто_
    for назва, ряди in (("розбіжності", розб), ("контроль", контр)):
        зг = sum(В[а][р] == В[б][р] for р in ряди); н = len(ряди)
        pa = collections.Counter(В[а][р] for р in ряди); pb = collections.Counter(В[б][р] for р in ряди)
        pe = sum(pa[k] * pb[k] for k in pa) / н / н
        з["згода_оглядачів"][назва] = {"згодні": зг, "з": н, "каппа_Коена": round(((зг / н) - pe) / (1 - pe), 3) if pe < 1 else None,
                                        "матриця": {f"{x} | {y}": c for (x, y), c in collections.Counter((В[а][р], В[б][р]) for р in ряди).most_common()}}
    # спільний вердикт: однаковий в обох; різний — «спірне»
    спільний = {р: (В[а][р] if В[а][р] == В[б][р] else "спірне") for р in табл}
    з["розбіжності"]["спільний"] = dict(collections.Counter(спільний[р] for р in розб).most_common())
    з["контроль"]["спільний"] = dict(collections.Counter(спільний[р] for р in контр).most_common())
else:
    спільний = None
пари = collections.defaultdict(list)
for р in розб: пари[f'{ключ[р]["каталог"]} → {ключ[р]["запис"]}'].append(р)
for пара, ряди in sorted(пари.items(), key=lambda x: -len(x[1])):
    з["за_парами"][пара] = {"речей": len(ряди), **{хто: dict(collections.Counter(В[хто][р] for р in ряди).most_common()) for хто in огляди},
                            **({"спільний": dict(collections.Counter(спільний[р] for р in ряди).most_common())} if спільний else {})}
# оцінка частки речей каталогу не на своєму місці (3004 речі проходу; 2 без слоту в записі — до згодних)
ВСЬОГО, РОЗБ = 3004, len(розб); ЗГ = ВСЬОГО - РОЗБ
з["оцінка_каталогу"] = {}
for хто in огляди:
    хиб_р = sum(В[хто][р] in ("запис", "жодне") for р in розб)
    хиб_к = sum(В[хто][р] == "хибне" for р in контр) / len(контр)
    з["оцінка_каталогу"][хто] = {"у_розбіжностях_каталог_хибний": хиб_р, "у_контролі_хибних": sum(В[хто][р] == "хибне" for р in контр),
                                  "оцінка_речей_не_на_місці": round(хиб_р + хиб_к * ЗГ), "частка_з_3004": round((хиб_р + хиб_к * ЗГ) / ВСЬОГО, 4)}
json.dump(з, open(З + "зведення.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
р_ = ["| ряд | вид | річ | кадри | каталог | запис / приманка | " + " | ".join(огляди) + " |", "|" + "---|" * (6 + len(огляди))]
for р in sorted(табл, key=lambda р: (ключ[р]["вид"] != "розбіжність", ключ[р]["каталог"], ключ[р].get("запис"), р)):
    к, т = ключ[р], табл[р]
    кадри = " ".join(f"[{і}]({u})" for і, u in enumerate(т["кадри"][:4], 1)) or "—"
    друге = к["запис"] if к["вид"] == "розбіжність" else f'{к["приманка"]} (приманка)'
    оц = " | ".join(f'{В[х][р]}' + (f' ({точніше(огляди[х][р], к)})' if точніше(огляди[х][р], к) else "") for х in огляди)
    р_.append(f'| {р} | {к["вид"]} | {т["назва"].replace("|", "/")[:70]} | {кадри} | {к["каталог"]} | {друге} | {оц} |')
open(З + "таблиця.md", "w", encoding="utf-8").write("# Таблиця огляду: кожна річ, кадри, оцінки\n\nОцінки: «каталог» / «запис» — правий лише він; «обидва» (у дужках — точніше); «жодне». Контроль: «правильне» — згодне місце каталогу й запису, «хибне» — ні.\n\n" + "\n".join(р_) + "\n")
print(json.dumps({к: з[к] for к in ("розбіжності", "контроль", "згода_оглядачів", "оцінка_каталогу", "обидва_точніше")}, ensure_ascii=False, indent=1))
