def json_файл(шлях):
    return json.loads(шлях.read_text(encoding="utf-8"))


def рядки_каталогу(шлях):
    with gzip.open(шлях, "rt", encoding="utf-8") as файл:
        for рядок in файл:
            річ = json.loads(рядок)
            if "ід" in річ:
                п = {}
                for назва, значення, *_ in річ["параметри"]:
                    if значення and str(значення).strip().casefold() not in ПОРОЖНЄ:
                        п[назва] = значення
                yield річ, п


def каталог(шлях):
    усі, одяг, взуття = Counter(), Counter(), Counter()
    слоти, іди = Counter(), Counter()
    with gzip.open(ДЖЕРЕЛА / "каталог_збагачення.json.gz", "rt", encoding="utf-8") as файл:
        кеш = json.load(файл)
    разом, разом_одяг = Counter(), Counter()
    відповідники = 0
    осі = {
        "крій": "крій", "рівень краю": "довжина",
        "принт, структурне поле v1": "візерунок", "формальність": "формальність",
        "масштаб мотиву": "масштаб_відн",
    }
    for річ, п in рядки_каталогу(шлях):
        слот = п.get("слот", "без_слота")
        слоти[слот] += 1
        іди[річ["ід"]] += 1
        поля = [міра for міра, ключі in ПОЛЯ.items()
                if (any(ключ in п for ключ in ключі) if ключі else bool(річ.get(міра)))]
        усі.update(поля)
        домен = (п.get("магазин") or urlsplit(річ["адреса"]).hostname or "").removeprefix("www.")
        доказ = кеш.get(f"{річ['ід']}@{домен}")
        відповідники += доказ is not None
        доказ = доказ or {}
        поєднані = [
            вісь for вісь, поле in осі.items()
            if вісь in поля or str(доказ.get(поле) or "").strip().casefold() not in ПОРОЖНЄ
        ]
        разом.update(поєднані)
        if слот in СЛОТИ_ОДЯГУ:
            разом_одяг.update(поєднані)
        if слот in СЛОТИ_ОДЯГУ:
            одяг.update(поля)
        if слот == "взуття":
            взуття.update(поля)
    print(f"Рядків {sum(слоти.values())}, різних ід {len(іди)}")
    print("Слоти:", dict(слоти.most_common()))
    print("| Поле | Усі | Одяг за сирим слотом | Взуття за сирим слотом |")
    print("|---|---:|---:|---:|")
    for міра in ПОЛЯ:
        print(f"| {міра} | {усі[міра]} | {одяг[міра]} | {взуття[міра]} |")
    print(f"Кеш {len(кеш)} записів, збіг ід@домену {відповідники} рядків.")
    for вісь in осі:
        print(f"{вісь}, сире поле або кеш: усі {разом[вісь]}, одяг {разом_одяг[вісь]}")


def оцінювач():
    # Беремо тільки наявні числові константи й одну функцію оцінки. Без імпортів
    # або інших операторів модуля продукту, без розбору записів сцен.
    шлях = ДЖЕРЕЛА / "пакет_моделі.py"
    дерево = ast.parse(шлях.read_text(encoding="utf-8"))
    назви = {
        "_ТОКЕНІВ_НА_КИРИЛИЧНУ", "_ТОКЕНІВ_НА_ЦИФРУ", "_ТОКЕНІВ_НА_ЛАТИНСЬКУ",
        "_ТОКЕНІВ_НА_ІНШИЙ_ЗНАК", "_ЛАТИНИЦЯ", "_ЦИФРИ",
    }
    простір = {}
    функція = None
    for вузол in дерево.body:
        if isinstance(вузол, ast.Assign):
            цілі = {n.id for ціль in вузол.targets for n in ast.walk(ціль) if isinstance(n, ast.Name)}
            if цілі & назви:
                for ціль in вузол.targets:
                    if isinstance(ціль, ast.Tuple):
                        for ключ, в in zip(ціль.elts, вузол.value.elts, strict=True):
                            простір[ключ.id] = ast.literal_eval(в)
                    else:
                        простір[ціль.id] = ast.literal_eval(вузол.value)
        if isinstance(вузол, ast.FunctionDef) and вузол.name == "токенів":
            функція = вузол
    assert функція is not None and set(простір) == назви
    exec(compile(ast.Module(body=[функція], type_ignores=[]), шлях, "exec"), простір)
    return простір["токенів"]


def токени(картки, шлях):
    оцінити = оцінювач()
    порівняння = []
    поля = ("Тип", "Місце в образі", "Родина кольору", "Крій", "Довжина", "Матеріал",
            "Каблук", "Підошва", "Сезон", "Формальність")
    джерела = {річ["ід"]: річ for річ, _ in рядки_каталогу(шлях) if річ["ід"] in картки}
    for номер, (ід, картка) in enumerate(картки.items(), 1):
        варіант = dict(картка["описи"][0]["поля"])
        річ = джерела[ід]
        # Однаковий конверт JSON. База — проксі набору колонок пулу зі старих
        # записів, а не знятий живий запит. Після — короткий опис-проксі з назви.
        спільне = [номер, річ["ціна"], *(варіант.get(поле) for поле in поля[:3])]
        до = [*спільне, *(варіант.get(поле) for поле in поля[3:])]
        назва = картка["назва"]
        ціль = [*спільне, назва[:120]]
        в_json = lambda рядок: json.dumps(рядок, ensure_ascii=False, separators=(",", ":"))
        порівняння.append((оцінити(в_json(до)), оцінити(в_json(ціль))))
    for назва, серія in zip(("старі колонки, проксі", "опис до 120 знаків, проксі"),
                            zip(*порівняння), strict=True):
        print(f"{назва}: n={len(серія)}, середнє {mean(серія):.1f}, "
              f"межі {min(серія)}–{max(серія)}")


def архівний_дріт():
    # Читаємо збережене повідомлення як дані. Жодного повтору сцени.
    шлях = (КОРІНЬ / "аудит/проби/Живий-через-міст/стенд/службове"
            / "с5_весілля_сестри/обміни.jsonl")
    with шлях.open(encoding="utf-8") as файл:
        запит = json.loads(json.loads(next(islice(файл, 6, None)))["запит"])
    текст = запит["messages"][0]["content"][0]["text"]
    пул = json.loads(текст)["pool"]
    колонки = пул["cols"]
    оцінити = оцінювач()
    числити = lambda форма: оцінити(json.dumps(форма, ensure_ascii=False, separators=(",", ":")))
    після = []
    for рядок in пул["rows"]:
        дані = dict(zip(колонки, рядок))
        основа = [дані[поле] for поле in ("n", "price", "type", "hex", "family")]
        додаток = рядок[len(колонки):]
        деталі = додаток[0] if додаток and isinstance(додаток[0], dict) else {}
        слова = [дані[поле] for поле in ("color", "fabric", "cut", "length")]
        слова.extend(деталі.get(поле) for поле in ("shop_color", "pattern", "details"))
        опис_проксі = ", ".join(str(слово) for слово in слова if слово)[:120]
        після.append([*основа, опис_проксі])
    до = [числити(рядок) for рядок in пул["rows"]]
    після = [числити(рядок) for рядок in після]
    print(f"Архівний пул: {len(до)} рядків, оцінено {числити(пул)} токенів у компактному JSON.")
    for назва, серія in (("до, архівні рядки", до), ("після, проксі опису", після)):
        print(f"{назва}: середнє {mean(серія):.1f}, межі {min(серія)}–{max(серія)}")


