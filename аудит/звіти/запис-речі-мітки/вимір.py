def читачі(повний):
    # Рядки з літералами — кандидати, серед них писачі, сторонні сутності,
    # тести та документація всередині рядків. Живої досяжності лічба не доводить.
    шаблон = re.compile(r"""['"](""" + "|".join(map(re.escape, sorted(ПОЛЯ_ПОШУКУ))) + r""")['"]""")
    властивість = re.compile(r"\.(?:" + "|".join(map(re.escape, sorted(ПОЛЯ_ПОШУКУ))) + r")(?![\w])")
    мови, збіги = Counter(), Counter()
    файли = subprocess.check_output(["git", "ls-files", "-z", "--", "джерела"], cwd=КОРІНЬ)
    for шлях in sorted(КОРІНЬ / імʼя for імʼя in файли.decode().split("\0") if імʼя):
        if шлях.suffix not in {".py", ".js", ".mjs", ".ts", ".html"} or not шлях.is_file():
            continue
        мови[шлях.suffix] += 1
        for номер, рядок in enumerate(шлях.read_text(encoding="utf-8").splitlines(), 1):
            if шаблон.search(рядок) or властивість.search(рядок):
                збіги[шлях.suffix] += 1
                if повний:
                    print(f"{шлях.relative_to(КОРІНЬ)}:{номер}: {рядок.strip()}")
    print("Переглянуто файлів:", dict(мови))
    print("Рядків-кандидатів за назвою мітки:", dict(збіги))


def огляд(шлях):
    картки = {к["ід"]: к for к in json_файл(КОРІНЬ / "ohliad-zapysu/повні.json")}
    власник = json_файл(ДАНІ / "відповіді_власника_повні.json")
