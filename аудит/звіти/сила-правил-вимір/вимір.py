def вимір_приймання(каталог, архівні_плани):
    """Повтор суду чинного main над показаними складами зі збереженим днем."""
    плани = реєстр_приймання()
    крамниця = {р["id"]: р for р in каталог}
    старі, ядро = defaultdict(Counter), defaultdict(Counter)
    склади, порожньо, бачили = [], [], set()
    for тека, план in архівні_плани:
        номер = план["номер"]
        запис = плани.get(номер)
        if запис is None:
            continue
        без_портрета = "с7-без-портрета" in тека.parts
        сирий = сирий_профіль(запис["профіль"], запис["зріст"], без_портрета)
        повтор = тека / "повтор.json"
        if повтор.is_file():
            записана = прочитати(повтор).get("жінка", {})
            if записана.get("skin") and not без_портрета:
                сирий["колір"].update({к: записана.get(в) for к, в in
                    (("шкіра", "skin"), ("волосся", "hair"), ("очі", "eyes"), ("кільце", "ring"))})
        for крок in рядки(тека / "руки.jsonl"):
            дія = крок.get("що", "")
            if not дія.startswith(("Образи після", "Старий збір закінчився")) or not крок.get("ситуація"):
                continue
            день, тіло = з_профілем(ситуація.з_json(крок["ситуація"]), сирий)
            старий_день = старий_день_з_паспорта(крок.get("паспорт") or {}, знання.день_правил(день))
            for картка in крок["картки"]:
                if not isinstance(картка, dict) or картка.get("рука") not in (1, 2) or not картка.get("речі"):
                    continue
                іди = tuple(р["id"] for р in картка["речі"] if р.get("id"))
                ключ = (тека, крок["крок"], іди)
                if ключ in бачили:
                    continue
                бачили.add(ключ)
                місце = dict(джерело=str(тека.relative_to(КОРІНЬ)), крок=крок["крок"], ситуація=номер,
                             рука=картка["рука"], іди=іди)
                відсутні = [і for і in іди if і not in крамниця]
                # Ідентичність і відомі поля показу зберігаємо навіть для
                # знятих товарів. Пропущені поля картки лишаються невідомими.
                речі = []
                for р in картка["речі"]:
                    ід = р.get("id")
                    if ід in крамниця:
                        речі.append(крамниця[ід])
                    elif ід and р.get("слот"):
                        речі.append({к: р[к] for к in ("id", "назва", "слот", "hex", "ціна") if р.get(к) is not None})
                if len(речі) != len(картка["речі"]):
                    порожньо.append(dict(місце, причина="немає ід або слота в записі картки"))
                    continue
                try:
                    до, після, вето = судження_на_складі(речі, день, старий_день, тіло)
                except (ValueError, TypeError, KeyError, IndexError) as помилка:
                    порожньо.append(dict(місце, причина=str(помилка)))
                    continue
                звести(старі, до)
                звести(ядро, після)
                склади.append(dict(місце, слова=план["слова"], день=крок["ситуація"],
                                    профіль=запис["профіль"], мірки=сирий["мірки"], вето=вето,
                                    речі_лише_з_картки=відсутні))
    зі_складами = {с["ситуація"] for с in склади}
    без_складів = sorted(плани.keys() - зі_складами - {"17264"})
    return dict(старий=старі, ядро=ядро, сцени=плани, склади=склади, пропуски=порожньо, без_складів=без_складів)


