def основа_каталогу(каталог):
    for слот in ("верх", "низ", "взуття", "верхній_шар", "сумка", "сережки"):
        доречні = [р for р in каталог if р.get("слот") == слот]
        if доречні:
            # Базова річ із виміром кольору, далі за стабільним порядком.
            yield next((р for р in доречні if р.get("lab")), доречні[0])


def підстановка(річ, основа, назва):
    заміщені = {"верх", "низ"} if річ["слот"] in ("сукня", "комплект") else {річ["слот"]}
    if назва in ("офіс", "спека"):
        заміщені.add("верхній_шар")
    return [річ, *(р for р in основа if р["слот"] not in заміщені and р["id"] != річ["id"])]


def звести(одержувач, джерело):
    for код, лічба in джерело.items():
        одержувач[код].update(лічба)


@lru_cache(maxsize=1)
def дні_партій():
    return tuple(каталожні_дні())


def партія(завдання):
    каталог, основа = завдання
    дні = дні_партій()
    результати = defaultdict(lambda: (defaultdict(Counter), defaultdict(Counter), Counter()))
    for номер, річ in каталог:
        назва, день, старий_день, тіло = дні[номер % len(дні)]
        д_старі, д_ядро, числа = результати[назва]
        числа["входів"] += 1
        try:
            старі, ядро, вето = судження_на_складі(підстановка(річ, основа, назва), день, старий_день, тіло)
        except (ValueError, TypeError, KeyError, IndexError) as помилка:
            числа[f"помилка · {type(помилка).__name__} · {помилка}"] += 1
            continue
        звести(д_старі, старі)
        звести(д_ядро, ядро)
        числа.update({"складів": 1, "вето": вето})
    return dict(результати)


def каталог_без_мережі():
    джерело = КОРІНЬ / "каталог_повний.xml.gz"
    with TemporaryDirectory(prefix="вимір-правил-") as тека:
        # Окремий порожній кеш і ліміт 0: не читаємо й не отримуємо кадри.
        шлях = feed.каталог_на_диску("каталог_повний.xml", тека=str(ДЖЕРЕЛА))
        каталог = feed.прогін(шлях, [], ліміт_фото=0, кеш=str(Path(тека) / "колір.json"),
                              кеш_бази=False)["каталог"]
    with джерело.open("rb") as потік:
        хеш = file_digest(потік, "sha256").hexdigest()
    return sorted(каталог, key=lambda р: str(р["id"])), хеш


def вимір_каталогу(каталог, робітники):
    основа = tuple(основа_каталогу(каталог))
    перелік = list(enumerate(каталог))
    шматки = ((перелік[і:і+144], основа) for і in range(0, len(каталог), 144))
    покриття = defaultdict(Counter)
    старі, ядро = defaultdict(Counter), defaultdict(Counter)
    with ProcessPoolExecutor(max_workers=робітники) as праця:
        for і, результат in enumerate(праця.map(партія, шматки), 1):
            for назва, (д_старі, д_ядро, числа) in результат.items():
                звести(старі, д_старі)
                звести(ядро, д_ядро)
                покриття[назва].update(числа)
            if і % 20 == 0:
                print(f"Каталог · {min(144*і, len(каталог))}/{len(каталог)}", file=sys.stderr)
    return dict(старий=старі, ядро=ядро, сцени=покриття,
                основа={р["слот"]: р["id"] for р in основа})


def літерали(вузол):
    if вузол is None:
        return set()
    return {в.value for в in ast.walk(вузол) if isinstance(в, ast.Constant) and isinstance(в.value, str)}


def входи_функції(вузол):
    """Ключі, які читає функція з інтерпретованим ід правила."""
    поля = defaultdict(set)
    for в in ast.walk(вузол):
        if not (isinstance(в, ast.Call) and isinstance(в.func, ast.Attribute) and в.func.attr == "get"
                and isinstance(в.func.value, ast.Name) and в.args
                and isinstance(в.args[0], ast.Constant) and isinstance(в.args[0].value, str)):
            continue
        імʼя = в.func.value.id.lower()
        if імʼя in ("f", "h", "тіло", "профіль", "особа", "мірки", "риси"):
            група = "вона"
        elif імʼя in ("сц", "сцен", "сценарій", "день", "контекст"):
            група = "день"
        elif імʼя in ("р", "r", "річ", "запис", "верх", "низ", "пара", "пальто"):
            група = "річ"
        else:
            continue
        поля[група].add(в.args[0].value)
    return поля


