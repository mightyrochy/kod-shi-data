def числа_шляху(за_правилом):
    усі = Counter()
    for ч in за_правилом.values():
        усі.update(ч)
    відсів = sum(в for к, в in усі.items() if к.startswith("відсів · "))
    if усі["знахідки"] != усі["дійшло"] + відсів:
        raise AssertionError("Число знахідок не дорівнює числу доставлених і відсіяних")
    return dict(зі_свідченням_судження=sum(ч.get("складів зі свідченням судження", 0) > 0 for ч in за_правилом.values()),
                із_знахідками=sum(ч.get("знахідки", 0) > 0 for ч in за_правилом.values()),
                дійшло_правил=sum(ч.get("дійшло", 0) > 0 for ч in за_правилом.values()),
                знахідки=усі["знахідки"], дійшло=усі["дійшло"], відсів=відсів,
                причини_відсіву={к.split(" · ", 1)[1]: в for к, в in усі.items() if к.startswith("відсів · ")},
                рядки=усі["рядків у вердикті"], заяви=усі["заяв у запиті"])


def брак_за_правилами(групи):
    поля = defaultdict(set)
    for назва in ("каталог", "приймання"):
        for шлях in ("старий", "ядро"):
            for код, ч in групи[назва][шлях].items():
                for ключ, кількість in ч.items():
                    if кількість > 0 and ключ.startswith("бракує · "):
                        поля[ключ.split(" · ", 1)[1]].add(код)
    return [{"поле": п, "правил": len(поля[п]), "ід": sorted(поля[п])}
            for п in sorted(поля, key=lambda п: (-len(поля[п]), п))]


def записати_результат(тека, каталог, хеш, групи, архів):
    метадані, записи, картки, _ = архів
    таблиця, статичні = таблиця_правил(групи, записи)
    не_ожили = {}
    for код, д in таблиця.items():
        проходи = [ч for гр in д["вимір"].values() for ч in гр.values()]
        if any(ч.get("знахідки") or ч.get("складів зі свідченням судження") for ч in проходи):
            continue
        поля = sorted({к.split(" · ", 1)[1] for ч in проходи for к in ч if к.startswith("бракує · ")})
        if поля:
            причина = "чекліст зафіксував брак входу"
        elif д["доказ видачі"] == "згадка у виконуваному коді":
            причина = "є згадка, місця видачі не встановлено"
        else:
            причина = "на цих складах емісії нема, причини мовчання запис не розрізняє"
        не_ожили[код] = {"причина": причина, "поля": поля}
    долі = Counter((з["сила"], з["роль запиту"], з["зміна складу"]) for з in записи)
    картка = Counter(з["системна заява на картці"] for з in записи if з["роль запиту"] == "опис")
    підсумок = {
        "каталог": {"речей": len(каталог), "sha256_архіву": хеш},
        "реєстр": статичні, "бракує": брак_за_правилами(групи), "не ожили": не_ожили,
        "вимір": {г: {**{к: в for к, в in дані.items() if к not in ("старий", "ядро")},
                      **{к: числа_шляху(дані[к]) for к in ("старий", "ядро")}}
                  for г, дані in групи.items()},
        "архіви": метадані,
        "долі в архівах": [{"сила": с, "роль": р, "зміна": з, "кількість": к}
                           for (с, р, з), к in sorted(долі.items())],
        "заяви опису на картках": картка,
    }
    for назва, дані in (("підсумок.json", підсумок), ("правила.json", таблиця)):
        (тека / назва).write_text(json.dumps(дані, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                                 encoding="utf-8")
    дані_архіву = json.dumps({"знахідки": записи, "картки": картки}, ensure_ascii=False, sort_keys=True)
    with (тека / "записані-проходи.json.gz").open("wb") as потік:
        with gzip.GzipFile(fileobj=потік, filename="", mode="wb", mtime=0) as стиснутий:
            стиснутий.write(дані_архіву.encode("utf-8"))
    return підсумок


