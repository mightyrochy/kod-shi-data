def прочитати(шлях):
    with (gzip.open if шлях.suffix == ".gz" else open)(шлях, "rt", encoding="utf-8") as потік:
        return json.load(потік)


def рядки(шлях):
    with (gzip.open if шлях.suffix == ".gz" else open)(шлях, "rt", encoding="utf-8") as потік:
        yield from (json.loads(р) for р in потік if р.strip())


def давній(речі, день, профіль, риси, план):
    """Старий суд над зібраним образом і штатне складання рядків вердикту."""
    перед_стелею = []
    обмежити = суд_огляд.обмежити_вагу

    def зняти(знахідки):
        готові = обмежити(знахідки)
        перед_стелею.extend(dict(з) for з in готові if з.get("під_підлогою"))
        return готові

    учасники = defaultdict(list)
    for р in речі:
        учасники[р["слот"]].append(р)
    спец = (план or {}).get("спец") or {}
    слоти = dict(спец.get("слоти") or {})
    if слоти:
        слоти.update(_схема=спец.get("схема"), _палітра=спец.get("палітра_практична"),
                     _контраст=(спец.get("палітра_практична") or {}).get("контраст_рівень"),
                     _намір=спец.get("намір"))
        if спец.get("поверхні") == "великі":
            слоти.update(_поверхні="великі", _сім_ї=спец.get("сім_ї_схеми") or ())
    with patch.object(суд_огляд, "обмежити_вагу", зняти):
        вирок = суд_від_моделі.перевірити_від_моделі(
            [р["id"] for р in речі], риси, речі, профіль if "профіль" in профіль else None,
            сценарій=день, кандидати=учасники, спец_слоти=слоти)
    сирі = list(вирок["знахідки"]) + list((вирок.get("реєстри") or {}).get("знахідки") or ())
    рядки_моделі, вето = вердикт_моделі.знахідки_вердикту(сирі, "о1")
    return сирі, перед_стелею, рядки_моделі, вето, вирок.get("чеклісти") or {}, вирок.get("опори") or ()


def новий(речі, день, профіль):
    """Ядро судить склад, а штатний серіалізатор записує видимі стилістці заяви."""
    речі_ядра = tuple(річ.читати(р) for р in речі)
    номери = {f"#{і}": р for і, р in enumerate(речі_ядра, 1)}
    образ = Образ("о1", 1, "модель", день.версія,
                  речі=tuple(dict(н=н, ід=р.ід) for н, р in номери.items()), номер="o1")
    пул = Пул(1, 1, день.версія, записи=номери)
    сирі = []
    судити = знання._суд_складу

    def зняти(*а, **к):
        результат = судити(*а, **к)
        сирі.extend(результат)
        return результат

    with patch.object(знання, "_суд_складу", зняти):
        вирок = суд.судити(образ, день, пул, профіль)
    if not isinstance(вирок, Вирок):
        raise ValueError(вирок)
    адреси = {р.ід: н for н, р in номери.items()}
    дріт = запит._образ(образ, вирок, опис=False)
    return сирі, дріт["findings"], вирок.чекліст, адреси


def ознаки_браку(з):
    """Читає структуровану причину, коли емітер її записав."""
    поля = з.get("без_входу")
    if not isinstance(поля, str):
        поля = ""
    if not поля:
        поля = з.get("чому") or з.get("суть") or ""
    коди = tuple(рядок.get("code") for рядок in з.get("заяви") or () if isinstance(рядок, dict))
    return коди or (поля,) if поля or коди else ("причину не записано",)


def поля_чекліста(поле):
    """Знімає списки ідентифікаторів речей, залишаючи назви потрібних полів."""
    return tuple(в.strip() for в in re.sub(r" \([^)]*@[^)]*\)", "", поле or "").split(",") if в.strip())


def рішення_знахідки(з):
    return (з.get("сила") not in ("питання", "утримано") and
            з.get("регістр") not in ("питання", "утримано") and not з.get("без_входу"))


def записати_знахідку(лічба, з):
    лічба["знахідки"] += 1
    if рішення_знахідки(з):
        лічба["знахідки_із_судженням"] += 1
    else:
        лічба["знахідки_без_судження"] += 1
        for поле in ознаки_браку(з):
            лічба[f"причина емісії · {поле}"] += 1
    лічба[f"сила · {з.get('сила') or 'невідома'}"] += 1


def старі_числа(результат, лічба):
    сирі, підлога, рядки_моделі, вето, чеклісти, опори = результат
    for з in сирі:
        код = з.get("правило")
        if not код:
            continue
        р = лічба[код]
        записати_знахідку(р, з)
        рядки, межі = вердикт_моделі.знахідки_вердикту([з], "о1")
        if рядки:
            р["дійшло"] += 1
        elif межі:
            р["дійшло"] += 1
            р["дійшло як вето"] += 1
        else:
            діагноз = вердикт_моделі._РЕЄСТР.обмежити_вагу([dict(з)])[0]
            р["відсів · підлога" if діагноз.get("під_підлогою")
              else "відсів · питання або нуль"] += 1
    for з in підлога:
        if з.get("правило"):
            р = лічба[з["правило"]]
            записати_знахідку(р, з)
            р["відсів · підлога огляду"] += 1
    for з in рядки_моделі:
        лічба[з["правило"]]["рядків у вердикті"] += 1
    for з in опори:
        if з.get("правило"):
            лічба[з["правило"]]["опор поза зауваженнями"] += 1
    стани = defaultdict(list)
    for група, пункти in чеклісти.items():
        if not isinstance(пункти, list) or група == "знахідки":
            continue
        for пункт in пункти:
            if not isinstance(пункт, dict):
                continue
            for код in пункт.get("правила", ()):
                стани[код].append(пункт)
    for код, пункти in стани.items():
        значення = {п["стан"] for п in пункти}
        if значення & {"пройдено", "не пройдено", "провал"}:
            лічба[код]["чекліст · суджено"] += 1
        elif "без входу" in значення:
            лічба[код]["чекліст · немає_входу"] += 1
            поля = {(б.get("input") if isinstance(б, dict) else б) or п.get("вхід")
                    for п in пункти if п["стан"] == "без входу" for б in (п.get("бракує") or ({},))}
            лічба[код].update(f"бракує · {п}" for п in поля if п)
        else:
            лічба[код]["чекліст · нема_чого"] += 1
    return len(вето)


def пункти_за_правилом(чекліст):
    стани = defaultdict(list)
    for код, стан in чекліст.items():
        for правило in ЧЕКЛІСТ.get(код, {}).get("правила", (код,)):
            стани[правило].append(стан)
    return стани


def числа_ядра(результат, лічба):
    сирі, дріт, чекліст, адреси = результат
    стани = пункти_за_правилом(чекліст)
    for код, варіанти in стани.items():
        значення = {в["стан"] for в in варіанти}
        стан = next(в for в in ("суджено", "немає_входу", "нема_чого") if в in значення)
        лічба[код][f"чекліст · {стан}"] += 1
        if стан == "немає_входу":
            поля = {п for в in варіанти for п in поля_чекліста(в.get("поле"))}
            лічба[код].update(f"бракує · {п}" for п in поля)
    по_коду = defaultdict(list)
    for заява in дріт:
        код = заява["rule"]
        по_коду[код].append(заява)
        лічба[код]["заяв у запиті"] += 1
    for з in сирі:
        код = з["правило"]
        р = лічба[код]
        записати_знахідку(р, з)
        опис = знання.ПРАВИЛА.get(код, {})
        if not опис:
            р["відсів · немає опису правила у ядрі"] += 1
            continue
        if з.get("без_входу") or "питання" in (з.get("сила"), з.get("регістр")):
            р["відсів · питання або брак входу"] += 1
            continue
        учасники = з.get("учасники")
        іди = (учасники.get("речі") if isinstance(учасники, dict) else None) or з.get("речі") or ()
        утримано = "утримано" in (з.get("сила"), з.get("регістр"))
        if any(видно["code"] == заява.get("code") and
               bool(видно.get("withheld")) == утримано and
               видно["values"] == запит._номери_заяви(заява.get("values") or {}, адреси) and
               (опис.get("гілки", {}).get(заява["code"]) == "вікна_заміни" or
                set(видно["items"]) == {адреси[і] for і in (*іди, *(заява.get("item_ids") or ())) if і in адреси})
               for заява in з.get("заяви", ()) if isinstance(заява, dict) and заява.get("code")
               for видно in по_коду[код]):
            р["дійшло"] += 1
        else:
            р["відсів · стан або свідок заяви"] += 1


def судження_на_складі(речі, день, старий_день, профіль):
    trace.ЗАПИСИ.clear()
    старі, ядро = defaultdict(Counter), defaultdict(Counter)
    давній_вихід = давній(речі, старий_день, профіль, день.риси_портрета or {}, день.план_палітри)
    вето = старі_числа(давній_вихід, старі)
    числа_ядра(новий(речі, день, профіль), ядро)
    trace.ЗАПИСИ.clear()
    for шлях in (старі, ядро):
        for лічба in шлях.values():
            if лічба["знахідки_із_судженням"] or лічба["чекліст · суджено"]:
                лічба["складів зі свідченням судження"] += 1
            if лічба["знахідки_без_судження"] or лічба["чекліст · немає_входу"]:
                лічба["складів з браком або утриманням"] += 1
    return старі, ядро, вето


def сирий_профіль(жінка, зріст=None, без_портрета=False):
    д = прочитати(ПРОБИ / f"жінки/{жінка}.json")
    м = д.get("мірки") or {}
    обхвати = м.get("обхвати") or м
    # Значення стенда, які приймання підставляє, коли їх немає у файлі жінки.
    типові = {"плечі": 98, "груди": 92, "талія": 74, "стегна": 99}
    кольори = {} if без_портрета else {к: д.get(в) for к, в in
               (("шкіра", "skin"), ("волосся", "hair"), ("очі", "eyes"), ("кільце", "ring"))}
    return {"мірки": {"зріст": int(зріст or м.get("зріст") or 168),
                     "обхвати": {к: обхвати.get(к, в) for к, в in типові.items()}},
            "колір": кольори}


