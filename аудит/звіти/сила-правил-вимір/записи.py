КОРІНЬ = Path(__file__).resolve().parents[3]
ПРОБИ = КОРІНЬ / "аудит/проби"
ПРИЙМАННЯ = Path(__file__).resolve().parents[1] / "ядро-образу-наново/приймання"
АРХІВИ = {
    "Н2": ПРОБИ / "приймання-н2-782c",
    "Н2 · доробка": ПРОБИ / "н2-доробка-90ded3b",
    "Н6 · Sonnet": ПРИЙМАННЯ / "хмара-sonnet",
    "Н6 · перевірка ходу": ПРИЙМАННЯ / "хід-збору-перевірка",
    "старий · четвертий живий повтор": ПРОБИ / "живий-як-людина-4/стенд/службове",
}


def json_з_тексту(текст):
    if isinstance(текст, dict):
        return текст
    if not isinstance(текст, str) or not текст.strip():
        return {}
    текст = текст.strip()
    if текст.startswith("```"):
        текст = текст.partition("\n")[2].strip()
    if текст.startswith("Catalogue photo for item "):
        _, ключ, решта = текст.partition('{"version":')
        текст = ключ + решта
    try:
        вихід = json.JSONDecoder().raw_decode(текст)[0]
    except ValueError:
        return {}
    return вихід if isinstance(вихід, dict) else {}


def відповідь_з_обміну(текст):
    дані = json_з_тексту(текст)
    if isinstance(дані.get("content"), list):
        for блок in дані["content"]:
            if блок.get("type") == "text":
                if вихід := json_з_тексту(блок.get("text")):
                    return вихід
        return {}
    return дані


def обміни(шлях, рядки):
    for н, обмін in enumerate(рядки(шлях), 1):
        сирий = обмін.get("запит") or {}
        запит = json_з_тексту(сирий)
        тексти = ([в["text"] for м in запит["messages"] for в in м.get("content", ())
                   if isinstance(в, dict) and в.get("type") == "text"] if "messages" in запит else [сирий])
        for текст in тексти:
            дані = json_з_тексту(текст)
            if isinstance(дані.get("verdict"), list):
                yield н, дані, відповідь_з_обміну(обмін.get("відповідь")), обмін.get("статус")


def тип_кроку(дані):
    роль = дані.get("task", {}).get("role", "")
    for фраза, тип in (("Improve the outfits", "ремонт"),
                       ("Choose one of", "вибір"),
                       ("Explain the chosen outfit", "опис")):
        if фраза in роль:
            return тип
    return "інший"


def еталон_складу(образ):
    return tuple(sorted(образ.get("items") or ()))


def разом_опис(відповідь):
    текст = [відповідь.get("text", ""), *(відповідь.get("how_to_wear") or ())]
    текст.extend(р.get("text", "") for р in відповідь.get("about_items") or () if isinstance(р, dict))
    return "\n".join(v for v in текст if isinstance(v, str) and v)


def записи_карток(тека, прочитати, рядки):
    """Повертає покази першого збору, другого збору й явної заміни."""
    стан, руки = тека / "стан.json", тека / "руки.jsonl"
    if стан.is_file():
        yield 0, "стан", прочитати(стан).get("картки") or (), None
    elif руки.is_file():
        for крок in рядки(руки):
            що = крок.get("що") or ""
            if що.startswith(("Образи після", "Замінити біля", "Старий збір закінчився")):
                yield крок["крок"], що, крок.get("картки") or (), крок.get("ситуація")


def картки_теки(тека, прочитати, рядки):
    for н, дія, картки, ситуація in записи_карток(тека, прочитати, рядки):
        for картка in картки:
            if not isinstance(картка, dict) or not картка.get("речі"):
                continue
            ядро = картка.get("ядро") or {}
            yield {"крок": н, "дія": дія, "рука": картка["рука"],
                   "вирок": картка.get("вирок") or ядро.get("вирок"),
                   "версія": ядро.get("версія_ситуації") or (ситуація or {}).get("версія"),
                   "номери": sorted(р["н"] for р in ядро.get("речі") or () if р.get("н")),
                   "речі": [{к: р.get(к) for к in ("id", "назва", "слот")}
                            for р in картка["речі"]],
                   "опис": картка.get("опис") or ядро.get("опис_en") or "",
                   "заяви_картки": ядро.get("заяви_картки"),
                   "невідоме": ядро.get("невідоме")}


def картка_за_вироком(картки, образ, склад, версія):
    збіги = [к for к in картки if к["рука"] in (1, 2) and к["вирок"] == образ
             and not к["дія"].startswith("Замінити біля")
             and (версія is None or к["версія"] in (None, версія))]
    явні = [к for к in збіги if к["номери"] and tuple(к["номери"]) == склад]
    if явні:
        return явні[0], "ід вироку та номери речей"
    # Зведений запис Н6 має ід вироку, SKU і текст, але без номерів пулу.
    # Збіг є непрямим, якщо в цьому проході є рівно одна ідентичність картки.
    різні = {(к["рука"], tuple(р["id"] for р in к["речі"])): к for к in збіги if not к["номери"]}
    if len(різні) == 1:
        return next(iter(різні.values())), "ід вироку та версія без звірки номерів речей"
    return None, None


def сила_у_запиті(знахідка):
    сила = знахідка.get("strength") or знахідка.get("сила")
    if сила:
        return сила
    регістр = знахідка.get("register") or знахідка.get("регістр")
    if регістр in ("гейт", "gate"):
        return "гейт у запиті"
    if знахідка.get("withheld") or регістр == "утримано":
        return "утримано"
    return "категорія відсутня"


def доля(тип, відповідь, образ, склад, знаход):
    if тип == "ремонт":
        після = next((о for о in відповідь.get("outfits") or () if о.get("id") == образ), None)
        if після is None or not після.get("items"):
            return "немає зіставної відповіді ремонту"
        дія = next((д.get("action") for д in після.get("done") or ()
                    if д.get("finding") == знаход), None)
        if еталон_складу(після) != склад:
            if дія in ("fixed", "partly"):
                return "склад змінено з посиланням на знахідку"
            return "склад змінено без посилання на знахідку"
        return "склад лишився після ремонту"
    if тип == "вибір":
        обрано = відповідь.get("chosen")
        if not обрано:
            return "немає зіставної відповіді вибору"
        if обрано != образ:
            return "вибрано інший склад"
        прийнято = any((з.get("finding") if isinstance(з, dict) else з) == знаход
                       for з in відповідь.get("accept") or ())
        return "обрано цей склад із визнанням" if прийнято else "обрано цей склад без визнання"
    if тип == "опис":
        return "є текст опису" if разом_опис(відповідь) else "опису немає"
    return "невідома роль"


def заяви_на_картці(картка, з):
    if картка is None or картка["заяви_картки"] is None:
        return "структурованого тексту картки немає"
    for заява in картка["заяви_картки"]:
        if заява.get("ід") == з.get("id") or (
                заява.get("код") == з.get("code") and заява.get("правило") == з.get("rule")):
            return "заява є"
    return "заяви в структурованому полі немає"


def архіви(прочитати, рядки):
    """Записує кожну передану заяву, відстежуючи її ід у межах одного обміну."""
    лічба, до_відтворення = {}, []
    знахідки, картки_усі = [], []
    for назва, корінь in АРХІВИ.items():
        файли = sorted({*корінь.rglob("обміни.jsonl"), *корінь.rglob("обміни.jsonl.gz")})
        теки = sorted({ш.parent for ш in файли} | {ш.parent for ш in корінь.rglob("стан.json")} |
                      {ш.parent for ш in корінь.rglob("руки.jsonl")})
        підсумок = Counter({"тек зі станом або обмінами": len(теки), "файлів обмінів": len(файли)})
        лічба[назва] = підсумок
        за_текою = {}
        for тека in теки:
            картки = list(картки_теки(тека, прочитати, рядки))
            за_текою[тека] = картки
            шлях = str(тека.relative_to(КОРІНЬ))
            картки_усі.extend(dict(джерело=шлях, **к) for к in картки)
            підсумок["знімків карток"] += len(картки)
            план = тека / "план.json"
            if план.is_file() and (тека / "руки.jsonl").is_file():
                до_відтворення.append((тека, прочитати(план)))
        for файл in файли:
            картки = за_текою[файл.parent]
            for н, дані, відповідь, статус in обміни(файл, рядки):
                тип = тип_кроку(дані)
                лічба[назва][f"запитів · {тип}"] += 1
                for обгортка in дані["verdict"]:
                    образ = {**(обгортка.get("your_outfit") or обгортка),
                             "findings": обгортка.get("findings") or ()}
                    склад = еталон_складу(образ)
                    if not склад:
                        continue
                    картка, звірка = картка_за_вироком(картки, образ["id"], склад, дані.get("version_of_day"))
                    for з in образ.get("findings", []):
                        заяви = з.get("statements") or [з]
                        коди = [запис.get("code") for запис in заяви if запис.get("code")]
                        правило = з.get("rule") or з.get("правило")
                        if правило is None and коди == ["outer_will_not_fit_over_bulky"]:
                            правило = "K-OUT-06"
                        підсумок["доставлених заяв у запитах"] += 1
                        if правило is None:
                            підсумок["заяв без коду правила"] += 1
                        знахідки.append({
                            "архів": назва, "джерело": str(файл.relative_to(КОРІНЬ)), "рядок": н,
                            "роль запиту": тип, "статус": статус, "версія дня": дані.get("version_of_day"),
                            "день": дані.get("day") or дані.get("case"), "образ": образ["id"], "склад": склад,
                            "ід знахідки": з.get("id"), "правило": правило, "код заяви": ", ".join(коди),
                            "факти": з.get("values") or з.get("statements") or з.get("what"), "вага": з.get("weight"), "сила": сила_у_запиті(з),
                            "регістр": з.get("register"), "ремонт": з.get("repair"),
                            "зміна складу": доля(тип, відповідь, образ["id"], склад, з.get("id")),
                            "крок картки": картка["крок"] if картка else None, "звірка картки": звірка,
                            "системна заява на картці": заяви_на_картці(картка, з),
                            "пояснення": разом_опис(відповідь) if тип == "опис" else None,
                        })
    return лічба, знахідки, картки_усі, до_відтворення
