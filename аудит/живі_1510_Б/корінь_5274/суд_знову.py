"""Перерахувати суд Б4 кодом дерева (argv[1]=тека джерела) на записаному стані; вивести без_входу, картку не_знаю і промпт мовного проходу."""
import sys, os, json, copy
дж, вердикти, вих = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, дж); os.chdir(дж)
import оцінка_образу as О, мовний_шар as М
d0 = json.load(open(вердикти))
е = d0["прогони"][0]["вердикти"][0]["етапи"]
записаний = е["суд"]
d = dict(d0["спільне"]["вхід_прогону"]); d.update(речі=е["речі"]["речі"], пікселі={}, сценарій_оцінки=е.get("сценарій_екрана") or {})
d.pop("каталог", None)
_ст = О._виміри
О._виміри = lambda *а, **к: copy.deepcopy(записаний["речі"])
суд = О.суд(d)
def ключі(с): return [(б.get("input") or б.get("point") or (б.get("rule") or [None])[0], б.get("kind")) for б in с.get("без_входу") or []]
print("без_входу: записано", len(записаний["без_входу"]), "перераховано", len(суд["без_входу"]), "збіг ключів", ключі(записаний) == ключі(суд))
print("образ", суд["образ"], "рівень", суд.get("рівень"), "записаний рівень", записаний.get("рівень"))
відп = open(os.path.join(os.path.dirname(вердикти), "VIDPOVIDI/seed3_03_ОЦІНКА_відповідь.txt"), encoding="utf-8").read().split("── ВІДПОВІДЬ", 1)[1].split("\n", 1)[1]
for ім, с in (("записаний", записаний), ("перерахований", суд)):
    к = О.прийняти_оцінку(відп, с)["картка"]
    тексти = {"не_знаю.%d" % і: json.dumps({"review_unknown": х["контекст"]}, ensure_ascii=False) if х.get("контекст") else "unknown: " + х["код"] for і, х in enumerate(к["не_знаю"])}
    для = json.loads(М.мова(json.dumps({"тексти": тексти}, ensure_ascii=False)))
    open(вих + "_" + ім + ".txt", "w").write(для["промпт"])
    print(ім, "не_знаю", len(к["не_знаю"]), "промпт", len(для["промпт"]), "знаків")
json.dump(суд["без_входу"], open(вих + "_без_входу.json", "w"), ensure_ascii=False, indent=1)
