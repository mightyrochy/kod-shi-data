def каталог(s, ms, t):
    if 'правило-без-входу' in ms:
        return 'ПС-17'
    if 'модель-вигадує' in ms:
        return 'ПС-11'
    if ВАРІАНТ.search(t) or (КАДР.search(t) and ('чуже-поле' in ms or ЧУЖЕ.search(t) or 'власн' in t
                                                or 'без кадру' in t or 'дані-неповні' in ms)):
        return 'ПС-3'
    if ЗНІМОК.search(t):
        return 'ПС-4'
    if 'код-читає-слова' in ms and (СЛОТ_СИЛЬНИЙ.search(t) or not КОЛІР.search(t)):
        return 'ПС-1'
    if 'чуже-поле' in ms or ЧУЖЕ.search(t):
        return 'ПС-2'
    if КОЛІР.search(t):
        if СЛОВО_КОЛЬОРУ.search(t) or 'код-читає-слова' in ms:
            return 'ПС-6'
        if МЕЖІ_КОЛЬОРУ.search(t) or 'копія-поняття' in ms:
            return 'ПС-7'
        if ВИМІР.search(t) or 'вимір-хибний' in ms:
            return 'ПС-5'
    if СЛОТ.search(t) or СЛОВА.search(t) or 'запис-без-читача' in ms or 'копія-поняття' in ms:
        return 'ПС-1'
    if 'дані-неповні' in ms:
        return 'ПС-4'
    if s == 'кадр-фото':
        return 'ПС-3'
    return 'каталог: поодинокі'


