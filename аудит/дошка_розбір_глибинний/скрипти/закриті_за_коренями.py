@functools.lru_cache(maxsize=4096)
def git(*аргументи):
    """Читає Git, зберігаючи помилку як брак доказу, а не порожній результат."""
    п = subprocess.run(['git', *аргументи], cwd=КОРІНЬ, capture_output=True)
    if п.returncode:
        raise RuntimeError(п.stderr.decode('utf-8', errors='replace').strip())
    return п.stdout.decode('utf-8', errors='strict')


def таблиця(шлях):
    """Читає TSV з однозначним номером кожного вхідного рядка."""
    with (КОРІНЬ / шлях).open(encoding='utf-8-sig', newline='') as ф:
        рядки = list(csv.DictReader(ф, delimiter='\t'))
    if len({р['n'] for р in рядки}) != len(рядки):
        raise ValueError(f'Повтор номера: {шлях}')
    return рядки


def відбиток(шлях):
    """Хешує текст з LF для однакового доказу в Windows та Linux checkout."""
    шлях = Path(шлях)
    вміст = шлях.read_bytes()
    if шлях.suffix.lower() in {'.py', '.js', '.mjs', '.html', '.md', '.json', '.txt',
                              '.ps1', '.sh', '.css', '.xml', '.csv', '.tsv', '.yml', '.yaml'}:
        вміст = вміст.replace(b'\r\n', b'\n')
    return hashlib.sha256(вміст).hexdigest()


def дошка(коміт):
    """Читає саме історичну дошку: нинішній статус може бути вже відкритим."""
    вихід = {}
    for л in git('show', f'{коміт}:аудит/БЕКЛОГ.md').splitlines():
        if re.match(r'^\|\s*\d+\s*\|', л):
            клітинки = [к.strip() for к in re.split(r'(?<!\\)\|', л)[1:-1]]
            # Давня дошка містить і скорочені рядки лише з номером,
            # джерелом, вагою та статусом. Відсутні поля не вигадуємо.
            клітинки += [''] * max(0, 7 - len(клітинки))
            вихід[клітинки[0]] = клітинки
    return вихід


def паспорти():
    """Бере повний клас разом з винятками, а не список назв коренів."""
    вихід = {}
    for ш in sorted((КОРІНЬ / 'аудит/корені').glob('*.md')):
        т = ш.read_text(encoding='utf-8')
        if not т.startswith('# Корінь '):
            continue
        к = re.search(r'^## Клас[^\n]*\n(.*?)(?=^## |\Z)', т, re.M | re.S)
        if not к:
            raise ValueError(f'Нема класу: {ш}')
        п = re.search(r'^прилад:\s*(.+)$', т, re.M)
        вихід[ш.stem] = {'клас': к[1].strip(), 'текст': т,
                        'прилад': п[1].strip().strip('`') if п else '',
                        'шлях': ш.relative_to(КОРІНЬ).as_posix(),
                        'рядок': т[:к.start(1)].count('\n') + 1}
    return вихід


