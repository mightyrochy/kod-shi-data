def зняти_прилади(код):
    """Виконує паспортні команди послідовно і повертає повні свідчення виміру.

    Команди беруться з локальних паспортів; моделей, мережі й самоперевірок
    не запускаємо. Вхідні файли хешуються для відтворення саме цього дерева.
    """
    база = git('rev-parse', код).strip()
    відхилення = git('diff', '--name-only', база, '--', 'джерела', 'zhnyvarka',
                     'аудит/корені', 'аудит/адаптери', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md')
    if відхилення.strip():
        raise ValueError(f'Робоче дерево відрізняється від вимірюваного main: {відхилення}')
    файли = git('ls-files', '-z', '--', 'джерела', 'zhnyvarka', 'аудит/корені',
                'аудит/адаптери', 'аудит/*.md', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md').split('\0')
    хеші = {ф: відбиток(КОРІНЬ / ф)
            for ф in файли if ф and (КОРІНЬ / ф).is_file()}
    виміри = {}
    for кор, п in паспорти().items():
        if not п['прилад']:
            continue
        # Ізольований дочірній Python цього приладу ігнорує PYTHONUTF8.
        # Його stdout і text=True батька мають користуватися однією локаллю;
        # власний stdout приладу для JSON захоплення лишається UTF-8.
        режим = 'utf8=0' if os.name == 'nt' and кор == 'Річ-колір-межі' else 'utf8'
        команда = [sys.executable, '-X', режим, *п['прилад'].split()]
        print(f'Прилад: {кор}', file=sys.stderr, flush=True)
        try:
            в = subprocess.run(команда, cwd=КОРІНЬ, capture_output=True, encoding='utf-8', timeout=900,
                               env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1', 'PYTHONIOENCODING': 'utf-8'})
            виміри[кор] = {'команда': п['прилад'], 'код': в.returncode,
                           'режим_utf8': режим, 'stdout': в.stdout, 'stderr': в.stderr}
        except subprocess.TimeoutExpired as пм:
            # 15 хв — договір приладу, аудит/КОД.md; це не довільний стоп сесії.
            вивід = пм.stdout.decode('utf-8') if isinstance(пм.stdout, bytes) else пм.stdout or ''
            виміри[кор] = {'команда': п['прилад'], 'код': 124, 'режим_utf8': режим,
                           'stdout': вивід, 'stderr': 'Перевищено 900 с за договором аудит/КОД.md'}
    return {'main': база, 'python': sys.version, 'файли': хеші, 'прилади': виміри}


def головна():
    """Обирає машинний або читабельний вихід без запису в репозиторій."""
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument('--джерело', default=ДЖЕРЕЛО)
    п.add_argument('--код', default=КОД)
    п.add_argument('--прилади', type=Path, default=КОРІНЬ / ТЕКА / 'закриті_прилади.json')
    п.add_argument('--формат', choices=('tsv', 'md', 'прилади'), default='tsv')
    а = п.parse_args()
    if а.формат == 'прилади':
        print(json.dumps(зняти_прилади(а.код), ensure_ascii=False, indent=2))
        return
    рядки, пасп, вимір, база = дані(а)
    if а.формат == 'md':
        зведення(рядки, пасп, вимір, база)
    else:
        ф = csv.DictWriter(sys.stdout, fieldnames=ПОЛЯ, delimiter='\t', lineterminator='\n')
        ф.writeheader()
        ф.writerows(рядки)


if __name__ == '__main__':
    головна()
