def історія(джерело):
    """Індексує PR і назви гілок лише серед предків історичного знімка."""
    пр, записи = collections.defaultdict(list), []
    for л in git('log', '--format=%H%x09%s', джерело).splitlines():
        ша, тема = л.split('\t', 1)
        записи.append((ша, тема))
        м = re.search(r'\(#(\d+)\)$|^Merge pull request #(\d+)\b', тема)
        if м:
            пр[м[1] or м[2]].append(ша)
    метадані = КОРІНЬ / ТЕКА / 'закриті_PR.json'
    if метадані.is_file():
        м = json.loads(метадані.read_text(encoding='utf-8'))
        if м['репозиторій'] != 'mightyrochy/kod-shi-data':
            raise ValueError('Метадані PR з іншого репозиторію')
        предки = {ш for ш, т in записи}
        for н, п in м['PR'].items():
            ша = (п.get('mergeCommit') or {}).get('oid', '')
            автор = (п.get('author') or {}).get('login')
            репо = (п.get('headRepository') or {}).get('nameWithOwner')
            if (п['state'] == 'MERGED' and автор == 'mightyrochy'
                    and репо == м['репозиторій'] and re.fullmatch('[0-9a-f]{40}', ша)
                    and ша in предки):
                # Метадані злиття точніші за згадку номера у темі стороннього коміту.
                пр[н] = [ша]
    return пр, записи


def коміти_закриття(к, пр, записи, джерело):
    """Читає номери з клітинки закриття, не плутаючи їх з номером рядка."""
    статус = к[3]
    номери = re.findall(r'#(\d+)\b', статус)
    знайдені = [ш for н in номери for ш in пр.get(н, [])]
    for короткий in re.findall(r'`([0-9a-f]{7,40})`', статус):
        try:
            ша = git('rev-parse', '--verify', f'{короткий}^{{commit}}').strip()
            if git('merge-base', ша, джерело).strip() == ша:
                знайдені.append(ша)
        except RuntimeError:
            pass
    if not знайдені:
        for гілка in re.findall(r'(?:claude|codex|gemini)/[^`\s)]+', статус):
            знайдені.extend(ш for ш, тема in записи if гілка in тема)
    return sorted(set(знайдені)), ','.join('#' + н for н in номери)


@functools.lru_cache(maxsize=2048)
def латка(ша):
    """Читає змінені рядки продукту й правил; діф не є доказом місця сам по собі."""
    текст = git('-c', 'core.quotePath=false', 'show', '--diff-merges=first-parent', '--format=', '--unified=0', ша, '--',
                'джерела', 'zhnyvarka', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md', 'аудит')
    файл, рядок, вихід = '', 0, collections.defaultdict(list)
    for л in текст.splitlines():
        if л.startswith('+++ b/'):
            файл = л[6:]
        elif л.startswith('@@ '):
            рядок = int(re.search(r'\+(\d+)', л)[1])
        elif л.startswith('+') and not л.startswith('+++'):
            вихід[файл].append((рядок, л[1:]))
            рядок += 1
        elif л.startswith(' '):
            рядок += 1
    return dict(вихід)


