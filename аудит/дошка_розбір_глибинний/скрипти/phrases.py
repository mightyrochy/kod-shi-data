cnt = collections.Counter(); ct = collections.defaultdict(collections.Counter)
for r in rows:
    for k, p in P.items():
        if re.search(p, r['raw']):
            cnt[k] += 1; ct[k][r['стан']] += 1
for k, v in cnt.most_common():
    print(f'{v:5d} {k:28s}', dict(ct[k].most_common(4)))
# closure with PR
pr = re.compile(r'#(\d{2,4})')
z = [r for r in rows if r['стан']=='ЗАКРИТО']
withpr = sum(1 for r in z if pr.search(r['st']))
print('ЗАКРИТО з #PR у стані:', withpr, 'з', len(z))
# closures without code change
БЕЗ = r'без правк|правки нема|не вада|проба застаріла|правило мало рацію|не відтворю|вже виправлено|уже виправлено|вже закрит|дубль|парасольк|знято|застаріл|не потрібн|не задача|самознят|звірено|зник сам'
nz = [r for r in z if re.search(БЕЗ, r['st'], re.I)]
print('ЗАКРИТО без правки/як не-вада/парасолька/звірено (за станом):', len(nz))
c2 = collections.Counter()
for r in nz:
    for k in ['без правк','не вада','проба застаріла','правило мало рацію','не відтворю','вже виправлено','уже виправлено','дубль','парасольк','застаріл','не потрібн','звірено']:
        if re.search(k, r['st'], re.I): c2[k]+=1
print(c2.most_common())
