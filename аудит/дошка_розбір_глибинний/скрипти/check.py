# -*- coding: utf-8 -*-
"""Перевірка TSV групи: python3 $ROZBIR/check.py 07  → помилки або «ГРУПА 07: УСЕ ГАРАЗД»."""
import os
import json, sys, re
РОБОЧА = os.environ.get('ROZBIR', '/tmp/rozbir')  # робоча тека розбору; запуск — з кореня репозиторію
g = int(sys.argv[1])
idx = {x['g']: x for x in json.load(open(РОБОЧА + '/index.json', encoding='utf-8'))}
need = idx[g]['nums']
fn = f'{РОБОЧА}/out/g{g:02d}.tsv'
try:
    lines = [l.rstrip('\n') for l in open(fn, encoding='utf-8') if l.strip()]
except FileNotFoundError:
    print('нема файлу', fn); sys.exit(1)
if lines and lines[0].startswith('n\t'): lines = lines[1:]
ДОЗВОЛЕНО = {
 2: {'ЗАКРИТО','ВІДКРИТО','ЧАСТКОВО','ЗНЯТО','ВІДКЛАДЕНО','НЕ_ЗАДАЧА','ДУБЛЬ','ІНШЕ'},
 3: {'вада-видима','вада-даних','вада-внутрішня','вада-мірила','вада-процесу','вимога','рішення','вимір'},
 4: {'каталог-жнива','кадр-фото','колір','розмова-паспорт','межа-модель-код','суд-корпус','добір-відбір','руки-2-4','показ-картка','мова-для-жінки','доставка-швидкодія','мірило-проби','процес-сесії','інше'},
 5: {'джерело','вимір','слово→код','ядро','модель-стилістка','код→слово','показ','доставка','мірило','процес','вимога','неясно'},
 7: {'власник','тестувальниця','живий-прогін','стенд-проба-CI','перевірка-рецензія','огляд-аудит','виконавець-побіжно','менеджер-куратор','невідомо'},
 8: {'корінь','симптом','мірило','документ','без-правки','неясно','—'},
 9: {'живий','проба','текст','нема','—'},
}
МЕХ = {'копія-поняття','запис-без-читача','форма-виходу-моделі','інструкція-моделі','модель-вигадує','код-читає-слова','код-пише-слова','вимір-хибний','дані-неповні','чуже-поле','правило-без-входу','цілі-розходяться','стан-показу','повільно','мірило-не-те','нема-мірила','неповна-правка','регресія','латка','межа-неясна','вимога-змінилась','процес-пам\'ять','процес-канал','процес-правило','процес-злиття','локальна'}
err = []; got = []
for i, l in enumerate(lines, 1):
    c = [x.replace('’', "'").replace('ʼ', "'") for x in l.split('\t')]
    if len(c) != 12: err.append(f'рядок TSV {i}: {len(c)} колонок замість 12: {l[:80]}'); continue
    try: got.append(int(c[0]))
    except ValueError: err.append(f'рядок TSV {i}: номер «{c[0]}»'); continue
    for k, allowed in ДОЗВОЛЕНО.items():
        if c[k-1].strip() not in allowed: err.append(f'{c[0]}: колонка {k} «{c[k-1]}» поза переліком')
    for t in c[5].split('+'):
        t = t.strip()
        if t not in МЕХ and not t.startswith('інше:'): err.append(f'{c[0]}: механізм «{t}» поза переліком')
    if not re.match(r'^(ні|тема:.+|повернення:.+|регресія:.+)$', c[9].strip()): err.append(f'{c[0]}: повтор «{c[9]}»')
miss = sorted(set(need) - set(got)); extra = sorted(set(got) - set(need))
dup = sorted({x for x in got if got.count(x) > 1})
if miss: err.append(f'бракує рядків: {miss[:40]}{"…" if len(miss)>40 else ""} ({len(miss)})')
if extra: err.append(f'зайві рядки: {extra[:40]}')
if dup: err.append(f'двічі: {dup[:40]}')
if err:
    print(f'ГРУПА {g:02d}: ПОМИЛОК {len(err)}'); print('\n'.join(err[:60])); sys.exit(1)
print(f'ГРУПА {g:02d}: УСЕ ГАРАЗД — {len(got)} рядків з {len(need)}')
