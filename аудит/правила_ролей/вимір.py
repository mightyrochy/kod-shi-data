def текст(дерево, файл):
    """Читає файл зі знімка Git або робочого дерева; відсутній файл має 0 байтів."""
    if дерево == ".":
        шлях = КОРІНЬ / файл
        return шлях.read_text(encoding="utf-8") if шлях.exists() else ""
    результат = subprocess.run(
        ["git", "show", f"{дерево}:{файл}"], cwd=КОРІНЬ, capture_output=True,
    )
    if результат.returncode:
        перевірка = subprocess.run(
            ["git", "ls-tree", дерево, "--", файл], cwd=КОРІНЬ, capture_output=True,
            check=True,
        )
        if перевірка.stdout:
            raise RuntimeError(результат.stderr.decode("utf-8"))
        return ""
    return результат.stdout.decode("utf-8")


def частина(вміст, заголовок):
    """Виділяє потрібний розділ разом із заголовком і завершальним розривом рядка."""
    початок = вміст.index(заголовок)
    кінець = вміст.find("\n## ", початок + len(заголовок))
    return вміст[початок:] if кінець < 0 else вміст[початок:кінець + 1]


def байти(вміст):
    """Повертає UTF-8 байти, а не кількість знаків чи оцінку токенів."""
    return len(вміст.encode("utf-8"))


def пакети(дерево, після):
    """Складає явні маршрути читання; наряд і змінні дані рахуються окремим доданком."""
    дані = {файл: текст(дерево, файл) for файл in ФАЙЛИ}
    дані["продукт:рішення"] = дані["аудит/ПРОДУКТ.md"].split("## Рекомендації Codex")[0]
    дані["картина:програма"] = частина(дані["аудит/КАРТИНА.md"], "## 3. Програма")
    дані["стан:адреси"] = частина(дані["аудит/СТАН.md"], "## Адреси")
    дані["перевірка:глибина"] = частина(дані["аудит/ПЕРЕВІРКА.md"], "## Глибина")
