"""М.7: байти стартового читання за роллю й агентом на двох деревах Git, без запуску продукту.

Маршрут — те, що велять прочитати на старті ядро, адаптер і файл ролі цього дерева; наряд, передача, листи й
рядки дошки — змінний доданок, не рахуються. Імпорт і файл — один раз. Запуск із кореня репозиторію:
    python3 аудит/правила_ролей/м7/вимір.py --до a4c069dab5231a88b151628298071a1adb577660 --після HEAD
"""
import argparse
import json
import subprocess
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]


def текст(дерево, файл):
    """Файл зі знімка Git («.» — робоче дерево); відсутній — порожній."""
    if дерево == ".":
        шлях = КОРІНЬ / файл
        return шлях.read_text(encoding="utf-8") if шлях.exists() else ""
    результат = subprocess.run(["git", "show", f"{дерево}:{файл}"], cwd=КОРІНЬ, capture_output=True)
    return результат.stdout.decode("utf-8") if not результат.returncode else ""


def розділ(вміст, початок, кінець):
    """Від рядка, що починається з `початок`, до рядка з `кінець` (не включно); нема — порожньо."""
    рядки = вміст.split("\n")
    i = next((н for н, р in enumerate(рядки) if р.startswith(початок)), None)
    if i is None:
        return ""
    j = next((н for н in range(i + 1, len(рядки)) if рядки[н].startswith(кінець)), len(рядки))
    return "\n".join(рядки[i:j]) + "\n"


def маршрути(дерево, після):
    д = {ф: текст(дерево, ф) for ф in [
        "AGENTS.md", "CLAUDE.md", "GEMINI.md", "аудит/CHATGPT.md", ".gemini/styleguide.md",
        "аудит/МЕНЕДЖЕР.md", "аудит/ДИСПЕТЧЕР.md", "аудит/ВИКОНАВЕЦЬ.md", "аудит/ПЕРЕВІРКА.md",
        "аудит/СТОРОЖ.md", "аудит/ЗАПУСКАЧ.md", "аудит/НОУТБУК.md", "аудит/МОДЕЛІ.md", "аудит/КОД.md",
        "аудит/СТАНДАРТ_КОДУ.md", "аудит/КАРТИНА.md", "аудит/СТАН.md", "аудит/ПРОДУКТ.md",
        "аудит/адаптери/CLAUDE_КЕРУВАННЯ.md", "аудит/проби/живі_порядок.md",
        "open-source-stylist/AGENTS.md", "open-source-stylist/CLAUDE.md"]}
    к = д["аудит/адаптери/CLAUDE_КЕРУВАННЯ.md"]
    д["перевірка:глибина"] = розділ(д["аудит/ПЕРЕВІРКА.md"], "## Глибина", "## ")
    д["продукт:рішення"] = д["аудит/ПРОДУКТ.md"].split("## Рекомендації Codex")[0]
    д["керування:створення"] = розділ(к, "## Створення", "## Події")
    д["керування:події"] = розділ(к, "## Події", "## Ноутбук")
    д["керування:ноутбук"] = розділ(к, "## Ноутбук", "## @@")
    д["стан:адреси"] = розділ(д["аудит/СТАН.md"], "## Адреси", "## Що йде")
    if після:
        # МЕНЕДЖЕР «Старт»: картина, «Черга» плану, у стані — ліміти, «Адреси» й «Що йде»
        д["план:черга"] = розділ(текст(дерево, "аудит/ПЛАН.md"), "## Черга", "## Н1")
        д["стан:менеджер"] = розділ(д["аудит/СТАН.md"], "Оновлено:", "## Номери рядків")
        менеджер = ["аудит/МЕНЕДЖЕР.md", "аудит/КАРТИНА.md", "план:черга", "стан:менеджер"]
        вибір = ["план:черга"]
    else:
        # до: картина й стан цілими; диспетчер обирав роботу за §3 «Програма» картини
        д["картина:програма"] = розділ(д["аудит/КАРТИНА.md"], "## 3.", "## 4.")
        менеджер = ["аудит/МЕНЕДЖЕР.md", "аудит/КАРТИНА.md", "аудит/СТАН.md"]
        вибір = ["картина:програма"]
    вик = ["аудит/ВИКОНАВЕЦЬ.md", "перевірка:глибина"]
    код = ["аудит/СТАНДАРТ_КОДУ.md", "аудит/КОД.md"]
    живий = ["аудит/проби/живі_порядок.md"]
    диспетчер = ["аудит/ДИСПЕТЧЕР.md", "аудит/СТАН.md"]
    м = {
        "менеджер · старт": ("Claude", менеджер),
        "менеджер · засів продукту": ("Claude", менеджер + ["продукт:рішення"]),
        "менеджер · створення диспетчера": ("Claude", менеджер + ["керування:створення"]),
        "диспетчер · подія": ("Claude", диспетчер),
        "диспетчер · призначення": ("Claude", диспетчер + вибір + ["аудит/МОДЕЛІ.md", "керування:створення"]),
        "сторож · CI": ("Claude", ["аудит/СТОРОЖ.md", "керування:події"]),
        "запускач · нагляд": ("Claude", ["аудит/ЗАПУСКАЧ.md", "стан:адреси"]),
        "запускач · запуск Claude": ("Claude", ["аудит/ЗАПУСКАЧ.md", "стан:адреси", "керування:ноутбук"]),
        "ноутбук · живий прогін": ("Claude", ["аудит/НОУТБУК.md"] + живий),
        "ноутбук · код": ("Claude", ["аудит/НОУТБУК.md"] + вик + код),
        "рецензент · Codex": ("Codex", [".gemini/styleguide.md"]),
        "рецензент · Gemini Code Assist": ("—", [".gemini/styleguide.md"]),
    }
    for агент in ["Claude", "Codex", "agy"]:
        м[f"виконавець · процес · {агент}"] = (агент, вик)
        м[f"виконавець · код · {агент}"] = (агент, вик + код)
        м[f"виконавець · open-source-stylist · {агент}"] = (агент, вик + код + ["open-source-stylist/AGENTS.md"] + (
            ["open-source-stylist/CLAUDE.md"] if агент == "Claude" else []))
        м[f"перевірка · процес · {агент}"] = (агент, ["аудит/ПЕРЕВІРКА.md"])
        м[f"перевірка · код · {агент}"] = (агент, ["аудит/ПЕРЕВІРКА.md"] + код)
        м[f"перевірка · живий Р3 · {агент}"] = (агент, ["аудит/ПЕРЕВІРКА.md"] + код + живий)
    адаптер = {"Claude": ["CLAUDE.md"], "Codex": ["аудит/CHATGPT.md"], "agy": ["GEMINI.md"], "—": []}
    вихід = {}
    for назва, (агент, файли) in м.items():
        склад = list(dict.fromkeys(["AGENTS.md"] + адаптер[агент] + файли))
        if "аудит/ПЕРЕВІРКА.md" in склад and "перевірка:глибина" in склад:
            склад.remove("перевірка:глибина")
        вихід[назва] = {"байти": sum(len(д[ф].encode("utf-8")) for ф in склад), "склад": склад}
    return вихід


def головна():
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument("--до", required=True)
    п.add_argument("--після", default="HEAD")
    п.add_argument("--json")
    а = п.parse_args()
    до, після = маршрути(а.до, False), маршрути(а.після, True)
    рядки = [(н, до[н]["байти"], після[н]["байти"]) for н in до]
    print("| роль · задача · агент | ДО | ПІСЛЯ | Δ |\n|---|---:|---:|---:|")
    for н, x, y in рядки:
        print(f"| {н} | {x:,} | {y:,} | {y - x:+,} |".replace(",", " "))
    if а.json:
        json.dump({"до": а.до, "після": а.після, "одиниця": "байти UTF-8, файл/розділ один раз",
                   "пакети": {н: {"до": до[н], "після": після[н]} for н in до}},
                  open(а.json, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


головна()
