import json, zlib, base64
R = lambda p: open("inp/" + p, encoding="utf-8").read()
head = """Ти — незалежна перевірка pull request у проєкті «Код Ші». Нижче: правила ролі «Перевірка», наряд перевірки й дифф PR.
У тебе НЕМА доступу до коду, мережі чи запуску — працюєш лише з цього тексту. Тому:
- блокувальна вада — те, що видно з диффу й тексту: помилка в логіці, ослаблення чи поломка перевірки, невиконана вимога наряду, хибна заява в описі/дошці;
- те, що можна підтвердити лише запуском (числа, CI, фото), познач окремо як «ПОТРЕБУЄ ЗАПУСКУ», блокувальною не роби, але якщо дифф сам дає підстави підозрювати вагому ваду — кажи її як блокувальну з доказом із диффу;
- не вигадуй вад: кожна — з файлом, рядком чи цитатою з диффу. Якщо вад нема — так і скажи.
Відповідь українською за шаблоном:
ВЕРДИКТ: ПЕРЕВІРЕНО або ДОРОБИТИ
БЛОКУВАЛЬНІ:
1. <файл:рядок> — <суть> — <доказ із диффу>
(або «нема»)
НЕБЛОКУВАЛЬНІ: …
ПОТРЕБУЄ ЗАПУСКУ: …
ЧИСЛО_БЛОКУВАЛЬНИХ: <ціле число>

=== ПРАВИЛА РОЛІ (аудит/ПЕРЕВІРКА.md) ===
"""
P = {}
for n in ("1868", "1852", "1881"):
    P[n] = head + R("rules.txt") + "\n\n=== НАРЯД ПЕРЕВІРКИ ===\n" + R(f"nar_{n}.txt") + "\n\n=== ДИФФ PR (git diff -U12) ===\n" + R(f"diff_{n}.txt")
    print(n, len(P[n]))
b = base64.b64encode(zlib.compress(json.dumps(P, ensure_ascii=False).encode("utf-8"), 9)).decode()
print(len(b))
open("payload_cell.py", "w", encoding="ascii").write("import base64,zlib,json\nP=json.loads(zlib.decompress(base64.b64decode('%s')).decode('utf-8'))\nprint({k:len(v) for k,v in P.items()})\n" % b)
