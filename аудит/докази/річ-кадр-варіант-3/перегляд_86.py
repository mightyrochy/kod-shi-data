def main():
    """Зберігає рішення з доказом і застосовує тільки незмінні історичні ключі."""
    шлях = КОРІНЬ / 'джерела/прилади/корінь_річ_кадр_варіант.json'
    база = json.loads(шлях.read_text(encoding='utf-8'))
    попередній = база.get('доробка_2', {}).get('перегляд_86')
    ключі = ([в['ключ'] for в in попередній] if попередній else
             [к for к, р in база['рішення'].items() if р['порушення'] and к.split('|')[2] == '2'])
    assert len(ключі) == 86
    огляд = []
    for ключ in ключі:
        р = база['рішення'][ключ]
        файл = ключ.split('|')[0]
        рядок = р['рядок_на_main']
        чому = ЗАЛИШИТИ.get(файл, {}).get(рядок)
        порушення = чому is not None
        if not порушення:
            чому = ПЕРЕНЕСТИ[файл]
        р.update(порушення=порушення, чому=чому)
        огляд.append(dict(ключ=ключ, файл=файл, рядок=рядок, код=р['код'],
                         порушення=порушення, чому=чому))
    база.setdefault('доробка_2', {})['перегляд_86'] = огляд
    шлях.write_text(json.dumps(база, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    (Path(__file__).parent / 'перегляд_86.json').write_text(
        json.dumps(огляд, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('Переглянуто 86; лишено', sum(в['порушення'] for в in огляд),
          'знято', sum(not в['порушення'] for в in огляд))


if __name__ == '__main__':
    main()
