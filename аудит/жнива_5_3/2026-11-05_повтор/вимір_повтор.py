"""ДО/ПІСЛЯ 13315: старі записи на сторінках знімка, повтори адреси, виміри; повтор перезбору — сталість. Аргументи: тека знімків, SHA ДО."""
import sys, gzip, json, collections
from pathlib import Path
К = Path(__file__).resolve().parents[3]; sys.path[:0] = [str(К/"джерела"), str(К/"zhnyvarka"), str(К/"джерела/проби")]
import жниварка as ж, woo_варіанти as ва, складальник as с
from кадр_варіант_каталог import давній
_, записи = с.читати_записи()
знімки = {п.name[:-8]: json.loads(gzip.decompress(п.read_bytes())) for п in Path(sys.argv[1]).glob("*.json.gz")}
знімки = {д: т for д, т in знімки.items() if т}
зб = json.loads(gzip.decompress((К/"джерела/каталог_збагачення.json.gz").read_bytes()))
км = json.loads(gzip.decompress((К/"джерела/каталог_кадри.json.gz").read_bytes()))
for стан, а, жн in (("ДО", давній("woo_варіанти", sys.argv[2]), давній("жниварка", sys.argv[2])), ("ПІСЛЯ", ва, ж)):
    нові, відп, з2, к2, звіт, черга = а.перебрати(записи, знімки, жн, зб, км, "2026-11-05")
    повтор = а.перебрати(нові, знімки, жн, з2, к2, "2026-11-05")
    for д in sorted(знімки):
        сторінки = {ва.норм_адреса(т.get("permalink")) for т in знімки[д]}
        старі = [з for з in нові if ва.магазин(з) == д and ва._параметр(з, "знято") != "2026-11-05" and ва.норм_адреса(з["адреса"]) in сторінки]
        ад = collections.Counter(з["адреса"] for з in нові if ва.магазин(з) == д)
        print(стан, д, "записів", sum(ва.магазин(з) == д for з in нові), "старих_на_сторінках_знімка", len(старі),
              "з_виміром", sum((з["ід"] + "@" + д) in з2 for з in старі), "повторів_адреси", sum(н - 1 for н in ад.values() if н > 1),
              "вимірів", sum(к.endswith("@" + д) for к in з2), {k: v for k, v in звіт[д].items() if k in ("старих_ід_вилучено", "колір_якого_нема_в_api", "лишились_як_були", "нових_ід")})
    print(стан, "усього", len(нові), "унікальних_ід", len({з["ід"] for з in нові}), "повтор_сталий", повтор[0] == нові,
          "повтор_записів", len(повтор[0]), "черга", len(черга))
