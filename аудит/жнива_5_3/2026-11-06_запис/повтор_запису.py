"""Перевірка записаного перезбору: (1) кожен старий ід (`<SHA ДО>`) — у нових записах або вилучений рядком таблиці
відповідності; повторів ід нема; (2) повтор того самого перезбору на записаних продуктових файлах нічого не міняє.
Запуск з кореня: python3 аудит/жнива_5_3/2026-11-06_запис/повтор_запису.py <тека Woo> <тека Shopify> <SHA ДО>"""
import csv, gzip, json, os, subprocess, sys
КОРІНЬ = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(КОРІНЬ, "zhnyvarka"))
import жниварка as ж, woo_варіанти as ва, shopify_варіанти as шв, складальник as с


def main():
    теки_woo, тека_shopify, до = sys.argv[1:4]
    сирі = subprocess.run(["git", "-C", КОРІНЬ, "show", до + ":каталог_записи_v1.jsonl.gz"], capture_output=True, check=True).stdout
    старі = {json.loads(р)["ід"] for р in gzip.decompress(сирі).splitlines()[1:]}
    шапка, записи = с.читати_записи()
    нові = [з["ід"] for з in записи]
    with open(os.path.join(КОРІНЬ, "zhnyvarka", "таблиця_відповідності_ж.tsv"), encoding="utf-8") as f:
        вилучені = {р["старий_ід"] for р in csv.DictReader(f, delimiter="\t") if р["спосіб"].startswith("вилучено")}
    втрачені = старі - set(нові) - вилучені
    print("старих ід %d, нових записів %d, повторів ід %d, вилучено таблицею %d, втрачено без рядка %d"
          % (len(старі), len(нові), len(нові) - len(set(нові)), len(старі - set(нові)), len(втрачені)))
    зб, км = ва.читати_json_gz(ва.ЗБАГАЧЕННЯ), ва.читати_json_gz(ва.КАДРИ)["записи"]
    знімки = {д: т for д, т in ва.читати_знімки(теки_woo).items() if т}
    р1 = ва.перебрати(записи, знімки, ж, зб, км, "2026-11-06")
    знімки_ш = {д: т for д, т in ва.читати_знімки(тека_shopify).items() if т}
    магазини = {м["домен"]: м for м in ж.читати_магазини(os.path.join(КОРІНЬ, "zhnyvarka", "магазини.tsv"))}
    р2 = шв.перебрати(р1[0], знімки_ш, шв.читати_рецепти(), р1[2], р1[3], "2026-11-06", ж=ж, магазини=магазини)
    різних = sum(1 for а, б in zip(записи, р2[0]) if а != б) + abs(len(записи) - len(р2[0]))
    print("повтор: записів %d → %d, різних записів %d, збагачення стале %s, виміри кадрів сталі %s"
          % (len(записи), len(р2[0]), різних, р2[2] == зб, р2[3] == км))
    return 0 if not втрачені and len(нові) == len(set(нові)) and not різних and р2[2] == зб and р2[3] == км else 1


if __name__ == "__main__":
    sys.exit(main())
