import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "джерела"))
import заміна_з_фото as фото


def вердикт(річ):
    return {"структура": {"ок": True}, "знахідки": [
        {"правило": "K-CLR-02", "сила": "strong", "речі": [річ]}
    ]}


до = вердикт("гольф")
після = вердикт("косуха")
відмова, результат = фото.перевірити_склад(
    ["новий гольф", "косуха"], lambda набори: [після], база=до)
assert відмова is None and результат == після
print("Перенесення K-CLR-02 на іншу річ: відмова відсутня")
