"""Штучний приклад перенесення того самого правила на іншу річ після фото.

Запуск з кореня: python аудит/корені/Е3-заміна-з-перевіркою-проба-фото.py
Це проба механізму порівняння вердиктів, а не прилад повного класу місць.
"""
import sys
import subprocess
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "джерела"))
import заміна_з_фото as фото


def вердикт(річ):
    """Дає змістовну сильну знахідку на конкретній речі."""
    return {"структура": {"ок": True}, "знахідки": [
        {"правило": "K-CLR-02", "суть": "вимір", "сила": "strong", "сила_нп": 1, "речі": [річ]}
    ]}


до = вердикт("гольф")
після = вердикт("косуха")
стара = types.ModuleType("фото_до")
exec(subprocess.check_output(["git", "show", "c93300a56c451b57d2b5d5c6b7576f79d760271f:джерела/заміна_з_фото.py"],
                             encoding="utf-8"), стара.__dict__)
відмова, результат = стара.перевірити_склад(
    ["новий гольф", "косуха"], lambda набори: [після], база=до)
assert відмова is None and результат == після
словник = {і: dict(id=і, слот=с) for і, с in
           [("гольф", "верх"), ("новий гольф", "верх"), ("косуха", "верхній_шар")]}
суддя = lambda набори: [до if "гольф" in н else після for н in набори]
підсумок = фото.вирішити({"на": "новий гольф"},
    dict(річ="гольф", чому="colour", запасні=["новий гольф"]), ["гольф", "косуха"],
    суддя, словник, {"верх": [словник["новий гольф"]]})
assert підсумок["стан"] == "refused"
print("Перенесення K-CLR-02 на іншу річ: ДО — прийнято; ПІСЛЯ — відхилено")
