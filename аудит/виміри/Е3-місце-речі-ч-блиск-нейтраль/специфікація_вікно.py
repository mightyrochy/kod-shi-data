"""Вікно b* у специфікації слотів ДО → ПІСЛЯ (Е3-місце-речі-ч-блиск-нейтраль).

Запуск з каталогу `джерела` дерева, яке міряють (ДО — `git archive c152382f`, ПІСЛЯ — робоче дерево):
    cd <дерево>/джерела && python3 -X utf8 <корінь>/аудит/виміри/Е3-місце-речі-ч-блиск-нейтраль/специфікація_вікно.py
Тепла особа, драп «золото / вершковий», п'ять схем, одинадцять слотів: скільки рядків фіду несуть b-вікно нейтралі
і які ID приобличчевої індукції лишаються в специфікації. Платних API й моделей нема."""
import sys, json, collections
sys.path.insert(0, ".")
import palette as P, colorspace as cs
F=cs.features(cs.hx("#e8b98f"),cs.hx("#3a2a1e"),cs.hx("#4a3527"))
наб=["верх","низ","сукня","комплект","верхній_шар","взуття","сумка","пояс","колготи","шарф","головний_убір"]
л=collections.Counter(); рядків=0; з_вікном=0; ids=set()
for сх in P.СХЕМИ:
    sp=P.специфікація(F,сх,наб,source="protocolized",драп={"метал":"золото","білий":"вершковий"})
    for s,v in sp["слоти"].items():
        for k in ("нейтраль_темп","якір_нейтраль_темп"):
            if k in v: л[(k,s)]+=1
    q=P.запит_у_фід(sp)
    for r in q:
        рядків+=1; з_вікном+= r.get("b_min") is not None
    t=json.dumps(sp,ensure_ascii=False)
    ids|={x for x in("R-CHEV-06","R-CHEV-07","R-CHEV-12","R-CHEV-13","R-PC-03","R-TYP-04") if x in t}
print("схем",len(P.СХЕМИ),"рядків фіду",рядків,"з b-вікном",з_вікном,"слотів з полем",sum(л.values()),dict(sorted(л.items())),"ID у специфікації",sorted(ids))
