# -*- coding: utf-8 -*-
"""Прогін фікстур судів блиску й нейтралі на одному дереві коду: `python3 -X utf8 прогін_фікстур.py <корінь_дерева>`.
Друкує JSON {випадок: вирок}. Той самий файл ганяє `порівняти.py` на базі й на робочому дереві; код дерева береться
лише з його `джерела/` (cwd і sys.path), тож ДО й ПІСЛЯ порівнюються на однакових входах."""
import json, os, sys

корінь = os.path.abspath(sys.argv[1])
os.chdir(os.path.join(корінь, "джерела"))
sys.path.insert(0, os.getcwd())
import outfit as О, суд_блиск as СБ, colorspace as Ц, palette as П

F_ТЕПЛА = Ц.features(Ц.hx("#deb295"), Ц.hx("#f1dbaa"), Ц.hx("#759087"))
F_НЕПРИДАТНА = Ц.features(Ц.hx("#c9b183"), Ц.hx("#f1dbaa"), Ц.hx("#759087"))   # знак осі підтону не стверджується


def елементи(*речі, стан="у_приміщенні"):
    """Речі з полями без площі-залежності: площа задана, щоб `метали` не просили вхід площі."""
    return О.елементи([dict(площа=0.02, hex="#b0b0b0", **р) for р in речі], стан=стан)


def стилістка(слово):
    return dict(місце_стилістки=dict(біля_обличчя=слово, слова="як вона вдягнена"))


def вирок(зн):
    return sorted((з["правило"], з.get("сила") if з.get("сила") == "питання" else з.get("регістр") or з.get("сила"),
                   з.get("сила_нп"), tuple(sorted(з.get("речі") or ()))) for з in зн)


def метали(речі, **к):
    return вирок(СБ.метали(елементи(*речі), к.pop("F", F_ТЕПЛА), речі=речі, **к))


def блиск(речі):
    """Образ «надворі»: верхній шар у приміщенні не вдягнено й елементів не дає; його верх видно (слово стилістки)."""
    речі = [dict(р, **dict(місце_стилістки=dict(видно="так"))) if р["слот"] == "верх" else р for р in речі]
    return вирок(СБ.блиск_бюджет(елементи(*речі, стан="надворі")))


def якір(**к):
    я = П.нейтраль_якір(F_НЕПРИДАТНА, source="protocolized", драп=dict(метал="срібло", білий="оптичний"), **к)
    return dict(near=я["near"], вага_вікна=я["вага_вікна"], вільно=я["вільно"], сила_переваги=я["сила_переваги"])


зол, срб = dict(метал="золото", полірування="полірований"), dict(метал="срібло", полірування="полірований")
вих = {}
# ── МЕТАЛИ: місце відоме (тип слота, слово стилістки, вимір) і невідоме ──────────────────────────────────────────────
вих["М1 сережки золото (тип 1.0) + каблучка й браслет срібло; назвала золото"] = метали(
    [dict(id="с", слот="сережки", **зол), dict(id="к", слот="каблучка", **срб), dict(id="б", слот="браслет", **срб)],
    драп=dict(метал="золото"))
вих["М2 сережки срібло (тип 1.0) + каблучка й браслет золото; назвала золото"] = метали(
    [dict(id="с", слот="сережки", **срб), dict(id="к", слот="каблучка", **зол), dict(id="б", слот="браслет", **зол)],
    драп=dict(метал="золото"))
for слово, мітка in (("так", "слово «так» (1.0)"), ("ні", "слово «ні» (0.0)"), (None, "місце невідоме")):
    річ = dict(id="н", слот="намисто", **зол)
    річ.update(стилістка(слово) if слово else {})
    вих["М3 намисто золото, %s + каблучка й браслет срібло; назвала срібло" % мітка] = метали(
        [річ, dict(id="к", слот="каблучка", **срб), dict(id="б", слот="браслет", **срб)], драп=dict(метал="срібло"))
вих["М4 намисто золото, виміряний near 0.4 (маска) + каблучка й браслет срібло; назвала срібло"] = метали(
    [dict(id="н", слот="намисто", near=0.4, **зол), dict(id="к", слот="каблучка", **срб),
     dict(id="б", слот="браслет", **срб)], драп=dict(метал="срібло"))
вих["М5 те саме без назви металу (тепло особи з фото й нейтралі), намисто «так»"] = метали(
    [dict(id="н", слот="намисто", **зол, **стилістка("так")), dict(id="к", слот="каблучка", **срб),
     dict(id="б", слот="браслет", **срб)], драп=dict(білий="холодний", нейтралі="холодні"))
вих["М6 бажання «без прикрас»: сережки золото (тип 1.0)"] = метали(
    [dict(id="с", слот="сережки", **зол)], прикраси="без прикрас")
вих["М7 бажання «без прикрас»: намисто золото, місце невідоме"] = метали(
    [dict(id="н", слот="намисто", **зол)], прикраси="без прикрас")
# ── БЛИСК: сусідство двох блискучих поверхонь ───────────────────────────────────────────────────────────────────
вих["Б1 верх і верхній шар блискучі"] = блиск([dict(id="в", слот="верх", блиск=2), dict(id="ш", слот="верхній_шар", блиск=2)])
вих["Б2 сережки й намисто «так» блискучі"] = блиск(
    [dict(id="с", слот="сережки", блиск=2), dict(id="н", слот="намисто", блиск=2, **стилістка("так"))])
вих["Б3 сережки й намисто блискучі, місце намиста невідоме"] = блиск(
    [dict(id="с", слот="сережки", блиск=2), dict(id="н", слот="намисто", блиск=2)])
вих["Б4 верх і низ блискучі"] = блиск([dict(id="в", слот="верх", блиск=2), dict(id="н", слот="низ", блиск=2)])
вих["Б5 пояс і сумка блискучі"] = блиск([dict(id="п", слот="пояс", блиск=2), dict(id="с", слот="сумка", блиск=2)])
вих["Б6 верх і верхній шар блискучі + матове взуття"] = блиск(
    [dict(id="в", слот="верх", блиск=2), dict(id="ш", слот="верхній_шар", блиск=2), dict(id="в2", слот="взуття", блиск=0)])
вих["Б7 верх і верхній шар блискучі + матова сукня (зона невідома)"] = блиск(
    [dict(id="в", слот="верх", блиск=2), dict(id="ш", слот="верхній_шар", блиск=2), dict(id="с", слот="сукня", блиск=0)])
вих["Б8 верх і верхній шар блискучі + матовий верх-шар поряд (та сама зона)"] = блиск(
    [dict(id="в", слот="верх", блиск=2), dict(id="ш", слот="верхній_шар", блиск=2), dict(id="ш2", слот="верхній_шар", блиск=0)])
# ── НЕЙТРАЛЬ-ЯКІР: вага слота й вісь відстані ───────────────────────────────────────────────────────────────────
for слот in ("сережки", "взуття", "низ", "пояс", "верх", "шарф", "сукня"):
    for дист in (None, "розмова", "повний_зріст"):
        вих["Н %s, відстань %s (місце — лише слот)" % (слот, дист)] = якір(слот=слот, дистанція=дист)
вих["Н верх, near 0.9 від викликача (запис місця речі)"] = якір(слот="верх", near=0.9)
print(json.dumps(вих, ensure_ascii=False, sort_keys=True))
