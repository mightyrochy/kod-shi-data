# -*- coding: utf-8 -*-
"""Порівнює входи відомих читачів Git на базі наряду та голові без запуску моделей.

Селектори відповідають коду бази 27c5d4686. Окремо від кількості файлів порівнює
весь набір унікальних відповідей ключ_без_лапок_3462.py, включно з двома архівами.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import sys

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / 'джерела/прилади'))
from читачі_записів import дерево

БАЗА = '27c5d4686ce699a0e799e2c827c6efe94c0e8881'
АРХІВИ = ('711f516b1bd8ec1a3bbd5dfac82dbe8286954490',
          'a96f5f6e43311cc13b0351c01e623daf9d6768c0')
ОБЛАСТІ = {
    'ключ_без_лапок_3462.py': r'/VIDPOVIDI/.*\.txt$',
    'вибір_мітка_2880.py': r'/VIDPOVIDI/.*ВЕРДИКТ_V1_ВИБІР_V1.*\.txt$',
    'ремонт_стеля_3640.py': r'/VIDPOVIDI/.*ВЕРДИКТ_V1_ОБРАЗИ_V1.*\.txt$',
    'мова_форма.py': r'^аудит/живі_12/.*мовний_шар',
    'промпти_перелік.py': r'^аудит/живі?[^/]*/.+/(?:VIDPOVIDI/seed\d+_\d+_.*\.txt|transport/\d+\.json)$',
    'промпти3_допит_6215.py': r'^аудит/живі_1016_1/.*/VIDPOVIDI/.*_ОЦІНКА_(?:відповідь|допит)\.txt$',
    'хід_форми_6067.py': r'^аудит/(?:живі_[^/]+/А|живі_пачка_14)/.*_мовний_шар_хід_розмови\.txt$',
    'нова_база.js': r'^аудит/проби/нічні/.*/база\.json$',
}


def маніфест(файли):
    """Фіксує імена й blob, щоб однакова кількість не приховувала інших входів."""
    return hashlib.sha256(''.join(п + '\0' + ша + '\n' for п, ша in sorted(файли.items())).encode()).hexdigest()


def відповіді(блоби):
    """Читає унікальні blob пачками й виділяє відповідь так само, як чинна проба."""
    вихід = {}
    for і in range(0, len(блоби), 512):
        пачка = блоби[і:і + 512]
        в = subprocess.run(['git', 'cat-file', '--batch'], cwd=КОРІНЬ,
                           input=''.join(ш + '\n' for ш in пачка).encode(),
                           stdout=subprocess.PIPE, check=True).stdout
        зсув = 0
        for ша in пачка:
            кінець = в.index(b'\n', зсув)
            розмір = int(в[зсув:кінець].split()[2])
            текст = io.TextIOWrapper(io.BytesIO(в[кінець + 1:кінець + 1 + розмір]), encoding='utf8').read()
            зсув = кінець + розмір + 2
            текст = текст.partition('\n── ВІДПОВІДЬ')[2].partition('\n')[2].strip()
            вихід[ша] = текст if '{' in текст else ''
    return вихід


def унікальні(голова, файли, тексти):
    """Зводить HEAD і архіви з перевіркою колізій MD5, який використовує чинний читач."""
    вихід = {}
    for ревізія in (голова, *АРХІВИ):
        for шлях, ша in sorted(файли[ревізія].items()):
            текст = тексти[ша]
            if not текст:
                continue
            ключ = hashlib.md5(текст.encode()).hexdigest()
            if ключ in вихід:
                assert вихід[ключ]['текст'] == текст, 'Колізія MD5'
            else:
                вихід[ключ] = {'текст': текст, 'джерело': ревізія + ':' + шлях}
    return вихід


def main():
    """Пише повноту областей і replay; повертає 1 при втраті чи підміні входів."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--голова', default='HEAD')
    парсер.add_argument('--вихід', type=Path, required=True)
    а = парсер.parse_args()
    голова = subprocess.check_output(['git', 'rev-parse', '--verify', а.голова + '^{commit}'], cwd=КОРІНЬ).decode().strip()
    знімки = {р: дерево(р) for р in (БАЗА, голова, *АРХІВИ)}
    області = {}
    for назва, взір in ОБЛАСТІ.items():
        пара = [{п: дані[1] for п, дані in знімки[р].items()
                 if п.startswith('аудит/') and re.search(взір, п)} for р in (БАЗА, голова)]
        до, після = пара
        області[назва] = {'до': len(до), 'після': len(після),
                          'втрачених': len(до.keys() - після.keys()),
                          'доданих': len(після.keys() - до.keys()),
                          'змінених': sum(до[п] != після[п] for п in до.keys() & після.keys()),
                          'маніфест_до': маніфест(до), 'маніфест_після': маніфест(після)}
    файли = {р: {п: дані[1] for п, дані in знімки[р].items()
                 if п.startswith('аудит/') and re.search(ОБЛАСТІ['ключ_без_лапок_3462.py'], п)} for р in знімки}
    блоби = sorted({ша for ф in файли.values() for ша in ф.values()})
    тексти = відповіді(блоби)
    до, після = унікальні(БАЗА, файли, тексти), унікальні(голова, файли, тексти)
    зняті, додані = до.keys() - після.keys(), після.keys() - до.keys()
    однакові = (set(в['текст'] for в in до.values()) == set(в['текст'] for в in після.values())
                and all(о['маніфест_до'] == о['маніфест_після'] for о in області.values()))
    підсумок = {'база': БАЗА, 'голова': голова, 'архіви': АРХІВИ, 'області': області,
                'відповідей_до': len(до), 'відповідей_після': len(після),
                'знятих_унікальних': len(зняті), 'доданих_унікальних': len(додані),
                'приклади_знятих': [до[к]['джерело'] for к in sorted(зняті)[:20]], 'однакові': однакові}
    а.вихід.parent.mkdir(parents=True, exist_ok=True)
    а.вихід.write_text(json.dumps(підсумок, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
    print(json.dumps({'відповідей_до': len(до), 'відповідей_після': len(після),
                      'областей': len(області), 'однакові': однакові}, ensure_ascii=False))
    return int(not однакові)


if __name__ == '__main__':
    sys.exit(main())
