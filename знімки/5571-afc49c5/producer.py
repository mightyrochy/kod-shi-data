def відбиток(річ):
    return hashlib.sha256(json.dumps(річ, ensure_ascii=False, sort_keys=True).encode()).hexdigest()

def знайти(обʼєкт, коди):
    вихід = []
    if isinstance(обʼєкт, dict):
        if обʼєкт.get('правило') in коди and 'сила' in обʼєкт:
            вихід.append(обʼєкт)
        for значення in обʼєкт.values():
            вихід += знайти(значення, коди)
    elif isinstance(обʼєкт, list):
        for значення in обʼєкт:
            вихід += знайти(значення, коди)
    return list({json.dumps(з, ensure_ascii=False, sort_keys=True): з for з in вихід}.values())

