звіт = []
def факт(назва, умова, **деталі):
    звіт.append(dict(назва=назва, пройдено=bool(умова), **деталі))

def елемент(рівень, номер=1):
    return dict(id=str(номер), річ=str(номер), слот='верх', тип='qa_unknown_type',
                формальність=рівень, модифікатори=[], зони=[])

def знімок():
    return dict(зламані=sorted(П.зламані()), вимкнені=sorted(П.вимкнені()),
                стежені=sorted(П.стежені()), тінь=П.тінь())

коди = П.ЗА_ІД['K-KOH-02']['коди']
for нижня in range(1, 11):
    for верхня in range(нижня, 11):
        смуга = [нижня, верхня]
        ціль = нижня - 1 if нижня > 1 else верхня + 1 if верхня < 10 else None
        with П.зламано(коди):
            знахідки = Ф.формальність_образу([елемент(нижня)], сцен=dict(діапазон=смуга))
            ремонти = [з for з in знахідки if з.get('правило') == 'K-KOH-02' and з.get('ремонт_заяви')]
            очікується = [] if ціль is None else [dict(code='use_target_formality_band', values=dict(band=[ціль, ціль]))]
            заяви = [з for р in ремонти for з in р.get('ремонт_заяви', [])]
            факт('суд_межа', (не_порожні := bool(ремонти)) == (ціль is not None)
                  and (ціль is None or any(з.get('values', {}).get('band') == [ціль, ціль] for з in заяви)),
                  смуга=смуга, ціль=ціль, заяви=заяви)
            речі = [елемент(р, р) for р in range(1, 11)]
            лишились, відсіяні, _ = К._поза_сценою(речі, dict(ошатність=смуга))
            фактичні = [р['формальність'] for р in лишились]
            факт('пул_межа', ціль is None or фактичні == [ціль], смуга=смуга, ціль=ціль, фактичні=фактичні)
        доступне, чому = П.вхід(П.ЗА_ІД['K-KOH-02'], dict(сценарій=dict(ошатність=смуга)))
        факт('жереб_межа', доступне == (ціль is not None), смуга=смуга, чому=чому)

невідоме = елемент(None)
невідоме.pop('формальність')
for назва, речі in [('усе_невідоме', [невідоме]), ('невідоме_і_ціль', [невідоме, елемент(3, 2)]),
                     ('невідоме_і_справне', [невідоме, елемент(5, 2)])]:
    with П.зламано(коди):
        знахідки = Ф.формальність_образу(речі, сцен=dict(діапазон=[4, 6]))
        тінь = П.тінь()
        питання = [з for з in знахідки if з.get('без_входу')]
        факт(назва, bool(питання) and all(з.get('сила_нп') == 0 and з.get('регістр') == 'питання' for з in питання)
              and all('1' not in т.get('речі', []) for т in тінь if т.get('дія') in ('target_band', 'keep_neighbor_items')),
              знахідки=знахідки, тінь=тінь)

база = [dict(id=str(н), слот=с) for н, с in enumerate(('верх', 'низ', 'взуття', 'сумка'), 1)]
повний = база + [dict(id='5', слот='пояс'), dict(id='6', слот='верхній_шар')]
for код in ('K-CRA-01', 'K-OUT-33'):
    with П.зламано(П.ЗА_ІД[код]['коди']):
        блокери, знахідки = С.структура_образу_заяви(повний, сценарій=dict(нагода='побачення', місце='ресторан', темп_c=5), верхні=[повний[-1]])
        тінь = П.тінь()
        картка = П.тінь_образу(тінь, [р['id'] for р in повний])
        зайва = П.тінь_образу(тінь, ['5', '6'])
        для_коду = [з for з in знахідки if з.get('правило', '').startswith(код)]
        факт('повний_образ_'+код, bool(для_коду) and bool(картка) and not зайва
              and all(т.get('сила') and т.get('сила_нп', 0) > 0 and т.get('суть') and т.get('речі') for т in картка),
              знахідки=для_коду, тінь=тінь, картка=картка, чужа_картка=зайва)

for код in ('K-CRA-01', 'K-OUT-33'):
    for сцена in (dict(місце='home', темп_c=5), dict(рух='sport', темп_c=5)):
        with П.зламано(П.ЗА_ІД[код]['коди']):
            _, знахідки = С.структура_образу_заяви(повний, сценарій=сцена, верхні=[повний[-1]])
            факт('застосовність_'+код, not any(т.get('правило', '').startswith(код) for т in П.тінь()), сцена=сцена)
for температура in (None, 10, 25, 'невідомо'):
    with П.зламано(['K-OUT-33']):
        кандидати = {'верхній_шар': [повний[-1]], 'верх': [повний[0]]}
        результат = В.хибний_пул_пальта(кандидати, dict(нагода='побачення', місце='ресторан', темп_c=температура))
        факт('температура_поза', результат == кандидати and not П.тінь(), температура=температура)

початок = знімок()
with П.зламано(['K-CRA-01', 'K-MAT-03'], стежити=['R-COL-16']):
    П.в_тінь('K-CRA-01', 'qa', суть='outer')
    зовнішній = знімок()
    try:
        with П.вимкнено(['K-OUT-33']):
            факт('вкладена_абляція', not П.зламані() and П.вимкнене('K-OUT-33'))
            with П.зламано(['K-KOH-02']):
                raise RuntimeError('qa_restore')
    except RuntimeError:
        pass
    факт('відновлення_винятку', знімок() == зовнішній, стан=знімок())
    факт('окремий_context', contextvars.Context().run(знімок) == початок)
    факт('змішана_абляція', П.зламане('K-CRA-01') and П.зламане('K-CRA-01-N')
          and not П.вимкнене('K-CRA-01') and П.вимкнене('K-MAT-03'))
факт('зовнішній_стан', знімок() == початок)
ключі = []
for контекст in (П.вимкнено([]), П.вимкнено(коди), П.зламано(коди)):
    with контекст:
        ключі.append(М._входи_пакета({}, None, None, None, вимкнені_правила=коди if П.вимкнені() or П.зламані() else ()))
факт('ключі_кешу', len({json.dumps(к, sort_keys=True) for к in ключі}) == 3, ключі=ключі)
інші = [з for з in П.ПЕРЕЛІК if з['ід'] not in ('K-CRA-01', 'K-KOH-02', 'K-OUT-33', 'R-MUA-02')]
for запис in інші:
    with П.зламано(запис['коди']):
        факт('інші_правила', not П.зламані() and all(П.вимкнене(к) for к in запис['коди']), правило=запис['ід'])
факт('макіяж_поза', 'R-MUA-02' in П.ПОЗА_ЖЕРЕБОМ)
(корінь / 'межі.json').write_text(json.dumps(звіт, ensure_ascii=False, indent=2))
print(json.dumps(dict(перевірок=len(звіт), невдалі=[з for з in звіт if not з['пройдено']]), ensure_ascii=False))
