#!/usr/bin/env python3
"""Хук PreToolUse на `send_message`: лист диспетчера менеджерові поза переліком не відходить.

Слово власника 29.10 ~09:16 UTC: «я не маю тобі нагадувати правила. Вони існують щоб їх виконувати. Чому правила не
виконуються?» `аудит/ДИСПЕТЧЕР.md`, «Стан і зведення»: лист менеджерові починається лише з «СЛОВО ВЛАСНИКА»,
«РІШЕННЯ ПОТРІБНЕ: …», «КОЛО», «ЛІМІТ», «ДИСПЕТЧЕР ПЕРЕДАЧА» чи «ЗВЕДЕННЯ <час UTC>», зведення — не частіше ніж раз на
~6 год; правило тримала пам'ять — тепер його перевіряє механізм у мить листа.

«СЛОВО ВЛАСНИКА» несе час і текст слова з транскрипту сесії-відправника (розбір — спільна функція
`слова_власника.слова_людини`), а не з пам'яті: 29.10 «~05:30» було 05:24, «~09:35» — 09:26 (наряд
хук-час-слова-власника). Лист менеджерові перевіряється від будь-якого відправника; транскрипт не читається —
пропуск з попередженням.

Адреси — рядки «менеджер» і «диспетчер» `аудит/СТАН.md` (робоче дерево сесії). Свою адресу сесія знає з
`CLAUDE_CODE_REMOTE_SDK_URL` (`…/sessions/cse_<id>` ↔ `session_<id>`); адреса невідома — правило для всіх відправників.
Відправник, чия адреса відома й не диспетчерська, правилом не зв'язаний. Час останнього зведення — файл
`~/.claude/листи_менеджерові_зведення` (для стенда: `ЛИСТИ_СТАН_ФАЙЛ`, час — `ЛИСТИ_ЗАРАЗ`, ISO UTC). Хук не падає сесію:
будь-яка помилка читання — пропуск листа з попередженням у stderr.

Слово власника в листі менеджерові — під «СЛОВО ВЛАСНИКА» чи вкладене в інший лист (26.10 21:30: «ДИСПЕТЧЕР: …»
і слова нижче), — звернене до самого відправника (питання, докір, вказівка; зокрема відповідь на його рядок у лапках
«"…" - …»), повертається раз з нагадуванням «слово про твою ділянку виконуєш ти; менеджерові — лише про продукт чи
правила» (рішення 06.11 у `аудит/корені/ПК-дотримання-правил.md`; слова власника 26.10 18:56, 29.10 05:42,
01.11 20:45, 06.11 05:28 і 06:48). Ознаки читаються зі слова власника з транскрипту (нема — з тексту листа
«СЛОВО ВЛАСНИКА»): рядок у лапках з тире після нього, ім'я ролі, наказ у ділянці диспетчера (прогін, ноутбук, слоти, злиття, черга,
нагадування), «?» чи «ти» — але не в слові про продукт (стилістка, образ, каталог…); `ознаки_звертання` бере й Stop-хук
`дотримання_диспетчера.py`. Той самий лист (те саме слово) удруге відходить — слово про продукт
чи правила відправник шле свідомо; відбитки повернених слів — файл `~/.claude/листи_менеджерові_повернені`
(для стенда: `ЛИСТИ_ПОВТОР_ФАЙЛ`).
"""
import hashlib
import json
import os
import re
import sys
from datetime import datetime, timedelta, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import слова_власника  # noqa: E402

ПЕРЕЛІК = ("СЛОВО ВЛАСНИКА", "РІШЕННЯ ПОТРІБНЕ:", "КОЛО", "ЛІМІТ", "ДИСПЕТЧЕР ПЕРЕДАЧА", "ЗВЕДЕННЯ")
ІНТЕРВАЛ = timedelta(hours=6)
АДРЕСА = re.compile(r"session_[A-Za-z0-9]+")
ЧАС = re.compile(r"\b(\d{1,2}):(\d{2})\b")
ЦИТАТА = re.compile(r"«([^»]+)»")
ШАПКА = re.compile(r"^СЛОВО ВЛАСНИКА\s*~?\s*(?:\d{1,2}:\d{2})?\s*(?:UTC)?\s*[:—-]?\s*")
ВІДПОВІДЬ_НА_РЯДОК = re.compile(r'["“”«][^"“”«»\n]{3,}["”»]\s*[-–—]\s')
ТИ = re.compile(r"(?<![\w'’])(?:ти|тебе|тобі|тобою|твій|твоя|твоє|твої|твого|твоєї|твоєму|твоїй|твоїм|твоїх|твоїми)"
                r"(?![\w'’])", re.I)
НАГАДУВАННЯ_СЛОВА = (
    "«СЛОВО ВЛАСНИКА» звернене до тебе ({ознаки}): слово про твою ділянку виконуєш ти; менеджерові — лише про продукт "
    "чи правила. `AGENTS.md`, «Пам'ять — у файлах»: «почуте в своєму чаті інша сесія шле менеджерові дослівно, крім "
    "питання до неї самої — на нього відповідає вона, а менеджер переслане лише вносить і вдруге не відповідає»; "
    "`аудит/ДИСПЕТЧЕР.md`, «Стан і зведення»: «Власникові пишеш сам, у своєму чаті, відповідь на його питання до тебе й "
    "дію, потрібну саме від нього, з точною дією й фактом того ж ходу; менеджера для цього не будиш.» Слово про продукт "
    "чи правила — надішли той самий лист ще раз: удруге він відходить.")
МІНІМУМ_ПІДРЯДКА = 25  # коротше слово («так», «ок») збігається з будь-яким листом: лише ціле у лапках, рядком чи після шапки


def попередження(т):
    print(f"хук листи_менеджерові: {т}; лист пропущено", file=sys.stderr)


def адреса_ролі(стан, роль):
    for рядок in стан.splitlines():
        комірки = [к.strip() for к in рядок.split("|")]
        if len(комірки) > 2 and комірки[1] == роль:
            збіг = АДРЕСА.search(комірки[2])
            return збіг.group(0) if збіг else None
    return None


def своя_адреса():
    збіг = re.search(r"/sessions/cse_([A-Za-z0-9]+)", os.environ.get("CLAUDE_CODE_REMOTE_SDK_URL", ""))
    return f"session_{збіг.group(1)}" if збіг else None


def зараз():
    т = os.environ.get("ЛИСТИ_ЗАРАЗ")
    return datetime.fromisoformat(т.replace("Z", "+00:00")) if т else datetime.now(timezone.utc)


def відмова(причина):
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "deny",
                                             "permissionDecisionReason": причина}}, ensure_ascii=False))


def стиснути(т):
    return " ".join(т.split())


def слова_в_листі(лист, слова):
    """Слова власника з транскрипту [(час, текст)], що стоять у листі: цілим у лапках, рядком чи після шапки; довге —
    і підрядком."""
    перший = лист.strip().splitlines()[0] if лист.strip() else ""
    тіло = стиснути(лист)
    цитати = [стиснути(ц) for ц in ЦИТАТА.findall(лист)]
    після_шапки = стиснути(ШАПКА.sub("", перший, count=1)).strip("«»\" ")
    цілі = set(цитати) | {після_шапки} | {стиснути(р).strip("«»\" ") for р in лист.splitlines()[1:]}

    def міститься(т):
        т = стиснути(т)
        return (т in цілі or (len(т) >= МІНІМУМ_ПІДРЯДКА and т in тіло)
                or any(len(ц) >= 10 and ц in т for ц in цитати))

    return [(коли, т) for коли, т in слова if міститься(т)]


def перевірити_час_слова(лист, шлях):
    """(причина відмови листа «СЛОВО ВЛАСНИКА» або None, знайдені слова). Час у першому рядку мусить збігатися до хвилини
    з часом слова."""
    слова = слова_власника.слова_людини(шлях)
    перший = лист.strip().splitlines()[0]
    збіг_часу = ЧАС.search(перший)
    час_листа = f"{int(збіг_часу[1]):02d}:{збіг_часу[2]}" if збіг_часу else None
    знайдені = слова_в_листі(лист, слова)

    def початок(слово):
        return f"{слово[0]} UTC «{стиснути(слово[1])[:80]}»"

    if not знайдені:
        початок_т = слова_власника.початок_транскрипту(шлях)
        if початок_т is None or (час_листа and f"{початок_т[:10]} {час_листа}" < початок_т):
            # транскрипт — файл контейнера: після перезапуску він порожній чи починається пізніше за слово
            попередження("транскрипт неповний (порожній чи починається пізніше за час слова)")
            return None, []
        найближче = ""
        if слова:
            def відстань(слово):
                г, х = слово[0][11:].split(":")
                return abs(int(г) * 60 + int(х) - int(час_листа[:2]) * 60 - int(час_листа[3:]))
            найближче = f" Найближче слово в транскрипті: {початок(min(reversed(слова), key=відстань) if час_листа else слова[-1])}."
        return ("«СЛОВО ВЛАСНИКА»: тексту листа нема серед слів власника в транскрипті цієї сесії — слово дослівно з "
                "чату, з часом UTC (`AGENTS.md`, «Пам'ять — у файлах»); почуте не в цьому чаті, а в пам'яті чи "
                f"переказі, листом «СЛОВО ВЛАСНИКА» не йде.{найближче}"), []
    часи = {коли[11:] for коли, _ in знайдені}
    if час_листа in часи:
        return None, знайдені
    точні = ", ".join(початок(с) for с in знайдені[:3])
    if not час_листа:
        return f"«СЛОВО ВЛАСНИКА»: у першому рядку нема часу UTC слова (ГГ:ХХ). Час слова з транскрипту: {точні}.", знайдені
    return (f"«СЛОВО ВЛАСНИКА»: час {час_листа} у листі не збігається з транскриптом до хвилини. Точний час слова: "
            f"{точні}."), знайдені


# Ознака звертання — ділянка відправника (диспетчера), а не форма речення (паспорт, «Вимір диспетчера 09.11»: слово про
# продукт з «?» чи «ти» хибно повертали, наказ диспетчерові без «ти» і «?» пропускали). Слова — основи без закінчень.
РОЛЬ = re.compile(r"(?<![\w'’])диспетчер\w*", re.I)
ДІЛЯНКА = re.compile(
    r"(?<![\w'’])(?:прогін\w*|прогон\w*|ноутбук\w*|слот\w*|відеокарт\w*|gpu|злит\w*|злив\w*|черг\w*|нагадуван\w*|"
    r"пульс\w*|архів\w*|виконав\w*|перевірк\w*|пачк\w*|наряд\w*|запуск\w*|передач\w*|зведенн\w*|ci|pr|сесі\w*|"
    r"таймер\w*)(?![\w'’])", re.I)
ПРОДУКТ = re.compile(
    r"(?<![\w'’])(?:стилістк\w*|образ\w*|сукн\w*|одяг\w*|вбрання|крамниц\w*|каталог\w*|тестувальн\w*|колір\w*|"
    r"кольор\w*|тканин\w*|взимку|влітку|взутт\w*|фото\w*|реч[іей]\w*|сумк\w*|куртк\w*)(?![\w'’])", re.I)
НАКАЗ = re.compile(r"(?:(?:^|[.!?\n]\s*)[А-ЯІЇЄҐ][а-яіїєґ']+(?:и|й|ь)(?=[\s,.!])|(?<![\w'’])не\s+[а-яіїєґ']+(?:й|и|ь)(?=[\s,.!]|$))")
ОЗНАКИ_ПОРЯДОК = ["відповідь на твій рядок у лапках", "звертання до диспетчера", "наказ у твоїй ділянці", "питання",
                  "звертання на «ти»"]


def ознаки_звертання(т):
    """Ознаки слова, зверненого до самого відправника (диспетчера): відповідь на його рядок у лапках, ім'я ролі, наказ у
    його ділянці (прогін, ноутбук, слоти, злиття, черга, нагадування…); питання чи «ти» — лише коли слово не про продукт
    (стилістка, образ, каталог…) або про ділянку."""
    ознаки = []
    ділянка, продукт = bool(ДІЛЯНКА.search(т)), bool(ПРОДУКТ.search(т))
    if ВІДПОВІДЬ_НА_РЯДОК.search(т):
        ознаки.append(ОЗНАКИ_ПОРЯДОК[0])
    if РОЛЬ.search(т):
        ознаки.append(ОЗНАКИ_ПОРЯДОК[1])
    if ділянка and НАКАЗ.search(т):
        ознаки.append(ОЗНАКИ_ПОРЯДОК[2])
    if ділянка or not продукт:
        if "?" in т:
            ознаки.append(ОЗНАКИ_ПОРЯДОК[3])
        if ТИ.search(т):
            ознаки.append(ОЗНАКИ_ПОРЯДОК[4])
    return ознаки


def слово_до_відправника(лист, знайдені, шапка):
    """Нагадування, коли слово власника в листі звернене до відправника й ще не поверталось; той самий лист удруге —
    None. Слова — знайдені в транскрипті; нема їх у листі «СЛОВО ВЛАСНИКА» (транскрипт неповний) — цитати листа чи текст
    після шапки."""
    if знайдені:
        тексти = sorted({стиснути(т) for _, т in знайдені})
    elif шапка:
        цитати = [стиснути(ц) for ц in ЦИТАТА.findall(лист)]
        рядки = лист.strip().splitlines()
        тексти = цитати or [стиснути(" ".join([ШАПКА.sub("", рядки[0], count=1)] + рядки[1:]))]
    else:
        return None
    звернені = [(т, ознаки_звертання(т)) for т in тексти]
    звернені = [(т, о) for т, о in звернені if о]
    if not звернені:
        return None
    відбиток = hashlib.sha256("\n".join(т for т, _ in звернені).encode("utf-8")).hexdigest()[:16]
    файл = os.environ.get("ЛИСТИ_ПОВТОР_ФАЙЛ") or os.path.expanduser("~/.claude/листи_менеджерові_повернені")
    try:
        with open(файл, encoding="utf-8") as ф:
            if відбиток in ф.read().split():
                return None
    except OSError:
        pass  # файлу ще нема — слово не поверталось
    try:
        os.makedirs(os.path.dirname(файл) or ".", exist_ok=True)
        with open(файл, "a", encoding="utf-8") as ф:
            ф.write(відбиток + "\n")
    except OSError as п:
        попередження(f"відбиток не записано ({п}), лист відходить")
        return None
    ознаки = sorted({о for _, оз in звернені for о in оз}, key=ОЗНАКИ_ПОРЯДОК.index)
    слова = "; ".join(f"«{т[:60]}{'…' if len(т) > 60 else ''}»" for т, _ in звернені[:3])
    return НАГАДУВАННЯ_СЛОВА.format(ознаки=", ".join(ознаки)) + f" Звернене: {слова}."


def main():
    дані = json.load(sys.stdin)
    вхід = дані.get("tool_input") or {}
    корінь = os.environ.get("CLAUDE_PROJECT_DIR") or дані.get("cwd") or "."
    with open(os.path.join(корінь, "аудит", "СТАН.md"), encoding="utf-8") as ф:
        стан = ф.read()
    менеджер = адреса_ролі(стан, "менеджер")
    if not менеджер or вхід.get("session_id") != менеджер:
        return
    лист = str(вхід.get("message", ""))
    рядки = [р.strip() for р in лист.splitlines() if р.strip()]
    перший = рядки[0] if рядки else ""
    шапка = перший.startswith("СЛОВО ВЛАСНИКА")
    шлях = дані.get("transcript_path") or ""
    причина, знайдені = None, []
    try:
        if шапка:
            причина, знайдені = перевірити_час_слова(лист, шлях)
        elif шлях:
            знайдені = слова_в_листі(лист, слова_власника.слова_людини(шлях))
    except (OSError, ValueError) as п:
        попередження(f"транскрипт не прочитано ({п})")
    причина = " ".join(п for п in (причина, слово_до_відправника(лист, знайдені, шапка)) if п) or None
    я = своя_адреса()
    від_диспетчера = not я or я == адреса_ролі(стан, "диспетчер")
    if від_диспетчера and not any(перший.startswith(п) for п in ПЕРЕЛІК):
        причина = ((причина + " ") if причина else "") + (
            "Лист менеджерові починається лише з «СЛОВО ВЛАСНИКА», «РІШЕННЯ ПОТРІБНЕ: <що вирішити>», «КОЛО», "
            "«ЛІМІТ», «ДИСПЕТЧЕР ПЕРЕДАЧА» чи «ЗВЕДЕННЯ <час UTC>» (`аудит/ДИСПЕТЧЕР.md`, «Стан і зведення»). "
            "Знахідка на твоїй ділянці — твій наряд, не лист менеджерові.")
    if причина:
        відмова(причина)
        return
    if not від_диспетчера or not перший.startswith("ЗВЕДЕННЯ"):
        return
    файл = os.environ.get("ЛИСТИ_СТАН_ФАЙЛ") or os.path.expanduser("~/.claude/листи_менеджерові_зведення")
    тепер = зараз()
    try:
        with open(файл, encoding="utf-8") as ф:
            минуле = datetime.fromisoformat(ф.read().strip())
    except (OSError, ValueError):
        минуле = None  # нема файлу чи він зіпсований — пропустити й записати
    if минуле and тепер - минуле < ІНТЕРВАЛ:
        відмова(f"«ЗВЕДЕННЯ» — не частіше ніж раз на ~6 год; попереднє було {минуле:%Y-%m-%d %H:%M} UTC, наступне — "
                f"не раніше {минуле + ІНТЕРВАЛ:%H:%M} UTC.")
        return
    try:
        os.makedirs(os.path.dirname(файл), exist_ok=True)
        with open(файл, "w", encoding="utf-8") as ф:
            ф.write(тепер.isoformat())
    except OSError as п:
        попередження(f"стан зведення не записано ({п})")


if __name__ == "__main__":
    try:
        main()
    except Exception as п:  # хук не падає сесію
        попередження(f"{type(п).__name__}: {п}")
